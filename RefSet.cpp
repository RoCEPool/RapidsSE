/*============================================================================*/
/* RefSet.cpp -- Row Ref Set                                                  */
/*============================================================================*/

#include "Data.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
RefSet* Data::_pRefSet(void* aAddr)
{
  RefSet* pRefSet = reinterpret_cast<RefSet*>(aAddr);
  
  return pRefSet;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RefSet::operator new(size_t, void* aAddr)
{
  return aAddr;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void RefSet::operator delete(void* aAddr)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RefSet::RefSet(i8 nRowRefs)
: Header(CN_REFSET)
{
  m_nRowRefs = nRowRefs;
  
  for (i8 i_RowRef = 0; i_RowRef < nRowRefs; i_RowRef++)
    m_iaRowRef[i_RowRef] = C_DATUM_NULL;
  
  _checkInitialised_(CN_REFSET);
  
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RefSet::~RefSet(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* how many bytes required for a RefSet with given number of row ref's        */
/*----------------------------------------------------------------------------*/
i8 RefSet::nBytesReq(i8 nRowRefs)
{
  i8 nBytes = sizeof(RefSet) - sizeof(i8) + (nRowRefs * sizeof(i8));
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get the number of row refs in this ref set                                 */
/*----------------------------------------------------------------------------*/
i8 RefSet::nRowRefs(void)
{
  return m_nRowRefs;
}

/*----------------------------------------------------------------------------*/
/* get a row ref from this ref set                                            */
/*----------------------------------------------------------------------------*/
i8 RefSet::iRowRef(i8 i_RowRef)
{
  ASSERT(i_RowRef < m_nRowRefs);
  
  return m_iaRowRef[i_RowRef];
}

/*----------------------------------------------------------------------------*/
/* set a row ref in this ref set                                              */
/*----------------------------------------------------------------------------*/
void RefSet::vRowRef(i8 i_RowRef, i8 iRowRef)
{
  ASSERT(i_RowRef < m_nRowRefs);
  
  m_iaRowRef[i_RowRef] = iRowRef;
}

