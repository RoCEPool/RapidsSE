#include "Data.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
RefSet* Data::_pRefSet(void* aAddr)
{
  RefSet* pRefSet = reinterpret_cast<RefSet*>(aAddr);
  
  return pRefSet;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RefSet::operator new(size_t, void* aAddr)
{
  return aAddr;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void RefSet::operator delete(void* aAddr)
{
}


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RefSet::RefSet(i8 nRowRefs)
: Object(CN_REFSET)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_REFSET);
  
  m_nRowRefs = C_UNKNOWN;
  
  for (i8 i_RowRef = 0; i_RowRef < nRowRefs; i_RowRef++)
    m_iaRowRef[i_RowRef] = C_UNKNOWN;
  
  _checkInitialised_(CN_REFSET);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_REFSET);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RefSet::~RefSet(void) noexcept(false)
{
}


