/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Semantic* Sessions::_pSemantic(void* aAddr)
{
  Semantic* pSemantic = reinterpret_cast<Semantic*>(aAddr);
  
  RASSERT_TYPE(pSemantic, CN_SEMANTIC);
  
  return pSemantic;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Semantic::operator new(size_t)
{
  Object* pObject = HeapMem::pAllocate(CN_SEMANTIC);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Semantic::operator delete(void* aAddr)
{
  Semantic* pSemantic = reinterpret_cast<Semantic*>(aAddr);
  
  HeapMem::vFree(pSemantic);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Semantic::Semantic(void)
: Object(CN_SEMANTIC)
{
  _precondition_(_MAGIC_,CN_SEMANTIC,_FOOTER_);
  
  _checkInitialised_(CN_SEMANTIC);
  
  _postcondition_(_MAGIC_,CN_SEMANTIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Semantic::~Semantic(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SEMANTIC,_FOOTER_);
  
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get ename-value set                                                        */
/*----------------------------------------------------------------------------*/
TagSet* Semantic::pTagSet(void)
{
  _precondition_(_MAGIC_,CN_SEMANTIC,_FOOTER_);
 
  return & m_oTagSet;
}



