#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVar::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: StrVar class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void StrVar::operator =(Stz* szStz)
{
  vClass(CN_STRVAR);

  StrLib::vCopyLen(m_caStr,(char*)szStz,sizeof(m_caStr)-1);
}

/*----------------------------------------------------------------------------*/
/* get azChar                                                                 */
/*----------------------------------------------------------------------------*/
char* StrVar::azChar(void)
{
  ASSERT(CN_STRVAR == eClass());
  
  return (char*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/* get size of str                                                            */
/*----------------------------------------------------------------------------*/
i8 StrVar::nSize(void)
{
  ASSERT(CN_STRVAR == eClass());
  
  return m_nBytesFollowing;
}

/*----------------------------------------------------------------------------*/
/* get stack usage in bytes                                                   */
/*----------------------------------------------------------------------------*/
i8 StrVar::nStackBytes(void)
{
  ASSERT(CN_STRVAR == eClass());

  return sizeof(StrVar);
}

/*----------------------------------------------------------------------------*/
/* get Stz                                                                    */
/*----------------------------------------------------------------------------*/
Stz* StrVar::szStz(void)
{
  ASSERT(CN_STRVAR == eClass());
  
  return (Stz*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void StrVar::vToString(Stz* szStz)
{
  ASSERT(CN_STRVAR == eClass());

  StrLib::vCopy((char*)szStz,m_caStr);
}

