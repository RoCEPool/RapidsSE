#include "Structures.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Graph* Structures::_pGraph(void* aAddr)
{
  Graph* pGraph = reinterpret_cast<Graph*>(aAddr);
  
  RASSERT_TYPE(pGraph,CN_GRAPH);
  
  return pGraph;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Graph::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_GRAPH);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Graph::operator new(size_t, Graph* pGraph)
{
  return pGraph;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Graph::operator delete(void* pGraphAddress)
{
  Graph* pGraph = reinterpret_cast<Graph*>(pGraphAddress);
  
  HeapMem::vFree(pGraph);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Graph::Graph(void)
: Object(CN_GRAPH)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);
  
  _checkInitialised_(CN_GRAPH);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Graph::~Graph(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* dump the graph                                                             */
/*----------------------------------------------------------------------------*/
void Graph::vDump(eCN eClass, Object* pObject, Stz* aTab)
{ 
  vTrace("\n"_Stz);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get number of values in queue                                              */
/*----------------------------------------------------------------------------*/
i8 Graph::iCount(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);
  
  return m_iCount;
}

/*----------------------------------------------------------------------------*/
/* grab write                                                                 */
/*----------------------------------------------------------------------------*/
void Graph::vGrabWrite(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);

  m_zLock.vGrabWrite();
}

/*----------------------------------------------------------------------------*/
/* drop write                                                                 */
/*----------------------------------------------------------------------------*/
void Graph::vDropWrite(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH,_FOOTER_);
  
  m_zLock.vDropWrite();
}

/*----------------------------------------------------------------------------*/
/* get root node of this graph                                                */
/*----------------------------------------------------------------------------*/
GraphNode* Graph::pRootNode(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH);
  
  return m_pRootNode;
}

/*----------------------------------------------------------------------------*/
/* set root node of this graph                                                */
/*----------------------------------------------------------------------------*/
void Graph::vRootNode(GraphNode* pRootNode)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH);
  
  m_pRootNode = pRootNode;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Graph::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPH);
  
  return &m_xFooter;
}

