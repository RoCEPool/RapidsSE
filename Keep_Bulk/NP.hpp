/* NP.hpp -- nullable pointers                                                */
/*============================================================================*/
#pragma once

namespace CorrectnessAlgebra
{
  template <class OBJECT, eCN eClassNo>
  class NP
  {
  public:
    OBJECT* m_pPointer;
    
    /*------------------------------------------------------------------------*/
    /* default constructor                                                    */
    /*------------------------------------------------------------------------*/
    NP<OBJECT,eClassNo>(void)
    {
      m_pPointer = nullptr;
    }

    /*------------------------------------------------------------------------*/
    /* constructor                                                            */
    /*------------------------------------------------------------------------*/
    NP<OBJECT,eClassNo>(OBJECT* pObject)
    {
      if (pObject && pObject->eClass() != eClassNo) {
        throw (i8)__LINE__;
      }
      m_pPointer = pObject;
    }
    
    /*------------------------------------------------------------------------*/
    /* assignment                                                             */
    /*------------------------------------------------------------------------*/
    void operator = (OBJECT* pObject)
    {
      if (pObject && pObject->eClass() != eClassNo) {
        throw (i8)__LINE__;
      }
      m_pPointer = pObject;
    }
    
    /*------------------------------------------------------------------------*/
    /* member                                                                 */
    /*------------------------------------------------------------------------*/
    OBJECT* operator -> (void)
    {
      if (m_pPointer == nullptr) {
        throw (i8)__LINE__;
      }
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* dereference                                                            */
    /*------------------------------------------------------------------------*/
    OBJECT* operator * (void)
    {
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* ! operator                                                             */
    /*------------------------------------------------------------------------*/
    bool operator ! (void)
    {
      return m_pPointer == nullptr;
    }
    
    /*------------------------------------------------------------------------*/
    /* == operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator == (OBJECT* object)
    {
      return m_pPointer == object;
    }
    
    /*------------------------------------------------------------------------*/
    /* != operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator != (OBJECT* object)
    {
      return m_pPointer != object;
    }
    
  };
}

