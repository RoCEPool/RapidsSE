#pragma once

namespace CorrectnessAlgebra
{
  static const u8 C_MAGIC = 0x4F4E434947414D5E; // ^MAGICNO
  
 class Magic
  {
  protected:
  union {
    u8   m_uMagic;
    char m_sMagic[8];
  };
  
  public:
    Magic(void);
    ~Magic(void);
  
    void  vSetMagic(void);
    i8    iMagic(void) const;
  
    void  vAssertMagic(void);
    bool  bValidMagic(void);
  };
  
  /*----------------------------------------------------------------------------*/
  /* constructor                                                                */
  /*----------------------------------------------------------------------------*/
  inline Magic::Magic(void)
  {
  }
  
  /*----------------------------------------------------------------------------*/
  /* destructor                                                                 */
  /*----------------------------------------------------------------------------*/
  inline Magic::~Magic(void)
  {
  }
  
  /*----------------------------------------------------------------------------*/
  /* set magic                                                                  */
  /*----------------------------------------------------------------------------*/
  inline void Magic::vSetMagic(void)
  {
    m_uMagic = C_MAGIC;
  }

}

/*--------------------------------------------------------------------------*/
/* check the object has a magic marker as its first word                    */
/*--------------------------------------------------------------------------*/
#ifdef __MAGIC_CHECK
  #define _magic_() ASSERT(iMagic() == C_MAGIC);
#else
  #define _magic_()
#endif

