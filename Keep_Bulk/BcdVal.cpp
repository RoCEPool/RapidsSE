#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
BcdVal* Values::_aBcdVal(void* aAddr)
{
  BcdVal* aBcdVal = reinterpret_cast<BcdVal*>(aAddr);
  
  RASSERT_TYPE(aBcdVal,CN_BCDVAL);
  
  return aBcdVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BcdVal::operator new(size_t)
{
  vFatal("fatal: BcdVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BcdVal::BcdVal(void)
: Value(CN_BCDVAL)
{
  m_iBcd = 0;
  
  _checkInitialised_(CN_BOLVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BcdVal::operator =(i8 iBcd)
{
  m_iBcd = iBcd;
}

/*----------------------------------------------------------------------------*/
/* get iBcd                                                                   */
/*----------------------------------------------------------------------------*/
i8 BcdVal::iBcd(void) const
{
  return m_iBcd;
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* BcdVal::aInt(void)
{
  return &m_iBcd;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 BcdVal::nSize(void) const
{
  return sizeof(BcdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BcdVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  *aWorkspace = m_iBcd;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void BcdVal::vMaxValue(void)
{
  m_iBcd = C_I8_MAX;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void BcdVal::vMidValue(void)
{
  m_iBcd  = 73;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void BcdVal::vMinValue(void)
{
  m_iBcd = C_I8_MIN;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void BcdVal::vNullValue(void)
{
  vSetNull();
}

