#include "Data.h"

#include "StorageEngine.h"

extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Coda* Data::_pCoda(void* aAddr)
{
  Coda* pCoda = reinterpret_cast<Coda*>(aAddr);
  
  return pCoda;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Coda::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_CODA);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Coda::operator new(size_t, void* aAddr)
{
  return aAddr;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Coda::operator delete(void* aAddr)
{
  Coda* pCoda = reinterpret_cast<Coda*>(aAddr);
  
  HeapMem::vFree(pCoda);
}


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Coda::Coda(void)
: Object(CN_CODA)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CODA,_FOOTER_);
  
  _checkInitialised_(CN_CODA);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_CODA,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Coda::~Coda(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/



/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Coda::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CODA);
  
  return &m_xFooter;
}

