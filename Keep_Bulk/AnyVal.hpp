/*============================================================================*/
/* AnyVal.hpp -- Layout of any concrete value on Stack                        */
/*============================================================================*/
#pragma once

namespace SenVM
{
  class AnyVal : public StkVal
  {
  private:
  
  public:
    void* operator new(size_t);
    
  };
  
  /*----------------------------------------------------------------------------*/
  /* safe cast                                                                  */
  /*----------------------------------------------------------------------------*/
  inline AnyVal* _aAnyVal(void* aAddr)
  {
    AnyVal* aAnyVal = reinterpret_cast<AnyVal*>(aAddr);
  
    return aAnyVal;
  }
}

