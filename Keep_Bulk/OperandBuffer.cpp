/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
OperandBuffer* MetaData::_pOperandBuffer(void* aAddress)
{
  OperandBuffer* pOperandBuffer = reinterpret_cast<OperandBuffer*>(aAddress);
  
  return pOperandBuffer;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
OperandBuffer::OperandBuffer(eCN eClassNo)
: LinkedBuffer(eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  m_pNextBuffer   = nullptr;
  m_pPrevBuffer   = nullptr;
  
  m_pHigherBuffer = nullptr;
  m_pLowerBuffer  = nullptr;
  
  MemLib::vZero(m__Padding,sizeof(m__Padding),eClassNo);

  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);  
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
OperandBuffer::~OperandBuffer(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


