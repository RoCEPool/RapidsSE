/*============================================================================*/
/* Element.cpp -- element part of an index key                                */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get bytes required for an element                                          */
/*----------------------------------------------------------------------------*/
i8 Element::iBytesRequired(const char* w)
{
  i8 iBytes = sizeof(Element) + String::iSize(w);
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/* get bytes required for an element                                          */
/*----------------------------------------------------------------------------*/
i8 Element::iBytesRequired(i8 iDataBytes)
{
  i8 iBytes = sizeof(Entry) + iDataBytes;
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Element::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Element class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Element::operator new(size_t iSize, Element* pElement)
{
  RASSERT(iSize);
  return pElement;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Element::Element(i8 iDataBytes)
{
  m_iDataBytes = iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Element::~Element(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get data                                                                   */
/*----------------------------------------------------------------------------*/
char* Element::pData(void)
{
  char* pDataAddr = pAdd<char*>(this,sizeof(Element));
  
  return pPoolCheck<char*>(pDataAddr);
}

/*----------------------------------------------------------------------------*/
/* get data bytes                                                             */
/*----------------------------------------------------------------------------*/
i8 Element::iDataBytes(void)
{
  return m_iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* set data bytes                                                             */
/*----------------------------------------------------------------------------*/
void Element::vDataBytes(i8 iDataBytes)
{
  m_iDataBytes = iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Element::vContentDump(void)
{
  vTrace("Element %p: (%lld bytes)\n",
         this,
         m_iDataBytes
         );
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this element                                          */
/*----------------------------------------------------------------------------*/
i8 Element::iSize(void)
{
  i8 iBytes = sizeof(Element) + m_iDataBytes;
  
  return iBytes;
}

