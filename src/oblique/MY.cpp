/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get current grid                                                           */
/*----------------------------------------------------------------------------*/
Grid* MY::pGrid(void)
{
  Grid* pGrid = AM::pGrid();

  return pGrid;
}

/*----------------------------------------------------------------------------*/
/* get current job                                                            */
/*----------------------------------------------------------------------------*/
Job* MY::pJob(void)
{
  Task* pTask = MY::pTask();
  
  Job* pJob = AM::pTaskJob(pTask);
  
  return pJob;
}

/*----------------------------------------------------------------------------*/
/* get current logic unit                                                     */
/*----------------------------------------------------------------------------*/
LogicUnit* MY::pLogicUnit(void)
{
  Job* pJob = MY::pJob();

  if (pJob)
    return pJob->m_pLogicUnit_job;
  else
    return nullptr;
}

/*----------------------------------------------------------------------------*/
/* get current node                                                           */
/*----------------------------------------------------------------------------*/
Node* MY::pNode(void)
{
  Grid* pGrid = MY::pGrid();
  
  if (! pGrid)
    return nullptr;

  Node* pNode = pGrid->pThisNode();

  return pNode;
}

/*----------------------------------------------------------------------------*/
/* get current op                                                             */
/*----------------------------------------------------------------------------*/
Op* MY::pOp(void)
{
  Job* pJob = MY::pJob();

  if (pJob)
    return pJob->m_pOp;
  else
    return nullptr;
}

/*----------------------------------------------------------------------------*/
/* get current operand kind                                                   */
/*----------------------------------------------------------------------------*/
eZK MY::eOperand(void)
{
  LogicUnit* pLogicUnit = MY::pLogicUnit();

  if (pLogicUnit)
    return pLogicUnit->m_eOperand;
  else
    return ZK_NONE;
}

/*----------------------------------------------------------------------------*/
/* get current op                                                             */
/*----------------------------------------------------------------------------*/
Pipeline* MY::pPipeline(void)
{
  Op* pOp = MY::pOp();

  if (pOp)
    return pOp->pPipeline();
  else
    return nullptr;
}

/*----------------------------------------------------------------------------*/
/* get current session                                                        */
/*----------------------------------------------------------------------------*/
Session* MY::pSession(void)
{
  Job* pJob = MY::pJob();
 
  Session* pSession = AM::pJobSession(pJob);

  return pSession;
}

/*----------------------------------------------------------------------------*/
/* get current stage                                                          */
/*----------------------------------------------------------------------------*/
Stage* MY::pStage(void)
{
  Op* pOp = MY::pOp();

  if (pOp)
    return pOp->pStage();
  else
    return nullptr;
}

/*----------------------------------------------------------------------------*/
/* get current stream                                                         */
/*----------------------------------------------------------------------------*/
Stream* MY::pStream(void)
{
  Op* pOp = MY::pOp();

  if (pOp)
    return pOp->pStream();
  else
    return nullptr;
}

/*----------------------------------------------------------------------------*/
/* get current task                                                           */
/*----------------------------------------------------------------------------*/
Task* MY::pTask(void)
{
  Task* pTask = AM::pThisTLSTask();

  return pTask;
}

/*----------------------------------------------------------------------------*/
/* get current thread                                                         */
/*----------------------------------------------------------------------------*/
Thread* MY::pThread(void)
{
  Thread* pThread = AM::pThisTLSThread();

  return pThread;
}

