/*----------------------------------------------------------------------------*/
/* find eCN for given class name                                              */
/*----------------------------------------------------------------------------*/
eCN ClassNumbers::eFind(Stz* szClassNm)
{
  for (i8 i_Class = 0; i_Class < CN_ENUMS; i_Class++)
    if (szClassNm->bSame(aCN[i_Class]))
      return (eCN)i_Class;
  
  return CN_NONE;
}

