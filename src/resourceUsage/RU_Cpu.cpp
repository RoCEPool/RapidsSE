#include "Resources.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RU_Cpu::RU_Cpu(void)
: RU(CN_RUCPU)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nBuffers = 0;
  m_nRows  = 0;
  m_nTicks = 0;
  //m_oTimer;
  
  _checkInitialised_(CN_RUCPU);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RU_Cpu::~RU_Cpu(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  //vReport();
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* end                                                                       */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vEnd(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_oTimer.vUpdate();
  m_nTicks += m_oTimer.iTickDelta();
}

/*----------------------------------------------------------------------------*/
/* report                                                                     */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vReport(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);

  vTrace("  %6lld %6lld\n"_Stz,
         m_nBuffers,
         m_nRows
         );
}

/*----------------------------------------------------------------------------*/
/* start                                                                       */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vStart(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_oTimer.vStart();
}

/*----------------------------------------------------------------------------*/
/* write report                                                               */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vWriteReport(File* pFile)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  AM::vFilePrint(pFile, "  Buffers#, Rows#, Time(ms), Time/Row(ns)\n"_Stz);
  
  i8 iTimeMs = TickingDevice::iToMsec(m_nTicks);
  i8 iTimeNs = TickingDevice::iToNsec(m_nTicks);
  
  AM::vFilePrint(pFile, "  %6lld, %6lld, %6lld, %6lld\n"_Stz,
         m_nBuffers,
         m_nRows,
         iTimeMs,
         m_nRows ? iTimeNs/m_nRows : 0
         );
}

/*----------------------------------------------------------------------------*/
/* inc alloc                                                                  */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vBuffersInc(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nBuffers++;
}

/*----------------------------------------------------------------------------*/
/* add rows                                                                   */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vRowsAdd(i8 nRows)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nRows += nRows;
}

/*----------------------------------------------------------------------------*/
/* get alloc                                                                  */
/*----------------------------------------------------------------------------*/
i8 RU_Cpu::nBuffers(void)
{
  return m_nBuffers;
}

/*----------------------------------------------------------------------------*/
/* get free                                                                   */
/*----------------------------------------------------------------------------*/
i8 RU_Cpu::nRows(void)
{
  return m_nRows;
}

