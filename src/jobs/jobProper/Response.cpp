#include "Plans.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Response* Plans::_pResponse(void* aAddr)
{
  Response* pResponse = reinterpret_cast<Response*>(aAddr);
  
  RASSERT_TYPE(pResponse,CN_RESPONSE);
  
  return pResponse;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Response::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_RESPONSE);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Response::operator delete(void* pAddress)
{
  Response* pResponse = reinterpret_cast<Response*>(pAddress);
  
  HeapMem::vFree(pResponse);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Response::Response(void)
: Object(CN_RESPONSE)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RESPONSE);
  
  m_i_Node          = C_UNKNOWN;
  m_sResponse       = ""_Stz;
  m_ixRowsProcessed = 0;
  m_ixRowsInvalid   = 0;
  m_ixRowsSkipped   = 0;
  m_eErrorCode      = EC_NONE;
  
  _checkInitialised_(CN_RESPONSE);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_RESPONSE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Response::~Response(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RESPONSE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Response::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RESPONSE);
  
  return &m_xFooter;
}

