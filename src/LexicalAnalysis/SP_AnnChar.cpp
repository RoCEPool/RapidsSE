#include "LexicalAnalysis.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_AnnChar::SP_AnnChar(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_AnnChar::~SP_AnnChar(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_AnnChar::sz(AnnChar* aAnnChar)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
    
  SP_Char spChar1;
  
  StrLib::vSprint(m_caResult,
                  "%s L%03lld C%02lld"_Stz,
                  
                  spChar1.sz(aAnnChar->m_cChar),
                  aAnnChar->m_iLine,
                  aAnnChar->m_iCol
                  );

  return (Stz*) &m_caResult[0];
}

