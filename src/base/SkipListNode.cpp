#include "BASE.h"

#include "SkipListNode.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipListNode::SkipListNode(void)
{
  for (i8 i_Pad = 0; i_Pad < C_SLN_PADDING; i_Pad++)
    m_cPadding[i_Pad] = 0;

  for (i8 i_Level = 0; i_Level < C_MAX_LVL_LEVELS; i_Level++)
    m_taNextSkipNode[i_Level] = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipListNode::~SkipListNode(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

u2 SkipListNode::uNext(i8 iLevel)
{
  return m_taNextSkipNode[iLevel];
}

void SkipListNode::vNext(i8 iLevel, u2 uOffset)
{
  m_taNextSkipNode[iLevel] = uOffset;
}
