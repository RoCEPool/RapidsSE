/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Mutex::SP_Mutex(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Mutex::~SP_Mutex(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Mutex::sz(Mutex* pMutex)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Mutex::sz_log(Mutex* pMutex)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  SP_Gid spThreadId;
  
  StrLib::vSprint(m_caResult,
                  "{%s }"_Stz,

                  aMK[pMutex->m_eMutex],
                  
                  C_VARGS_END);

  return (Stz*) &m_caResult[0];
}


