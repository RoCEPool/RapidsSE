CacheLine::CacheLine(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
CacheLine::~CacheLine(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/* is address on a cache line boundary?                                       */
/*----------------------------------------------------------------------------*/
bool CacheLine::bOnCacheLineBoundary(void* aAddress)
{
  bool bOn = AlignedObject::bOnBoundary(aAddress,sizeof(CacheLine));
  
  return bOn;
}

/*----------------------------------------------------------------------------*/
/* is nBytes a muliple of CacheLine?                                          */
/*----------------------------------------------------------------------------*/
bool CacheLine::bMultipleCacheLines(i8 nBytes)
{
  bool bIsMultiple = nBytes % sizeof(CacheLine) == 0 ? true : false;
  
  return bIsMultiple;
}

