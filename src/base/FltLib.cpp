#include "BASE.h"

#include <limits.h>

d8 C_D8_MIN;
d8 C_D8_MAX;
d8 C_D8_MID;

/*----------------------------------------------------------------------------*/
/* init globals                                                               */
/*----------------------------------------------------------------------------*/
void FltLib::vInitGlobals(void)
{
  _static_
  
  C_D8_MIN = DBL_MIN + DBL_EPSILON;
  C_D8_MAX = DBL_MAX;
  C_D8_MID = DBL_MAX / 2.0;
}


