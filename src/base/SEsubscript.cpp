/*============================================================================*/
/* SEsubscript.cpp -- subscript with limit                                    */
/*============================================================================*/

#include "BASE.h"

#include "SEsubscript.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(void)
{
  m_uLimit     = 0;
  m_uSubscript = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(u8 uLimit)
{
  m_uLimit     = uLimit;
  m_uSubscript = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(u8 uLimit, u8 uSubscript)
{
  m_uLimit     = uLimit;
  m_uSubscript = uSubscript;
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : u8 (subscript)                                  */
/*----------------------------------------------------------------------------*/
SEsubscript::operator u8(void)
{
  return m_uSubscript;
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void SEsubscript::operator =(u8 uSubscript)
{
  m_uSubscript = uSubscript;
}

/*----------------------------------------------------------------------------*/
/* operator  ++ increment (postfix form)                                      */
/*----------------------------------------------------------------------------*/
u8 SEsubscript::operator ++(int)
{
  u8 temp;
  temp = m_uSubscript++;
  return temp;
}

/*----------------------------------------------------------------------------*/
/* operator : less than                                                       */
/*----------------------------------------------------------------------------*/
bool SEsubscript::operator <(u8 uSubscript)
{
  return m_uSubscript < uSubscript;
}

/*----------------------------------------------------------------------------*/
/* inc subscript                                                              */
/*----------------------------------------------------------------------------*/
void SEsubscript::vIncSubscript(void)
{
  m_uSubscript++;
}

/*----------------------------------------------------------------------------*/
/* get limit                                                                  */
/*----------------------------------------------------------------------------*/
u8 SEsubscript::uLimit(void)
{
  return m_uLimit;
}

/*----------------------------------------------------------------------------*/
/* set limit                                                                  */
/*----------------------------------------------------------------------------*/
void SEsubscript::vLimit(u8 uLimit)
{
  m_uLimit = uLimit;
}

/*----------------------------------------------------------------------------*/
/* get subscript                                                              */
/*----------------------------------------------------------------------------*/
u8 SEsubscript::uSubscript(void)
{
  return m_uSubscript;
}

/*----------------------------------------------------------------------------*/
/* set subscript                                                              */
/*----------------------------------------------------------------------------*/
void SEsubscript::vSubscript(u8 uSubscript)
{
  m_uSubscript = uSubscript;
}

/*----------------------------------------------------------------------------*/
/* is subscript valid?                                                        */
/*----------------------------------------------------------------------------*/
bool SEsubscript::bValid(void)
{
  if (m_uSubscript < m_uLimit)
    return true;
  
  return false;
}

