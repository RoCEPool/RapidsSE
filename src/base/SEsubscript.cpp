/*============================================================================*/
/* SEsubscript.cpp -- subscript with limit                                    */
/*============================================================================*/

#include "BASE.h"

#include "SEsubscript.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(void)
{
  m_uLimit     = 0;
  m_uSubscript = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(i8 iLimit)
{
  m_uLimit     = iLimit;
  m_uSubscript = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SEsubscript::SEsubscript(i8 iLimit, i8 iSubscript)
{
  m_uLimit     = iLimit;
  m_uSubscript = iSubscript;
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : i8 (subscript)                                  */
/*----------------------------------------------------------------------------*/
SEsubscript::operator i8(void)
{
  return m_uSubscript;
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void SEsubscript::operator =(i8 iSubscript)
{
  m_uSubscript = iSubscript;
}

/*----------------------------------------------------------------------------*/
/* operator  ++ increment (postfix form)                                      */
/*----------------------------------------------------------------------------*/
i8 SEsubscript::operator ++(int)
{
  i8 temp;
  temp = m_uSubscript++;
  return temp;
}

/*----------------------------------------------------------------------------*/
/* operator : less than                                                       */
/*----------------------------------------------------------------------------*/
bool SEsubscript::operator <(i8 iSubscript)
{
  return m_uSubscript < iSubscript;
}

/*----------------------------------------------------------------------------*/
/* inc subscript                                                              */
/*----------------------------------------------------------------------------*/
void SEsubscript::vIncSubscript(void)
{
  m_uSubscript++;
}

/*----------------------------------------------------------------------------*/
/* get limit                                                                  */
/*----------------------------------------------------------------------------*/
i8 SEsubscript::iLimit(void)
{
  return m_uLimit;
}

/*----------------------------------------------------------------------------*/
/* set limit                                                                  */
/*----------------------------------------------------------------------------*/
void SEsubscript::vLimit(i8 iLimit)
{
  m_uLimit = iLimit;
}

/*----------------------------------------------------------------------------*/
/* get subscript                                                              */
/*----------------------------------------------------------------------------*/
i8 SEsubscript::iSubscript(void)
{
  return m_uSubscript;
}

/*----------------------------------------------------------------------------*/
/* set subscript                                                              */
/*----------------------------------------------------------------------------*/
void SEsubscript::vSubscript(i8 iSubscript)
{
  m_uSubscript = iSubscript;
}

/*----------------------------------------------------------------------------*/
/* is subscript valid?                                                        */
/*----------------------------------------------------------------------------*/
bool SEsubscript::bValid(void)
{
  if (m_uSubscript < m_uLimit)
    return true;
  
  return false;
}

