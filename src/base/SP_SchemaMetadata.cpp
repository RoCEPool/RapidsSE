/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_SchemaMetadata::SP_SchemaMetadata(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_SchemaMetadata::~SP_SchemaMetadata(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint schema and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_SchemaMetadata::sz(SchemaMetadata* pSchemaMeta)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
          
  StrLib::vSprint(m_caResult
                  
    ,"%s/%s"_Stz
                  
    ,pSchemaMeta->szCatalogName()
    ,pSchemaMeta->szSchemaName()
                  
    );

  return (Stz*) &m_caResult[0];
}

