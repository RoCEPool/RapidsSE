#include "BASE.h"

#include "LocalStr.hpp"


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
LocalStr::LocalStr(void)
{
  m_i_LclStr   = C_UNKNOWN;
  m_i_NextFree = C_UNKNOWN;

  m_pText      = nullptr;

  // m_xSizeArea
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
LocalStr::~LocalStr(void) noexcept(false)
{
  if (m_pText) {
    delete m_pText;
    m_pText = nullptr;
  }
}

/*----------------------------------------------------------------------------*/
/*-- Operators ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : as LocalStr*                                    */
/*----------------------------------------------------------------------------*/
LocalStr::operator LocalStr*(void)
{
  return this;
}

/*----------------------------------------------------------------------------*/
/* get text                                                                   */
/*----------------------------------------------------------------------------*/
Text* LocalStr::pText(void)
{
  return m_pText;
}

