/*----------------------------------------------------------------------------*/
/* get text                                                                   */
/*----------------------------------------------------------------------------*/
Stz* LocalStr::szText(void)
{
  return m_pText->szGet();
}

/*----------------------------------------------------------------------------*/
/* set text                                                                   */
/*----------------------------------------------------------------------------*/
void LocalStr::vText(Stz* szText)
{
  m_pText->vSet(szText);
}


