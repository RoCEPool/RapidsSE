/* set size of str                                                            */
/*----------------------------------------------------------------------------*/
void LocalCell::vStzSize(i8 nSize)
{
  m_wxValueCell = nSize;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void LocalCell::vToStz(Stz* szDst)
{
  if (CN_INTVAL == eType())
    * szDst = iInt();
  else
  if (CN_STZVAL == eType())
    StrLib::vCopy(szDst->azChar(),m_caStringArea);
  else
  if (CN_PTRVAL == eType())
    * szDst = reinterpret_cast<void*>(pObj());
  else
    NEVER_REACH;

}

