/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push this StzVal on stack                 */
/*----------------------------------------------------------------------------*/
i8 LocalCell::nStackUsage(void)
{
  i8 nBytes;
  
  if (CN_STZVAL == eType())
    nBytes = sizeof(m_wxType)
               + sizeof(m_wxValueCell)
               + m_wxValueCell.iGetColVal();
  else
    nBytes = sizeof(m_wxType)
               + sizeof(m_wxValueCell);

  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get adddress of Stz area                                                   */
