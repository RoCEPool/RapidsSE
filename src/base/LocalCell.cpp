/*----------------------------------------------------------------------------*/
/* copy source stack value into this one                                      */
/*----------------------------------------------------------------------------*/
void LocalCell::vCopy(LocalCell* aSrcVal, i8 nBytes)
{
  if (! nBytes)
    nBytes = aSrcVal->nStackUsage();
  
  MemLib::vCopy(this,aSrcVal,nBytes,CN_STACK);
}

