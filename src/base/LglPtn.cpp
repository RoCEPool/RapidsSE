/*----------------------------------------------------------------------------*/
/* auto conversion operator : ???                                             */
/*----------------------------------------------------------------------------*/
LglPtn::operator LglPtn*(void)
{
  return this;
}

/*----------------------------------------------------------------------------*/
/* auto conversion operator : i8                                              */
/*----------------------------------------------------------------------------*/
LglPtn::operator i8(void)
{
  return m_iAsI8;
}


/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
void LglPtn::operator =(i8 iAsI8)
{
  m_iAsI8 = iAsI8;
}

/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
void LglPtn::operator =(LglPtn tLglPtn)
{
  m_iAsI8 = tLglPtn.iAsI8();
}


/*----------------------------------------------------------------------------*/
/* operator  ++                                                               */
/*----------------------------------------------------------------------------*/
i8 LglPtn::operator ++(int)
{
  i8 temp;
  temp = m_iAsI8++;
  return temp;
}

/*----------------------------------------------------------------------------*/
/* atomically inc (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 LglPtn::operator ++(void)
{
  
  i8 iAsI8 = ++ m_iAsI8;
  
  return iAsI8;
}


/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
bool LglPtn::operator <(i8 iAsI8)
{
  return m_iAsI8 < iAsI8;
}


