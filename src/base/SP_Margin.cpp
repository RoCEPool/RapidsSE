#include "BASE.h"

#include "SP_Margin.hpp"
#include "MY.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Margin::SP_Margin(void)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
    
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Margin::~SP_Margin(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint the margin                                                          */
/*----------------------------------------------------------------------------*/
void SP_Margin::vMargin(void)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
  
  Now spNow;
  
  vCatf("+ %s %s"_Stz
        
        ,MY::szNodeNm()
        ,spNow.sz());
}

/*----------------------------------------------------------------------------*/
/* return Stz* of result                                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_Margin::sz(void)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);

  vMargin();

  return (Stz*) &m_caResult[0];
}

