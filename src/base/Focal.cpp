#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Focal::Focal(eCN eClassNo, i8 iObjectId)
: Object(eClassNo)
{
  m_iObjectId = iObjectId;

  m_iStepNo   = C_UNKNOWN;
  m_iStepTk   = AM::iRdTickingDevice();
  
  m_eEvent    = EV_NONE;
  m_iDuration = C_UNKNOWN;
  
  m__spare0   = C_UNKNOWN;
  m__spare1   = C_UNKNOWN;
  m__spare2   = C_UNKNOWN;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Focal::~Focal(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get last step sequence number                                              */
/*----------------------------------------------------------------------------*/
i8 Focal::iStepNo(void)
{
  return m_iStepNo;
}

/*----------------------------------------------------------------------------*/
/* inc last step sequence number                                              */
/*----------------------------------------------------------------------------*/
void Focal::vIncStepNo(void)
{
  m_iStepNo++;
  
  m_iStepTk = AM::iRdTickingDevice();
}

