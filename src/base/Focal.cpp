#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Focal::Focal(eCN eClassNo, i8 iObjectId)
: Object(eClassNo)
{
  m_iObjectId = iObjectId;

  m_iEventNo  = C_UNKNOWN;
  m_iEventTick   = AM::iRdTickingDevice();
  
  m_eEvent    = EV_NONE;
  m_iDuration = C_UNKNOWN;
  
  m__spare0   = C_UNKNOWN;
  m__spare1   = C_UNKNOWN;
  m__spare2   = C_UNKNOWN;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Focal::~Focal(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get last event                                                             */
/*----------------------------------------------------------------------------*/
eEV Focal::eEvent(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_eEvent;
}

/*----------------------------------------------------------------------------*/
/* set last event                                                             */
/*----------------------------------------------------------------------------*/
void Focal::vEvent(eEV eEvent)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_eEvent = eEvent;
}

/*----------------------------------------------------------------------------*/
/* get event no                                                               */
/*----------------------------------------------------------------------------*/
i8 Focal::iEventNo(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iEventNo;
}

/*----------------------------------------------------------------------------*/
/* inc event no                                                               */
/*----------------------------------------------------------------------------*/
void Focal::vEventNoInc(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_iEventNo++;
}

/*----------------------------------------------------------------------------*/
/* get event no                                                               */
/*----------------------------------------------------------------------------*/
i8 Focal::iEventTick(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iEventTick;
}

/*----------------------------------------------------------------------------*/
/* set event tick                                                             */
/*----------------------------------------------------------------------------*/
void Focal::vEventTickSet(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_iEventTick = AM::iRdTickingDevice();
}

/*----------------------------------------------------------------------------*/
/* get object id                                                              */
/*----------------------------------------------------------------------------*/
