/*----------------------------------------------------------------------------*/
/* get object name                                                            */
/*----------------------------------------------------------------------------*/
Stz* Focal::sObjectNm(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_sObjectNm;
}

/*----------------------------------------------------------------------------*/
/* set object name                                                            */
/*----------------------------------------------------------------------------*/
void Focal::vObjectNm(Stz* szObjectNm)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_sObjectNm = szObjectNm;
}

/*----------------------------------------------------------------------------*/
/* set next event                                                             */
/*----------------------------------------------------------------------------*/
void Focal::vNextEvent(eEV eEvent)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  vEventTickSet();
  vEvent(eEvent);
  vEventNoInc();
}

