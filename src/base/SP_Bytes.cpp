#include "BASE.h"

#include "SP_Bytes.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Bytes::SP_Bytes(void)
: SP(CN_SPELAPSED)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
  
  _checkInitialised_(CN_SPELAPSED);
  
  _postcondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Bytes::~SP_Bytes(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint SP_Bytes and return Stz* to result                                  */
/*----------------------------------------------------------------------------*/
Stz* SP_Bytes::sz(i8 nBytes)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);

  s32 sBuf;
  MagLib::vByteMag(nBytes,sBuf);
  StrLib::vCopy(m_caResult, sizeof(m_caResult), sBuf.azChar());

  return (Stz*) &m_caResult[0];
}


