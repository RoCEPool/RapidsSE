/*============================================================================*/
/* Pds_t.hpp -- Primary Data Structure (PDS) Template                          */
/*============================================================================*/
#pragma once

#include "Pds.hpp"
#include "SkipListNode.hpp"
#include "SkipListSet.hpp"

namespace BASE
{
  template <class ITEM>
  class Pds_t : public Pds
  {
  public:

    // must be last
    Footer m_xFooter;

  public:
    Pds_t(void);
    ~Pds_t(void) noexcept(false);


    ITEM* aAllotEntry(i8 iKey);

  public:
    Footer* aFooter(void);
  };
}

using namespace BASE;

////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
template <class ITEM>
Pds_t<ITEM>::Pds_t(void)
  : Pds(sizeof(ITEM))
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
template <class ITEM>
Pds_t<ITEM>::~Pds_t(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* Allot an entry in this Skip List                                           */
/*----------------------------------------------------------------------------*/
template <class ITEM>
ITEM* Pds_t<ITEM>::aAllotEntry(i8 iKey)
{
  return (ITEM*) Pds::aAllotSkipListSet(iKey);
}

