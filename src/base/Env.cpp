#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* translate environment variable                                             */
/*----------------------------------------------------------------------------*/
bool Env::bGet(Stz* szName, String* pValue)
{
  char* aValue = getenv(szName->azChar());
  if ( ! aValue )
    return false;
  
  pValue->vCopy((Stz*)aValue);
  
  return true;
}

