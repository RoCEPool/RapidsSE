#include "BASE.h"

#include "MasterLock.hpp"
#include "MY.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
MasterLock::MasterLock(eCN eClassNo)
: Object(eClassNo)
, m_okLock(this)
{
  _precondition_(_MAGIC_);
     
  m_pHoldingTask = nullptr;
  
  _postcondition_(_MAGIC_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
MasterLock::~MasterLock(void) noexcept(false)
{
  _precondition_(_MAGIC_);
  
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* drop read lock                                                             */
/*----------------------------------------------------------------------------*/
u8 MasterLock::uLockWord(void)
{
  _precondition_(_MAGIC_);
  
  return m_okLock.uLockWord();
}

/*----------------------------------------------------------------------------*/
/* drop read lock                                                             */
/*----------------------------------------------------------------------------*/
void MasterLock::vDropRead(void)
{
  _precondition_(_MAGIC_);
  
  m_okLock.vDropRead();
}

/*----------------------------------------------------------------------------*/
/* try and grab a read lock                                                   */
/*----------------------------------------------------------------------------*/
bool MasterLock::bGrabRead(void)
{
  _precondition_(_MAGIC_);
  
  bool b = m_okLock.bGrabRead();
  
  return b;

}

/*----------------------------------------------------------------------------*/
/* grab a read lock (may block)                                               */
/*----------------------------------------------------------------------------*/
void MasterLock::vGrabRead(void)
{
  _precondition_(_MAGIC_);
  
  m_okLock.vGrabRead();
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* drop write lock                                                            */
/*----------------------------------------------------------------------------*/
void MasterLock::vDropWrite(void)
{
  _precondition_(_MAGIC_);
  
  RASSERT(MY::pTask() == m_pHoldingTask);
  m_pHoldingTask = nullptr;
  
  m_okLock.vDropWrite();
}

/*----------------------------------------------------------------------------*/
/* try and grab a write lock                                                  */
/*----------------------------------------------------------------------------*/
bool MasterLock::bGrabWrite(void)
{
  _precondition_(_MAGIC_);
  
  bool b = m_okLock.bGrabWrite();
  
  if (b)
    m_pHoldingTask = MY::pTask();

  return b;
}

/*----------------------------------------------------------------------------*/
/* grab a write lock (may block)                                              */
/*----------------------------------------------------------------------------*/
void MasterLock::vGrabWrite(void)
{
  _precondition_(_MAGIC_);
  
  m_okLock.vGrabWrite();
  
  m_pHoldingTask = MY::pTask();
}

/*----------------------------------------------------------------------------*/
/* is write locked?                                                           */
/*----------------------------------------------------------------------------*/
bool MasterLock::bIsWriteLocked(void)
{
  _precondition_(_MAGIC_);

  bool bWriteLocked = m_okLock.bIsWriteLocked();
  
  return bWriteLocked;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void MasterLock::vResetStats(void)
{
  _precondition_(_MAGIC_);
  
  m_okLock.vResetStats();  
}


/*----------------------------------------------------------------------------*/
/* get read grabs                                                             */
/*----------------------------------------------------------------------------*/
i8 MasterLock::iReadGrabs(void)
{
  _precondition_(_MAGIC_);

  i8 iReadGrabs = m_okLock.iReadGrabs();
  
  return iReadGrabs;
}

/*----------------------------------------------------------------------------*/
/* get read collisions                                                        */
/*----------------------------------------------------------------------------*/
i8 MasterLock::iReadCollisions(void)
{
  _precondition_(_MAGIC_);

  i8 iReadCollisions = m_okLock.iReadCollisions();
  
  return iReadCollisions;
}

/*----------------------------------------------------------------------------*/
/* get write grabs                                                            */
/*----------------------------------------------------------------------------*/
i8 MasterLock::iWriteGrabs(void)
{
  _precondition_(_MAGIC_);

  i8 iWriteGrabs = m_okLock.iWriteGrabs();
  
  return iWriteGrabs;
}

/*----------------------------------------------------------------------------*/
/* get write collisions                                                        */
/*----------------------------------------------------------------------------*/
i8 MasterLock::iWriteCollisions(void)
{
  _precondition_(_MAGIC_);

  i8 iWriteCollisions = m_okLock.iWriteCollisions();
  
  return iWriteCollisions;
}

