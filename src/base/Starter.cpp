/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Starter::Starter(void)
: Object(CN_STARTER)
{
  _precondition_(_MAGIC_,CN_STARTER,_FOOTER_);
  
  _checkInitialised_(CN_STARTER);
  
  _postcondition_(_MAGIC_,CN_STARTER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Starter::~Starter(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_STARTER,_FOOTER_);
}

