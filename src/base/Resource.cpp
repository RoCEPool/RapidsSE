#include "BASE.h"

#include "Resource.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Resource* BASE::_pResource(void* aAddress)
{
  Resource* pResource = reinterpret_cast<Resource*>(aAddress);
  
  return pResource;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo)
: Loggable(eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  m_pIsFor = nullptr;

  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);  
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo, Object* pIsFor)
: Loggable(eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  m_pIsFor = pIsFor;

  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Resource::~Resource(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get resource id                                                            */
/*----------------------------------------------------------------------------*/
i8 Resource::iResId(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iObjectId;
}

