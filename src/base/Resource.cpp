#include "BASE.h"

#include "Resource.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Resource* BASE::_pResource(void* aAddress)
{
  Resource* pResource = reinterpret_cast<Resource*>(aAddress);
  
  return pResource;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo, Object* pIsFor)
: Loggable(eClassNo)
, m_xResourceId(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
  
  m_pIsFor = pIsFor;
  
  m_sPath  = C_NO_NAME;


  _postcondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Resource::~Resource(void) noexcept(false)
{
  _precondition_(_MAGIC_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get path                                                                   */
/*----------------------------------------------------------------------------*/
Stz* Resource::szPath(void)
{
  _precondition_(_MAGIC_);
  
  return m_sPath;
}


/*----------------------------------------------------------------------------*/
/* get resource id                                                            */
/*----------------------------------------------------------------------------*/
i8 Resource::iResId(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iObjectId;
}

