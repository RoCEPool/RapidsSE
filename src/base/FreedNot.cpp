/*============================================================================*/
/* FreedNot.cpp -- free chunk in heap (but no in free list)                   */
/*============================================================================*/

#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* FreedNot::operator new(size_t, FreedNot* aFreedNot)
{
  return aFreedNot;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void FreedNot::operator delete(void*)
{
  vThrow(FK_FATAL,__func__,__FILE__,__LINE__,
         "fatal: FreedNot class cannot be deleted"_Stz);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FreedNot::FreedNot(void)
: Header(CN_NONE)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
FreedNot::~FreedNot(void) noexcept(false)
{
  vThrow(FK_FATAL,__func__,__FILE__,__LINE__,
         "fatal: FreedNot class cannot be deleted"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* initialize a free chunk                                                    */
/*----------------------------------------------------------------------------*/
void FreedNot::vInit(eCN eWasClass)
{
  vSetMagic();
  vSetClassNo(CN_FREEDNOT);
  m_eWasClass = eWasClass;
}

/*----------------------------------------------------------------------------*/
/* get the was-class of the free chunk                                        */
/*----------------------------------------------------------------------------*/
eCN FreedNot::eWasClass(void)
{
  return m_eWasClass;
}

/*----------------------------------------------------------------------------*/
/* set the was-class of the free chunk                                        */
/*----------------------------------------------------------------------------*/
void FreedNot::vWasClass(eCN eWasClass)
{
  m_eWasClass = eWasClass;
}

