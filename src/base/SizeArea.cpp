#include "SizeArea.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SizeArea::SizeArea(void)
{
  m_jStrSize = 1;
  MemLib::vZero(m_caArea,sizeof(m_caArea),CN_LOCALSTRS);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SizeArea::~SizeArea(void) noexcept(false)
{

}

/*----------------------------------------------------------------------------*/
/*-- Operators ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : as SizeArea*                                    */
/*----------------------------------------------------------------------------*/
SizeArea::operator SizeArea*(void)
{
  return this;
}

/*----------------------------------------------------------------------------*/
/* get area                                                                   */
/*----------------------------------------------------------------------------*/
char* SizeArea::azArea(void)
{
  return (char*)m_caArea;
}

/*----------------------------------------------------------------------------*/
/* get area                                                                   */
/*----------------------------------------------------------------------------*/
Stz* SizeArea::szArea(void)
{
  return (Stz*)m_caArea;
}

/*----------------------------------------------------------------------------*/
/* re-initialise size area                                                    */
/*----------------------------------------------------------------------------*/
void SizeArea::vReInitialise(void)
{
  m_jStrSize = 1;
  MemLib::vZero(m_caArea,sizeof(m_caArea),CN_LOCALSTRS);
}

/*----------------------------------------------------------------------------*/
/* get size                                                                   */
/*----------------------------------------------------------------------------*/
i8 SizeArea::jStrSize(void)
{
  return m_jStrSize;
}

