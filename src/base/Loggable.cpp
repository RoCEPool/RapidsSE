/*----------------------------------------------------------------------------*/
/* log next event                                                             */
/*----------------------------------------------------------------------------*/
void Loggable::vAddRow(eEV eEvent, Stz* szNote)
{
  _precondition_(_MAGIC_);
  UNUSED(eEvent);
  UNUSED(szNote);
  
//  printf("Loggable::vAddRow : %s %s\n",
//         aEV[eEvent]->azChar(),
//         szNote->azChar());

  WriteBehind* pWriteBehind = AM::THREAD::pWriteBehind();
  
  if (! pWriteBehind)
    return;
  
  pWriteBehind->vDepositEvent(C_VARGS_BEGIN,
                              eEvent,
                              szNote,
                              C_VARGS_END);
}

