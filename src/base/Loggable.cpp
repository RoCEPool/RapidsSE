{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_sObjectNm;
}

/*----------------------------------------------------------------------------*/
/* set object name                                                            */
/*----------------------------------------------------------------------------*/
void Loggable::vObjectNm(Stz* szObjectNm)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_sObjectNm = szObjectNm;
}

/*----------------------------------------------------------------------------*/
/* set next event                                                             */
/*----------------------------------------------------------------------------*/
void Loggable::vNextEvent(eEV eEvent)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  vEventTickSet();
  vEvent(eEvent);
  vEventNoInc();
}

