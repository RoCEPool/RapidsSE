#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Loggable::Loggable(eCN eClassNo, i8 iObjectId)
: Object(eClassNo)
{
  if (-9 == iObjectId)
    m_iObjectId = AM::iNextObjectNo(eClassNo);
  else
    m_iObjectId = iObjectId; //AM::iNextObjectNo(eClassNo);

  m_iEventNo  = C_UNKNOWN;
  m_iEventTick   = AM::iRdTickingDevice();
  
  m_eEvent    = EV_NONE;
  m_iDuration = C_UNKNOWN;
  
  m__spare0   = C_UNKNOWN;
  m__spare1   = C_UNKNOWN;
  m__spare2   = C_UNKNOWN;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Loggable::~Loggable(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get last event                                                             */
/*----------------------------------------------------------------------------*/
eEV Loggable::eEvent(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_eEvent;
}

/*----------------------------------------------------------------------------*/
/* set last event                                                             */
/*----------------------------------------------------------------------------*/
void Loggable::vEvent(eEV eEvent)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_eEvent = eEvent;
}

/*----------------------------------------------------------------------------*/
/* get event no                                                               */
/*----------------------------------------------------------------------------*/
i8 Loggable::iEventNo(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iEventNo;
}

/*----------------------------------------------------------------------------*/
/* inc event no                                                               */
/*----------------------------------------------------------------------------*/
void Loggable::vEventNoInc(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_iEventNo++;
}

/*----------------------------------------------------------------------------*/
/* get event no                                                               */
/*----------------------------------------------------------------------------*/
i8 Loggable::iEventTick(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iEventTick;
}

/*----------------------------------------------------------------------------*/
/* set event tick                                                             */
/*----------------------------------------------------------------------------*/
void Loggable::vEventTickSet(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_iEventTick = AM::iRdTickingDevice();
}

