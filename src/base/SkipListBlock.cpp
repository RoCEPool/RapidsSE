/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipListBlock::SkipListBlock(eCN eClassNo, i8 nSizeEnt)
{
  UNUSED(eClassNo);
  UNUSED(nSizeEnt);
  vSetKey(0);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipListBlock::~SkipListBlock(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* Get start addr of item                                                     */
/*----------------------------------------------------------------------------*/
void* SkipListBlock::aItem(void)
{
  return (void*) m_xItem;
}

/*----------------------------------------------------------------------------*/
/* Get key as i8                                                              */
/*----------------------------------------------------------------------------*/
i8 SkipListBlock::iKey(void)
{
//  conceptual__item* pItem = (conceptual__item*) m_xItem;
  return m_xItem[0];
}

/*----------------------------------------------------------------------------*/
/* return next                                                                */
/*----------------------------------------------------------------------------*/
SkipListBlock* SkipListBlock::aNext(void)
{
   return nullptr;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void SkipListBlock::vSetKey(i8 iKey)
{
  conceptual__item* pItem = (conceptual__item*) m_xItem;
  pItem->iKey = (i8) iKey;
}

/*----------------------------------------------------------------------------*/
/* get Row start addr (assumes i8 key in pds)                                 */
/*----------------------------------------------------------------------------*/
Row* SkipListBlock::aRow(void)
{
  return aAdd<Row*>(m_xItem, sizeof(i8));
}


