#include "BASE.h"

#include "SkipListBlock.hpp"
#include "MiniHeap_t.hpp"
/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipListBlock::SkipListBlock(eCN eClassNo, i8 nSizeEnt)
{
  UNUSED(eClassNo);
  UNUSED(nSizeEnt);
  vSetKey(0);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipListBlock::~SkipListBlock(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* Get start addr of body in item                                             */
/*----------------------------------------------------------------------------*/
void* SkipListBlock::aItemBody(void)
{
  return (void*) aAdd<void*>(m_xItem, member_size(conceptual__item, iKey));
}

/*----------------------------------------------------------------------------*/
/* Get start addr of key in item                                              */
/*----------------------------------------------------------------------------*/
void* SkipListBlock::aItemKey(void)
{
  return (void*) m_xItem;
}

/*----------------------------------------------------------------------------*/
/* Get key as i8                                                              */
/*----------------------------------------------------------------------------*/
i8 SkipListBlock::iKey(void)
{
  conceptual__item* pItem = (conceptual__item*) m_xItem;
  return pItem->iKey;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void SkipListBlock::vSetKey(i8 iKey)
{
  conceptual__item* pItem = (conceptual__item*) m_xItem;
  pItem->iKey = (i8) iKey;
}

