#include "BASE.h"

#include "Id_2part.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id_2part::Id_2part(void)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* get number of bits for node number                                         */
/*----------------------------------------------------------------------------*/
i8 Id_2part::nNodeBits(void)
{
  return 16;
}

/*----------------------------------------------------------------------------*/
/* get bitmask for node number                                                */
/*----------------------------------------------------------------------------*/
u8 Id_2part::uNodeMask(void)
{
         //fedcba9876543210
  return 0xFFFF000000000000;
}

/*----------------------------------------------------------------------------*/
/* get uNodeNo                                                                */
/*----------------------------------------------------------------------------*/
u8 Id_2part::uNodeNo(void)
{
  return m_uNodeNo;
}

/*----------------------------------------------------------------------------*/
/* set uNodeNo                                                                */
/*----------------------------------------------------------------------------*/
void Id_2part::vNodeNo(u8 uNodeNo)
{
  m_uNodeNo = uNodeNo;

}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* get number of bits for object number                                       */
/*----------------------------------------------------------------------------*/
i8 Id_2part::nObjectBits(void)
{
  return 48;
}

/*----------------------------------------------------------------------------*/
/* get bitmask for object number                                              */
/*----------------------------------------------------------------------------*/
u8 Id_2part::uObjectMask(void)
{
         //fedcba9876543210
  return 0x0000FFFFFFFFFFFF;
}

/*----------------------------------------------------------------------------*/
/* get uObjectNo                                                              */
/*----------------------------------------------------------------------------*/
u8 Id_2part::uObjectNo(void)
{
  return m_uObjectNo;
}

/*----------------------------------------------------------------------------*/
/* set uObjectNo                                                              */
/*----------------------------------------------------------------------------*/
void Id_2part::vObjectNo(u8 uObjectNo)
{
  m_uObjectNo = uObjectNo;
}

