#include "BASE.h"

#include "TypeValue.hpp"


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TypeValue::TypeValue(void)
{
  m_wxType.vSetMagic();
  m_wxType.vSetClassNo(CN_NONE);
  
  m_wxValue = C_UNKNOWN;

}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TypeValue::~TypeValue(void) noexcept(false)
{

}

/*----------------------------------------------------------------------------*/
/*-- Operators ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : as TypedCell*                                   */
/*----------------------------------------------------------------------------*/
TypeValue::operator TypeValue*(void)
{
  return this;
}

/*----------------------------------------------------------------------------*/
/* get pointer to type                                                        */
/*----------------------------------------------------------------------------*/
_Header* TypeValue::axType(void)
{
  return & m_wxType;
}

/*----------------------------------------------------------------------------*/
/* get pointer to value                                                       */
/*----------------------------------------------------------------------------*/
Dtm* TypeValue::axValue(void)
{
  return & m_wxValue;
}

