#include "BASE.h"

#include "Id.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* get number of bits for node number                                         */
/*----------------------------------------------------------------------------*/
i8 Id::nNodeBits(void)
{
  return 16;
}

/*----------------------------------------------------------------------------*/
/* get bitmask for node number                                                */
/*----------------------------------------------------------------------------*/
u8 Id::uNodeMask(void)
{
         //fedcba9876543210
  return 0xFFFF000000000000;
}

/*----------------------------------------------------------------------------*/
/* get uNodeNo                                                                */
/*----------------------------------------------------------------------------*/
u8 Id::uNodeNo(void)
{
  return m_uNodeNo;
}

/*----------------------------------------------------------------------------*/
/* set uNodeNo                                                                */
/*----------------------------------------------------------------------------*/
void Id::vNodeNo(u8 uNodeNo)
{
  m_uNodeNo = uNodeNo;

}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/* get number of bits for object number                                       */
/*----------------------------------------------------------------------------*/
i8 Id::nObjectBits(void)
{
  return 48;
}

/*----------------------------------------------------------------------------*/
/* get bitmask for object number                                              */
/*----------------------------------------------------------------------------*/
u8 Id::uObjectMask(void)
{
         //fedcba9876543210
  return 0x0000FFFFFFFFFFFF;
}

/*----------------------------------------------------------------------------*/
/* get uObjectNo                                                              */
/*----------------------------------------------------------------------------*/
u8 Id::uObjectNo(void)
{
  return m_uObjectNo;
}

/*----------------------------------------------------------------------------*/
/* set uObjectNo                                                              */
/*----------------------------------------------------------------------------*/
void Id::vObjectNo(u8 uObjectNo)
{
  m_uObjectNo = uObjectNo;
}

