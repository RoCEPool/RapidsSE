/*============================================================================*/
/* SEcursor.hpp -- cursor based on subscript with limit                       */
/*============================================================================*/
#pragma once

#include "SEsubscript.hpp"

template <class CLASS>
class SEcursor : public SEsubscript
{
  protected:
  
  CLASS* m_pObject;
  
  public:

  /*--------------------------------------------------------------------------*/
  /* constructor                                                              */
  /*--------------------------------------------------------------------------*/
  SEcursor<CLASS>(void)
  {
    m_pObject = nullptr;
  }
  
  /*--------------------------------------------------------------------------*/
  /* operator  * deref                                                        */
  /*--------------------------------------------------------------------------*/
  CLASS* operator *(void)
  {
    return m_pObject;
  }
  
  /*--------------------------------------------------------------------------*/
  /* operator -> member                                                       */
  /*--------------------------------------------------------------------------*/
  CLASS* operator ->(void)
  {
    return m_pObject;
  }
  
  /*--------------------------------------------------------------------------*/
  /* operator  ++ increment (postfix form)                                    */
  /*--------------------------------------------------------------------------*/
  i8 operator ++(int)
  {
  }

  /*--------------------------------------------------------------------------*/
  /* get object                                                               */
  /*--------------------------------------------------------------------------*/
  CLASS* pGet(void)
  {
    return m_pObject;
  }
  
  /*--------------------------------------------------------------------------*/
  /* is there a pointer?                                                      */
  /*--------------------------------------------------------------------------*/
  bool bIsNotNull(void)
  {
    if (m_pObject)
      return true;
    else
      return false;
  }
  
  /*--------------------------------------------------------------------------*/
  /* is null pointer?                                                         */
  /*--------------------------------------------------------------------------*/
  bool bIsNull(void)
  {
    if (! m_pObject)
      return true;
    else
      return false;
  }

  /*--------------------------------------------------------------------------*/
  /* set object                                                               */
  /*--------------------------------------------------------------------------*/
  void vSet(CLASS* pObject)
  {
    m_pObject = pObject;
  }
  
};

/*============================================================================*/
/* end                                                                        */
/*============================================================================*/
