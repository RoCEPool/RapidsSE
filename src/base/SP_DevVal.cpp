#include "BASE.h"

#include "SP_DecVal.hpp"
#include "DecVal.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_DecVal::SP_DecVal(void)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
    
  _checkInitialised_(CN_SPMEDIUM);
  
  _postcondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_DecVal::~SP_DecVal(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint the margin                                                          */
/*----------------------------------------------------------------------------*/
void SP_DecVal::vDecVal(DecVal xDecVal)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);
    
  vInit();
  
  if (xDecVal.m_bScaled)
    vCatf("%9lldE%02lld"_Stz
          ,(i8)xDecVal.m_iValue
          ,xDecVal.m_nPlaces
          );
  else
    vCatf("%18lld (%02lld implied places)"_Stz
          ,(i8)xDecVal.m_iValue
          ,xDecVal.m_nPlaces
          );
}

/*----------------------------------------------------------------------------*/
/* return Stz* of result                                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_DecVal::sz(void)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);

  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* return Stz* of result                                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_DecVal::sz(DecVal xDecVal)
{
  _precondition_(_MAGIC_,CN_SPMEDIUM,_FOOTER_);

  vDecVal(xDecVal);
  
  return (Stz*) &m_caResult[0];
}

