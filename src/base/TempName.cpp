#include "BASE.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TempName::TempName(void)
: Object(CN_TEMPNAME)
, m_okLock(this)
{
  _precondition_(_MAGIC_,CN_TEMPNAME,_FOOTER_);
  
  m_oBirth.vNow();
  
  m_sClicker = "aaaaaaaa"_Stz;
  
  _checkInitialised_(CN_TEMPNAME);
  
  _postcondition_(_MAGIC_,CN_TEMPNAME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TempName::~TempName(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_TEMPNAME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* generate next name                                                         */
/*----------------------------------------------------------------------------*/
void TempName::vNextName(s32& sName)
{
  _precondition_(_MAGIC_,CN_TEMPNAME,_FOOTER_);
  
  m_okLock.vGrabWrite();
  
  sName.vSprint("%s_%x"_Stz,
                m_sClicker.szStz(),
                m_oBirth.m_wIvl.T.m_xIvl.u.m_xIvlSec.m_uSeconds);
  
  StrLib::vClick(m_sClicker.azChar());
  
  m_okLock.vDropWrite();
}


