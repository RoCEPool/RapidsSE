/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_TableMetadata::SP_TableMetadata(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_TableMetadata::~SP_TableMetadata(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint table and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* SP_TableMetadata::sz(TableMetadata* pTableMeta)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
          
  StrLib::vSprint(m_caResult
                  
    ,"%s/%s/%s"_Stz
                  
    ,pTableMeta->szCatalogName()
    ,pTableMeta->szSchemaName()
    ,pTableMeta->szTableName()
                  
    );

  return (Stz*) &m_caResult[0];
}

