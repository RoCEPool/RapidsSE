  /*--------------------------------------------------------------------------*/
  /* set class                                                                */
  /*--------------------------------------------------------------------------*/
  inline void vClass(eCN eClass)
  {
    m_eClass = eClass;
  }
  
  /*--------------------------------------------------------------------------*/
  /* set magic                                                                */
  /*--------------------------------------------------------------------------*/
  inline void vMagic(void)
  {
    m_uMagic = C_MAGIC;
  }
  
