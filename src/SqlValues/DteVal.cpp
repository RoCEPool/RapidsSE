#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DteVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: DteVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Dte DteVal::wDte(void)
{
  ASSERT(bIsClass(CN_DTEVAL));
  
  return m_wDte;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void DteVal::vDte(Dte wDte)
{
  vClass(CN_DTEVAL);
  m_wDte = wDte;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a DteVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 DteVal::nStackUsage(void)
{
  return sizeof(DteVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void DteVal::vToStz(Stz* szDst)
{
  if (m_wDte.bIsNull()) {
    szDst->vConcat(C_NULL);
    return;
  }
  
  * szDst = m_wDte;
}

