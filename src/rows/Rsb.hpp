#pragma once

namespace Rows
{
  class Rsb : public Object
  {
  private:

    m8 m_maCells[]; // C++ flexible member array must be last

  public:
    Rsb(void);
   ~Rsb(void) noexcept(false);
        
  private:
  
  public:

  /*----------------------------------------------------------------------------*/
  /* get cell0 address                                                          */
  /*----------------------------------------------------------------------------*/
  inline m8* amCell0_rsb(void)
  {
    return (m8*)&m_maCells[0];
  }

    
  /*----------------------------------------------------------------------------*/
  /* get i8 integer                                                             */
  /*----------------------------------------------------------------------------*/
  inline bool bIsNull_rsb(i8 i_Col)
  {
    ASSERT(i_Col >= 0);
      
    i8* aI8 = (i8*) & m_maCells[i_Col];
    
    i8 iVal = * aI8;

    if (C_DATUM_NULL == iVal)
      return true;
    else
      return false;
  }

  /*----------------------------------------------------------------------------*/
  /* get d8 float                                                               */
  /*----------------------------------------------------------------------------*/
  inline d8 dVal_rsb(i8 i_Col)
  {
    ASSERT(i_Col >= 0);
        
    d8* aD8 = (d8*) & m_maCells[i_Col];
    
    d8 dVal = * aD8;
    
    return dVal;
  }

  /*----------------------------------------------------------------------------*/
  /* set d8 float                                                               */
  /*----------------------------------------------------------------------------*/
  inline void vVal_rsb(i8 i_Col, d8 dValue)
  {
    ASSERT(i_Col >= 0);
    
    d8* aD8 = (d8*) & m_maCells[i_Col];
    
    * aD8 = dValue;
  }
    
  /*----------------------------------------------------------------------------*/
  /* get i8 integer                                                             */
  /*----------------------------------------------------------------------------*/
  inline i8 iVal_rsb(i8 i_Col)
  {
    ASSERT(i_Col >= 0);
    
    i8* aI8 = (i8*) & m_maCells[i_Col];
    
    i8 iVal = * aI8;

    return iVal;
  }

  /*----------------------------------------------------------------------------*/
  /* set i8 integer                                                             */
  /*----------------------------------------------------------------------------*/
  inline void vVal_rsb(i8 i_Col, i8 iVal)
  {
    ASSERT(i_Col >= 0);
    
    i8* aI8 = (i8*) & m_maCells[i_Col];
    
    * aI8 = iVal;
  }

  /*----------------------------------------------------------------------------*/
  /* get Stz* string                                                            */
  /*----------------------------------------------------------------------------*/
  inline Stz* szVal_rsb(i8 i_Col)
  {
    ASSERT(i_Col >= 0);

    i8 i_Ofs = (i8) m_maCells[i_Col];
      
    Stz* szStz = aAdd<Stz*>(&m_maCells[i_Col],i_Ofs);
        
    return szStz;
  }
        
  };
  
  Rsb* _aRsb(void* aAddr);
}

