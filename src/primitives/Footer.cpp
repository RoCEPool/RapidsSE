/*============================================================================*/
/* Footer.cpp -- Footer for Concrete Classes                                  */
/*============================================================================*/

#include "BASE.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer::Footer(void)
{
#ifdef WITH_DEBUG_VERSION
  u4 uProcId;
  m_iWhenAllocated = Hardware::iReadTsc(&uProcId);
#else
  m_iWhenAllocated = C_UNKNOWN;
#endif

  m_uFooter = C_FOOTER;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer::~Footer(void)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* ASSERT footer                                                              */
/*----------------------------------------------------------------------------*/
void Footer::vAssertFooter(void) const
{
  ASSERT(m_uFooter == C_FOOTER);
}

/*----------------------------------------------------------------------------*/
/* is a valid footer                                                          */
/*----------------------------------------------------------------------------*/
eEC Footer::eValidFooter(void)
{
  if (C_FOOTER == m_uFooter)
    return EC_NONE;
  
  return EC_OBJECT_FOOTER_INVALID;
}

/*----------------------------------------------------------------------------*/
/* set footer                                                                 */
/*----------------------------------------------------------------------------*/
void Footer::vSetFooter(void)
{
#ifdef WITH_DEBUG_VERSION
  u4 uProcId;
  m_iWhenAllocated = Hardware::iReadTsc(&uProcId);
#else
  m_iWhenAllocated = C_UNKNOWN;
#endif

  m_uFooter = C_FOOTER;
}

/*----------------------------------------------------------------------------*/
/* sprint the header into readable form                                       */
/*----------------------------------------------------------------------------*/
void Footer::vSprint(Stz* szHeader, i8 nBufSize)
{
  StrLib::vSprint(szHeader,
                  nBufSize,
                  "Footer: %c%c%c%c%c%c%c%c (%s)"_Stz,
                  m_caFooter[0],
                  m_caFooter[1],
                  m_caFooter[2],
                  m_caFooter[3],
                  m_caFooter[4],
                  m_caFooter[5],
                  m_caFooter[6],
                  m_caFooter[7],
                  bValidFooter() ? "valid footer" : "not-valid footer"
                  );
}

/*----------------------------------------------------------------------------*/
/* test for valid footer                                                      */
/*----------------------------------------------------------------------------*/
bool Footer::bValidFooter(void)
{
  if (m_uFooter == C_FOOTER)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* test for valid footer                                                      */
/*----------------------------------------------------------------------------*/
i8 Footer::iWhenAllocated(void)
{
  return m_iWhenAllocated;
}

