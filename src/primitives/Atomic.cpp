/* atomically dec                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iDec(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = Atomic::uAtomicDec(&m_iInt);
  
  return i;
}

