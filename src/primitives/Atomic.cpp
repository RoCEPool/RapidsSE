/* atomically inc                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iInc(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Atomic::uAtomicInc(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* get value                                                                  */
/*----------------------------------------------------------------------------*/
i8 Atomic::iVal(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  return m_iInt;
}

