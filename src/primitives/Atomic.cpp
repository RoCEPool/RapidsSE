/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Atomic::Atomic(void)
: Object(CN_ATOMIC)
{
  m_iInt = 0;
  
  _checkInitialised_(CN_ATOMIC);
  
  _postcondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Atomic::~Atomic(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* atomically add word                                                        */
/*----------------------------------------------------------------------------*/
u8 Atomic::uAtomicAdd(i8* pWord, i8 iValue)
{
  // Ref: https://gcc.gnu.org/onlinedocs/gcc/_005f_005fatomic-Builtins.html
  u8 uResult = __atomic_add_fetch((u8*)pWord, iValue, __ATOMIC_SEQ_CST);
  
  return uResult;
}

/*----------------------------------------------------------------------------*/
/* atomically decrement word                                                  */
/*----------------------------------------------------------------------------*/
u8 Atomic::uAtomicDec(i8* pWord)
{
  // Ref: https://gcc.gnu.org/onlinedocs/gcc/_005f_005fatomic-Builtins.html
  u8 uResult = __atomic_sub_fetch((u8*)pWord, 1, __ATOMIC_SEQ_CST);
  
  return uResult;
}

/*----------------------------------------------------------------------------*/
/* atomically increment word                                                  */
/*----------------------------------------------------------------------------*/
u8 Atomic::uAtomicInc(i8* pWord)
{
  // Ref: https://gcc.gnu.org/onlinedocs/gcc/_005f_005fatomic-Builtins.html
  u8 uResult = __atomic_add_fetch((u8*)pWord, 1, __ATOMIC_SEQ_CST);

  return uResult;
}

/*----------------------------------------------------------------------------*/
/* atomic test and set                                                        */
/*----------------------------------------------------------------------------*/
bool Atomic::bTestAndSet(u8* pWord, u8 uIf, u8 uThen)
{
  bool uResult = __atomic_compare_exchange_n(pWord, &uIf, uThen, false, __ATOMIC_SEQ_CST, __ATOMIC_RELAXED);
  return uResult;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* check lock initialization                                                  */
/*----------------------------------------------------------------------------*/
void Atomic::vCheckInit(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  ASSERT(0 == m_iInt); // logic check
}

/*----------------------------------------------------------------------------*/
/* reset atomic                                                               */
/*----------------------------------------------------------------------------*/
void Atomic::vResetAtomic(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  m_iInt = 0;
}

/*----------------------------------------------------------------------------*/
/* atomically add                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iAdd(i8 iValue)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Atomic::uAtomicAdd(&m_iInt, iValue);
  
  return i;
}

