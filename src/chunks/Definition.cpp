#include "Chunks.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Definition* Chunks::_pDefinition(void* aAddr)
{
  Definition* pDefinition = reinterpret_cast<Definition*>(aAddr);
  
  return pDefinition;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void Definition::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Definition::Definition(eCN eClassNo)
: Operand(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Definition::~Definition(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}

