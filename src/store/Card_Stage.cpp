/*                                                                            */
/*----------------------------------------------------------------------------*/
void Card_Stage::vRenameStage(i8 i_Stage)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD,_FOOTER_);

  s32 sStageNm;
  vFormStageNm(sStageNm,i_Stage);

  vValue(sStageNm);
}

