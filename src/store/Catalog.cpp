/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Catalog* STORE::_pCatalog(void* aAddr)
{
  Catalog* pCatalog = reinterpret_cast<Catalog*>(aAddr);
  
  if (pCatalog && CN_CATALOG != pCatalog->eGetClassNo())
    vTrace("_pCatalog got class %s\n"_Stz,aCN[pCatalog->eGetClassNo()]);
  
  RASSERT_TYPE(pCatalog,CN_CATALOG);
  
  return pCatalog;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Catalog::operator new(size_t)
{
  Catalog* pCatalog = nullptr;
  
  return pCatalog;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Catalog::operator delete(void*)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Catalog::Catalog(void)
: Folder(CN_CATALOG)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CATALOG,_FOOTER_);
  
  
  _checkInitialised_(CN_CATALOG);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_CATALOG,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Catalog::~Catalog(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CATALOG,_FOOTER_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get name of current catalog                                                */
/*----------------------------------------------------------------------------*/
Stz* Catalog::szCurrCatalog(DicStack* pDicStack)
{
  _static_;
    
  for (i8 i_Dic = pDicStack->iCount() - 1; i_Dic >= 0; i_Dic--) {
    
    Dic* pDic = pDicStack->pPick(i_Dic);
    Stz* szDicNm = pDic->szDicNm();

    Word* pDicKind = pDic->pDicKind();
    Stz* szDicKindNm = pDicKind ? pDicKind->szWordNm() : "n/a"_Stz;

    vTrace("[%lld] %s %s\n"_Stz,
           i_Dic,
           szDicNm,
           szDicKindNm);
    
  }

  return nullptr;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Catalog::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CATALOG);
  
  return &m_xFooter;
}


