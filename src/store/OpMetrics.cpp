/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* OpMetrics::operator new(size_t nSize, MetricsWsp* pMetricsWsp)
{
  void* aEmbedded = pMetricsWsp->aAllot(nSize);
  
  return aEmbedded;
}

