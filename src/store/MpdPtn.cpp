/*----------------------------------------------------------------------------*/
/* is the mapped node same as given node                                      */
/*----------------------------------------------------------------------------*/
bool MpdPtn::bIsNode(i8 iNodeId)
{
  if (iNodeId == m_uNodeId)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* is the mapped node same as this/current node                               */
/*----------------------------------------------------------------------------*/
bool MpdPtn::bIsThisNode(void)
{
  if (AM::GRID::iThisNodeId() == m_uNodeId)
    return true;
  
  return false;
}

