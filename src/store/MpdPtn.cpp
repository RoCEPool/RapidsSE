/*----------------------------------------------------------------------------*/
/* map                                                                        */
/*----------------------------------------------------------------------------*/
void MpdPtn::vMap(void)
{
  m_uMappedNodeId   = AM::pPtnMap()->iMappedNodeId(m_u_LglPtn);
  m_uMappedStreamId = AM::pPtnMap()->i_MappedPtnNo(m_u_LglPtn);
}

