/*----------------------------------------------------------------------------*/
/* map                                                                        */
/*----------------------------------------------------------------------------*/
void MpdPtn::vMap(void)
{
  m_uNodeId = AM::pLglPtnMap()->iNodeId(m_uLglPtn);
  m_uPtnNo  = AM::pLglPtnMap()->iPtnNo(m_uLglPtn);
}

/*----------------------------------------------------------------------------*/
/* map and then test if logical partition is valid / within bounds            */
/*----------------------------------------------------------------------------*/
bool MpdPtn::bMapValid(void)
{
  vMap();
  
  if (m_uLglPtn < AM::PTNMAP::nPtnsInGrid())
    return true;
  
  return false;
}

