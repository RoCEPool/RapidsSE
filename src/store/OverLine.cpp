/*============================================================================*/
/* OverLine.cpp -- an overflow line                                           */
/*============================================================================*/

#include "BASE.h"

#include "CmdLineArgs.hpp"

#include "OverLine.hpp"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
OverLine::OverLine(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
OverLine::~OverLine(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return size of overflow line in bytes                                      */
/*----------------------------------------------------------------------------*/
i8 OverLine::jSizeBytes(void)
{
  i8 nSizeBytes = jSizeUnits() * sizeof(SpaceUnit);

  return nSizeBytes;
}

/*----------------------------------------------------------------------------*/
/* return size of overflow line in units                                      */
/*----------------------------------------------------------------------------*/
i8 OverLine::jSizeUnits(void)
{
  i8 nSizeUnits = w8_1B(0);
  
  return nSizeUnits;
}

/*----------------------------------------------------------------------------*/
/* return size of overflow line in words                                      */
/*----------------------------------------------------------------------------*/
i8 OverLine::jSizeWords(void)
{
  i8 nSizeWords = jSizeBytes() / C_BYTES_PER_WORD;

  return nSizeWords;
}

/*----------------------------------------------------------------------------*/
/* get the size <U> of this overflow in units                                 */
/*----------------------------------------------------------------------------*/
i8 OverLine::iU(void)
{
  i8 nUnits = w8_1B(0);
  
  return nUnits;
}

/*----------------------------------------------------------------------------*/
/* set the size <U> of this overflow in units                                 */
/*----------------------------------------------------------------------------*/
void OverLine::vU(i8 nUnits)
{
  v1B(0,nUnits);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* dump over line                                                             */
/*----------------------------------------------------------------------------*/
void OverLine::vDump(void)
{
  i8 nSizeBytes = jSizeBytes();
  MemLib::vWordDump(this,nSizeBytes);
}

