/*----------------------------------------------------------------------------*/
/* verify there are no stream column ordinals                                 */
/*----------------------------------------------------------------------------*/
void Xverify::V_vNo_Terms_StmColOdn(Card* p_card)
{
  //_precondition_(_ADDRESS_,_MAGIC_,CN_TRANSFORMS,_FOOTER_);

  CardIter xCI(p_card);
  while (Card* p_child = xCI.pEachChild()) {
    if (p_child->bIsCard(CK_STREAM))
      continue;

    if (p_child->bIsCard(CK_TERM)) {
      if (Card::bIsStreamColOrdinal(p_card->szValue()))
        vDebugPoint();

      RASSERT(! Card::bIsStreamColOrdinal(p_card->szValue()));
      continue;
    }

    V_vNo_Terms_StmColOdn(p_child);
  }
}

