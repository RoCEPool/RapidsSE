/*----------------------------------------------------------------------------*/
/* get agg level                                                              */
/*----------------------------------------------------------------------------*/
eAL Card_Aggreg::eAggLevel(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD_AGGREG,_FOOTER_);
  
  return m_eAggLevel;
}

/*----------------------------------------------------------------------------*/
/* set agg level                                                              */
/*----------------------------------------------------------------------------*/
void Card_Aggreg::vAggLevel(eAL eAggLevel)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD_AGGREG,_FOOTER_);
  
  m_eAggLevel = eAggLevel;
}


