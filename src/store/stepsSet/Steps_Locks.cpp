#include "BASE.h"
#include "Step.hpp"
#include "EnterExit.h"
#include "StepAccum.hpp"
#include "Steps.hpp"


/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Locks(void)
{
  vAddStep("locks::show"_Stz,  &Step::vLocksShow);
  vAddStep("locks::reset"_Stz, &Step::vLocksReset);
}

/*----------------------------------------------------------------------------*/
/* locks::list -- list lock stats                                             */
/*----------------------------------------------------------------------------*/
void Step::vLocksShow(void)
{
  ENTRY();

  AM::pLocks()->vShow();

  EXIT();
}

/*----------------------------------------------------------------------------*/
/* locks::reset -- reset locks                                                */
/*----------------------------------------------------------------------------*/
void Step::vLocksReset(void)
{
  ENTRY();
  
  AM::pLocks()->vReset();
  
  EXIT();
}

