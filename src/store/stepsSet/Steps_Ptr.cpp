/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Ptr(void)
{
  vAddStep("ptr.isNull"_Stz,      &Step::vPtrIsNull);
}

/*----------------------------------------------------------------------------*/
/* + -- add top two integers on stack                                         */
/*----------------------------------------------------------------------------*/
void Step::vPtrIsNull(void)
{
  ENTRY();

  Object* pObj = m_pDataStack->pPopPtr(__func__);

  m_pDataStack->vPushBol(pObj == nullptr);

  EXIT();
}


