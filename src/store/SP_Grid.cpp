/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Grid::SP_Grid(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Grid::~SP_Grid(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Grid::sz(Grid* pGrid)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  "%lld nodes %lld "
                  "partitions/table %lld total partitions"_Stz,
                  
                  pGrid->nKnownNodes(),
                  
                  AM::PTNMAP::nPtnsPerTable(),
                  AM::PTNMAP::nPtnsInGrid(),

                  C_VARGS_END
                  );
  
  return (Stz*) &m_caResult[0];
}


