#include "BASE.h"

#include "SkipRoots.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
SkipRoots* STORE::_aSkipRoots(void* aAddr)
{
  SkipRoots* aFreeEntry = reinterpret_cast<SkipRoots*>(aAddr);
  
  return aFreeEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipRoots::SkipRoots(void)
: Ent(CN_ENT,sizeof(SkipRoots))
{
  i8 nLvlLevels = AM::nLvlLevels();

  
  PoolBuffer* pBuffer = PoolBuffer::pWithinPoolBuffer((Object*)this);
  i8 i_PoolBuffer = pBuffer->iBufferNo();

  vBuffer(i_PoolBuffer);
  vSkipLevels(nLvlLevels);
  vElmSeqSize(0);

  for (i8 i_Pad = 0; i_Pad < C_SKIPROOTS_PADDING; i_Pad++)
    m_iPadding[i_Pad] = 0;
  
  for (i8 i_Level = 0; i_Level < C_MAX_LVL_LEVELS; i_Level++)
    vNextEntry(i_Level,C_ENT_END_TICKET);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipRoots::~SkipRoots(void) noexcept(false)
{
}


