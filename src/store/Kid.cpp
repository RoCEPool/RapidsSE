/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bEach(void)
{
  vNext();
  if (bInRange())
    return true;

  return false;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bEach_reverse(void)
{
  vPrev();
  if (bInRange())
    return true;

  return false;
}


/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bEach(eCK eCard)
{
  while (bEach())
    if (eChild() == eCard)
      return true;

  return false;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bEach_reverse(eCK eCard)
{
  while (bEach_reverse())
    if (eChild() == eCard)
      return true;

  return false;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bIsFirst(void)
{
  i8 nChildren = m_pParent->nChildCards();

  if (nChildren && 0 == m_i_Child)
    return true;

  return false;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Kid::bIsLast(void)
{
  i8 nChildren = m_pParent->nChildCards();

  if (nChildren && nChildren - 1 == m_i_Child)
    return true;

  return false;
}

