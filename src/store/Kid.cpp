/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
Card* Kid::pChild(i8 i_Child)
{
  i8 nChildren = m_pParent->nChildCards();

  if (i_Child >= 0 && i_Child < nChildren) {
    Card* pChild = m_pParent->pGetChild(i_Child);
    return pChild;
  }

  return nullptr;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
eCK Kid::eChild(void)
{
  Card* pChild = this->pChild();

  if (pChild)
    return pChild->eCard();

  return CK_NONE;
}

