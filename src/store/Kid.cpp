void Kid::vBeginForward(void)
{

  if (C_UNKNOWN == m_i_Child)
    m_i_Child= 0;
  else
    m_i_Child++;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
void Kid::vBeginReverse(void)
{

  if (C_UNKNOWN == m_i_Child)
    m_i_Child = m_pParent->nChildCards() - 1;
  else
    m_i_Child--;
}

