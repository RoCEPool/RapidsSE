/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
void Kid::vBeginEach_forward(void)
{
  _nonProper_

  vChildReset();
  m_bBegun   = true;
  m_bForwards = true;
  m_bEnded   = false;
}

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
void Kid::vBeginEach_reverse(void)
{
  _nonProper_

  vChildReset();
  m_i_Child = m_pParent->nChildCards() - 1;


  m_bBegun   = true;
  m_bForwards = false;
  m_bEnded   = false;
}

