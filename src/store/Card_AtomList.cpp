/*----------------------------------------------------------------------------*/
/* pop subcard                                                                */
/*----------------------------------------------------------------------------*/
Card_Atom* Card_AtomList::pPopAtom(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD_ATOMLIST,_FOOTER_);
  
  Card_Atom* pCard_Atom = _pCard_Atom(pPop());
  
  return pCard_Atom;
}

