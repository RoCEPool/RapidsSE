/*----------------------------------------------------------------------------*/
/* test if the expr has an aggregate op                                       */
/*----------------------------------------------------------------------------*/
bool Card_Expr::bHasAggOp(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD_EXPR,_FOOTER_);

  bool bHasAggOp = false;

  ListExoIter2_t<Card>* pAtom_I = pNewIter();

  while (pAtom_I->bHasNext()) {
    Card_Atom* pCard_Atom = _pCard_Atom(pAtom_I->pNext());
    
    if (pCard_Atom->bIsAggOp()) {
      bHasAggOp = true;
      break;
    }
  }
  
  delete pAtom_I;

  return bHasAggOp;
}

/*----------------------------------------------------------------------------*/
/* pop subcard                                                                */
/*----------------------------------------------------------------------------*/
Card_Atom* Card_Expr::pPopAtom(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD_EXPR,_FOOTER_);
  
  Card_Atom* pCard_Atom = _pCard_Atom(pPop());
  
  return pCard_Atom;
}


