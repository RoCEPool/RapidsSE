/*----------------------------------------------------------------------------*/
/* Creates a unique ID for an object name so that the names of siblings       */
/* do not conflict and are unique.                                            */
/*----------------------------------------------------------------------------*/
void LogicalNode::vObjName(Stz *szPrefix, s256 &sBuf)
{
  ASSERT(szPrefix);

  sBuf.vSprint("%s%04lld"_Stz, szPrefix, ms_pObjId->iInc());
}

