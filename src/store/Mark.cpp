/*----------------------------------------------------------------------------*/
/* formatted sprint                                                           */
/*----------------------------------------------------------------------------*/
void Mark::vSprint(Stz* szFormat, ...)
{
  _precondition_(_MAGIC_, CN_MARK, _FOOTER_);

  va_list args;
  va_start(args,szFormat);

  m_sChrSeq.vSprintVA(szFormat,args);

  va_end(args);
}



