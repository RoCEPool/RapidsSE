/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
bool Card_IdxCol::bIsReplicated(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CARD,_FOOTER_);

  Stz* szVal = szValue();
  char cTblSyn = *(szVal->azChar()+1);

  if (cTblSyn >= 'A' and cTblSyn <= 'Z')
    return true;

  return false;
}

