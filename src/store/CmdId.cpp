#include "BASE.h"

#include "CmdId.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
CmdId::CmdId(void)
{
  m_uNode = 0;
  m_uCmd  = 0;
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* auto conversion operator : i8 (subscript)                                  */
/*----------------------------------------------------------------------------*/
CmdId::operator i8(void)
{
  return m_uCmd;
}

/*----------------------------------------------------------------------------*/
/* get command no                                                             */
/*----------------------------------------------------------------------------*/
i8 CmdId::iCmdNo(void)
{
  return m_uCmd;
}

/*----------------------------------------------------------------------------*/
/* generate next command id                                                   */
/*----------------------------------------------------------------------------*/
void CmdId::vNextCmdId()
{
  m_uNode = 0;
  m_uCmd  = 0;
}

/*----------------------------------------------------------------------------*/
/* get node id                                                                */
/*----------------------------------------------------------------------------*/
i8 CmdId::iNodeId(void)
{
  return m_uNode;
}

