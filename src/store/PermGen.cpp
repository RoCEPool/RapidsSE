/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PermGen::PermGen(i8 nLevels)
: Object(CN_PERMGEN)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PERMGEN,_FOOTER_);

  m_nLevels = nLevels;

  m_iCurrLevel = C_UNKNOWN;
  for (i8 i_Level = 0; i_Level < C_PERM_LEVELS; i_Level++) {
    m_iaAction[i_Level]    = C_UNKNOWN;
    m_iaSubscript[i_Level] = C_UNKNOWN;
  }

  _checkInitialised_(CN_PERMGEN);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_PERMGEN,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
PermGen::~PermGen(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PERMGEN,_FOOTER_);
  
}


