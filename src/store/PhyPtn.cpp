PhyPtn::PhyPtn(void)
{
  m_iAsI8 = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PhyPtn::PhyPtn(i8 iAsI8)
{
  m_iAsI8 = iAsI8;
}


