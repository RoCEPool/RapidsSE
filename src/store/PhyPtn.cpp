{
  return this;
}

/*----------------------------------------------------------------------------*/
/* auto conversion operator : i8                                              */
/*----------------------------------------------------------------------------*/
PhyPtn::operator i8(void)
{
  return m_iAsI8;
}


/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
void PhyPtn::operator =(i8 iAsI8)
{
  m_iAsI8 = iAsI8;
}

/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
void PhyPtn::operator =(PhyPtn tPhyPtn)
{
  m_iAsI8 = tPhyPtn.iAsI8();
}


/*----------------------------------------------------------------------------*/
/* operator  ++                                                               */
/*----------------------------------------------------------------------------*/
i8 PhyPtn::operator ++(int)
{
  i8 temp;
  temp = m_iAsI8++;
  return temp;
}

/*----------------------------------------------------------------------------*/
/* atomically inc (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 PhyPtn::operator ++(void)
{
  
  i8 iAsI8 = ++ m_iAsI8;
  
  return iAsI8;
}


/*----------------------------------------------------------------------------*/
/* assignment operator : ???                                                  */
/*----------------------------------------------------------------------------*/
bool PhyPtn::operator <(i8 iAsI8)
{
  return m_iAsI8 < iAsI8;
}


