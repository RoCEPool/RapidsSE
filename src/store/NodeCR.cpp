#include "BASE.h"

#include "NodeCR.hpp"
#include "Grid.hpp"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NodeCR::NodeCR(void)
{
  Grid* pGrid = AM::pGrid();
  
  m_uLimit = pGrid->nKnownNodes();
  m_pObject = pGrid->pGetNthNode(m_uSubscript);
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator ++ increment (postfix form)                                        */
/*----------------------------------------------------------------------------*/
Node* NodeCR::operator ++(int)
{
  Node* pPrev = m_pObject;
  Grid* pGrid = AM::pGrid();

  vIncSubscript();
  if (bValid())
    m_pObject = pGrid->pGetNthNode(m_uSubscript);
  else
    m_pObject = nullptr;
  
  return pPrev;
}

