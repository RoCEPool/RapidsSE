#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_User(void)
{
  vAddStep("user::name"_Stz,  &Step::vUserName);
}

/*----------------------------------------------------------------------------*/
/* user::name -- get user name                                                */
/*----------------------------------------------------------------------------*/
void Step::vUserName(void)
{
  ENTRY();
  
  s32 sUserNme( (Stz*)getenv("USER") );
  
  m_pDataStack->vPushStr(sUserNme);

  EXIT();
}

