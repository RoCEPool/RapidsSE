#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_RegIndex(void)
{
  vAddStep("index[]"_Stz,      &Step::vRegIndexGet);
  vAddStep("index[].set"_Stz,  &Step::vRegIndexSet);
}

/*----------------------------------------------------------------------------*/
/* index[] -- get index                                                       */
/*----------------------------------------------------------------------------*/
void Step::vRegIndexGet(void)
{
  ENTRY();
  
  m_pDataStack->vPushPtr(*m_pLogicUnit->m_xpIndex);
  
  EXIT();
}

/*----------------------------------------------------------------------------*/
/* index[].set -- set index                                                   */
/*----------------------------------------------------------------------------*/
void Step::vRegIndexSet(void)
{
  ENTRY();
  
  m_pLogicUnit->m_xpIndex = _pIndex(m_pDataStack->pPopPtr(__func__));
  
  EXIT();
}

