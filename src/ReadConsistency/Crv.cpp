/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Crv::Crv(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Crv::~Crv(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calc the bytes need for a crv row given size of crw buffer                 */
/*----------------------------------------------------------------------------*/
i8 Crv::nCrvBytesNeed(i8 nCrwBytes)
{
  i8 nBytesNeeded = sizeof(Crv) - sizeof(Crw) + nCrwBytes;
  
  ASSERT(nBytesNeeded == nCrwBytes + 16); // cross-check
  
  return nBytesNeeded;
}

/*----------------------------------------------------------------------------*/
/* form key used for finding a prior version                                  */
/*----------------------------------------------------------------------------*/
void Crv::vFormFindKey(EntWrk* aEntWrk, Rrf xwRef, t8 tPerspective)
{
  aEntWrk->vAppendRef(xwRef);
  aEntWrk->vAppendInt(tPerspective);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of the consistent row copy                                     */
/*----------------------------------------------------------------------------*/
Crw* Crv::aCrw(void)
{
  return & m_xCrw_RC;
}

/*----------------------------------------------------------------------------*/
/* get reference of the current row                                           */
/*----------------------------------------------------------------------------*/
Rrf Crv::xwRef(void)
{
  return m_xwRef;
}

/*----------------------------------------------------------------------------*/
/* take a consistent copy of the given compact row                            */
/*----------------------------------------------------------------------------*/
void Crv::vTakeVersion(Rrf xwRef, Crw* aCrw, i8 nCrwBytes)
{
  m_nCrvSize = nCrvBytesNeed(nCrwBytes);
  
  m_xwRef = xwRef;
  
  MemLib::vCopy(&m_xCrw_RC,aCrw,nCrwBytes,CN_CRVBUFFER);
}


