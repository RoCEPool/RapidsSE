#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Tsp::SP_Tsp(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
  
  // set default Tsp format
  vFormat(F_TSP);
  
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Tsp::~SP_Tsp(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tsp::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTsp(C_YEAR_MAX,C_12_DEC,31, 23,59,59,999999) );
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tsp::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTsp(2018,C_02_FEB,1, 4,3,2,1) );
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tsp::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTsp(C_YEAR_MIN,C_01_JAN,1, 0,0,0,0) );
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Tme and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* SP_Tsp::sz(i8 iTsp)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  Dtm wTsp;
  
  wTsp = iTsp;
  
  if (wTsp.m_wTsp.m_uMicro) {
    
    char caFraction[16];
    StrLib::vFormatFraction(caFraction,wTsp.m_wTsp.m_uMicro,6);
    
    StrLib::vSprint(m_caResult,
                    (Stz*)F_TSP_frac,

                    (i8)wTsp.m_wTsp.m_uYearDelta + C_YEAR_BASE,
                    (i8)wTsp.m_wTsp.m_uMonth,
                    (i8)wTsp.m_wTsp.m_uDay,
                    
                    (i8)wTsp.m_wTsp.m_uHour,
                    (i8)wTsp.m_wTsp.m_uMinute,
                    (i8)wTsp.m_wTsp.m_uSecond,
                    
                    caFraction);
  }
  else {
    StrLib::vSprint(m_caResult,
                    (Stz*)F_TSP,

                    (i8)wTsp.m_wTsp.m_uYearDelta + C_YEAR_BASE,
                    (i8)wTsp.m_wTsp.m_uMonth,
                    (i8)wTsp.m_wTsp.m_uDay,
                    
                    (i8)wTsp.m_wTsp.m_uHour,
                    (i8)wTsp.m_wTsp.m_uMinute,
                    (i8)wTsp.m_wTsp.m_uSecond);
  }

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SP_Tsp::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL);
  
  return &m_xFooter;
}

