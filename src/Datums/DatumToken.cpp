/*----------------------------------------------------------------------------*/
/* assign datum from token                                                    */
/*----------------------------------------------------------------------------*/
void DatumToken::vAssign(Datum_h* pDatum, Token* pTkn, Column* pCol)
{
  Format* pFmt = AM::pFmt();
  
  char* azCrs = pTkn->azChars();
  
  bool b = CsvValue::bToDtm(pDatum,pCol,&azCrs,pFmt);
  ASSERT(b);
}

