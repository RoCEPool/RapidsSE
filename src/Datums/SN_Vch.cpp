#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Vch::SN_Vch(void)
: Scan(CN_SNVCH)
{
  _precondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
    
  _checkInitialised_(CN_SNVCH);
  
  _postcondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Vch::~SN_Vch(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
Stz* SN_Vch::sz(char** aacCrs, i8 iLength, Format* pFmt,
               bool bSawLeadingEnclosed,
               i8& nChars_)
{
  _precondition_(_MAGIC_,CN_SNVCH);
  
  if ( ! StrLib::bExtractVarchar(aacCrs,
                                 m_caVch,
                                 iLength,
                                 bSawLeadingEnclosed,
                                 pFmt->m_cEnclosedBy_Leading,
                                 pFmt->m_cEnclosedBy_Trailing,
                                 pFmt->m_cEscapeChar,
                                 pFmt->m_cFieldDelimiter,
                                 pFmt->m_cRecordTerminator,
                                 pFmt->m_bAllowNonPrintable,
                                 nChars_) )
    THROW_USER("StrLib::bExtractVarchar"_Stz);

  return (Stz*) &m_caVch[0];
}



/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Vch::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNVCH);
  
  return &m_xFooter;
}

