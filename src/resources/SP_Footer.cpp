#include "Resources.h"

extern SizeHeap  gxaSizeHeap[];

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Footer::SP_Footer(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Footer::~SP_Footer(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Footer::sz(Footer* aFoot)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  "<(%s)>"_Stz,
                  
                  aFoot->bValidFooter() ? "valid-footer" : "invalid-footer"
                  );

  
  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Footer::sz(Object* pObject)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  eCN eClass = pObject->eClass();
  i8 nObjectSize = gxaSizeHeap[eClass].m_nClassSize;

  Footer* aFoot = aAdd<Footer*>(pObject,nObjectSize-sizeof(Footer));

  return sz(aFoot);
}


