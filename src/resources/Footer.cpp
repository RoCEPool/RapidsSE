/*============================================================================*/
/* Footer.cpp -- Footer for Concrete Classes                                  */
/*============================================================================*/

#include "Correctness.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer::Footer(void)
{
  m__PadToDoubleWord = 0;
  m_uFooter = C_FOOTER;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer::~Footer(void)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* ASSERT footer                                                              */
/*----------------------------------------------------------------------------*/
void Footer::vAssertFooter(void) const
{
  ASSERT(m_uFooter == C_FOOTER);
}

/*----------------------------------------------------------------------------*/
/* set footer                                                                 */
/*----------------------------------------------------------------------------*/
void Footer::vSetFooter(void)
{
  m__PadToDoubleWord = 0;
  m_uFooter = C_FOOTER;
}

/*----------------------------------------------------------------------------*/
/* sprint the header into readable form                                       */
/*----------------------------------------------------------------------------*/
void Footer::vSprint(Stz* szHeader)
{
  StrLib::vSprint(szHeader,
                  "Footer: %c%c%c%c%c%c%c%c (%s)"_Stz,
                  m_caFooter[0],
                  m_caFooter[1],
                  m_caFooter[2],
                  m_caFooter[3],
                  m_caFooter[4],
                  m_caFooter[5],
                  m_caFooter[6],
                  m_caFooter[7],
                  bValidFooter() ? "valid footer" : "not-valid footer"
                  );
}

/*----------------------------------------------------------------------------*/
/* test for valid footer                                                      */
/*----------------------------------------------------------------------------*/
bool Footer::bValidFooter(void)
{
  if (m_uFooter == C_FOOTER)
    return true;
  else
    return false;
}

