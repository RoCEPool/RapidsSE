Header::Header(void)
{

}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Header::Header(eCN eClassNo)
{
  vMagic();
  vClass(eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Header::~Header(void)
{
  // vAssertHeader();         //! This causes an assert failure. Ray to fix ASAP
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* ASSERT header                                                              */
/*----------------------------------------------------------------------------*/
void Header::vAssertHeader(void)
{
  ASSERT(bValidMagic());
}

/*----------------------------------------------------------------------------*/
/* sprint the header into readable form                                       */
/*----------------------------------------------------------------------------*/
void Header::vSprint(Stz* szHeader)
{
  StrLib::vSprint(szHeader,
                  "Magic: %c%c%c%c Class %03d %s (%s)"_Stz,
                  m_caMagic[0],
                  m_caMagic[1],
                  m_caMagic[2],
                  m_caMagic[3],
                  m_eClass,
                  aCN[m_eClass],
                  bValidMagic() ? "valid magic" : "not-valid magic"
                  );
}

