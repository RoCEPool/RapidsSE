#include "Resources.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Char::SP_Char(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Char::~SP_Char(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint char and return Stz* to result                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_Char::sz(char cChar)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
    
  if ('\0' == cChar)
    StrLib::vSprint(m_caResult,
                    "null hex %02x"_Stz,
                    
                    cChar
                    );
  else
  if ('\n' == cChar)
    StrLib::vSprint(m_caResult,
                    "\\n   hex %02x"_Stz,
                    
                    cChar
                    );
  else
  if (' ' > cChar)
    StrLib::vSprint(m_caResult,
                    "%s hex %02x"_Stz,
                    
                    StrLib::azAscii(cChar),
                    cChar
                    );
  else
    StrLib::vSprint(m_caResult,
                    "'%c'  hex %02x"_Stz,
                    
                    cChar,
                    cChar
                    );
  
  return (Stz*) &m_caResult[0];
}

