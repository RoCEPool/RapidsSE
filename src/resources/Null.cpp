#include "Assembler.h"

i8 gi_NullValue = C_DATUM_NULL;

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy null into destination                                                 */
/*----------------------------------------------------------------------------*/
i8 Null::nCopy(byte* ayDst)
{
  * (i8*)ayDst = C_DATUM_NULL;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy null into destination                                                 */
/*----------------------------------------------------------------------------*/
i8 Null::nCopy(byte** aayDst)
{
  ** (i8**)aayDst = C_DATUM_NULL;
  
  (*aayDst) += sizeof(i8);
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy null into destination                                                 */
/*----------------------------------------------------------------------------*/
void Null::vCopy(byte* ayDst)
{
  * (i8*)ayDst = C_DATUM_NULL;
}

/*----------------------------------------------------------------------------*/
/* copy null into destination                                                 */
/*----------------------------------------------------------------------------*/
void Null::vCopy(byte** aayDst)
{
  ** (i8**)aayDst = C_DATUM_NULL;
  
  (*aayDst) += sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* add number of bytes to given address                                       */
/*----------------------------------------------------------------------------*/
bool Null::bIsNull(i8 iValue)
{
  if (C_DATUM_NULL == iValue)
    return true;
  else
    return false;
}

