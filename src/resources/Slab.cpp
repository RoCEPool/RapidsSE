#include "Resources.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* Slab::operator new(size_t)
{
  Slab* pSlab = (Slab*)HeapMem::pAllocate(CN_SLAB);
  
  return pPoolCheck<void*>(pSlab);
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void Slab::operator delete(void* pSlabAddress)
{
  Slab* pSlab = static_cast<Slab*>(pSlabAddress);
  
  HeapMem::vFree(pSlab);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Slab::Slab(void)
: Object(CN_SLAB)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB);
  
  m_pNextSlab = nullptr;
  
  MemLib::vZero(m__PadToCacheLine,sizeof(m__PadToCacheLine),CN_SLAB);
  
  m_xWsp.vFill(0xEF,CN_SLAB);
  
  _checkInitialisedSize_(sizeof(Slab));

  _postcondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Slab::~Slab(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* allot given number of bytes                                                */
/*----------------------------------------------------------------------------*/
byte* Slab::ayAllotBytes(i8 nBytes)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  // test sufficient freespace
  if (m_xWsp.nFree() < nBytes)
    return nullptr;
  
  // allot bytes in the wsp
  byte* ayBytes = m_xWsp.ayAllot(nBytes);
  
  return ayBytes;
}

/*----------------------------------------------------------------------------*/
/* get next slab                                                              */
/*----------------------------------------------------------------------------*/
Slab* Slab::pNextSlab(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  return m_pNextSlab;
}

/*----------------------------------------------------------------------------*/
/* set next slab                                                              */
/*----------------------------------------------------------------------------*/
void Slab::vNextSlab(Slab* pNextSlab)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  m_pNextSlab = pNextSlab;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Slab::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return &m_xFooter;
}

