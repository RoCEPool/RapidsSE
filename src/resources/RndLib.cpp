/*----------------------------------------------------------------------------*/
/* choose a random logarithemic level (up to n levels, at given frequency)    */
/*----------------------------------------------------------------------------*/
i8 RndLib::iLogLevel(i8 nLvlLevels, i8 iLvlRatio, i8& i_NextRnd)
{
  RASSERT(nLvlLevels >= C_MIN_LVL_LEVELS && nLvlLevels <= C_MAX_LVL_LEVELS);
  RASSERT(iLvlRatio  >= C_MIN_LVL_RATIO  && iLvlRatio  <= C_MAX_LVL_RATIO);

  //
  // This function generates a number between 0 and nLevels - 1.
  //
  // A level 0 is generated most of the time,
  //   the probability that a level 1 is generated is 1 / (2 ^ uFrequency),
  //   the probability that a level 2 is generated is 1 / (2 ^ uFrequency ^ 2),
  //   the probability that a level 3 is generated is 1 / (2 ^ uFrequency ^ 3).
  //
  // So if uFrequency is 2,
  //   then level 1 will probably be generated once every 4 times,
  //        level 2 will probably be generated once every 16 times,
  //        level 4 will probably be generated once every 64 times.
  //
  
  //
  // The algorithm works by repeatedly examining a subset of bits from a
  // random pattern.  The probability that all bits are zero is a function of
  // the number of bits in the subset.  The more bits in the subset the
  // less likely (logarithemically) that all bits are zero.
  //
  
  u8 uBitMask = C_ALL_BITS_ON >> (C_BITS_PER_WORD - iLvlRatio);
  
  u8 uBitSubset = 0;
  u8 nSubsetsLeft = 0;
  u8 uRndLibPattern = 0;
  
  // step thru bit subsets until we find a subset with some bits set
  i8 nAllZeroSubsets;
  for (nAllZeroSubsets = -1; ! uBitSubset; nAllZeroSubsets++) {
    
    // if all bits used from the random bit pattern, generate a new pattern
    if (0 == nSubsetsLeft) {
      
      if (C_UNKNOWN == i_NextRnd)
        uRndLibPattern = RndLib::uInteger();
      else
        uRndLibPattern = RndLib::uRepeatable(i_NextRnd);

      nSubsetsLeft = nLvlLevels / iLvlRatio;
    }

    // take the next lower subset of bits
    uBitSubset = uRndLibPattern & uBitMask;
    uRndLibPattern >>= iLvlRatio;
    nSubsetsLeft--;
  }
  
  // compute the level based on the number of times we observed subsets
  // whose bits were all zero
  i8 iLevel = ((nAllZeroSubsets >= nLvlLevels)
                ? nLvlLevels - 1
                : nAllZeroSubsets) + 1;
    
  return iLevel;
}

/*----------------------------------------------------------------------------*/
/* random skip level which is a number 1..max, at given logarithm frequency   */
/*----------------------------------------------------------------------------*/
i8 RndLib::iSkipLevel(i8 nLvlLevels, i8 iLvlRatio)
{
  RASSERT(nLvlLevels >= C_MIN_LVL_LEVELS && nLvlLevels <= C_MAX_LVL_LEVELS);
  RASSERT(iLvlRatio  >= C_MIN_LVL_RATIO  && iLvlRatio  <= C_MAX_LVL_RATIO);

  ASSERT(nLvlLevels * iLvlRatio <= (i8)C_BITS_PER_WORD);

  //SP_Bits spBits;
  
  u8 uRatioMask = ~ (C_ALL_BITS_ON << iLvlRatio);
  //vTrace("uFreqMask: %s\n"_Stz,spBits.sz(uBitMask));
  
  
  u8 uPattern = RndLib::uInteger();
  

  i8 iLevel = 1;
  for (i8 iGrp = 0; iGrp < iLvlRatio; iGrp++) {
    //vTrace("uPattern: %s\n"_Stz,spBits.sz(uPattern));
    u8 uGrpBits = uPattern & uRatioMask;
    //vTrace("uGrpBits: %s\n"_Stz,spBits.sz(uGrpBits));
    if (uGrpBits)
      break;
    if (++iLevel == nLvlLevels)
      break;
    uPattern >>= iLvlRatio;
  }
  
  ASSERT(iLevel >= 1 && iLevel <= nLvlLevels);
  
  //if (iLevel > 3)
  //  vDebugPoint();

  return iLevel;
}

