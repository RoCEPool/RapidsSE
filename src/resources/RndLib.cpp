/*----------------------------------------------------------------------------*/
/* generate random bytes of given length                                      */
/*----------------------------------------------------------------------------*/
void RndLib::vBytes(byte* ayBytes, i8 iLength)
{
  static char caCharSet[69] = // 68 actual chars + the '\0'
    "abcdefghijklmnopqrstuvwxyz ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-#?!";
  // 01234567890123456789012345678901234567890123456789012345678901234567
  // 0         1         2         3         4         5         6      6
  
  byte* z = ayBytes;
  
  for (i8 i = 0; i < iLength; i++)
    *z++ = caCharSet[iInteger(68)];
  
  *z = '\0';
}


/*----------------------------------------------------------------------------*/
/* generate a random number                                                   */
/*----------------------------------------------------------------------------*/
i8 RndLib::iInteger(void)
{
  i8 iRand = Mersenne::genrand64_int63();
  
  return iRand;
}

/*----------------------------------------------------------------------------*/
/* generate a random number                                                   */
/*----------------------------------------------------------------------------*/
i8 RndLib::iInteger(i8 iMax)
{
  i8 iRand = Mersenne::genrand64_int63() % iMax;
  
  return iRand;
}

/*----------------------------------------------------------------------------*/
/* generate a random number between low and high (inclusive)                  */
/*----------------------------------------------------------------------------*/
i8 RndLib::iInteger(i8 iLow, i8 iHigh)
{
  i8 r = Mersenne::genrand64_int63();
  
  i8 m = iHigh - iLow + 1;
  i8 v = r % m;
  i8 n = v + iLow;
  
  assert (n >= iLow);
  assert (n <= iHigh);
  
  return n;
}

