#include "Resources.h"

extern SizeHeap  gxaSizeHeap[];

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Header::SP_Header(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Header::~SP_Header(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Header::sz(Header* aHeader)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  eCN eClassNo  = aHeader->eClass();
  i8 nClassSize = gxaSizeHeap[eClassNo].m_nClassSize;

  StrLib::vSprint(m_caResult,
                  "<cn%03d %s %lldB %s>"_Stz,
                  
                  eClassNo,
                  aCN[eClassNo],
                  nClassSize,
                  aHeader->bValidMagic() ? "valid-magic" : "invalid-magic"
                  );

  return (Stz*) &m_caResult[0];
}


