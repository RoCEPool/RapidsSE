#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BcdVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: BcdVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Bcd BcdVal::wBcd(void)
{
  ASSERT(bIsClass(CN_BCDVAL));
  
  return m_wBcd;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void BcdVal::vBcd(Bcd wBcd)
{
  vClass(CN_BCDVAL);
  m_wBcd = wBcd;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a BcdVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 BcdVal::nStackUsage(void)
{
  return sizeof(BcdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BcdVal::vToStz(Stz* szDst)
{
  if (m_wBcd.bIsNull()) {
    szDst->vConcat(C_NULL);
    return;
  }
  
  * szDst = m_wBcd.m_iAsI8;
}

