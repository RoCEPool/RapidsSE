#!/bin/bash

DIR="$(dirname "$0")"
VERSION_FILE="${DIR}/Version.h"

BUILD_GIT_HASH="$(git rev-parse --short=16 HEAD)"
BUILD_DATE="$(date)"
BUILD_HOSTNAME="$(hostname -f)"
BUILD_USERNAME="$(whoami)"
BUILD_BRANCH="$(git rev-parse --abbrev-ref HEAD)"

function updateVersionFile() {
  rm -f "${VERSION_FILE}"

  {
    echo "/*============================================================================*/"
    echo "/* Version.h -- Dynamically generated version information                     */"
    echo "/*============================================================================*/"
    echo ""
    echo "// auto-generated by: generateVersion.sh"
    echo ""
    echo "static const Stz* C_BUILD_GIT_HASH = \"${BUILD_GIT_HASH}\"_Stz;"
    echo "static const Stz* C_BUILD_DATE     = \"${BUILD_DATE}\"_Stz;"
    echo "static const Stz* C_BUILD_HOSTNAME = \"${BUILD_HOSTNAME}\"_Stz;"
    echo "static const Stz* C_BUILD_USERNAME = \"${BUILD_USERNAME}\"_Stz;"
    echo "static const Stz* C_BUILD_BRANCH   = \"${BUILD_BRANCH}\"_Stz;"
    echo ""
    echo "/*============================================================================*/"
    echo "/* end                                                                        */"
    echo "/*============================================================================*/"
  } >> "${VERSION_FILE}"
}


function isVersionFileUpToDate() {
  if [ ! -f "${VERSION_FILE}" ]; then
    echo "Version file doesn't exist. Creating version file with git hash ${BUILD_GIT_HASH}."
    false
    return
  fi

  # Version file exists. Extract the git hash and compare it.
  local re='C_BUILD_GIT_HASH = "([^"]+)"_Stz;'

  local versionFileContents
  versionFileContents="$(<"${VERSION_FILE}")"

  if [[ "${versionFileContents}" =~ ${re}  ]]; then
    if [ "${#BASH_REMATCH[@]}" -ne 2 ]; then
      echo "Could not extract out old git hash from version file (no matching regex group). Creating new version file with git hash ${BUILD_GIT_HASH}."
      false
      return
    fi

    # now we can compare the matches
    local oldGitHash="${BASH_REMATCH[1]}"

    if [ "${BUILD_GIT_HASH}" != "${oldGitHash}" ]; then
      echo "Git hash has changed from ${oldGitHash} to ${BUILD_GIT_HASH}."
      false
      return
    fi

    echo "Git hash has not changed from ${oldGitHash}."
    true
    return
  fi

  echo "Could not extract out old git hash from version file (doesn't match regex). Creating new version file with git hash ${BUILD_GIT_HASH}."
  false
}

if ! isVersionFileUpToDate; then
  updateVersionFile
fi
