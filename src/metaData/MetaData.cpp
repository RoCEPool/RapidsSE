/*----------------------------------------------------------------------------*/
/* things to check at boot time                                               */
/*----------------------------------------------------------------------------*/
void MetaData::vCheckAssumptions(void)
{
  ALWAYS(sizeof(Operand)      == sizeof(CacheLine));
  ALWAYS(sizeof(LinkedBuffer) == 2 * sizeof(CacheLine));
  
  ALWAYS(sizeof(StreamDef)    < C_SIZE_LARGE_OBJECT);
}

