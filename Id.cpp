/*============================================================================*/
/* Id.cpp -- the id of an item in a mini-heap                                 */
/*============================================================================*/

#include "Indexes.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t)
{
  vFatal("fatal: ItemId class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t, Id* pId)
{
  return pId;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uLevels  = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(Id& xId)
{
  vAssign(xId);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(u8 uBuffer, u8 uItem, u8 uOffsets)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uLevels  = uOffsets;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Id::~Id(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Id::operator =(Id& xId)
{
  vAssign(xId);
}

/*----------------------------------------------------------------------------*/
/* get id as an i8 integer                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iAsI8(void)
{
  i8 iId;
  
  iId  = m_uBuffer << 48;
  iId |= m_uItem;
  
  return iId;
}

/*----------------------------------------------------------------------------*/
/* assign id                                                                  */
/*----------------------------------------------------------------------------*/
void Id::vAssign(Id& xId)
{
  m_uBuffer  = xId.m_uBuffer;
  m_uItem    = xId.m_uItem;
  m_uLevels  = xId.m_uLevels;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Id::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Id::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get number of levels                                                       */
/*----------------------------------------------------------------------------*/
i8 Id::nLevels(void)
{
  return (i8)m_uLevels;
}

/*----------------------------------------------------------------------------*/
/* set number of levels                                                       */
/*----------------------------------------------------------------------------*/
void Id::vLevels(i8 nLevels)
{
  m_uLevels = nLevels;
}

