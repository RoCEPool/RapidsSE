#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryApi::vSet(LogEntry* pLogEntry, i8 iSsnId, eAA eApiAct)
{
  pLogEntry->m_eKind = EK_API;
  
  m_iSsnId  = iSsnId;
  m_eItfAct = eApiAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryApi::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("A"_Stz,m_iSsnId),
                aAA[m_eItfAct]);
}

