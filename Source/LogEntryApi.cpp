#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryItf::vSet(LogEntry* pLogEntry, i8 iItfId, eAA eApiAct)
{
  pLogEntry->m_eKind = EK_ITF;
  
  m_iItfId  = iItfId;
  m_eItfAct = eApiAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryItf::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz(m_iItfId),
                aAA[m_eItfAct]);
}

