#include "Dictionaries.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IPval::operator new(size_t iSize)
{
  vFatal("fatal: IPval class cannot be new'd\n");
  
  //vExitFatal();
  
  exit(EXIT_FAILURE);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IPval::IPval(void)
: Value(CN_IPVAL)
{
  m_pCell = nullptr;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IPval::operator =(Cell* pCell)
{
  m_pCell = pCell;
}

/*----------------------------------------------------------------------------*/
/* get pWord                                                                  */
/*----------------------------------------------------------------------------*/
Cell* IPval::pCell(void) const
{
  return m_pCell;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IPval::iSize(void) const
{
  return sizeof(IPval);
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void IPval::vToCommand(char* aWorkspace)
{
  String::wToPointer(m_pCell,aWorkspace);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IPval::vToString(char* aWorkspace)
{
  String::wToPointer(m_pCell,aWorkspace);
}

