/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* GraphNode::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ZSMALL_);
  
  return &m_xFooter;
}

