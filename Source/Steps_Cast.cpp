#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Cast(void)
{
  vAddStep("(int)"_Stz,           &Step::vCastInt);
  vAddStep("(ptr)"_Stz,           &Step::vCastPtr);
}

/*----------------------------------------------------------------------------*/
/* (int) -- cast ptr to int                                                   */
/*----------------------------------------------------------------------------*/
void Step::vCastInt(void)
{
  ENTRY(); // ENTRY("vCastInt"_Stz);
  
  Object* pPtr;
  if ( ! m_pDataStack->bPopObject(pPtr) )
    THROW_DSTACK();
  
  m_pDataStack->vPushI8((i8)pPtr);
  
  EXIT();
}

/*----------------------------------------------------------------------------*/
/* (ptr) -- cast int to ptr                                                   */
/*----------------------------------------------------------------------------*/
void Step::vCastPtr(void)
{
  ENTRY(); // ENTRY("vCastPtr"_Stz);
  
  i8 iInt;
  if ( ! m_pDataStack->bPopI8(iInt) )
    THROW_DSTACK();
  
  m_pDataStack->vPushPtr((Object*)iInt);
  
  EXIT();
}

