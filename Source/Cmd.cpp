#include "CompilerStream.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Cmd* CompilerStream::_pCmd(void* aAddr)
{
  Cmd* pCmd = reinterpret_cast<Cmd*>(aAddr);
  
  return pCmd;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void Cmd::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Cmd::Cmd(eCN eClassNo)
: Operand(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Cmd::~Cmd(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}

