/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Ring::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Ring class cannot be new'd");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Ring::operator delete(void* pBufferAddress)
{
  RASSERT(pBufferAddress);
  vFatal("fatal: Ring class cannot be deleted");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ring::Ring(void)
: Object(CN_RING)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RING,_FOOTER_);
  
  for (auto i = 0; i < C_ASSIGNMENT; i++)
    m_iAssignment[i] = 0;
  
  _checkInitialised_(CN_RING);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Ring::~Ring(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RING,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Ring::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RING);
  
  return &m_xFooter;
}

