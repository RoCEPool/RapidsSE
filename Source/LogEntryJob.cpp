#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set variable entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryJob::vSet(LogEntry* pLogEntry, Job* pJob, eJA eJobAct)
{  
  pLogEntry->m_eKind = EK_JOB;
  
  m_iJobId  = pJob->m_iUniqueId;
  m_eJobAct = eJobAct;
}

/*----------------------------------------------------------------------------*/
/* cat sprint to given string                                                 */
/*----------------------------------------------------------------------------*/
void _LogEntryJob::vSprint(s4K& sString)
{
  SP_Id spId;
  
  sString.vCatSprint(",%s,%s"_Stz,
                
                      spId.sz("J"_Stz,m_iJobId),
                      aJA[m_eJobAct]);
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryJob::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("J"_Stz,m_iJobId),
                aJA[m_eJobAct]);
}

