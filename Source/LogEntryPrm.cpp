#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryPrm::vSet(LogEntry* pLogEntry, i8 iPrmId, ePA ePrmAct)
{
  pLogEntry->m_eKind = EK_PRM;
  
  m_iPrmId  = iPrmId;
  m_ePrmAct = ePrmAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryPrm::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("P"_Stz,m_iPrmId),
                aPA[m_ePrmAct]);
}

