#include "Forth.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Register* Forth::_pRegister(void* aAddr)
{
  Register* pRegister = reinterpret_cast<Register*>(aAddr);
  
  RASSERT_TYPE(pRegister,CN_REGISTER);
  
  return pRegister;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Register::operator new(size_t)
{
  vFatal("fatal: Register class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Register::Register(void)
: Value(CN_REGISTER)
{
  _memZero_(m_xWsp.aArea(),C_WSP_REGISTER,CN_REGISTER);
  
  *(this) = (i8)0;
  
 _checkInitialised_(CN_REGISTER);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void Register::operator =(i8 iInt)
{
  vSetClass(CN_INTVAL);
  
  *_aIntVal(this) = iInt;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void Register::operator =(Object* pPtr)
{
  vSetClass(CN_PTRVAL);
  
  *_aPtrVal(this) = pPtr;
}

