#include "MetaData.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IdxColVec* MetaData::_pIdxColVec(void* pAddr)
{
  IdxColVec* pIdxColVec = reinterpret_cast<IdxColVec*>(pAddr);
  
  RASSERT_TYPE(pIdxColVec,CN_IDXCOLVEC);
  
  return pIdxColVec;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IdxColVec::operator new(size_t)
{
  Object* pIdxColVec = HeapMem::pAllocate(CN_IDXCOLVEC);
  
  return pIdxColVec;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void IdxColVec::operator delete(void* pAddress)
{
  IdxColVec* pIdxColVec = reinterpret_cast<IdxColVec*>(pAddress);
  
  HeapMem::vFree(pIdxColVec);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IdxColVec::IdxColVec(IndexDef* pIndexDef)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_IDXCOLVEC,_FOOTER_);

  m_pIndexDef = pIndexDef;
  
  _checkInitialised_(CN_IDXCOLVEC);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_IDXCOLVEC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
IdxColVec::~IdxColVec(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_IDXCOLVEC,_FOOTER_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get which index definition                                                 */
/*----------------------------------------------------------------------------*/
IndexDef* IdxColVec::pIndexDef(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_IDXCOLVEC,_FOOTER_);
  
  return m_pIndexDef;
}

/*----------------------------------------------------------------------------*/
/* set which index definition                                                 */
/*----------------------------------------------------------------------------*/
void IdxColVec::vIndexDef(IndexDef* pIndexDef)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_IDXCOLVEC,_FOOTER_);
  
  m_pIndexDef = pIndexDef;
}


