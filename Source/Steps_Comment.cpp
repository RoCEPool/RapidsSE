#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Comment(void)
{
  vAddStep("("_Stz,               &Step::vComment,          true );
}

/*----------------------------------------------------------------------------*/
/* comment -- comment                                                         */
/*----------------------------------------------------------------------------*/
void Step::vComment(void)
{
  ENTRY(); // ENTRY("vComment"_Stz);
  
  for (;;) {
    m_pCompiler->vReadToken_cpl();
    if (m_pTokeniser->szToken()->bEqual(")"_Stz))
      break;
  }
  
  EXIT();
}

