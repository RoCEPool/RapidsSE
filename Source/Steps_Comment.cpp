/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Comment(void)
{
  vAddStep("("_Stz,               &Task::vComment,          true );
}

/*----------------------------------------------------------------------------*/
/* comment -- comment                                                         */
/*----------------------------------------------------------------------------*/
void Task::vComment(MP_Task mpTask)
{
  ENTRY("vComment"_Stz);
  
  for (;;) {
    mpTask->m_pCompiler->m_pTokeniser->vNextToken();
    if (mpTask->m_pCompiler->m_pTokeniser->sToken().bEqual(")"_Stz))
      break;
  }
  
  EXIT();
}

