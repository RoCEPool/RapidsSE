#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Comment(void)
{
  vAddStep("("_Stz,               &Step::vComment,          true );
}

/*----------------------------------------------------------------------------*/
/* comment -- comment                                                         */
/*----------------------------------------------------------------------------*/
INTRINSIC(vComment)
{
  ENTRY("vComment"_Stz);
  
  for (;;) {
    pForth->m_pTask->m_pCompiler->m_pTokeniser->vNextToken();
    if (pForth->m_pTask->m_pCompiler->m_pTokeniser->sToken().bEqual(")"_Stz))
      break;
  }
  
  EXIT();
}

