#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RowWsp::operator new(size_t iSize)
{
  ASSERT(iSize);
  vFatal("fatal: RowWsp class cannot be new'd\n");
  
  ASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RowWsp::operator new(size_t iSize, RowWsp* pRow)
{
  ASSERT(iSize);
  return pRow;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RowWsp::RowWsp(i8 iDataBytes)
: Header(CN_ROW)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ROW);
  
  m_iTxId      = -1;
  m_iDataBytes = iDataBytes;

  pFooter()->vSetFooter();
  
  _checkInitialised_(sizeof(RowWsp));
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ROW,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RowWsp::~RowWsp(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ROW,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* RowWsp::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ROW);
  
  Footer* pFooter = static_cast<Footer*>(
                      pvAdd(this,sizeof(RowWsp) + m_iDataBytes));
  
  return pFooter;
}

