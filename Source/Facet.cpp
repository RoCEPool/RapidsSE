/*----------------------------------------------------------------------------*/
/* get fact                                                                   */
/*----------------------------------------------------------------------------*/
Fact* Facet::pFact(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_FACET,_FOOTER_);
  
  return m_pFact;
}

/*----------------------------------------------------------------------------*/
/* get kind                                                                   */
/*----------------------------------------------------------------------------*/
Fact* Facet::pFacetKind(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_FACET,_FOOTER_);
  
  return m_pFacetKind;
}

