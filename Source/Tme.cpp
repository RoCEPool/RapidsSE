/*----------------------------------------------------------------------------*/
/*-- Null --------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* test if null                                                               */
/*----------------------------------------------------------------------------*/
bool Tme::bIsNull(void)
{
  if (C_DATUM_NULL == m_iValue)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set to null                                                                */
/*----------------------------------------------------------------------------*/
void Tme::vSetNull(void)
{
  m_iValue = C_DATUM_NULL;
}

/*----------------------------------------------------------------------------*/
/* sprint tme datum                                                           */
/*----------------------------------------------------------------------------*/
void Tme::vSprint(Stz* aDst)
{
  if (bIsNull()) {
    StrLib::vSprint(aDst,"null%c"_Stz,
                    '\0');
    return;
  }
  
  u8 uMicro = x.m_uMicro;

  if (uMicro) {
    char caFraction[16];
    StrLib::vFormatFraction(caFraction,uMicro,6);
    
    StrLib::vSprint(aDst,"%02lld:%02lld:%02lld.%s%c"_Stz,
                    (i8)x.m_uHour,
                    (i8)x.m_uMinute,
                    (i8)x.m_uSecond,
                    caFraction,
                    '\0');
    return;
  }
  
  StrLib::vSprint(aDst,"%02lld:%02lld:%02lld%c"_Stz,
                  (i8)x.m_uHour,
                  (i8)x.m_uMinute,
                  (i8)x.m_uSecond,
                  '\0');
}

