/*============================================================================*/
/* Id.cpp -- id part of an index key                                          */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: RowId class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t iSize, Id* pId)
{
  RASSERT(iSize);
  return pId;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
  m_uBuffer = 0;
  m_uRow    = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(u8 uBuffer, u8 uRow)
{
  m_uBuffer = uBuffer;
  m_uRow = uRow;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Id::~Id(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Id::operator =(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Id::vContentDump(void)
{
  vTrace("Id %p: %llu.%llu\n"_Str,
         this,
         m_uBuffer,
         m_uRow
         );
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Id::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* form the id from given buffer and row                                      */
/*----------------------------------------------------------------------------*/
void Id::vForm(i8 iBuffer, i8 iRow)
{
  m_uBuffer = iBuffer;
  m_uRow = iRow;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iRow(void)
{
  return (i8)m_uRow;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Id::vRow(i8 iRow)
{
  m_uRow = iRow;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vId(Id& xId)
{
  m_uBuffer = xId.m_uBuffer;
  m_uRow    = xId.m_uRow;
}

/*----------------------------------------------------------------------------*/
/* get row from buffer                                                        */
/*----------------------------------------------------------------------------*/
Entry* Id::pRow(void)
{
  RowBuffer* pRowBuffer = reinterpret_cast<RowBuffer*>(gpBufferPool->pToBuffer(m_uBuffer));
  
  Entry* pRow = pRowBuffer->pFirstRow();
  u8 uRowNo = 0;
  while (m_uRow != uRowNo) {
    pRow = pRowBuffer->pNextRow(pRow);
    uRowNo++;
  }
  ASSERT(pRow);
  return pRow;
}

