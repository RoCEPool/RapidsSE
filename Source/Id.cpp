/*============================================================================*/
/* Id.cpp -- the id of an item in a mini-heap                                 */
/*============================================================================*/

#include "Data.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t)
{
  vFatal("fatal: ItemId class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t, Id* pId)
{
  return pId;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
  m_uBuffer = 0;
  m_uItem    = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(Id& xId)
{
  vAssign(xId);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(u8 uBuffer, u8 uItem, u8 uOffsets)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uOffsets = uOffsets;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Id::~Id(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Id::operator =(Id& xId)
{
  vAssign(xId);
}

/*----------------------------------------------------------------------------*/
/* get id as an i8 integer                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iAsI8(void)
{
  i8 iId;
  
  iId  = m_uBuffer << 48;
  iId |= m_uItem;
  
  return iId;
}

/*----------------------------------------------------------------------------*/
/* assign id                                                                  */
/*----------------------------------------------------------------------------*/
void Id::vAssign(Id& xId)
{
  m_uBuffer  = xId.m_uBuffer;
  m_uItem    = xId.m_uItem;
  m_uOffsets = xId.m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* form the id from given buffer and row                                      */
/*----------------------------------------------------------------------------*/
void Id::vAssign(i8 iBuffer, i8 iItem)
{
  m_uBuffer = iBuffer;
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Id::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Id::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get number of offsets                                                      */
/*----------------------------------------------------------------------------*/
i8 Id::nOffsets(void)
{
  return (i8)m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets                                                      */
/*----------------------------------------------------------------------------*/
void Id::vOffsets(i8 nOffsets)
{
  m_uOffsets = nOffsets;
}

