/*============================================================================*/
/* Id.cpp -- id part of an index key                                          */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t)
{
  vFatal("fatal: RowId class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t, Id* pId)
{
  return pId;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
  m_uBuffer = 0;
  m_uRow    = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(u8 uBuffer, u8 uRow)
{
  m_uBuffer = uBuffer;
  m_uRow = uRow;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Id::~Id(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Id::operator =(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* get id as an i8 integer                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iAsI8(void)
{
  i8 iId;
  
  iId  = m_uBuffer << 48;
  iId |= m_uRow;
  
  return iId;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Id::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* form the id from given buffer and row                                      */
/*----------------------------------------------------------------------------*/
void Id::vForm(i8 iBuffer, i8 iRow)
{
  m_uBuffer = iBuffer;
  m_uRow = iRow;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Id::iRow(void)
{
  return (i8)m_uRow;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Id::vRow(i8 iRow)
{
  m_uRow = iRow;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vId(Id& xId)
{
  m_uBuffer = xId.m_uBuffer;
  m_uRow    = xId.m_uRow;
}

/*----------------------------------------------------------------------------*/
/* get number of offsets                                                      */
/*----------------------------------------------------------------------------*/
i8 Id::nOffsets(void)
{
  return (i8)m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets                                                      */
/*----------------------------------------------------------------------------*/
void Id::vOffsets(i8 nOffsets)
{
  m_uOffsets = nOffsets;
}

