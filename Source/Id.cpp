/*============================================================================*/
/* Id.cpp -- id part of an index key                                          */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: RowId class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Id::operator new(size_t iSize, Id* pId)
{
  RASSERT(iSize);
  return pId;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(void)
{
  m_uBuffer = 0;
  m_uRow    = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Id::Id(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Id::~Id(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Id::operator =(Id& xId)
{
  vId(xId);
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Id::vContentDump(void)
{
  vTrace("Id %p: %llu.%llu\n"_Str,
         this,
         m_uBuffer,
         m_uRow
         );
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
u8 Id::uBuffer(void)
{
  return m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vBuffer(u8 uBuffer)
{
  m_uBuffer = uBuffer;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
u8 Id::uRow(void)
{
  return m_uRow;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Id::vRow(u8 uRow)
{
  m_uRow = uRow;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void Id::vId(Id& xId)
{
  m_uBuffer = xId.m_uBuffer;
  m_uRow    = xId.m_uRow;
}

/*----------------------------------------------------------------------------*/
/* get row from buffer                                                        */
/*----------------------------------------------------------------------------*/
Row* Id::pRow(void)
{
  RowBuffer* pRowBuffer = reinterpret_cast<RowBuffer*>(gpBufferPool->pToBuffer(m_uBuffer));
  
  Row* pRow = pRowBuffer->pFirstRow();
  u8 uRowNo = 0;
  while (m_uRow != uRowNo) {
    pRow = pRowBuffer->pNextRow(pRow);
    uRowNo++;
  }
  ASSERT(pRow);
  return pRow;
}

