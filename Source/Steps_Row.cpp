#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Row(void)
{
  vAddStep("Row[].intColumn@"_Stz,     &Step::vRowIntColumnFetch);
}

/*----------------------------------------------------------------------------*/
/* Subset[]@ -- fetch subset                                                  */
/*----------------------------------------------------------------------------*/
void Step::vRowIntColumnFetch(void)
{
  ENTRY(); // ENTRY("vSubsetNext"_Stz);
  
  i8 iColumn;
  
  if ( ! m_pDataStack->bPopInt(iColumn) )
    THROW_DSTACK();
  
  Row* aRow = *m_pRegSet->m_xpRow;
  
  m_pDataStack->vPushInt(aRow->m_waColVal[iColumn].m_iI8);
  
  EXIT();
}

