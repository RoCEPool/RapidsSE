/*============================================================================*/
/* s16K.cpp -- a 16KB-byte s-string                                           */
/*============================================================================*/

#include "Magic.h"
#include "Memory.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s16K::s16K(void)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  Memory::vCheckInitialised(this,sizeof(s16K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s16K::s16K(s16K& rArg)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(rArg.a());
  
  Memory::vCheckInitialised(this,sizeof(s16K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s16K::s16K(const char* aArg)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg);
  
  Memory::vCheckInitialised(this,sizeof(s16K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s16K::s16K(const char* aArg, i8 nChars)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg,nChars);
  
  Memory::vCheckInitialised(this,sizeof(s16K));
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s16K::~s16K(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s16K::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s16K::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s16K::operator = (s& rArg)
{
  vCopy(rArg.a());
}

