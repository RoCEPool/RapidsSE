/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Accum* MockEE::_pAccum(void* aAddr)
{
  Accum* pAccum = reinterpret_cast<Accum*>(aAddr);
  
  RASSERT( ! pAccum || CN_ACCUM == pAccum->eClass() );
 
  return pAccum;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Accum::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  void* pObject = Heaps::pAllocate(CN_ACCUM);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Accum::operator delete(void* pDataAddress)
{
  AccessPath* pAccessPath = reinterpret_cast<AccessPath*>(pDataAddress);
  
  Heaps::vFree(pAccessPath);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Accum::Accum(void)
: Object(CN_ACCUM)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ACCUM,_FOOTER_);
  
  m_iGroup = 0;
  m_iCount = 0;
  m_iSum   = 0;
  m_iMin   = C_I8_MAX;
  m_iMax   = C_I8_MIN;
  
  _checkInitialised_(CN_ACCUM);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ACCUM,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Accum::~Accum(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ACCUM,_FOOTER_);
}

