/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Id::SP_Id(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Id::~SP_Id(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint SP_Id and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* SP_Id::sz(Stz* szPrefix, i8 iId)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  union {
    i8  iId;
    _Id wId;
  } U;
  
  U.iId = iId;
  
  StrLib::vSprint(m_caResult,
                  "%s%lld.%03lld"_Stz,
                  
                  szPrefix,
                  U.wId.m_uNodeNo,
                  U.wId.m_uIdNo);

  return (Stz*) &m_caResult[0];
}


