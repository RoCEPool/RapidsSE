/*----------------------------------------------------------------------------*/
/* sprint SP_Id and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* SP_Id::sz(i8 iId)
{
  union {
    i8  iId;
    _Id wId;
  } U;
  
  U.iId = iId;
  
  StrLib::vSprint(m_caResult,
                  "%lld.%lld"_Stz,
                  U.wId.m_uNodeNo,
                  U.wId.m_uIdNo);

  return (Stz*) &m_caResult[0];
}

