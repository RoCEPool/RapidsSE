/*============================================================================*/
/* Ref.cpp -- Reference to another buffer item                                */
/*============================================================================*/

#include "Rows.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Ref::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: Ref class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new(aId)                                                          */
/*----------------------------------------------------------------------------*/
void* Ref::operator new(size_t, Ref* aRef)
{
  return aRef;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uOffsets = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(Ref& xRef)
{
  vAssign(xRef);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(u8 uBuffer, u8 uItem, u8 uOffsets)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uOffsets = uOffsets;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Ref::~Ref(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::operator =(Ref& xRef)
{
  vAssign(xRef);
}

/*----------------------------------------------------------------------------*/
/* get id as an i8 integer                                                    */
/*----------------------------------------------------------------------------*/
i8 Ref::iAsI8(void)
{
  i8 iRef;

  iRef  = m_uBuffer << 48;
  iRef |= m_uItem;

  return iRef;
}

/*----------------------------------------------------------------------------*/
/* assign id                                                                  */
/*----------------------------------------------------------------------------*/
void Ref::vAssign(Ref& xRef)
{
  m_uBuffer  = xRef.m_uBuffer;
  m_uItem    = xRef.m_uItem;
  m_uOffsets  = xRef.m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Ref::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Ref::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Ref::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get number of levels                                                       */
/*----------------------------------------------------------------------------*/
i8 Ref::nOffsets(void)
{
  return (i8)m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* set number of levels                                                       */
/*----------------------------------------------------------------------------*/
void Ref::vOffsets(i8 nLevels)
{
  m_uOffsets = nLevels;
}

