/*============================================================================*/
/* Ref.cpp -- Reference to another buffer item                                */
/*============================================================================*/

#include "Rows.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(void)
{
  vSetNil();
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(u8 uBuffer, u8 uItem, u8 uLevels)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uLevels  = uLevels;
  
  m_uKind    = KE_GENERAL;
  m_uPayload = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Ref::~Ref(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::operator =(Ref xwRef)
{
  vSet(xwRef);
}

/*----------------------------------------------------------------------------*/
/* get contents as an i8 integer                                              */
/*----------------------------------------------------------------------------*/
i8 Ref::iAsI8(void)
{
  return m_iAsI8;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Ref::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* is nil reference?                                                          */
/*----------------------------------------------------------------------------*/
bool Ref::bIsNil(void)
{
  if (0 == m_uBuffer)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* get item                                                                   */
/*----------------------------------------------------------------------------*/
i8 Ref::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set item                                                                   */
/*----------------------------------------------------------------------------*/
void Ref::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get entry key kind                                                        */
/*----------------------------------------------------------------------------*/
eKE Ref::eKind(void)
{
  return (eKE)m_uKind;
}

/*----------------------------------------------------------------------------*/
/* set entry key kind                                                        */
/*----------------------------------------------------------------------------*/
void Ref::vKind(eKE eKind)
{
  m_uKind = eKind;
}

/*----------------------------------------------------------------------------*/
/* is there a payload after ent?                                              */
/*----------------------------------------------------------------------------*/
bool Ref::bPayload(void)
{
  return (bool)m_uPayload;
}

/*----------------------------------------------------------------------------*/
/* set is there a payload                                                     */
/*----------------------------------------------------------------------------*/
void Ref::vPayload(bool bPayLoad)
{
  m_uPayload = bPayLoad;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Ref::vReset(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uLevels  = 0;
  
  m_uKind    = 0;
  m_uPayload = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* set ref                                                                    */
/*----------------------------------------------------------------------------*/
void Ref::vSet(Ref xwRef)
{
  m_uBuffer  = xwRef.m_uBuffer;
  m_uItem    = xwRef.m_uItem;
  m_uLevels  = xwRef.m_uLevels;
  m_uKind    = xwRef.m_uKind;
  m_uPayload = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* set nil ref                                                                */
/*----------------------------------------------------------------------------*/
void Ref::vSetNil(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uLevels  = 0;
  
  m_uKind    = 0;
  m_uPayload = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* get number of skip levels                                                  */
/*----------------------------------------------------------------------------*/
i8 Ref::nSkipLevels(void)
{
  return (i8)m_uLevels;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets that follow                                          */
/*----------------------------------------------------------------------------*/
void Ref::vSkipLevels(i8 nSkipLevels)
{
  m_uLevels = nSkipLevels;
}

