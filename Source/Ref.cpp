#include "Rows.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(void)
{
  vSetNil();
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ref::Ref(u8 uBuffer, u8 uItem, u8 uOffsets)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uOffsets = uOffsets;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Ref::~Ref(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::operator =(Ref xwRef)
{
  vSet(xwRef);
}

/*----------------------------------------------------------------------------*/
/* get id as an i8 integer                                                    */
/*----------------------------------------------------------------------------*/
i8 Ref::iAsI8(void)
{
//  i8 iRef;
//
//  iRef  = m_uBuffer << 48;
//  iRef |= m_uItem;
//
//  return iRef;
  
  return m_iAsI8;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Ref::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Ref::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* is nil reference?                                                          */
/*----------------------------------------------------------------------------*/
bool Ref::bIsNil(void)
{
  if (0 == m_uBuffer)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* get row                                                                    */
/*----------------------------------------------------------------------------*/
i8 Ref::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set row                                                                    */
/*----------------------------------------------------------------------------*/
void Ref::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get number of levels                                                       */
/*----------------------------------------------------------------------------*/
i8 Ref::nOffsets(void)
{
  return (i8)m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* set number of levels                                                       */
/*----------------------------------------------------------------------------*/
void Ref::vOffsets(i8 nLevels)
{
  m_uOffsets = nLevels;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Ref::vReset(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uOffsets = 0;
}

/*----------------------------------------------------------------------------*/
/* set ref                                                                    */
/*----------------------------------------------------------------------------*/
void Ref::vSet(Ref xwRef)
{
  m_uBuffer  = xwRef.m_uBuffer;
  m_uItem    = xwRef.m_uItem;
  m_uOffsets = xwRef.m_uOffsets;
}

/*----------------------------------------------------------------------------*/
/* set nil ref                                                                */
/*----------------------------------------------------------------------------*/
void Ref::vSetNil(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uOffsets = 0;
}

