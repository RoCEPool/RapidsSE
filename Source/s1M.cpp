#include "Values.h"
#include "Memory.hpp"
#include "StorageEngine.h"

extern BufferPool*  gpBufferPool;

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s1M::s1M(void)
: StrVal(CN_S1M,C_S1M_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S1M_DATAAREA);
  
  _checkInitialised_(CN_S1M);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s1M::s1M(s1M& rArg)
: StrVal(CN_S1M,C_S1M_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);

  Memory::vZero(m_mDataArea, C_S1M_DATAAREA);
  
  StrVal::vCopy(rArg.a());
  
  _checkInitialised_(CN_S1M);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s1M::s1M(const char* aArg)
: StrVal(CN_S1M,C_S1M_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S1M_DATAAREA);
  
  StrVal::vCopy(aArg);
  
  _checkInitialised_(CN_S1M);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s1M::~s1M(void)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s1M::operator = (const char* aArg)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
  StrVal::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s1M::operator = (char* aArg)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
  StrVal::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s1M::operator = (StrVal& rArg)
{
  _precondition_(_MAGIC_,CN_S1M,_FOOTER_);
  
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s1M::pFooter(void)
{
  _precondition_(_MAGIC_,CN_S1M);
  
  return &m_xFooter;
}

