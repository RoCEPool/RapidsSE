/*============================================================================*/
/* on.cpp - offset number                                                     */
/*============================================================================*/

#include "DBobjects.h"
  
/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
on::on(void)
{
  // DO NOT INITIALISE -- ray
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
on::on(u8 uOffsetNo)
{
  m_uOffsetNo = uOffsetNo;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
on::~on(void)
{
}
 
/*----------------------------------------------------------------------------*/
/* nil offset no indicator                                                    */
/*----------------------------------------------------------------------------*/
on on::nNil(void)
{
  return -1;
}

/*----------------------------------------------------------------------------*/
/* convert offset no to level no                                              */
/*----------------------------------------------------------------------------*/
u8 on::nToLevelNo(void)
{
  u8 nLevelNo = m_uOffsetNo + 1;
  return nLevelNo;
}

/*----------------------------------------------------------------------------*/
/* get next offset number                                                     */
/*----------------------------------------------------------------------------*/
u8 on::operator *(void)
{
  return m_uOffsetNo;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool on::operator ==(on n)
{
  return m_uOffsetNo == *n;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool on::operator !=(on n)
{
  return m_uOffsetNo != *n;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool on::operator <=(on n)
{
  return m_uOffsetNo <= *n;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool on::operator >=(on n)
{
  return m_uOffsetNo >= *n;
}

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
on on::operator +(u8 u)
{
  return m_uOffsetNo + u;
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
on on::operator -(u8 u)
{
  return m_uOffsetNo - u;
}

/*----------------------------------------------------------------------------*/
/* postfix increment                                                          */
/*----------------------------------------------------------------------------*/
on on::operator ++(int)
{
  return ++m_uOffsetNo;
}

/*----------------------------------------------------------------------------*/
/* _bn buffer number literal suffix                                           */
/*----------------------------------------------------------------------------*/
on DBobjects::operator "" _on(unsigned long long u)
{
  return (on)u;
}

