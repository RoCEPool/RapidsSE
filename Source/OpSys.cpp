#include "System.h"

static struct utsname gxUtsName;

/*----------------------------------------------------------------------------*/
/* get information about                                                     */
/*----------------------------------------------------------------------------*/
void OpSys::vGetInfo(void)
{
  int iResult = uname(&gxUtsName);
  
  if (0 == iResult)
    return;
  
  vWarn("OpSys::vGetInfo: uname() error; errno=%d"_Stz,errno);
}

