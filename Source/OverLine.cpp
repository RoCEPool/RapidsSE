#include "Data.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
OverLine::OverLine(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
OverLine::~OverLine(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return size of overflow line in bytes                                      */
/*----------------------------------------------------------------------------*/
i8 OverLine::nBytes(void)
{
  i8 nSizeBytes = nWords() * C_BYTES_PER_WORD;
  
  return nSizeBytes;
}

/*----------------------------------------------------------------------------*/
/* return size of overflow line in words                                      */
/*----------------------------------------------------------------------------*/
i8 OverLine::nWords(void)
{
  i8 nSizeWords = w8_1B(0);
  
  return nSizeWords;
}

