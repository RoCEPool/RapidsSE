/*============================================================================*/
/* IpVal.cpp - instruction pointer value                                      */
/*============================================================================*/

#include "Values.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IpVal* Values::_aIpVal(void* aAddr)
{
  IpVal* aIpVal = reinterpret_cast<IpVal*>(aAddr);
  
  RASSERT_TYPE(aIpVal,CN_FIPVAL);
  
  return aIpVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IpVal::operator new(size_t)
{
  vFatal("fatal: IpVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IpVal::IpVal(void)
: Value(CN_FIPVAL)
{
  m_pPtr = nullptr;
  
  _checkInitialised_(CN_FIPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IpVal::operator =(Cell* aPtr)
{
  m_pPtr = aPtr;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IpVal::nSize(void) const
{
  return sizeof(IpVal);
}

/*----------------------------------------------------------------------------*/
/* get pVal                                                                   */
/*----------------------------------------------------------------------------*/
Cell* IpVal::aIpPtr(void) const
{
  return pPoolCheck<Cell*>(m_pPtr);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IpVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = reinterpret_cast<void*>(m_pPtr);
}

