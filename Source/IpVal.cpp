#include "Values.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IpVal* Values::_pIpVal(void* aAddr)
{
  IpVal* pIpVal = reinterpret_cast<IpVal*>(aAddr);
  
  RASSERT_TYPE(pIpVal,CN_IPVAL);
  
  return pIpVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IpVal::operator new(size_t)
{
  vFatal("fatal: IpVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IpVal::IpVal(void)
: Value(CN_IPVAL)
{
  m_pPtr = nullptr;
  
  _checkInitialised_(CN_IPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IpVal::operator =(Cell* pPtr)
{
  m_pPtr = pPtr;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IpVal::nSize(void) const
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* get pVal                                                                   */
/*----------------------------------------------------------------------------*/
Cell* IpVal::pIpPtr(void) const
{
  return pPoolCheck<Cell*>(m_pPtr);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IpVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = reinterpret_cast<void*>(m_pPtr);
}

