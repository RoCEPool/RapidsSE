/*============================================================================*/
/* IpVal.cpp - instruction pointer value                                      */
/*============================================================================*/

#include "Values.h"
#include "Dictionaries.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IpVal* Values::_pIpVal(void* pAddr)
{
  IpVal* pIpVal = reinterpret_cast<IpVal*>(pAddr);
  
  RASSERT( !pIpVal || CN_IPVAL == pIpVal->eClass() );
  
  return pIpVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IpVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: IpVal class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IpVal::IpVal(void)
: Value(CN_IPVAL)
{
  m_pPtr = nullptr;
  
  _checkInitialised_(CN_IPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IpVal::operator =(Cell* pPtr)
{
  m_pPtr = pPtr;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IpVal::iSize(void) const
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* get pVal                                                                   */
/*----------------------------------------------------------------------------*/
Cell* IpVal::pIpPtr(void) const
{
  return pPoolCheck<Cell*>(m_pPtr);
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void IpVal::vToCommand(char* aWorkspace)
{
  ASSERT(aWorkspace);
  ASSERT("Should never be called");
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IpVal::vToString(char* aWorkspace)
{
  String::wToPointer(m_pPtr,aWorkspace);
}

