/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Job_Space::vDump(eCN eClass, Object* pObject, Stz* aTab)
{
  RASSERT(CN_JOB_SPACE == eClass);
  RASSERT(pObject->eClass() == CN_JOB_SPACE);
  
  Job_Space* pJob_Space = _pJob_Space(pObject);

  pJob_Space->vShow();
}

