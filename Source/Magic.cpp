Magic::~Magic(void)
{
}

/*----------------------------------------------------------------------------*/
/* assert magic                                                               */
/*----------------------------------------------------------------------------*/
void Magic::vAssertMagic(void)
{
  _magic_();
}

/*----------------------------------------------------------------------------*/
/* test for valid magic                                                       */
/*----------------------------------------------------------------------------*/
bool Magic::bValidMagic(void)
{
   if (C_MAGIC == m_uMagic)
     return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* get magic                                                                  */
/*----------------------------------------------------------------------------*/
i8 Magic::iMagic(void) const
{
  return m_uMagic;
}

/*----------------------------------------------------------------------------*/
/* set magic                                                                  */
/*----------------------------------------------------------------------------*/
void Magic::vSetMagic(void)
{
  m_uMagic = C_MAGIC;
}

