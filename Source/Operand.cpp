#include "Streams.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Operand* Streams::_pOperand(void* aAddress)
{
  Operand* pOperand = reinterpret_cast<Operand*>(aAddress);
  
  return pOperand;
}

/*----------------------------------------------------------------------------*/
/* is given class a valid operand?                                            */
/*----------------------------------------------------------------------------*/
bool Streams::_bIsValidOperand(eCN eClass)
{
  switch(eClass) {
    case CN_ENDMARKER:
    case CN_CRWBUFFER:
    case CN_IRWBUFFER:
    case CN_STREAMDEF:
      return true;
    default:
      return false;
  }
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Operand::Operand(eCN eClassNo)
: AlignedObject(eClassNo,sizeof(Operand))
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
    
  MemLib::vZero(m__Padding,sizeof(m__Padding),eClassNo);

  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);  
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Operand::~Operand(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


