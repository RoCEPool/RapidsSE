#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryOp::vSet(LogEntry* pLogEntry, Op* pOp, eOA eOpAct)
{
  pLogEntry->m_eKind = EK_OPR;
  
  m_iOpId  = pOp->m_iUniqueId;
  m_eOpAct = eOpAct;
}

/*----------------------------------------------------------------------------*/
/* cat sprint to given string                                                 */
/*----------------------------------------------------------------------------*/
void _LogEntryOp::vSprint(s4K& sString)
{
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryOp::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("O"_Stz,m_iOpId),
                aOA[m_eOpAct]);
}

