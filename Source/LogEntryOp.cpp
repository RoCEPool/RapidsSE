#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryOp::vSet(LogEntry* pLogEntry, Op* pOp, i8 iOpId, eOA eOpAct)
{
  pLogEntry->m_eKind = EK_OPR;
  
  m_iOpId  = iOpId;
  m_eOpAct = eOpAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryOp::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("O"_Stz,m_iOpId),
                aOA[m_eOpAct]);
}

