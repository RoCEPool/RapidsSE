#include "Pool.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* Slab::operator new(size_t iSize)
{
  RASSERT(iSize);
  Buffer* pBuffer = gpBufferPool->pAllocBuffer();
  
  return pPoolCheck<void*>(pBuffer);
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void Slab::operator delete(void* pSlabAddress)
{
  Buffer* pBuffer = static_cast<Buffer*>(pSlabAddress);
  
  gpBufferPool->vFree(pBuffer);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Slab::Slab(void)
: Buffer(CN_SLAB)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB);
  
  m_pNextSlab = nullptr;
  
  _checkInitialisedSize_(sizeof(Slab));

  _postcondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Slab::~Slab(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* allot given number of bytes                                                */
/*----------------------------------------------------------------------------*/
char* Slab::aAllotBytes(i8 nBytes)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  // test sufficient freespace
  if (m_xWsp.nFree() < nBytes)
    return nullptr;
  
  // allot bytes in the wsp
  char* aBytes = m_xWsp.aAllot(nBytes);
  
  return aBytes;
}

/*----------------------------------------------------------------------------*/
/* get next slab                                                              */
/*----------------------------------------------------------------------------*/
Slab* Slab::pNextSlab(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  return m_pNextSlab;
}

/*----------------------------------------------------------------------------*/
/* set next slab                                                              */
/*----------------------------------------------------------------------------*/
void Slab::vNextSlab(Slab* pNextSlab)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SLAB,_FOOTER_);
  
  m_pNextSlab = pNextSlab;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Slab::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return &m_xFooter;
}

