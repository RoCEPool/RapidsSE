#include "LexicalAnalysis.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Token::SP_Token(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Token::~SP_Token(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_Token::sz(Token* pToken)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
    
  StrLib::vSprint(m_caResult,
                  "Token %p: [%lld (%2lld,%2lld)] %s %s"_Stz,
                  
                  pToken,
                  pToken->i_Token(),
                  pToken->iLineNo(),
                  pToken->iColNo(),
                  aTN[pToken->eToken()],
                  pToken->szChars()
                  );
  
  return (Stz*) &m_caResult[0];
}

