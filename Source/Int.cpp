/*----------------------------------------------------------------------------*/
/* extract int datum                                                          */
/*----------------------------------------------------------------------------*/
bool Int::bExtractInt(Str* aDst, Str* aSrc, i8& nBytesTaken)
{
  char* aExt = (char*)aSrc;
  
  i8 iInt;
  bool b = StrLib::bExtractI8(&aExt,&iInt);
  if (b) {
    MemLib::vCopy(aDst,&iInt,sizeof(i8));
  
    nBytesTaken = sizeof(i8);
  }
  
  return b;
}

