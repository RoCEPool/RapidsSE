/*============================================================================*/
/* IntVar.cpp - Integer Sen Variable                                          */
/*============================================================================*/

#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVar::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: IntVar class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVar::operator =(i8 iInt)
{
  vClass(CN_INTVAR);

  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get iInt                                                                   */
/*----------------------------------------------------------------------------*/
i8 IntVar::iInt(void)
{
  ASSERT(CN_INTVAR == eClass());

  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IntVar::nStackBytes(void)
{
  ASSERT(CN_INTVAR == eClass());
  
  return sizeof(IntVar);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVar::vToString(Stz* aWorkspace)
{
  ASSERT(CN_INTVAR == eClass());

  if (C_DATUM_NULL == m_iInt) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  * aWorkspace = m_iInt;
}

