/*----------------------------------------------------------------------------*/
/* get row address                                                            */
/*----------------------------------------------------------------------------*/
RowData* RowWrk::aRowData(void)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  RowData* aThisRow = (RowData*)aEmbedded();
  return aThisRow;
}

/*----------------------------------------------------------------------------*/
/* get row size                                                               */
/*----------------------------------------------------------------------------*/
i8 RowWrk::nRowSize(void)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  return nEmbeddedSize();
}

/*----------------------------------------------------------------------------*/
/* set row size                                                               */
/*----------------------------------------------------------------------------*/
void RowWrk::vRowSize(i8 nRowSize)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  vEmbeddedSize(nRowSize);
}

/*----------------------------------------------------------------------------*/
/* set row entry                                                              */
/*----------------------------------------------------------------------------*/
void RowWrk::vSetEntry(Item* aEntry)
{
  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
  // set id, transaction and offsets
  
  aEntry->vId(xId());
  aEntry->vOffsets(nOffsets());
  
  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
  // copy row into this entry
  
  RowData* aSrcRow = aRowData();
  RowData* aDstRow = _aRowData(aEntry->aDataArea());
  i8 nRowSize  = this->nRowSize();
  
  MemLib::vCopy(aDstRow,aSrcRow,nRowSize,CN_ENTRY);
}

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void RowWrk::vShow(ColumnVec* pColVec)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  RowData* aThisRow = aRowData();
  aThisRow->vShow(pColVec, true);
  vTrace("\n"_Stz);
}

