#include "Data.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RowWrk::operator new(size_t)
{
  vFatal("fatal: EntWrk class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RowWrk::operator new(size_t, RowWrk* pRowWrk)
{
  return pRowWrk;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RowWrk::RowWrk(void)
: EntWrk(CN_ROWWRK)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  _checkInitialisedSize_(sizeof(RowWrk));
  
  _postcondition_(_MAGIC_,CN_ROWWRK,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RowWrk::~RowWrk(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_ROWWRK,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get row address                                                            */
/*----------------------------------------------------------------------------*/
Row* RowWrk::aRow(void)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  Row* aThisRow = (Row*)aEmbedded();
  return aThisRow;
}

/*----------------------------------------------------------------------------*/
/* get row size                                                               */
/*----------------------------------------------------------------------------*/
i8 RowWrk::nRowSize(void)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  return nEmbeddedSize();
}

/*----------------------------------------------------------------------------*/
/* set row size                                                               */
/*----------------------------------------------------------------------------*/
void RowWrk::vRowSize(i8 nRowSize)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  vEmbeddedSize(nRowSize);
}

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void RowWrk::vShow(ColumnVec* pColVec)
{
  _precondition_(_MAGIC_,CN_ROWWRK);
  
  Row* aThisRow = aRow();
  aThisRow->vShow(pColVec, true);
  vTrace("\n"_Stz);
}

