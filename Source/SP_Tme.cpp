#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Tme::SP_Tme(void)
: Sprint(CN_SPTME)
{
  _precondition_(_MAGIC_,CN_SPTME,_FOOTER_);
  
  // set default Tme format
  vFormat(F_TME);
  
  _checkInitialised_(CN_SPTME);
  
  _postcondition_(_MAGIC_,CN_SPTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Tme::~SP_Tme(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Tme and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* SP_Tme::sz(i8 iTme)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  Word wTme = iTme;
  
  if (wTme.m_wDtm.xTme.m_uMicro) {
    
    char caFraction[16];
    StrLib::vFormatFraction(caFraction,wTme.m_wDtm.xTme.m_uMicro,6);
    
    StrLib::vSprint(m_caResult,
                    (Stz*)F_TME_frac,

                    (i8)wTme.m_wDtm.xTme.m_uHour,
                    (i8)wTme.m_wDtm.xTme.m_uMinute,
                    (i8)wTme.m_wDtm.xTme.m_uSecond,
                    
                    caFraction);
  }
  else {
    StrLib::vSprint(m_caResult,
                    (Stz*)F_TME,

                    (i8)wTme.m_wDtm.xTme.m_uHour,
                    (i8)wTme.m_wDtm.xTme.m_uMinute,
                    (i8)wTme.m_wDtm.xTme.m_uSecond);
  }

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tme::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTme(23,59,59,999999) );
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tme::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTme(3,3,2,1) );
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Tme::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iTme(0,0,0,0) );
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SP_Tme::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPTME);
  
  return &m_xFooter;
}

