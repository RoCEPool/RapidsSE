/*============================================================================*/
/* bn.cpp - buffer number                                                     */
/*============================================================================*/

#include "Pool.h"
  
/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
bn::bn(void)
{
  // DO NOT INITIALISE -- ray
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
bn::bn(i8 iBufferNo)
{
  m_iBufferNo = iBufferNo;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
bn::~bn(void)
{
}
 
/*----------------------------------------------------------------------------*/
/* nil buffer no indicator                                                    */
/*----------------------------------------------------------------------------*/
bn bn::nNil(void)
{
  return -1;
}

/*----------------------------------------------------------------------------*/
/* get next buffer number                                                     */
/*----------------------------------------------------------------------------*/
i8 bn::operator *(void)
{
  return m_iBufferNo;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool bn::operator ==(bn n)
{
  return m_iBufferNo == *n;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool bn::operator !=(bn n)
{
  return m_iBufferNo != *n;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool bn::operator <=(bn n)
{
  return m_iBufferNo <= *n;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool bn::operator >=(bn n)
{
  return m_iBufferNo >= *n;
}

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
bn bn::operator +(int i)
{
  return m_iBufferNo + i;
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
bn bn::operator -(int i)
{
  return m_iBufferNo - i;
}

/*----------------------------------------------------------------------------*/
/* postfix increment                                                          */
/*----------------------------------------------------------------------------*/
bn bn::operator ++(int i)
{
  return ++m_iBufferNo;
}

/*----------------------------------------------------------------------------*/
/* _bn buffer number literal suffix                                           */
/*----------------------------------------------------------------------------*/
bn Pool::operator "" _bn(unsigned long long i)
{
  return (bn)i;
}

