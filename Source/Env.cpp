#include "System.h"

/*----------------------------------------------------------------------------*/
/* translate environment variable                                             */
/*----------------------------------------------------------------------------*/
bool Env::bGet(s32& sName, s256& sValue)
{
  char* aValue = getenv(sName.aChar());
  if ( ! aValue )
    return false;
  
  sValue.vCopy((Stz*)aValue);
  
  return true;
}

