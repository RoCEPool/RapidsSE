#include "System.h"

/*----------------------------------------------------------------------------*/
/* translate environment variable                                             */
/*----------------------------------------------------------------------------*/
bool Env::bGet(s256& sName, s256& sValue)
{
  char* aValue;
  
  aValue = getenv(sName.aStr());
  if ( ! aValue )
    return false;
  
  StrLib::vCopyLen(sValue.aStr(),aValue,256);
  
  return true;
}

