#include "Env.hpp"

/*----------------------------------------------------------------------------*/
/* translate environment variable                                             */
/*----------------------------------------------------------------------------*/
bool Env::bGet(s256& sName, s256& sValue)
{
  char* aValue;
  
  aValue = getenv(sName.a());
  if ( ! aValue )
    return false;
  
  String::vCopyLen(sValue.a(),aValue,256);
  
  return true;
}

