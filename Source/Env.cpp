#include "Env.hpp"

/*---------------------------------------------------------------------------*/
/* translate environment variable                                            */
/*---------------------------------------------------------------------------*/
bool Env::bGetEnv(const char* aEnvName, char* aEnvValue)
{
  char* aValue;
  
  aValue = getenv(aEnvName);
  if ( ! aValue )
    return false;

  String::vCopy(aEnvValue,aValue);
  
  return true;
}

