/*============================================================================*/
/* s32.cpp -- a 256 byte s-string                                             */
/*============================================================================*/

#include "Magic.h"
#include "Memory.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(void)
: s(CN_S32,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  Memory::vCheckInitialised(this,sizeof(s32));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(s32& rArg)
: s(CN_S32,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  s::vCopy(rArg.a());
  
  Memory::vCheckInitialised(this,sizeof(s32));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(const char* aArg)
: s(CN_S32,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  s::vCopy(aArg);
  
  Memory::vCheckInitialised(this,sizeof(s32));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(const char* aArg, i8 nChars)
: s(CN_S32,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  s::vCopy(aArg,nChars);
  
  Memory::vCheckInitialised(this,sizeof(s32));
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s32::~s32(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (s& rArg)
{
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void s32::vInit()
{
  s::vInit(C_S_SIZE);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s32::pFooter(void)
{
  return &m_xFooter;
}

