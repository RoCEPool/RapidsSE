/*============================================================================*/
/* s32.cpp -- a 256 byte s-string                                             */
/*============================================================================*/

#include "Common.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(void)
: s(C_S_SIZE)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(s32& rArg)
: s(C_S_SIZE)
{
  s::vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(const char* aArg)
: s(C_S_SIZE)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s32::s32(const char* aArg, i8 nChars)
: s(C_S_SIZE)
{
  s::vCopy(aArg,nChars);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s32::~s32(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s32::operator = (s& rArg)
{
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void s32::vInit()
{
  s::vInit(C_S_SIZE);
}

