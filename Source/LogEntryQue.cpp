#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryQue::vSet(LogEntry* pLogEntry, i8 iQueId, eQA eQueAct)
{
  pLogEntry->m_eKind = EK_QUE;
  
  m_iQueId  = iQueId;
  m_eQueAct = eQueAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryQue::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("Q"_Stz,m_iQueId),
                aQA[m_eQueAct]);
}

