#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryTsk::vSet(LogEntry* pLogEntry, Task* pTask, i8 iTskId, eTA eTskAct)
{
  pLogEntry->m_eKind = EK_TSK;
  
  m_iTskId  = iTskId;
  m_eTskAct = eTskAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryTsk::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("T"_Stz,m_iTskId),
                aTA[m_eTskAct]);
}

