#include "Esses.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* String::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: String class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
String::String(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
String::~String(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy arg into this string                                                  */
/*----------------------------------------------------------------------------*/
void String::vCatSprint(Stz* szFormat, ...)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();
  
  va_list vaArgs;
  
  char* aEnd = aAdd<char*>(m_caStr,nLength());
  
  va_start(vaArgs,szFormat);
  vsprintf(aEnd,(char*)szFormat,vaArgs);
  va_end(vaArgs);
}

/*----------------------------------------------------------------------------*/
/* concat argument                                                            */
/*----------------------------------------------------------------------------*/
void String::vConcat(Stz* szArg)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();
  
  StrLib::vConcat(m_caStr,szArg->azChar());
}


/*----------------------------------------------------------------------------*/
/* copy arg into this string                                                  */
/*----------------------------------------------------------------------------*/
void String::vCopy(Stz* szArg)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  StrLib::vCopyLen(m_caStr,szArg->azChar(),m_nSize - 1);

  aFooter()->vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/* get size of string                                                         */
/*----------------------------------------------------------------------------*/
i8 String::nLength(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  i8 nLen = StrLib::nLength(m_caStr);
  
  return nLen;
}

/*----------------------------------------------------------------------------*/
/* get size of string                                                         */
/*----------------------------------------------------------------------------*/
i8 String::nSize(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return m_nSize;
}

/*----------------------------------------------------------------------------*/
/* vSprint: formatted sprint                                                  */
/*----------------------------------------------------------------------------*/
void String::vSprint(Stz* szFormat, ...)
{
  va_list args;
  va_start(args,szFormat);
  
  vsprintf(m_caStr,szFormat->azChar(),args);
  
  va_end(args);
}

/*----------------------------------------------------------------------------*/
/* get size of string                                                         */
/*----------------------------------------------------------------------------*/
i8 String::nStackUsage(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();
  
  i8 nBytes = sizeof(_Header) + sizeof(i8) + StrLib::nSize(m_caStr);
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get char*                                                                  */
/*----------------------------------------------------------------------------*/
char* String::azStr(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return (char*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/* get Stz*                                                                   */
/*----------------------------------------------------------------------------*/
Stz* String::szStz(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return (Stz*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* String::aFooter(void)
{
  m_xHeader.vAssertHeader();

  i8 nSizeHeaderBody = sizeof(m_xHeader) + sizeof(m_nSize) + m_nSize;
  
  Footer* aFooter = aAdd<Footer*>(this,nSizeHeaderBody);
  
  return aFooter;
}

