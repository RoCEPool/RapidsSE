#include "Esses.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* String::operator new(size_t)
{
  vThrow(FK_FATAL,__func__,__FILE__,__LINE__,
         "fatal: String class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
String::String(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
String::~String(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy arg into this string                                                  */
/*----------------------------------------------------------------------------*/
void String::vCopy(Stz* szArg)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  StrLib::vCopyLen(m_caStr,szArg->azChar(),m_nSize - 1);

  aFooter()->vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/* get size of string                                                         */
/*----------------------------------------------------------------------------*/
i8 String::nSize(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return m_nSize;
}

/*----------------------------------------------------------------------------*/
/* get char*                                                                  */
/*----------------------------------------------------------------------------*/
char* String::azStr(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return (char*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/* get Stz*                                                                   */
/*----------------------------------------------------------------------------*/
Stz* String::szStz(void)
{
  m_xHeader.vAssertHeader();
  aFooter()->vAssertFooter();

  return (Stz*) m_caStr;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* String::aFooter(void)
{
  m_xHeader.vAssertHeader();

  i8 nSizeHeaderBody = sizeof(m_xHeader) + sizeof(m_nSize) + m_nSize;
  
  Footer* aFooter = aAdd<Footer*>(this,nSizeHeaderBody);
  
  return aFooter;
}

