#include "CorrectnessAlgebra.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer_Emb::Footer_Emb(void)
{
  m_uFooter = C_FOOTER_EMB;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer_Emb::~Footer_Emb(void)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/* ASSERT Footer_Emb                                                          */
/*----------------------------------------------------------------------------*/
void Footer_Emb::vAssertFooter(void) const
{
  ASSERT(m_uFooter == C_FOOTER_EMB);
}

/*----------------------------------------------------------------------------*/
/* set Footer_Emb                                                             */
/*----------------------------------------------------------------------------*/
void Footer_Emb::vSetFooter(void)
{
  m_uFooter = C_FOOTER_EMB;
}

