#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Atomic::operator new(size_t, Atomic* pAtomic)
{
  //UNUSED(iSize)
  return pAtomic;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Atomic::operator delete(void* pAtomicAddress)
{
  RASSERT(pAtomicAddress);
  // do nothing
  // must be explicitly free'd by caller
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Atomic::Atomic(void)
: Object(CN_ATOMIC)
{
  m_iInt = 0;
  
  _checkInitialised_(CN_ATOMIC);
  
  _postcondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Atomic::~Atomic(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* check lock initialization                                                  */
/*----------------------------------------------------------------------------*/
void Atomic::vCheckInit(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  ASSERT(0 == m_iInt); // logic check
}

/*----------------------------------------------------------------------------*/
/* atomically add                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iAdd(i8 iValue)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Synch::uAtomicAdd(&m_iInt, iValue);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically inc                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iInc()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = Synch::uAtomicInc(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iDec()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = Synch::uAtomicDec(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Atomic::operator =(i8 iInt)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* dereference / get value                                                    */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator *(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* atomically inc (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator ++(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Synch::uAtomicInc(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator --(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Synch::uAtomicDec(&m_iInt);

  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically add                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator +=(i8 iValue)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Synch::uAtomicAdd(&m_iInt, iValue);

  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically subtract                                                        */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator -=(i8 iValue)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = Synch::uAtomicAdd(&m_iInt, ( - iValue) );  // nb the minus sign
  
  return i;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Atomic::aFooter(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC);
  
  return &m_xFooter;
}

