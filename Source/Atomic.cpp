#include "Common.h"

#include "Pool.h"

extern BufferPool* gpBufferPool;

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Atomic::operator new(size_t iSize, Atomic* pAtomic)
{
  RASSERT(iSize);
  return pAtomic;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Atomic::operator delete(void* pAtomicAddress)
{
  RASSERT(pAtomicAddress);
  // do nothing
  // must be explicitly free'd by caller
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Atomic::Atomic(void)
: Header(CN_ATOMIC)
{
  m_iInt = 0;
  
  _checkInitialised_(sizeof(Atomic));
  
  _postcondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Atomic::~Atomic(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* check lock initialization                                                  */
/*----------------------------------------------------------------------------*/
void Atomic::vCheckInit(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  ASSERT(0 == m_iInt); // logic check
}

/*----------------------------------------------------------------------------*/
/* atomically inc                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iInc()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = iAtomicInc(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iDec()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = iAtomicDec(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Atomic::operator =(i8 iInt)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* dereference / get value                                                    */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator *(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* atomically inc (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator ++(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = iAtomicInc(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator --(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = iAtomicDec(&m_iInt);

  return i;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Atomic::pFooter(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC);
  
  return &m_xFooter;
}

