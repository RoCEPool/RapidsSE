#include "Common.h"

#include "Pool.h"

extern BufferPool* gpBufferPool;

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Atomic::operator new(size_t iSize, Atomic* pAtomic)
{
  ASSERT(iSize);
  return pAtomic;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Atomic::operator delete(void* pAtomicAddress)
{
  // do nothing
  // must be explicitly free'd by caller
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Atomic::Atomic(void)
: Header(CN_ATOMIC)
{
  vInit();
  
  Memory::vCheckInitialised(this,sizeof(Atomic));
  
  _postcondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Atomic::~Atomic(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void Atomic::vInit(void)
{  
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  m_iValue = 0;
}

/*----------------------------------------------------------------------------*/
/* check lock initialization                                                  */
/*----------------------------------------------------------------------------*/
void Atomic::vCheckInit()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  ASSERT(0 == m_iValue); // logic check
}

/*----------------------------------------------------------------------------*/
/* atomically inc                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iInc()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = iAtomicInc(&m_iValue);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec                                                             */
/*----------------------------------------------------------------------------*/
i8 Atomic::iDec()
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);

  i8 i = iAtomicDec(&m_iValue);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* dereference / get value                                                    */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator *(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  return m_iValue;
}

/*----------------------------------------------------------------------------*/
/* atomically inc (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator ++(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = iAtomicInc(&m_iValue);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* atomically dec (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Atomic::operator --(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC,_FOOTER_);
  
  i8 i = iAtomicDec(&m_iValue);

  return i;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Atomic::pFooter(void)
{
  _precondition_(_MAGIC_,CN_ATOMIC);
  
  return &m_xFooter;
}

