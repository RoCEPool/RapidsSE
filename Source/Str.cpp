/*----------------------------------------------------------------------------*/
/* bEqual: test if this Str is equal to arg (same case)                       */
/*----------------------------------------------------------------------------*/
bool Str::bEqual(Str* aArg)
{
  i8 iDiff = strcmp(s(),aArg->s());
  
  if (0 == iDiff)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* bIsNumeric: test if this Str is numeric                                    */
/*----------------------------------------------------------------------------*/
bool Str::bIsNumeric(void)
{
  bool bNumeric = StrLib::bIsNumeric(s());
  
  return bNumeric;
}

/*----------------------------------------------------------------------------*/
/* iLength: get length in bytes of arg (not including terminating null)       */
/*----------------------------------------------------------------------------*/
i8 Str::iLength(void)
{
  i8 iLen = strlen(s());
  
  return iLen;
}

/*----------------------------------------------------------------------------*/
/* bSame: test if this Str is same as arg (ignores case)                      */
/*----------------------------------------------------------------------------*/
bool Str::bSame(Str* aArg)
{
  i8 iDiff = strcasecmp(s(),aArg->s());
  
  if (0 == iDiff)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of arg (including terminating null)                      */
/*----------------------------------------------------------------------------*/
i8 Str::nSize(void)
{
  i8 n = StrLib::iSize(s());
  
  return n;
}

/*----------------------------------------------------------------------------*/
/* vSprint: formatted sprint                                                  */
/*----------------------------------------------------------------------------*/
void Str::vSprint(Str* aFormat, ...)
{
  va_list args;
  va_start(args,aFormat);
  
  vsprintf(s(),aFormat->s(),args);
  
  va_end(args);
}

/*----------------------------------------------------------------------------*/
/* iToI8: convert arg to i8                                                   */
/*----------------------------------------------------------------------------*/
i8 Str::iToI8(void)
{
  //i8 i = atoll(s);
  
  //return i;
  
  const char* ps = s();
  
  i8 i = 0;
  
  // skip leading 0's
  while (*ps && '0' == *ps)
    ps++;
  
  if (*ps && ('x' == *ps || 'X' == *ps)) {
    ps++;
    while (*ps && StrLib::bIsHex(*ps)) {
      i8 j = StrLib::iHexToInw(*ps++);
      i = i * 16 + j;
    }
  }
  else {
    while (*ps && StrLib::bIsDigit(*ps)) {
      i8 j = (*ps++ - '0');
      i = i * 10 + j;
    }
  }
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* convert to lower case                                                      */
/*----------------------------------------------------------------------------*/
void Str::vToLower(void)
{
  StrLib::vToLower(s());
}

