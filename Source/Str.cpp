{
  StrLib::vConcat(a(),aArg->a());
}

/*----------------------------------------------------------------------------*/
/* bEqual: test if this Str is equal to arg (same case)                       */
/*----------------------------------------------------------------------------*/
bool Str::bEqual(Str* aArg)
{
  i8 iDiff = strcmp(a(),aArg->a());
  
  if (0 == iDiff)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* bSame: test if this Str is same as arg (ignores case)                      */
/*----------------------------------------------------------------------------*/
bool Str::bSame(Str* aArg)
{
  i8 iDiff = strcasecmp(a(),aArg->a());
  
  if (0 == iDiff)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* iToI8: convert arg to i8                                                   */
/*----------------------------------------------------------------------------*/
i8 Str::iToI8(void)
{
  //i8 i = atoll(s);
  
  //return i;
  
  const char* s = a();
  
  i8 i = 0;
  
  // skip leading 0's
  while (*s && '0' == *s)
    s++;
  
  if (*s && ('x' == *s || 'X' == *s)) {
    s++;
    while (*s && StrLib::bIsHex(*s)) {
      i8 j = StrLib::iHexToInw(*s++);
      i = i * 16 + j;
    }
  }
  else {
    while (*s && StrLib::bIsDigit(*s)) {
      i8 j = (*s++ - '0');
      i = i * 10 + j;
    }
  }
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* iLength: get length in bytes of arg (not including terminating null)       */
/*----------------------------------------------------------------------------*/
i8 Str::iLength(void)
{
  i8 iLen = strlen(a());
  
  return iLen;
}

