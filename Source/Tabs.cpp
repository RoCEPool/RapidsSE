#include "Debugging.h"

/*----------------------------------------------------------------------------*/
/* single tab                                                                 */
/*----------------------------------------------------------------------------*/
const char* Debugging::aSingleTab(void)
{
  return "  ";
}

/*----------------------------------------------------------------------------*/
/* double tab                                                                 */
/*----------------------------------------------------------------------------*/
const char* Debugging::aDoubleTab(void)
{
  return "      ";
}

/*----------------------------------------------------------------------------*/
/* get tab                                                                    */
/*----------------------------------------------------------------------------*/
const char* Debugging::aTab(i8 iDepth)
{
  switch(iDepth) {
    case  0:  return "";
    case  1:  return "  ";
    case  2:  return "    ";
    case  3:  return "      ";
    case  4:  return "        ";
    case  5:  return "          ";
    case  6:  return "            ";
    case  7:  return "              ";
    case  8:  return "                ";
    case  9:  return "                  ";
    case 10:  return "                    ";
    case 11:  return "                      ";
    case 12:  return "                        ";
    case 13:  return "                          ";
    case 14:  return "                            ";
    case 15:  return "                              ";
    case 16:  return "                                ";
    default:  return "  (tabbed-out)                    ";
  }
}

