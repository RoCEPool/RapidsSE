#include "Debugging.h"

/*----------------------------------------------------------------------------*/
/* single tab                                                                 */
/*----------------------------------------------------------------------------*/
Str* Debugging::aSingleTab(void)
{
  return "  "_Str;
}

/*----------------------------------------------------------------------------*/
/* double tab                                                                 */
/*----------------------------------------------------------------------------*/
Str* Debugging::aDoubleTab(void)
{
  return "      "_Str;
}

/*----------------------------------------------------------------------------*/
/* get tab                                                                    */
/*----------------------------------------------------------------------------*/
Str* Debugging::aTab(i8 iDepth)
{
  switch(iDepth) {
    case  0:  return ""_Str;
    case  1:  return "  "_Str;
    case  2:  return "    "_Str;
    case  3:  return "      "_Str;
    case  4:  return "        "_Str;
    case  5:  return "          "_Str;
    case  6:  return "            "_Str;
    case  7:  return "              "_Str;
    case  8:  return "                "_Str;
    case  9:  return "                  "_Str;
    case 10:  return "                    "_Str;
    case 11:  return "                      "_Str;
    case 12:  return "                        "_Str;
    case 13:  return "                          "_Str;
    case 14:  return "                            "_Str;
    case 15:  return "                              "_Str;
    case 16:  return "                                "_Str;
    default:  return "  (tabbed-out)                    "_Str;
  }
}

