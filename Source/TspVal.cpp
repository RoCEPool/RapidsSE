#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TspVal* Values::_pTspVal(void* aAddr)
{
  TspVal* pTspVal = reinterpret_cast<TspVal*>(aAddr);
  
  RASSERT( !pTspVal || CN_TSPVAL == pTspVal->eClass() );
  
  return pTspVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TspVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: TspVal class cannot be new'd\n"_Str);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TspVal::TspVal(void)
: Value(CN_INTVAL)
{
  _checkInitialised_(CN_TSPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TspVal::operator =(i8 iTsp)
{
  //vTrace("TspVal: diff %lld\n"_Str,nSub(&m_iTsp,this));
  
  *aInt() = iTsp;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TspVal::operator =(Tsp xTsp)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  *aInt() = xTsp.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iTsp                                                                   */
/*----------------------------------------------------------------------------*/
i8 TspVal::iTsp(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TspVal::nSize(void)
{
  return sizeof(TspVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* TspVal::aInt(void)
{
  return (i8*)&x;
}

