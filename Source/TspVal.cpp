#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TspVal* Values::_aTspVal(void* aAddr)
{
  TspVal* aTspVal = reinterpret_cast<TspVal*>(aAddr);
  
  RASSERT_TYPE(aTspVal,CN_TSPVAL);
  
  return aTspVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TspVal::operator new(size_t)
{
  vFatal("fatal: TspVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TspVal::TspVal(void)
: Value(CN_TSPVAL)
{
  _checkInitialised_(CN_TSPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TspVal::operator =(i8 iTsp)
{
  //vTrace("TspVal: diff %lld\n"_Stz,nSub(&m_iTsp,this));
  
  *aInt() = iTsp;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TspVal::operator =(Tsp xTsp)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = xTsp.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iTsp                                                                   */
/*----------------------------------------------------------------------------*/
i8 TspVal::iTsp(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TspVal::nSize(void)
{
  return sizeof(TspVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* TspVal::aInt(void)
{
  return (i8*)&xTsp;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TspVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }

  StrLib::vSprint(aWorkspace,
                  "%ll04d-%ll02d-%ll02d %ll02d:%ll02d:%ll02d.%lld"_Stz,
                  (i8)xTsp.m_uYearDelta + C_BASE_YEAR,
                  (i8)xTsp.m_uMonth,
                  (i8)xTsp.m_uDay,
                  (i8)xTsp.m_uHour,
                  (i8)xTsp.m_uMinute,
                  (i8)xTsp.m_uSecond,
                  (i8)xTsp.m_uMicro
                  );
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void TspVal::vMaxValue(void)
{
  xTsp.m_uSpare = 0;
  
  xTsp.m_uMicro  = 999999;
  xTsp.m_uSecond = 59;
  xTsp.m_uMinute = 59;
  xTsp.m_uHour   = 23;
  
  xTsp.m_uDay   = 31;
  xTsp.m_uMonth = 12;
  xTsp.m_uYearDelta  = C_BASE_YEAR + C_YEAR_RANGE;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void TspVal::vMidValue(void)
{
  xTsp.m_uSpare = 0;
  
  xTsp.m_uMicro  = 1;
  xTsp.m_uSecond = 2;
  xTsp.m_uMinute = 3;
  xTsp.m_uHour   = 4;
  
  xTsp.m_uDay   = 1;
  xTsp.m_uMonth = 2;
  xTsp.m_uYearDelta  = 2018 - C_BASE_YEAR;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void TspVal::vMinValue(void)
{
  xTsp.m_uSpare = 0;
  
  xTsp.m_uMicro  = 0;
  xTsp.m_uSecond = 0;
  xTsp.m_uMinute = 0;
  xTsp.m_uHour   = 0;
  
  xTsp.m_uDay   = 1;
  xTsp.m_uMonth = 1;
  xTsp.m_uYearDelta  = C_BASE_YEAR - C_BASE_YEAR; // silly I know, but it reminds us
                                          // that year is delta from a base
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void TspVal::vNullValue(void)
{
  vSetNull();
}

