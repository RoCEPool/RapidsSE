#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TspVal* Values::_pTspVal(void* aAddr)
{
  TspVal* pTspVal = reinterpret_cast<TspVal*>(aAddr);
  
  RASSERT( !pTspVal || CN_TSPVAL == pTspVal->eClass() );
  
  return pTspVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TspVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: TspVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TspVal::TspVal(void)
: Value(CN_INTVAL)
{
  m_iTsp = 0;
  
  _checkInitialised_(CN_TSPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TspVal::operator =(i8 iTsp)
{
  //vTrace("TspVal: diff %lld\n"_Str,nSub(&m_iTsp,this));
  
  m_iTsp = iTsp;
}

/*----------------------------------------------------------------------------*/
/* get iTsp                                                                   */
/*----------------------------------------------------------------------------*/
i8 TspVal::iTsp(void) const
{
  return m_iTsp;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TspVal::nSize(void) const
{
  return sizeof(TspVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TspVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_iTsp;
}

