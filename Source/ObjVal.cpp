#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ObjVal* Values::_pObjVal(void* aAddr)
{
  ObjVal* pObjVal = reinterpret_cast<ObjVal*>(aAddr);
  
  RASSERT( !pObjVal || CN_OBJVAL == pObjVal->eClass() );
  
  return pObjVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ObjVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: StrVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ObjVal::ObjVal(i8 iSize)
: Value(CN_OBJVAL)
{
  m_iSize = iSize;
  
  _checkInitialised_(CN_OBJVAL);
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 ObjVal::nSize(void) const
{
  return m_iSize;
}

