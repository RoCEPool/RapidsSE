#include "Values.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ObjVal::operator new(size_t iSize)
{
  vFatal("fatal: StrVal class cannot be new'd\n");
  
  //vExitFatal();
  
  exit(EXIT_FAILURE);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ObjVal::ObjVal(i8 iSize)
: Value(CN_OBJVAL)
{
  m_iSize = iSize;
  
  Memory::vCheckInitialised(this,sizeof(ObjVal));
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 ObjVal::iSize(void) const
{
  return m_iSize;
}

