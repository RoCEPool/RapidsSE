/*============================================================================*/
/* SP_TknVecStr.cpp - Token VEctor to String sprint helper       (on c stack) */
/*============================================================================*/

#include "Commands.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_TknVecStr::SP_TknVecStr(void)
: Object(CN_SPSTRING)
{
  _precondition_(_MAGIC_,CN_SPSTRING,_FOOTER_);
  
#ifdef WITH_CHECK_INITIALISED
  MemLib::vZero(m_caResult,sizeof(m_caResult),CN_SPSTRING);
#endif
  
  _checkInitialised_(CN_SPSTRING);
  
  _postcondition_(_MAGIC_,CN_SPSTRING,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_TknVecStr::~SP_TknVecStr(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSTRING,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint SP_TknVecStr and return Stz* to result                              */
/*----------------------------------------------------------------------------*/
Stz* SP_TknVecStr::sz(TokenVec* pTknVec)
{
  _precondition_(_MAGIC_,CN_SPSTRING,_FOOTER_);
  
  StrLib::vSprint(m_caResult,"%s"_Stz,pTknVec->pGet(0)->szText());
  
  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

__aFooterFunction(SP_TknVecStr);

