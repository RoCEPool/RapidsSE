#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Dte::SP_Dte(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
  
  // set default Dte format
  vFormat(F_DTE);
  
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Dte::~SP_Dte(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Dte and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* SP_Dte::sz(i8 iDte)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  Dtm wDte;
  wDte = iDte;
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  
                  (i8)wDte.m_wDte.m_uYearDelta + C_YEAR_BASE,
                  (i8)wDte.m_wDte.m_uMonth,
                  (i8)wDte.m_wDte.m_uDay);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Dte::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(C_YEAR_MAX,C_12_DEC,31) );
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Dte::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(2018,C_02_FEB,1) );
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Dte::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(C_YEAR_MIN,C_01_JAN,1) );
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SP_Dte::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL);
  
  return &m_xFooter;
}

