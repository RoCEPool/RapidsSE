#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
DteVal* Values::_aDteVal(void* aAddr)
{
  DteVal* aDteVal = reinterpret_cast<DteVal*>(aAddr);
  
  RASSERT_TYPE(aDteVal,CN_DTEVAL);
  
  return aDteVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DteVal::operator new(size_t)
{
  vFatal("fatal: DteVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DteVal::DteVal(void)
: Value(CN_DTEVAL)
{
  
  _checkInitialised_(CN_DTEVAL);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* DteVal::aInt(void)
{
  return (i8*)&xDte;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 DteVal::nSize(void) const
{
  return sizeof(DteVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void DteVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  StrLib::vSprint(aWorkspace,
                  "%ll04d-%ll02d-%ll02d"_Stz,
                  (i8)xDte.m_uYearDelta + C_BASE_YEAR,
                  (i8)xDte.m_uMonth,
                  (i8)xDte.m_uDay
                  );
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void DteVal::vMaxValue(void)
{
  xDte.m_uSpare = 0;
  xDte.m_uDay   = 31;
  xDte.m_uMonth = 12;
  xDte.m_uYearDelta  = C_BASE_YEAR + C_YEAR_RANGE;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void DteVal::vMidValue(void)
{
  xDte.m_uSpare = 0;
  xDte.m_uDay   = 1;
  xDte.m_uMonth = 2;
  xDte.m_uYearDelta  = 2018 - C_BASE_YEAR;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void DteVal::vMinValue(void)
{
  xDte.m_uSpare = 0;
  xDte.m_uDay   = 1;
  xDte.m_uMonth = 1;
  xDte.m_uYearDelta  = C_BASE_YEAR - C_BASE_YEAR; // silly I know, but it reminds us
                                          // that year is delta from a base
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void DteVal::vNullValue(void)
{
  vSetNull();
}

