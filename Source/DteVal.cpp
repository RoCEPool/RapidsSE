#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
DteVal* Values::_pDteVal(void* aAddr)
{
  DteVal* pDteVal = reinterpret_cast<DteVal*>(aAddr);
  
  RASSERT( !pDteVal || CN_DTEVAL == pDteVal->eClass() );
  
  return pDteVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DteVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: DteVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DteVal::DteVal(void)
: Value(CN_DTEVAL)
{
  m_iDte = 0;
  
  _checkInitialised_(CN_DTEVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void DteVal::operator =(Dte xDte)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  m_iDte = xDte.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void DteVal::operator =(i8 iDte)
{
  //vTrace("DteVal: diff %lld\n"_Str,nSub(&m_iDte,this));
  
  m_iDte = iDte;
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* DteVal::aInt(void)
{
  return &m_iDte;
}

/*----------------------------------------------------------------------------*/
/* get iDte                                                                   */
/*----------------------------------------------------------------------------*/
i8 DteVal::iDte(void) const
{
  return m_iDte;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 DteVal::nSize(void) const
{
  return sizeof(DteVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void DteVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_iDte;
}

