/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TimeMarker* ControlData::_pTimeMarker(void* aAddr)
{
  TimeMarker* pOp = reinterpret_cast<TimeMarker*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* TimeMarker::operator new(size_t)
{
  TimeMarker* pEndMarker =
    static_cast<TimeMarker*>(HeapMem::pAllocate(CN_PAUSEMARKER));
  
  return pEndMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void TimeMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TimeMarker::TimeMarker(void)
: Operand(CN_PAUSEMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);

  _checkInitialised_(CN_PAUSEMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TimeMarker::~TimeMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);
}


