/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Op* PushDown::_pOp(void* aAddr)
{
  Op* pOp = reinterpret_cast<Op*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Op::Op(eCN eClassNo, Job* pJob)
: Object(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
  
  m_pJob          = pJob;
  
  m_pOperandQueue = new OperandQueue;
  m_fpOpFun       = nullptr;
  m_pOpOut        = nullptr;
  
  m_pOperand      = nullptr;
  
  m_pExecutingTask = nullptr;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Op::~Op(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  delete m_pOperandQueue;
}

/*----------------------------------------------------------------------------*/
/* this executing / tls job                                                   */
/*----------------------------------------------------------------------------*/
Op* Op::pThisTLSOp(void)
{
  Task* pTask = Task::pThisTLSTask();
  
  Op* pOp = pTask->pOp();
  
  return pOp;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* op loop                                                                    */
/*----------------------------------------------------------------------------*/
void Op::vOpLoop(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);

//  while (bGetNextOperand()) {
//    (*m_fpOpFun)(this);
//  }
  
  (*m_fpOpFun)(this);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* append oprand to this op's operand queue                                   */
/*----------------------------------------------------------------------------*/
void Op::vAppendIn(Operand* pOperand)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  vTrace("Op::vAppendIn : %p\n"_Stz,pOperand);
}

/*----------------------------------------------------------------------------*/
/* append operand to output op's operand queue                                */
/*----------------------------------------------------------------------------*/
void Op::vAppendOut(Operand* pOperand)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  vTrace("Op::vAppendOut : %p\n"_Stz,pOperand);
  m_pOpOut->vAppendIn(pOperand);
}

/*----------------------------------------------------------------------------*/
/* call op function                                                           */
/*----------------------------------------------------------------------------*/
void Op::vCallOpFun(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  (*m_fpOpFun)(this);
}

/*----------------------------------------------------------------------------*/
/* get next operand                                                           */
/*----------------------------------------------------------------------------*/
bool Op::bGetNextOperand(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  m_pOperand = nullptr;

  return false;
}

/*----------------------------------------------------------------------------*/
/* set op out                                                                 */
/*----------------------------------------------------------------------------*/
void Op::vOpOut(Op* pOpOut)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  m_pOpOut = pOpOut;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* set job                                                                    */
/*----------------------------------------------------------------------------*/
void Op::vJob(Jobs::Job* pJob)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_pJob = pJob;
}


