#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
spDTE::spDTE(void)
: Sprint(CN_SPDTE)
{
  _precondition_(_MAGIC_,CN_SPDTE,_FOOTER_);
  
  // set default Dte format
  vFormat(F_DTE);
  
  _checkInitialised_(CN_SPDTE);
  
  _postcondition_(_MAGIC_,CN_SPDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
spDTE::~spDTE(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Dte and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* spDTE::sz(i8 iDte)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  Word wDte = iDte;
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  
                  (i8)wDte.m_wDtm.xDte.m_uYearDelta + C_YEAR_BASE,
                  (i8)wDte.m_wDtm.xDte.m_uMonth,
                  (i8)wDte.m_wDtm.xDte.m_uDay);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spDTE::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(C_YEAR_MAX,C_12_DEC,31) );
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spDTE::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(2018,C_02_FEB,1) );
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spDTE::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz( Dtm::iDte(C_YEAR_MIN,C_01_JAN,1) );
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* spDTE::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPDTE);
  
  return &m_xFooter;
}

