/*============================================================================*/
/* s256.cpp -- a 256-byte s-string                                            */
/*============================================================================*/

#include "Values.h"
#include "Memory.hpp"
#include "StorageEngine.h"

extern BufferPool*  gpBufferPool;

/*----------------------------------------------------------------------------*/
/* new a thread from existing memory                                          */
/*----------------------------------------------------------------------------*/
void* s256::operator new(size_t iSize, s256* pS256)
{
  RASSERT(iSize);
  
  return pS256;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(void)
: sRefactor(CN_S256,C_S256_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S256_DATAAREA);
  
  _checkInitialised_(CN_S256);
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(s256& rArg)
: sRefactor(CN_S256,C_S256_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S256_DATAAREA);
  
  sRefactor::vCopy(rArg.a());
  
  _checkInitialised_(CN_S256);
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(const char* aArg)
: sRefactor(CN_S256,C_S256_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S256_DATAAREA);
  
  sRefactor::vCopy(aArg);
  
  _checkInitialised_(CN_S256);
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s256::~s256(void)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (const char* aArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  sRefactor::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (char* aArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  sRefactor::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (sRefactor& rArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void s256::vInit()
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  sRefactor::vInit(C_S256_DATAAREA);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s256::pFooter(void)
{
  _precondition_(_MAGIC_,CN_S256);
  
  return &m_xFooter;
}

