/*============================================================================*/
/* s256.cpp -- a 256-byte s-string                                            */
/*============================================================================*/

#include "Magic.h"
#include "Memory.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(void)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  Memory::vCheckInitialised(this,sizeof(s256));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(s256& rArg)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(rArg.a());
  
  Memory::vCheckInitialised(this,sizeof(s256));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(const char* aArg)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg);
  
  Memory::vCheckInitialised(this,sizeof(s256));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(const char* aArg, i8 nChars)
: s(C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg,nChars);
  
  Memory::vCheckInitialised(this,sizeof(s256));
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s256::~s256(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (s& rArg)
{
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void s256::vInit()
{
  s::vInit(C_S_SIZE);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s256::pFooter(void)
{
  return &m_xFooter;
}

