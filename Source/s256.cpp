/*============================================================================*/
/* s256.cpp -- a 256-byte s-string                                            */
/*============================================================================*/

#include "Magic.h"
#include "Memory.hpp"
#include "StorageEngine.h"

extern BufferPool*  gpBufferPool;

/*----------------------------------------------------------------------------*/
/* new a thread from existing memory                                          */
/*----------------------------------------------------------------------------*/
void* s256::operator new(size_t iSize, s256* pS256)
{
  RASSERT(iSize);
  
  return pS256;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(void)
: s(CN_S256,C_S_SIZE)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  _checkInitialised_(sizeof(s256));
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(s256& rArg)
: s(CN_S256,C_S_SIZE)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(rArg.a());
  
  _checkInitialised_(sizeof(s256));
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s256::s256(const char* aArg)
: s(CN_S256,C_S_SIZE)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg);
  
  _checkInitialised_(sizeof(s256));
  
  _postcondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s256::~s256(void)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (const char* aArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (char* aArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s256::operator = (s& rArg)
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void s256::vInit()
{
  _precondition_(_MAGIC_,CN_S256,_FOOTER_);
  
  s::vInit(C_S_SIZE);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s256::pFooter(void)
{
  _precondition_(_MAGIC_,CN_S256);
  
  return &m_xFooter;
}

