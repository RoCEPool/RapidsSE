#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snDTE::snDTE(void)
: Scan(CN_SNDTE)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
  
  _checkInitialised_(CN_SNDTE);
  
  _postcondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snDTE::~snDTE(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snDTE::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  return &m_xFooter;
}

