#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snDTE::snDTE(void)
: Scan(CN_SNDTE)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
  
  _checkInitialised_(CN_SNDTE);
  
  _postcondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snDTE::~snDTE(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 snDTE::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  i8 iYear, iMonth, iDay;
  
  if ( ! StrLib::bExtractDate2(aacCrs,
                               iYear, iMonth, iDay,
                               pScnFmt->m_eDateComponent,
                               pScnFmt->m_cDateSeparator) )
    throw C_UNKNOWN;

  Dte xDte;
  
  xDte.x.m_uYearDelta  = iYear - C_BASE_YEAR;
  xDte.x.m_uMonth = iMonth;
  xDte.x.m_uDay   = iDay;
  xDte.x.m_uSpare = 0;

  m_iValue = xDte.iAsI8();
  
  return m_iValue;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snDTE::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  return &m_xFooter;
}

