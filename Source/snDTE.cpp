#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snDTE::snDTE(void)
: Scan(CN_SNDTE)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
  
  // set default Dte format
  vFormat(F_DTE);
  
  _checkInitialised_(CN_SNDTE);
  
  _postcondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snDTE::~snDTE(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Dte and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* snDTE::sz(i8 iDte)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  Word wDte = iDte;
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  
                  (i8)wDte.xEdt.m_uYearInEra + C_BASE_YEAR,
                  (i8)wDte.xEdt.m_uMonth,
                  (i8)wDte.xEdt.m_uDay);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snDTE::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  return &m_xFooter;
}

