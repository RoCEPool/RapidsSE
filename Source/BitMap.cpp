/*============================================================================*/
/* BitMap.cpp - an array of bit arrays                                        */
/*============================================================================*/

#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BitMap::operator new(size_t)
{
  BitMap* pBitMap = (BitMap*)HeapMem::pAllocate(CN_BITMAP);
  
  return pPoolCheck<void*>(pBitMap);
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void BitMap::operator delete(void* pAddress)
{
  BitMap* pBitMap = static_cast<BitMap*>(pAddress);
  
  HeapMem::vFree(pBitMap);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BitMap::BitMap(void)
: Object(CN_BITMAP)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_BITMAP);
  
  for (i8 i_BitArray = 0; i_BitArray < C_BIT_ARRAYS; i_BitArray++)
    m_pBitArray[i_BitArray] = new BitArray;
  
  _checkInitialised_(CN_BITMAP);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_BITMAP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
BitMap::~BitMap(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_BITMAP,_FOOTER_);
}


/*----------------------------------------------------------------------------*/
/* set bit on                                                                 */
/*----------------------------------------------------------------------------*/
void BitMap::vSetOn(i8 i_Array, i8 i_Bit)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_BITMAP,_FOOTER_);

  m_pBitArray[i_Array]->vSetOn(i_Bit);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* BitMap::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_BITMAP);
  
  return &m_xFooter;
}

