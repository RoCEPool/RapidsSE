/*----------------------------------------------------------------------------*/
/* test for backslash                                                         */
/*----------------------------------------------------------------------------*/
bool AnnChar::bIsBackSlash(void)
{
  if ('\\' == m_cChar)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* test for blank                                                             */
/*----------------------------------------------------------------------------*/
bool AnnChar::bIsBlank(void)
{
  if (' ' == m_cChar)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* test for a close square bracket ]                                          */
/*----------------------------------------------------------------------------*/
bool AnnChar::bIsCloseBracket(void)
{
  if (']' == m_cChar)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* test for a colon                                                           */
/*----------------------------------------------------------------------------*/
