#include "LexicalAnalysis.h"

/*----------------------------------------------------------------------------*/
/* test for blank                                                             */
/*----------------------------------------------------------------------------*/
bool AnnChar::bIsBlank(void)
{
  if (' ' == m_cChar)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* test for EOF                                                               */
/*----------------------------------------------------------------------------*/
bool AnnChar::bIsEOF(void)
{
  if (! m_cChar)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* reset this annotated char                                                  */
/*----------------------------------------------------------------------------*/
void AnnChar::vReset(void)
{
  //_precondition_(_ADDRESS_,_MAGIC_,CN_CHARACTERISE,_FOOTER_);
  
  m_cChar  = '\0';
  m_iLine  = C_UNKNOWN;
  m_iCol   = C_UNKNOWN;
}

