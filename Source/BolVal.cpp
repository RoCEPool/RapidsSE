#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
BolVal* Values::_aBolVal(void* aAddr)
{
  BolVal* aBolVal = reinterpret_cast<BolVal*>(aAddr);
  
  RASSERT_TYPE(aBolVal,CN_BOLVAL);
  
  return aBolVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BolVal::operator new(size_t)
{
  vFatal("fatal: BolVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BolVal::BolVal(void)
: Value(CN_BOLVAL)
{
  m_iBol = 0;
  
  _checkInitialised_(CN_BOLVAL);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* BolVal::aInt(void)
{
  return (i8*)&m_iBol;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BolVal::operator =(Dtm xBol)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = xBol.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BolVal::operator =(i8 iBol)
{
  //vTrace("BolVal: diff %lld\n"_Stz,nSub(&m_iBol,this));
  
  m_iBol = iBol;
}

/*----------------------------------------------------------------------------*/
/* get iBol                                                                   */
/*----------------------------------------------------------------------------*/
i8 BolVal::iBol(void) const
{
  return m_iBol;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 BolVal::nSize(void) const
{
  return sizeof(BolVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BolVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }

  if (m_iBol) {
    aWorkspace->vConcat("true"_Stz);
    return;
  }

  aWorkspace->vConcat("false"_Stz);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void BolVal::vMaxValue(void)
{
  m_iBol = true;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void BolVal::vMidValue(void)
{
  m_iBol = true;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void BolVal::vMinValue(void)
{
  m_iBol = false;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void BolVal::vNullValue(void)
{
  vSetNull();
}

