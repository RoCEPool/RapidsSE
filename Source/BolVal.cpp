#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BolVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: BolVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BolVal::vBol(Bol wBol)
{
  vClass(CN_BOLVAL);
  u.m_wBol = wBol;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a BolVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 BolVal::nStackUsage(void)
{
  return sizeof(BolVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BolVal::vToStz(Stz* szDst)
{
  if (C_DATUM_NULL == u.m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = u.m_iInt;
}

