#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
BolVal* Values::_pBolVal(void* aAddr)
{
  BolVal* pBolVal = reinterpret_cast<BolVal*>(aAddr);
  
  RASSERT( !pBolVal || CN_BOLVAL == pBolVal->eClass() );
  
  return pBolVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BolVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: BolVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BolVal::BolVal(void)
: Value(CN_BOLVAL)
{
  m_bBol = 0;
  
  _checkInitialised_(CN_BOLVAL);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* BolVal::aInt(void)
{
  return (i8*)&m_bBol;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BolVal::operator =(Bol xBol)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  *aInt() = xBol.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BolVal::operator =(i8 iBol)
{
  //vTrace("BolVal: diff %lld\n"_Str,nSub(&m_iBol,this));
  
  m_bBol = iBol;
}

/*----------------------------------------------------------------------------*/
/* get iBol                                                                   */
/*----------------------------------------------------------------------------*/
i8 BolVal::iBol(void) const
{
  return m_bBol;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 BolVal::nSize(void) const
{
  return sizeof(BolVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BolVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_bBol;
}

