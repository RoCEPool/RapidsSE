#include "Indexing.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
SkipRoots* Indexing::_aSkipRoots(void* aAddr)
{
  SkipRoots* aFreeEntry = reinterpret_cast<SkipRoots*>(aAddr);
  
  return aFreeEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipRoots::SkipRoots(void)
: Ent(CN_ENT,sizeof(SkipRoots))
{
  PoolBuffer* pBuffer = PoolBuffer::pWithinPoolBuffer((Object*)this);
  i8 i_Buffer = pBuffer->iBufferNo();

  vBuffer(i_Buffer);
  vOffsets(C_DEF_LVL_MAXIMUM);
  vElmSeqSize(0);

  for (i8 i_Pad = 0; i_Pad < C_SKIPROOTS_PADDING; i_Pad++)
    m_iPadding[i_Pad] = -1;
  
  for (i8 i_Neo = 0; i_Neo < C_DEF_LVL_MAXIMUM; i_Neo++)
    vNEO(i_Neo,-1);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipRoots::~SkipRoots(void) noexcept(false)
{
}


