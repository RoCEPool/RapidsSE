/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
SkipRoots* Data::_aSkipRoots(void* aAddr)
{
  SkipRoots* aFreeEntry = reinterpret_cast<SkipRoots*>(aAddr);
  
  return aFreeEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipRoots::SkipRoots(void)
: Item(CN_ENTRY,sizeof(SkipRoots))
{
  m_iaNextOffset[0] = -1;
  m_iaNextOffset[1] = -1;
  m_iaNextOffset[2] = -1;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipRoots::~SkipRoots(void) noexcept(false)
{
}


