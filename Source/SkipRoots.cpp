/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
SkipRoots* MetaData::_aSkipRoots(void* aAddr)
{
  SkipRoots* aFreeEntry = reinterpret_cast<SkipRoots*>(aAddr);
  
  return aFreeEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SkipRoots::SkipRoots(void)
: Ent(CN_ENT,sizeof(SkipRoots))
{
  PoolBuffer* pBuffer = PoolBuffer::pGetPoolBuffer((Object*)this);
  bn nBufferNo = pBuffer->nPoolBufferNo();

  m_xId.vBuffer(*nBufferNo);
  vLevels(3);
  m_nKeyBytes = 0;

  m_iPadding[0] = -1;
  m_iPadding[1] = -1;
  m_iPadding[2] = -1;
  m_iPadding[3] = -1;
  
  vNEO(0,-1);
  vNEO(1,-1);
  vNEO(2,-1);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SkipRoots::~SkipRoots(void) noexcept(false)
{
}


