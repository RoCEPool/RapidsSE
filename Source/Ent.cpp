/*----------------------------------------------------------------------------*/
/* get address of next entry offset array                                     */
/*----------------------------------------------------------------------------*/
NEO* Ent::aNEO(void)
{
  i8 i_NEO = sizeof(Ent) + m_xKey.nSizeKey();

  NEO* aNEO = aAdd<NEO*>(this,i_NEO);
  
  return aNEO;
}

