/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Ent::Ent(eCN eClassNo, i8 nSizeEnt_Without_NEO)
: Header(eClassNo)
{
  i8 nKeyBytes = static_cast<i4>(nSizeEnt_Without_NEO - sizeof(Ent));
  
  m_xKey.vSizeKey(nKeyBytes);
  
#ifdef WITH_DEBUG_VERSION
  m_iSkipNo = -1;
#endif
}

