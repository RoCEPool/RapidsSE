/*----------------------------------------------------------------------------*/
/* get a next entry offset                                                    */
/*----------------------------------------------------------------------------*/
i4 Ent::iNEO(i8 iOffset)
{
  ASSERT(iOffset >= 0 && iOffset < nLevels());
  
  //NEO* aNEO = this->aNEO();
  
  //i4 iNEO = aNEO->m_iOffset[iOffset];
  
  i4 iNEO = *(aAdd<i4*>(this, m_nSizeItem_WithoutOffsets + sizeof(i4) * iOffset));
  
  return iNEO;
}

/*----------------------------------------------------------------------------*/
/* set a next entry offset                                                    */
/*----------------------------------------------------------------------------*/
void Ent::vNEO(i8 iOffset, i4 iNEO)
{
  ASSERT(iOffset >= 0 && iOffset < nLevels());
  
  //NEO* aNEO = this->aNEO();
  
  //aNEO->m_iOffset[iOffset] = iNEO;
  
  *(aAdd<i4*>(this, m_nSizeItem_WithoutOffsets + sizeof(i4) * iOffset)) = iNEO;
  
}

/*----------------------------------------------------------------------------*/
/* dump the NEO after this entry                                              */
/*----------------------------------------------------------------------------*/
void Ent::vNEOdump(void)
{
  NEO* aNEO = this->aNEO();
  vTrace("Ent %p levels: %lld NEO: %p"_Stz,
         this,nLevels(),aNEO);
  
  for (i8 i_Level = 0; i_Level < nLevels(); i_Level++)
    vTrace(" %lld: %d"_Stz,i_Level,aNEO->m_iOffset[i_Level]);
  
  vTrace("\n"_Stz);
}

/*----------------------------------------------------------------------------*/
/* get size of the NEO after this entry                                       */
/*----------------------------------------------------------------------------*/
i8 Ent::iNEOsize(void)
{
  i8 nBytes = sizeof(i4) * nLevels();
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get size of entry with neo                                                 */
/*----------------------------------------------------------------------------*/
i8 Ent::nSizeBytes(void)
{
  i8 nBytes = m_nSizeItem_WithoutOffsets + iNEOsize();
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get size key                                                               */
/*----------------------------------------------------------------------------*/
i8 Ent::nSizeKey(void)
{
  return (i8)(m_nSizeItem_WithoutOffsets - sizeof(Ent));
}

/*----------------------------------------------------------------------------*/
/* test for valid entry                                                       */
/*----------------------------------------------------------------------------*/
bool Ent::bValidItem(void)
{  
  if (! bValidMagic()) {
    vTrace("Not valid magic\n"_Stz);
    return false;
  }
  
  if ( ! (CN_ENT == eClass() || CN_FREEITEM == eClass()) ) {
    vTrace("Not valid class\n"_Stz);
    return false;
  }
  
#ifdef USE_LW_FOOOTER
  if (! aFooter()->bValidFooter()) {
    vTrace("Not valid footer\n"_Stz);
    return false;
  }
#endif
  
  return true;
}


/*----------------------------------------------------------------------------*/
/*-- Private -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of next entry offset array                                     */
/*----------------------------------------------------------------------------*/
NEO* Ent::aNEO(void)
{
  NEO* aNEO = aAdd<NEO*>(this, m_nSizeItem_WithoutOffsets);
  
  return aNEO;
}

