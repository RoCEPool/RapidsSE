#include "Sessions.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_ReqTuple::SP_ReqTuple(void)
: SP(CN_SPID)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  _checkInitialised_(CN_SPID);
  
  _postcondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_ReqTuple::~SP_ReqTuple(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Header and return Stz* to result                                    */
/*----------------------------------------------------------------------------*/
Stz* SP_ReqTuple::sz(ReqTuple* aReqTuple)
{
  _precondition_(_MAGIC_,CN_SPID,_FOOTER_);
  
  SP_Id spId;
  
  StrLib::vSprint(m_caResult,
                  "<%lld=%s=%s=%s>"_Stz,
                  
                  aReqTuple->m_i_State,
                  spId.sz(IK_REQUEST,aReqTuple->m_iReqId),
                  aReqTuple->m_bMarkTrace ? "Trace"_Stz : "NoTrace"_Stz,
                  aReqTuple->m_bLogJob    ? "Log"_Stz   : "NoLog"_Stz
                  );
  
  return (Stz*) &m_caResult[0];
}


