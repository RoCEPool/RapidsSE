#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
FltVal* Values::_pFltVal(void* aAddr)
{
  FltVal* pFltVal = reinterpret_cast<FltVal*>(aAddr);
  
  RASSERT_TYPE(pFltVal,CN_FLTVAL);
  
  return pFltVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FltVal::operator new(size_t)
{
  vFatal("fatal: FltVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FltVal::FltVal(void)
: Value(CN_FLTVAL)
{
  m_dFlt = 0.0;
  
  _checkInitialised_(CN_FLTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void FltVal::operator =(d8 dFlt)
{
  //vTrace("FltVal: diff %lld\n"_Stz,nSub(&m_iFlt,this));
  
  m_dFlt = dFlt;
}

/*----------------------------------------------------------------------------*/
/* get dFlt                                                                   */
/*----------------------------------------------------------------------------*/
d8 FltVal::dFlt(void) const
{
  return m_dFlt;
}

/*----------------------------------------------------------------------------*/
/* get aFlt                                                                   */
/*----------------------------------------------------------------------------*/
d8* FltVal::aFlt(void)
{
  return &m_dFlt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 FltVal::nSize(void) const
{
  return sizeof(FltVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FltVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = m_dFlt;
}

