#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
FltVal* Values::_aFltVal(void* aAddr)
{
  FltVal* aFltVal = reinterpret_cast<FltVal*>(aAddr);
  
  RASSERT_TYPE(aFltVal,CN_FLTVAL);
  
  return aFltVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FltVal::operator new(size_t)
{
  vFatal("fatal: FltVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FltVal::FltVal(void)
: Value(CN_FLTVAL)
{
  m_dFlt = 0.0;
  
  _checkInitialised_(CN_FLTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void FltVal::operator =(d8 dFlt)
{
  //vTrace("FltVal: diff %lld\n"_Stz,nSub(&m_iFlt,this));
  
  m_dFlt = dFlt;
}

/*----------------------------------------------------------------------------*/
/* get dFlt                                                                   */
/*----------------------------------------------------------------------------*/
d8 FltVal::dFlt(void) const
{
  return m_dFlt;
}

/*----------------------------------------------------------------------------*/
/* get aFlt                                                                   */
/*----------------------------------------------------------------------------*/
d8* FltVal::aFlt(void)
{
  return &m_dFlt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 FltVal::nSize(void) const
{
  return sizeof(FltVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FltVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  *aWorkspace = m_dFlt;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void FltVal::vMaxValue(void)
{
  m_dFlt = C_D8_MAX;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void FltVal::vMidValue(void)
{
  m_dFlt = 73.0;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void FltVal::vMinValue(void)
{
  m_dFlt = C_D8_MIN;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void FltVal::vNullValue(void)
{
  vSetNull();
}

