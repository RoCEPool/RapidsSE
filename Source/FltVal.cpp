#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
FltVal* Values::_pFltVal(void* aAddr)
{
  FltVal* pFltVal = reinterpret_cast<FltVal*>(aAddr);
  
  RASSERT( !pFltVal || CN_FLTVAL == pFltVal->eClass() );
  
  return pFltVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FltVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: FltVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FltVal::FltVal(void)
: Value(CN_FLTVAL)
{
  m_iFlt = 0;
  
  _checkInitialised_(CN_FLTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void FltVal::operator =(i8 iFlt)
{
  //vTrace("FltVal: diff %lld\n"_Str,nSub(&m_iFlt,this));
  
  m_iFlt = iFlt;
}

/*----------------------------------------------------------------------------*/
/* get iFlt                                                                   */
/*----------------------------------------------------------------------------*/
i8 FltVal::iFlt(void) const
{
  return m_iFlt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 FltVal::nSize(void) const
{
  return sizeof(FltVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FltVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_iFlt;
}

