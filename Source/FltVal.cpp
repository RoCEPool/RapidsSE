#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FltVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: FltVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Flt FltVal::wFlt(void)
{
  ASSERT(bIsClass(CN_FLTVAL));
  
  return u.m_wFlt;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void FltVal::vFlt(Flt wFlt)
{
  vClass(CN_FLTVAL);
  u.m_wFlt = wFlt;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a FltVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 FltVal::nStackUsage(void)
{
  return sizeof(FltVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FltVal::vToStz(Stz* szDst)
{
  if (C_DATUM_NULL == u.m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = u.m_iInt;
}

