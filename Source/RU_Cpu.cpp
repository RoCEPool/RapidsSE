#include "ResourceUsage.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RU_Cpu::RU_Cpu(void)
: RU(CN_RUCPU)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  vInit();
  
  _checkInitialised_(CN_RUCPU);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RU_Cpu::~RU_Cpu(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  //vReport();
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vInit(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nBuffers = 0;
  m_nRows  = 0;
  //m_oTimer;
}

/*----------------------------------------------------------------------------*/
/* report                                                                     */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vReport(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);

  vTrace("  %6lld %6lld\n"_Stz,
         m_nBuffers,
         m_nRows
         );
}

/*----------------------------------------------------------------------------*/
/* write report                                                               */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vWriteReport(File* pFile)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  AM::vFilePrint(pFile, "  Buffers#, Rows#\n"_Stz);
    
  AM::vFilePrint(pFile, "  %6lld, %6lld\n"_Stz,
         m_nBuffers,
         m_nRows
         );
}

/*----------------------------------------------------------------------------*/
/* inc alloc                                                                  */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vBuffersInc(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nBuffers++;
}

/*----------------------------------------------------------------------------*/
/* inc free                                                                   */
/*----------------------------------------------------------------------------*/
void RU_Cpu::vRowsInc(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RUCPU,_FOOTER_);
  
  m_nRows++;
}

/*----------------------------------------------------------------------------*/
/* get alloc                                                                  */
/*----------------------------------------------------------------------------*/
i8 RU_Cpu::nBuffers(void)
{
  return m_nBuffers;
}

/*----------------------------------------------------------------------------*/
/* get free                                                                   */
/*----------------------------------------------------------------------------*/
i8 RU_Cpu::nRows(void)
{
  return m_nRows;
}

