#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Tme::SN_Tme(void)
: Scan(CN_SNTME)
{
  _precondition_(_MAGIC_,CN_SNTME,_FOOTER_);
  
  _checkInitialised_(CN_SNTME);
  
  _postcondition_(_MAGIC_,CN_SNTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Tme::~SN_Tme(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Tme::i(char** aacCrs, Column* pCol, Format* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNTME);
  
  i8 iHour, iMinute, iSecond, iMicro;
  
  if ( ! StrLib::bExtractTime(aacCrs, iHour, iMinute, iSecond, iMicro) )
    THROW("StrLib::bExtractTime"_Stz);

  m_wDtm.xTme.m_uHour   = iHour;
  m_wDtm.xTme.m_uMinute = iMinute;
  m_wDtm.xTme.m_uSecond = iSecond;
  m_wDtm.xTme.m_uMicro  = iMicro;
  m_wDtm.xTme.m_uSpare  = 0;
  
  return m_wDtm.m_iI8;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Tme::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNTME);
  
  return &m_xFooter;
}

