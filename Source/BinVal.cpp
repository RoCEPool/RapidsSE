#include "Values.h"

extern i8 giClassSize[];

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
BinVal* Values::_pBinVal(void* pAddr)
{
  BinVal* pBinVal = reinterpret_cast<BinVal*>(pAddr);
  
  RASSERT( !pBinVal || CN_BINVAL == pBinVal->eClass() );
  
  return pBinVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BinVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: BinVal class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BinVal::operator new(size_t iSize, BinVal* pBinVal)
{
  RASSERT(iSize);

  return pBinVal;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BinVal::BinVal(void)
: Value(CN_BINVAL)
{
  m_iBytes = 0;
  
  _checkInitialised_(CN_BINVAL);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BinVal::BinVal(i8 iChars)
: Value(CN_BINVAL)
{
  m_iBytes = iChars;
  
  Memory::vZero(pData(),m_iBytes);
  
  _checkInitialised_(CN_BINVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BinVal::operator =(const Object* pObject)
{
  m_iBytes = giClassSize[pObject->eClass()];
  
  Memory::vCopy(m_cArray, pObject, m_iBytes);
}

/*----------------------------------------------------------------------------*/
/* get iChars                                                                 */
/*----------------------------------------------------------------------------*/
i8 BinVal::iBytes(void) const
{
  return m_iBytes;
}

/*----------------------------------------------------------------------------*/
/* reset string value                                                         */
/*----------------------------------------------------------------------------*/
void BinVal::vReset(void)
{
  m_iBytes = 0;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 BinVal::iSize(void) const
{
  i8 iOverrun = m_iBytes > 8 ? m_iBytes - 8 : 0;
  
  i8 iSize = sizeof(BinVal) + iOverrun;
  
  return iSize;
}

/*----------------------------------------------------------------------------*/
/* set size in bytes                                                          */
/*----------------------------------------------------------------------------*/
void BinVal::vSize(void)
{
  ASSERT(0);
  //m_iBytes = String::iSize(m_sStr);
}

/*----------------------------------------------------------------------------*/
/* set size in bytes                                                          */
/*----------------------------------------------------------------------------*/
void BinVal::vSize(i8 iSize)
{
  m_iBytes = iSize;
}

/*----------------------------------------------------------------------------*/
/* get pObject class                                                          */
/*----------------------------------------------------------------------------*/
eCN BinVal::eObjectClass(void)
{
  Object* pBinaryObject = (Object*)pData();
  
  return pBinaryObject->eClass();
}

/*----------------------------------------------------------------------------*/
/* get data area                                                              */
/*----------------------------------------------------------------------------*/
char* BinVal::pData(void)
{
  return &m_cArray[0];
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calculate number of bytes reqired to hold object of given length           */
/*----------------------------------------------------------------------------*/
i8 BinVal::nBytesRequired(i8 iLength)
{
  i8 nBytes = sizeof(BinVal) + iLength + 1 - 8;
  
  return nBytes;
}

