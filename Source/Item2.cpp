/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Item2::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Item class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Item2::operator new(size_t iSize, Item2* pItem)
{
  RASSERT(iSize);
  return pItem;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Item2::Item2(eCN eClassNo, i8 nSizeItem)
{
  m_nSizeItem = nSizeItem;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Item2::~Item2(void)
{

}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this item                                             */
/*----------------------------------------------------------------------------*/
i8 Item2::nSizeItem(void)
{
  return m_nSizeItem;
}

/*----------------------------------------------------------------------------*/
/* get address after this item                                                */
/*----------------------------------------------------------------------------*/
char* Item2::aAddressAfter(void)
{
  char* aAfter = pAdd<char*>(this,m_nSizeItem);
  
  return aAfter;
}

