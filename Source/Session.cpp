#include "Interface.h"

extern SessionList*  gpSessionList;

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Session::operator new(size_t iSize)
{
  ASSERT(gpSessionList);
  
  Session* pSession = gpSessionList->pAllocSession();
  
  return pSession;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Session::operator delete(void* pSessionAddress)
{
  Session* pSession = reinterpret_cast<Session*>(pSessionAddress);
  
  gpSessionList->vFreeSession(pSession);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Session::Session(void)
: Object(CN_SESSION)
{
  m_pUser = nullptr;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Session::vDump(void)
{
  vTrace("Seesion: %p\n",this);
}

