#pragma once

#include "Common.h"

namespace Common
{
  
  template <class OBJECT, eCN eClassNo>
  class NNP
  {
  public:
    OBJECT* m_pPointer;
    
    /*------------------------------------------------------------------------*/
    /* constructor                                                            */
    /*------------------------------------------------------------------------*/
    NNP<OBJECT,eClassNo>(OBJECT* pObject)
    {
      if (!pObject || (pObject && pObject->eClass() != eClassNo)) {
        throw (i8)__LINE__;
      }
      m_pPointer = pObject;
    }
    
    /*------------------------------------------------------------------------*/
    /* assignment                                                             */
    /*------------------------------------------------------------------------*/
    void operator = (OBJECT* pObject)
    {
      if (!pObject || (pObject && pObject->eClass() != eClassNo)) {
        throw (i8)__LINE__;
      }
      m_pPointer = pObject;
    }
    
    /*------------------------------------------------------------------------*/
    /* member                                                                 */
    /*------------------------------------------------------------------------*/
    OBJECT* operator -> (void)
    {
      if (m_pPointer == nullptr) {
        throw (i8)__LINE__;
      }
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* dereference                                                            */
    /*------------------------------------------------------------------------*/
    OBJECT* operator * (void)
    {
      if (m_pPointer == nullptr) {
        throw (i8)__LINE__;
      }
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* == operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator == (OBJECT* object)
    {
      return m_pPointer == object;
    }
    
    /*------------------------------------------------------------------------*/
    /* != operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator != (OBJECT* object)
    {
      return m_pPointer != object;
    }
    
  };
}

