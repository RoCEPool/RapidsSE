#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
spFLT::spFLT(void)
: Sprint(CN_SPFLT)
{
  _precondition_(_MAGIC_,CN_SPFLT,_FOOTER_);
  
  // set default Flt format
  vFormat(F_FLT);
  
  _checkInitialised_(CN_SPFLT);
  
  _postcondition_(_MAGIC_,CN_SPFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
spFLT::~spFLT(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint spFLT and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* spFLT::sz(d8 dFlt)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  dFlt);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* spFLT::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPFLT);
  
  return &m_xFooter;
}

