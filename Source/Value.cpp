/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Value::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Value class cannot be new'd\n");
  
  RASSERT(0);
}

