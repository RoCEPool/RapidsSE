#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Decider::operator new(size_t iSize, Decider* pDecider)
{
  RASSERT(iSize);
  return pDecider;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Decider::operator delete(void* pDeciderAddress)
{
  RASSERT(pDeciderAddress);
  // do nothing
  // must be explicitly free'd by caller
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Decider::Decider(void)
: Object(CN_DECIDER)
{
  m_iInt = 0;
  
  _checkInitialised_(CN_DECIDER);
  
  _postcondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Decider::~Decider(void)
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* check lock initialization                                                  */
/*----------------------------------------------------------------------------*/
void Decider::vCheckInit(void)
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
  
  ASSERT(0 == m_iInt); // logic check
}

/*----------------------------------------------------------------------------*/
/* atomically dec                                                             */
/*----------------------------------------------------------------------------*/
i8 Decider::iDec()
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);

  i8 i = Synch::uAtomicDec(&m_iInt);
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Decider::operator =(i8 iInt)
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
  
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* dereference / get value                                                    */
/*----------------------------------------------------------------------------*/
i8 Decider::operator *(void)
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
  
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* atomically dec (prefix form)                                               */
/*----------------------------------------------------------------------------*/
i8 Decider::operator --(void)
{
  _precondition_(_MAGIC_,CN_DECIDER,_FOOTER_);
  
  i8 i = Synch::uAtomicDec(&m_iInt);

  return i;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Decider::aFooter(void)
{
  _precondition_(_MAGIC_,CN_DECIDER);
  
  return &m_xFooter;
}

