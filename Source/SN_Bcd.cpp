#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Bcd::SN_Bcd(void)
: Scan(CN_SNBCD)
{
  _precondition_(_MAGIC_,CN_SNBCD,_FOOTER_);
    
  _checkInitialised_(CN_SNBCD);
  
  _postcondition_(_MAGIC_,CN_SNBCD,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Bcd::~SN_Bcd(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNBCD,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Bcd::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNBCD);
  
  if ( ! StrLib::bExtractDecimal(aacCrs,m_wDtm.m_iBcd,
                                 pCol->iColumnLength(),pCol->iColumnScale()) )
    throw C_UNKNOWN;
  
  return m_wDtm.m_iBcd;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Bcd::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNBCD);
  
  return &m_xFooter;
}

