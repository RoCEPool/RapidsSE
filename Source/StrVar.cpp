#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
void* Values::_pStrVar(void* aAddr)
{
  Object* pStrVar = reinterpret_cast<Object*>(aAddr);
  
  RASSERT_CAST( !pStrVar || CN_STRVAR == pStrVar->eClass() );
  
  return pStrVar;
}

