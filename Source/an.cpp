/*============================================================================*/
/* an.cpp - atomic number                                                     */
/*============================================================================*/

#include "Types.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
an::an(void)
{
  m_iNumber = -1;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
an::~an(void)
{
}

/*----------------------------------------------------------------------------*/
/* add atomically                                                             */
/*----------------------------------------------------------------------------*/
i8 an::iAdd(i8* pValue1, i8 iValue2)
{
  i8 iOldValue;
  
  iOldValue = __sync_fetch_and_add(pValue1, iValue2);
  
  return iOldValue + iValue2;
}

/*----------------------------------------------------------------------------*/
/* subtract atomically                                                        */
/*----------------------------------------------------------------------------*/
i8 an::iSub(i8* pValue1, i8 iValue2)
{
  i8 iOldValue;
  
  iOldValue = __sync_fetch_and_sub(pValue1, iValue2);
  
  return iOldValue + iValue2;
}

/*----------------------------------------------------------------------------*/
/* get the number                                                             */
/*----------------------------------------------------------------------------*/
i8 an::operator *(void)
{
  return m_iNumber;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool an::operator ==(i8 iValue)
{
  return m_iNumber == iValue;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool an::operator !=(i8 iValue)
{
  return m_iNumber != iValue;
}

/*----------------------------------------------------------------------------*/
/* < operator                                                                 */
/*----------------------------------------------------------------------------*/
bool an::operator <(i8 iValue)
{
  return m_iNumber < iValue;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool an::operator <=(i8 iValue)
{
  return m_iNumber <= iValue;
}

/*----------------------------------------------------------------------------*/
/* > operator                                                                 */
/*----------------------------------------------------------------------------*/
bool an::operator >(i8 iValue)
{
  return m_iNumber > iValue;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool an::operator >=(i8 iValue)
{
  return m_iNumber >= iValue;
}

/*----------------------------------------------------------------------------*/
/* prefix increment (returns new value)                                       */
/*----------------------------------------------------------------------------*/
i8 an::operator ++()
{
  return an::iAdd(&m_iNumber, 1);
}

/*----------------------------------------------------------------------------*/
/* prefix decrement (returns new value)                                       */
/*----------------------------------------------------------------------------*/
i8 an::operator --()
{
  return iSub(&m_iNumber, 1);
}

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
i8 an::operator +(i8 iValue)
{
  return iAdd(&m_iNumber, iValue);
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
i8 an::operator -(i8 iValue)
{
  return iSub(&m_iNumber, iValue);
}

