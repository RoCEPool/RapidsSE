extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
DtmVal* Data::_pDtmVal(void* aAddr)
{
  DtmVal* pDtmVal = reinterpret_cast<DtmVal*>(aAddr);
  
  return pDtmVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DtmVal::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_DTMVAL);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void DtmVal::operator delete(void* aAddr)
{
  DtmVal* pDtmVal = reinterpret_cast<DtmVal*>(aAddr);
  
  HeapMem::vFree(pDtmVal);
}


/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DtmVal::DtmVal(void)
: Object(CN_DTMVAL)
{
  _precondition_(_MAGIC_,CN_DTMVAL,_FOOTER_);
  
  m_pCol   = nullptr;
  m_eDatum = DM_NONE;
  m_wDtm.m_iInt   = C_UNKNOWN;
  m_nChars = 0;

  //m_sVch
  
  _checkInitialised_(CN_DTMVAL);
  
  _postcondition_(_MAGIC_,CN_DTMVAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
DtmVal::~DtmVal(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* test null                                                                   */
/*----------------------------------------------------------------------------*/
bool DtmVal::bIsNull(void)
{
  _precondition_(_MAGIC_,CN_DTMVAL,_FOOTER_);

  if (m_wDtm.m_iInt == C_DATUM_NULL)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set null                                                                   */
/*----------------------------------------------------------------------------*/
void DtmVal::vSetNull(void)
{
  _precondition_(_MAGIC_,CN_DTMVAL,_FOOTER_);

  m_wDtm.m_iInt = C_DATUM_NULL;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* DtmVal::aFooter(void)
{
  _precondition_(_MAGIC_,CN_DTMVAL);
  
  return &m_xFooter;
}

