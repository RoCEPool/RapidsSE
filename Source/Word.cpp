/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Word::Word(void)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Word::Word(i8 iArg)
{
  m_iI8 = iArg;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Word::Word(w8 wArg)
{
  m_wW8 = wArg;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Word::~Word(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/* is address on a word boundary?                                             */
/*----------------------------------------------------------------------------*/
bool Word::bOnWordBoundary(void* aAddress)
{
  bool bOn = MemLib::bOnBoundary(aAddress,sizeof(Word));
  
  return bOn;
}

/*----------------------------------------------------------------------------*/
/*-- Operators ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign iArg                                                                */
/*----------------------------------------------------------------------------*/
void Word::operator =(i8 iArg)
{
  m_iI8 = iArg;
}

/*----------------------------------------------------------------------------*/
/* assign wArg                                                                */
/*----------------------------------------------------------------------------*/
void Word::operator =(w8 wArg)
{
  m_wW8 = wArg;
}

