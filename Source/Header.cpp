#include "CorrectnessAlgebra.h"

#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
Header::Header(eCN eClassNo)
{
  vSetMagic();
  vSetClass(eClassNo);
  
  m_bWordBody = false;
}

/*----------------------------------------------------------------------------*/
/* test for valid magic                                                       */
/*----------------------------------------------------------------------------*/
bool Header::bValidMagic(void)
{
  if (C_MAGIC == m_uMagic)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set is word body                                                           */
/*----------------------------------------------------------------------------*/
void Header::vWordBody(bool bWordBody)
{
  m_bWordBody = bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get is word body                                                           */
/*----------------------------------------------------------------------------*/
bool Header::bWordBody(void)
{  
  return m_bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get class name                                                             */
/*----------------------------------------------------------------------------*/
Stz* Header::aClass(void)
{
  return aCN[eClass()];
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Header::aFooter(void)
{
  return nullptr;
}

