#include "CorrectnessAlgebra.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Foot::Foot(void)
{
  m_uFoot = C_FOOT;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Foot::~Foot(void)
{
  vAssertFoot();
}

/*----------------------------------------------------------------------------*/
/* ASSERT Foot                                                                */
/*----------------------------------------------------------------------------*/
void Foot::vAssertFoot(void) const
{
  ASSERT(m_uFoot == C_FOOT);
}

/*----------------------------------------------------------------------------*/
/* set Foot                                                                   */
/*----------------------------------------------------------------------------*/
void Foot::vSetFoot(void)
{
  m_uFoot = C_FOOT;
}

