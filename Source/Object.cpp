/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
Object::Object(eCN eClassNo)
{
  vSetMagic();
  vClass(eClassNo);
  
  m_bWordBody = false;
  
  _precondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* get class name                                                             */
/*----------------------------------------------------------------------------*/
Str* Object::aClass(void)
{
  return aCN[eClass()];
}

/*----------------------------------------------------------------------------*/
/* set class                                                                  */
/*----------------------------------------------------------------------------*/
void Object::vClass(eCN eClass)
{
  m_eClass = eClass;
}

/*----------------------------------------------------------------------------*/
/* set is word body                                                           */
/*----------------------------------------------------------------------------*/
void Object::vWordBody(bool bWordBody)
{
  _precondition_(_MAGIC_);
  
  m_bWordBody = bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get is word body                                                           */
/*----------------------------------------------------------------------------*/
bool Object::bWordBody(void)
{
  _precondition_(_MAGIC_);
  
  return m_bWordBody;
}


