#include "CorrectnessAlgebra.h"

#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
Object::Object(eCN eClassNo)
{
  vSetMagic();
  vSetClass(eClassNo);
  
  m_bWordBody = false;
  
  _precondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* get the buffer no (as i8) of the buffer that the object is within          */
/*----------------------------------------------------------------------------*/
i8 Object::iBufferNo(void)
{
  _precondition_(_MAGIC_);
  
  i8 iBufferNo = *(this->nBufferNo());
  
  return iBufferNo;
}

/*----------------------------------------------------------------------------*/
/* get the buffer no of the buffer that the object is within                  */
/*----------------------------------------------------------------------------*/
Pool::bn Object::nBufferNo(void)
{
  _precondition_(_MAGIC_);
  
  Buffer* pBuffer = Buffer::pGetBuffer(this);
  
  bn nBufferNo = pBuffer->nBufferNo();
  
  return nBufferNo;
}

/*----------------------------------------------------------------------------*/
/* test for valid magic                                                       */
/*----------------------------------------------------------------------------*/
bool Object::bValidMagic(void)
{
  if (C_MAGIC == m_uMagic)
    return true;
  
  return false;
}

/*----------------------------------------------------------------------------*/
/* set is word body                                                           */
/*----------------------------------------------------------------------------*/
void Object::vWordBody(bool bWordBody)
{
  _precondition_(_MAGIC_);
  
  m_bWordBody = bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get is word body                                                           */
/*----------------------------------------------------------------------------*/
bool Object::bWordBody(void)
{
  _precondition_(_MAGIC_);
  
  return m_bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get class name                                                             */
/*----------------------------------------------------------------------------*/
Stz* Object::aClass(void)
{
  return aCN[eClass()];
}

