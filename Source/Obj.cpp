extern BufferPool*  gpBufferPool;

/*----------------------------------------------------------------------------*/
/* initialize Obj                                                            */
/*----------------------------------------------------------------------------*/
Obj::Obj(eCN eClassNo)
{
  vSetMagic();
  vClass(eClassNo);
  
  m_bWordBody = false;
  
  _precondition_(_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* initialize magic                                                           */
/*----------------------------------------------------------------------------*/
void Obj::vInitMagic(void)
{
  _precondition_(_MAGIC_);
  
  vSetMagic();
}

/*----------------------------------------------------------------------------*/
/* get magic                                                                  */
/*----------------------------------------------------------------------------*/
i8 Obj::iMagic(void) const
{
  return m_uMagic;
}

/*----------------------------------------------------------------------------*/
/* set magic                                                                  */
/*----------------------------------------------------------------------------*/
void Obj::vSetMagic(void)
{
  m_uMagic = MAGIC;
}

/*----------------------------------------------------------------------------*/
/* get class name                                                             */
/*----------------------------------------------------------------------------*/
Str* Obj::aClass(void)
{
  return aCN[eClass()];
}

/*----------------------------------------------------------------------------*/
/* set class                                                                  */
/*----------------------------------------------------------------------------*/
void Obj::vClass(eCN eClass)
{
  m_eClass = eClass;
}

/*----------------------------------------------------------------------------*/
/* set is word body                                                           */
/*----------------------------------------------------------------------------*/
void Obj::vWordBody(bool bWordBody)
{
  _precondition_(_MAGIC_);
  
  m_bWordBody = bWordBody;
}

/*----------------------------------------------------------------------------*/
/* get is word body                                                           */
/*----------------------------------------------------------------------------*/
bool Obj::bWordBody(void)
{
  _precondition_(_MAGIC_);
  
  return m_bWordBody;
}


