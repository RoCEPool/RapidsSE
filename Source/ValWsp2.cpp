#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ValWsp2* Values::_pValWsp2(void* aAddr)
{
  ValWsp2* pValWsp2 = reinterpret_cast<ValWsp2*>(aAddr);
  
  RASSERT( !pValWsp2 || CN_VALWSP == pValWsp2->eClass() );
  
  return pValWsp2;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ValWsp2::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: ValWsp2 class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ValWsp2::ValWsp2(void)
: Value(CN_VALWSP)
{
  _precondition_(_MAGIC_,CN_VALWSP);                    //! need to add _FOOTER_
  
  _postcondition_(_MAGIC_,CN_VALWSP);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp2::operator =(i8 iInt)
{
  vClass(CN_INTVAL);
  _precondition_(_MAGIC_,CN_INTVAL);
  
  *_pIntVal(this) = iInt;  
}

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp2::operator =(Object* pPtr)
{
  vClass(CN_PTRVAL);
  _precondition_(_MAGIC_,CN_PTRVAL);
  
  *_pPtrVal(this) = pPtr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp2::operator =(Str* pStr)
{
  vClass(CN_STRVAL);
  _precondition_(_MAGIC_,CN_STRVAL);

  _pStrVal(this)->vAssign(pStr);
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp2::vAssignBinary(Object* pObject)
{
  vClass(CN_BINVAL);
  _precondition_(_MAGIC_,CN_BINVAL);
  
  *_pBinVal(this) = pObject;
}

/*----------------------------------------------------------------------------*/
/* get integer (ignoring type)                                                */
/*----------------------------------------------------------------------------*/
i8 ValWsp2::iAsInt(void)
{
  _precondition_(_MAGIC_);
  
  IntVal* pIntVal = reinterpret_cast<IntVal*>(this);
  
  i8 i = pIntVal->iInt();
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
char* ValWsp2::aWspArea(void)
{
  return m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* ValWsp2::pFooter(void)
{
  _precondition_(_MAGIC_);
  
  return &m_xFooter;
}

