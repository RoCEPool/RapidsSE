#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get total bytes required for entry                                         */
/*----------------------------------------------------------------------------*/
i8 EntryData::nBytesRequired(i8 nLevels, i8 nKeyBytes)
{
  i8 nBytes = Levels::nBytesRequired(nLevels)
              + nKeyBytes;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
EntryData* DBobjects::_aEntryData(void* aAddr)
{
  EntryData* aEntryData = reinterpret_cast<EntryData*>(aAddr);
  
  return aEntryData;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryData::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: EntryData class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy bytes                                                                 */
/*----------------------------------------------------------------------------*/
void EntryData::vCopyBytes(void* aSrc, i8 nBytes)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);

  void* aDst = this;
  
  MemLib::vCopy(aDst,aSrc,nBytes);
}

/*----------------------------------------------------------------------------*/
/* get key                                                                    */
/*----------------------------------------------------------------------------*/
Key* EntryData::aKey(i8 nLevels)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Key* aKey = pAdd<Key*>(this,(sizeof(i8)*(nLevels-1)));
  
  return aKey;
}

/*----------------------------------------------------------------------------*/
/* get levels                                                                 */
/*----------------------------------------------------------------------------*/
Levels* EntryData::aLevels(i8 nLevels)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  if ( ! nLevels )
    return nullptr;
  
  Levels* aLevels = _aLevels(this);
  
  return aLevels;
}

