#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get total bytes required for entry                                         */
/*----------------------------------------------------------------------------*/
i8 EntryData::nBytesRequired(i8 nOffsets, i8 nKeyBytes)
{
  i8 nOffsetBytes = RightVec::nBytesRequired(nOffsets);
  
  i8 nBytes = nOffsetBytes + nKeyBytes;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
EntryData* DBobjects::_aEntryData(void* aAddr)
{
  EntryData* aEntryData = reinterpret_cast<EntryData*>(aAddr);
  
  return aEntryData;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryData::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: EntryData class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy bytes                                                                 */
/*----------------------------------------------------------------------------*/
void EntryData::vCopyBytes(void* aSrc, i8 nBytes)
{
  void* aDst = this;
  
  MemLib::vCopy(aDst,aSrc,nBytes);
}

/*----------------------------------------------------------------------------*/
/* get key                                                                    */
/*----------------------------------------------------------------------------*/
Key* EntryData::aKey(i8 nOffsets)
{
  ASSERT(nOffsets >= 0 && nOffsets < C_FLAT_OFFSETS);
  
  i8 nOffsetBytes = RightVec::nBytesRequired(nOffsets);
  
  Key* aKey = pAdd<Key*>(this,nOffsetBytes);
  
  return aKey;
}

/*----------------------------------------------------------------------------*/
/* get offsets                                                                */
/*----------------------------------------------------------------------------*/
RightVec* EntryData::aRightVec(i8 nOffsets)
{
  ASSERT(nOffsets >= 0 && nOffsets < C_FLAT_OFFSETS);
  
  RightVec* aRightVec = _aRightVec(this);
  
  return aRightVec;
}

