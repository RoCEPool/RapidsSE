/*============================================================================*/
/* EntryData.cpp -- entry data                                                */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

extern i8 gnIndexOffsets;

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
EntryData* DBobjects::_aEntryData(void* aAddr)
{
  EntryData* aEntryData = reinterpret_cast<EntryData*>(aAddr);
  
  return aEntryData;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryData::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: EntryData class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get offsets                                                                */
/*----------------------------------------------------------------------------*/
RightVec* EntryData::aRightVec(i8 nOffsets)
{
  ASSERT(nOffsets >= 0 && nOffsets <= gnIndexOffsets);
  
  RightVec* aRightVec = _aRightVec(this);
  
  return aRightVec;
}

