#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set object entry                                                           */
/*----------------------------------------------------------------------------*/
void _LogEntryObj::vSet(LogEntry* pLogEntry, Object* pObject, eCA eObjAct)
{
  pLogEntry->m_eKind = EK_OBJ;
  
  m_pObject = pObject;
  m_eObjAct = eObjAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryObj::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%p,%s"_Stz,
                
                m_pObject,
                aCA[m_eObjAct]);
}

