/*============================================================================*/
/* snINT.cpp - Int scan helper                                                */
/*============================================================================*/

#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snINT::snINT(void)
: Sprint(CN_SNINT)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
  
  // set default Int format
  vFormat(F_INT);
  
  _checkInitialised_(CN_SNINT);
  
  _postcondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snINT::~snINT(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint snINT and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* snINT::sz(i8 iInt)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  iInt);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snINT::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNINT);
  
  return &m_xFooter;
}

