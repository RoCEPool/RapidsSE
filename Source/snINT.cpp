#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snINT::snINT(void)
: Scan(CN_SNINT)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
    
  _checkInitialised_(CN_SNINT);
  
  _postcondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snINT::~snINT(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 snINT::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNINT);
  
  if ( ! StrLib::bExtractInteger(aacCrs,&m_iValue,
                                 true/*bWithSign*/) )
    throw C_UNKNOWN;

  return C_UNKNOWN;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snINT::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNINT);
  
  return &m_xFooter;
}

