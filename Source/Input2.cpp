/*----------------------------------------------------------------------------*/
/* push command file                                                          */
/*----------------------------------------------------------------------------*/
void Input2::vPushFile(char* pWord)
{
  s256 sPath(pWord);
  
  m_xInputParser.vPush();
  bool b = m_xInputParser.bUseFile(sPath);
  ASSERT(b);
  m_xInputParser.vBegin();
}

/*----------------------------------------------------------------------------*/
/* pop command file                                                           */
/*----------------------------------------------------------------------------*/
void Input2::vPopFile(void)
{
  bool b = m_xInputParser.bPop();
  
  ASSERT(b);
}

