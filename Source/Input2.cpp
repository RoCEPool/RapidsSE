#include "Input2.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Input2::Input2(void)
{
  m_xInputParser.vMalloc(true);
  m_xInputParser.vPrompt("se.2> ");
  
  m_xInputParser.vPush();
  m_xInputParser.vUseStdin();
  m_xInputParser.vBegin();
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Input2::~Input2(void)
{
}

/*----------------------------------------------------------------------------*/
/* run seitf>                                                                 */
/*----------------------------------------------------------------------------*/
void Input2::vNext(char* pWords[])
{
  while (true) {
   
    for (i8 i = 0; i < 16; i++)
      *pWords[i] = '\0';
    
    i8 i = 0;
    while (LT_NONE != m_xInputParser.eNextLiteral(pWords[i])) {
      //vTrace("Word [%lld] %s\n",i,pWords[i]);
      i++;
    }
    
    break;
  }
    
}

