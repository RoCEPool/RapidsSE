#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Now::Now(void)
: Object(CN_NOW)
{
  _precondition_(_MAGIC_,CN_NOW,_FOOTER_);
  
  m_oTime.vSetNowLocal();
  
  char* z = m_sFormatted.aChar();
  
  m_oTime.vAppendLocal(&z);

  _checkInitialised_(CN_SINCE);
  
  _postcondition_(_MAGIC_,CN_NOW,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Now::~Now(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_NOW,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Stz* Now::sFormatted(void)
{
  _precondition_(_MAGIC_,CN_NOW,_FOOTER_);
  
  return m_sFormatted.aStz();
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Now::aFooter(void)
{
  _precondition_(_MAGIC_,CN_NOW);
  
  return &m_xFooter;
}

