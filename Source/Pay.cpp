/*============================================================================*/
/* Pay.cpp -- payload part of an index entry                                  */
/*============================================================================*/

#include "Entries.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Pay* Entries::_aPay(void* aAddr)
{
  Pay* aPay = reinterpret_cast<Pay*>(aAddr);
  
  return aPay;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Pay::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: Pay class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Pay::Pay(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Pay::~Pay(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* increment the size of the payload                                          */
/*----------------------------------------------------------------------------*/
void Pay::vIncPayBytes(i8 nDeltaBytes)
{
  m_nPayBytes += nDeltaBytes;
}

/*----------------------------------------------------------------------------*/
/* get size of the payload                                                    */
/*----------------------------------------------------------------------------*/
i8 Pay::nPayBytes(void)
{
  return m_nPayBytes;
}

/*----------------------------------------------------------------------------*/
/* set size of the payload                                                    */
/*----------------------------------------------------------------------------*/
void Pay::vPayBytes(i8 nBytes)
{
  m_nPayBytes = nBytes;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Pay::vReset(void)
{
  m_nPayBytes = 0;
}

