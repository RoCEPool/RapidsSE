/*============================================================================*/
/* Pay.cpp -- payload part of an index entry                                  */
/*============================================================================*/

#include "Entries.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Pay* Entries::_aPay(void* aAddr)
{
  Pay* aPay = reinterpret_cast<Pay*>(aAddr);
  
  return aPay;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Pay::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: Pay class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Pay::Pay(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Pay::~Pay(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get size of the payload                                                    */
/*----------------------------------------------------------------------------*/
i8 Pay::nPayloadBytes(void)
{
  return m_nPayloadBytes;
}

/*----------------------------------------------------------------------------*/
/* set size of the payload                                                    */
/*----------------------------------------------------------------------------*/
void Pay::vPayloadBytes(i8 nPayloadBytes)
{
  m_nPayloadBytes = nPayloadBytes;
}

/*----------------------------------------------------------------------------*/
/* get size of this pay                                                       */
/*----------------------------------------------------------------------------*/
i8 Pay::nPaySize(void)
{
  return sizeof(Pay) + m_nPayloadBytes;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Pay::vReset(void)
{
  m_nPayloadBytes = 0;
}

