/*============================================================================*/
/* spINT.cpp - Int sprint helper                                              */
/*============================================================================*/

#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
spINT::spINT(void)
: Sprint(CN_SPINT)
{
  _precondition_(_MAGIC_,CN_SPINT,_FOOTER_);
  
  // set default Int format
  vFormat(F_INT);
  
  _checkInitialised_(CN_SPINT);
  
  _postcondition_(_MAGIC_,CN_SPINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
spINT::~spINT(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint spINT and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* spINT::sz(i8 iInt)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  iInt);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spINT::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(C_I8_MAX);
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spINT::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(73);
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spINT::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(C_I8_MIN);
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* spINT::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPINT);
  
  return &m_xFooter;
}

