/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWrk::EntWrk(eCN eClassNo)
: Object(eClassNo)
{
  _precondition_(_MAGIC_);

  // check initialisation of rowid
  ASSERT(0 == m_xId.iBuffer() &&
         0 == m_xId.iItem()   &&
         0 == m_xId.nOffsets());
  
  m_xWsp.vInit();
  
  m_aEmbedded = m_xWsp.aArea();
  
  _checkInitialisedSize_(sizeof(EntWrk));
  
  _postcondition_(_MAGIC_,eClassNo,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWrk::~EntWrk(void) noexcept(false)
{
  _precondition_(_MAGIC_,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of embedded object                                             */
/*----------------------------------------------------------------------------*/
char* EntWrk::aEmbedded(void)
{  
  _precondition_(_MAGIC_,_FOOTER_);
  
//  char* aData = m_xWsp.aArea();
//  
//  return aData;
  
  return m_aEmbedded;
}

/*----------------------------------------------------------------------------*/
/* set address of embedded object                                             */
/*----------------------------------------------------------------------------*/
void EntWrk::vEmbedded(char* aEmbedded)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_aEmbedded = aEmbedded;
}

/*----------------------------------------------------------------------------*/
/* get the size of the entry required to contain the embedded object          */
/*----------------------------------------------------------------------------*/
i8 EntWrk::nEntrySize(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  i8 nData = nDataSize();
  
  i8 nBytes = sizeof(Item) + nData;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get row id                                                                 */
/*----------------------------------------------------------------------------*/
