{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return m_xId;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void EntWrk::vId(Id& xId)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_xId = xId;
}

/*----------------------------------------------------------------------------*/
/* get address of next available chunk                                        */
/*----------------------------------------------------------------------------*/
char* EntWrk::aLatter(void)
{
  return m_xWsp.aLatter();
}

/*----------------------------------------------------------------------------*/
/* get nLevel                                                                 */
/*----------------------------------------------------------------------------*/
i8 EntWrk::nOffsets(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return m_xId.nOffsets();
}

/*----------------------------------------------------------------------------*/
/* get offset bytes                                                           */
/*----------------------------------------------------------------------------*/
i8 EntWrk::nOffsetSize(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  i8 nBytes = sizeof(i4) * m_xId.nOffsets();
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets                                                      */
/*----------------------------------------------------------------------------*/
void EntWrk::vOffsets(i8 nOffsets)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_xId.vOffsets(nOffsets);
}

/*----------------------------------------------------------------------------*/
/* set a random number of offsets                                             */
/*----------------------------------------------------------------------------*/
void EntWrk::vRandomOffsets(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  i8 nOffsets = Random::iLogLevel(3,C_FLAT_FREQ + 1) + 1;
  
  m_xId.vOffsets(nOffsets);
}

/*----------------------------------------------------------------------------*/
/* reset embedded address                                                     */
/*----------------------------------------------------------------------------*/
void EntWrk::vReset(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_aEmbedded = m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/* take chunk                                                                 */
/*----------------------------------------------------------------------------*/
void EntWrk::vTake(i8 iSize)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_xWsp.vTake(iSize);
}

