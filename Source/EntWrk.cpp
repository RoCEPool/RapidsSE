#include "DBobjects.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWrk::EntWrk(eCN eClassNo)
: Object(eClassNo)
{
  _precondition_(_MAGIC_);

  // check initialisation of rowid
  ASSERT(0 == m_xId.iBuffer() && 0 == m_xId.iRow());
  
  m_nOffsets = -1;
  
  m_xEmbeddedWsp.vInit();
  
  _checkInitialisedSize_(sizeof(EntWrk));
  
  _postcondition_(_MAGIC_,eClassNo,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWrk::~EntWrk(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of embedded object                                             */
/*----------------------------------------------------------------------------*/
char* EntWrk::aEmbedded(void)
{  
  _precondition_(_MAGIC_,_FOOTER_);
  
  char* aData = m_xEmbeddedWsp.aArea();
  
  return aData;
}

/*----------------------------------------------------------------------------*/
/* get row id                                                                 */
/*----------------------------------------------------------------------------*/
Id& EntWrk::xId(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return m_xId;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void EntWrk::vId(Id& xId)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_xId = xId;
}

/*----------------------------------------------------------------------------*/
/* get address of next available chunk                                        */
/*----------------------------------------------------------------------------*/
char* EntWrk::aLatter(void)
{
  return m_xEmbeddedWsp.aLatter();
}

/*----------------------------------------------------------------------------*/
/* get nLevel                                                                 */
/*----------------------------------------------------------------------------*/
i8 EntWrk::nOffsets(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  //ASSERT(m_nOffsets >= 0 && m_nOffsets <= gpAttachMap->m_nIndexOffsets);
  
  return m_nOffsets;
}

/*----------------------------------------------------------------------------*/
/* get offset bytes                                                           */
/*----------------------------------------------------------------------------*/
i8 EntWrk::nOffsetSize(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  //ASSERT(m_nOffsets >= 0 && m_nOffsets <= gpAttachMap->m_nIndexOffsets);
  
  //vTrace("sizeof(i4) %d sizeof(long) %d\n"_Stz,sizeof(i4),sizeof(long));
  
  i8 nBytes = sizeof(i4) * m_nOffsets;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets                                                      */
/*----------------------------------------------------------------------------*/
void EntWrk::vOffsets(i8 nOffsets)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_nOffsets = nOffsets;
}

/*----------------------------------------------------------------------------*/
/* take chunk                                                                 */
/*----------------------------------------------------------------------------*/
void EntWrk::vTake(i8 iSize)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  m_xEmbeddedWsp.vTake(iSize);
}

