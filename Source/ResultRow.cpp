#include "DBobjects.h"

#include "StorageEngine.h"

extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ResultRow* DBobjects::_pResultRow(void* aAddr)
{
  ResultRow* pResultRow = reinterpret_cast<ResultRow*>(aAddr);
  
  return pResultRow;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ResultRow::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: ResultRow class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ResultRow::operator new(size_t iSize, ResultRow* pResultRow)
{
  RASSERT(iSize);
  return pResultRow;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ResultRow::ResultRow(i8 nSizeResultRow)
: Item(CN_RESULTROW,nSizeResultRow)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RESULTROW);
  
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
ResultRow::~ResultRow(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}

/*----------------------------------------------------------------------------*/
/* get row address                                                            */
/*----------------------------------------------------------------------------*/
Row* ResultRow::aRow(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_RESULTROW);
  
  Row* aRow = pAdd<Row*>(this,sizeof(Item));

  return aRow;
}

