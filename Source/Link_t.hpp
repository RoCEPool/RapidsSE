/*============================================================================*/
/* Link_t.hpp -- non-locking atomic test and set pointer                      */
/*============================================================================*/
#pragma once

namespace Structures
{
  template <class _CLASS>
  class Link_t
  {
  public:
  
    ////////////////////////////////////////////////////////////////////////////
    //                              member variables                          //
    ////////////////////////////////////////////////////////////////////////////
    _CLASS m_wLink;
  

    ////////////////////////////////////////////////////////////////////////////
    //                              template functions                        //
    ////////////////////////////////////////////////////////////////////////////
  
    /*------------------------------------------------------------------------*/
    /* constructor                                                            */
    /*------------------------------------------------------------------------*/
    Link_t<_CLASS>(void)
    {
      m_wLink = (_CLASS)0;
    }
    
    /*------------------------------------------------------------------------*/
    /* dereference operator                                                   */
    /*------------------------------------------------------------------------*/
    _CLASS operator * (void)
    {
      return m_wLink;
    }
  
    /*------------------------------------------------------------------------*/
    /* test and set                                                           */
    /*------------------------------------------------------------------------*/
    void vReset(void)
    {
      m_wLink = (_CLASS)0;
    }
  
    /*------------------------------------------------------------------------*/
    /* set (without testing)                                                  */
    /*------------------------------------------------------------------------*/
    void vSetWithoutTest(_CLASS wValue)
    {
      m_wLink = wValue;
    }
  
    /*------------------------------------------------------------------------*/
    /* test and set                                                           */
    /*------------------------------------------------------------------------*/
    bool bTestAndSet(_CLASS wIfValue, _CLASS wSetValue)
    {
      bool bWasSet = Atomic::bTestAndSet((u8*)&m_wLink,wIfValue,wSetValue);
    
      return bWasSet;
    }
  };
}

