#pragma once

namespace Structures
{
  template <class OBJECT>
  class Link_t
  {
  public:
    OBJECT* m_pPointer;
    
    /*------------------------------------------------------------------------*/
    /* constructor                                                            */
    /*------------------------------------------------------------------------*/
    Link_t<OBJECT>(void)
    {
      m_pPointer = nullptr;
    }
    
    /*------------------------------------------------------------------------*/
    /* dereference operator                                                   */
    /*------------------------------------------------------------------------*/
    OBJECT* operator * (void)
    {
      return m_pPointer;
    }
  
    /*------------------------------------------------------------------------*/
    /* test and set                                                           */
    /*------------------------------------------------------------------------*/
    bool bSetNull(void)
    {
      m_pPointer = nullptr;
    }
  
    /*------------------------------------------------------------------------*/
    /* test and set                                                           */
    /*------------------------------------------------------------------------*/
    bool bTestAndSet(OBJECT* pIfObject, OBJECT* pSetObject)
    {
      bool bWasSet = Atomic::bTestAndSet(&m_pPointer,pIfObject,pSetObject);
    
      return bWasSet;
    }
  };
}

