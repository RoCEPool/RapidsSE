#pragma once

namespace Structures
{
  template <class OBJECT>
  class Link_t
  {
  public:
    OBJECT* m_pPointer;
    
    /*------------------------------------------------------------------------*/
    /* constructor                                                            */
    /*------------------------------------------------------------------------*/
    Link_t<OBJECT>(void)
    {
      m_pPointer = nullptr;
    }
    
    /*------------------------------------------------------------------------*/
    /* member                                                                 */
    /*------------------------------------------------------------------------*/
    OBJECT* operator -> (void)
    {
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* dereference                                                            */
    /*------------------------------------------------------------------------*/
    OBJECT* operator * (void)
    {
      return m_pPointer;
    }
    
    /*------------------------------------------------------------------------*/
    /* == operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator == (OBJECT* pObject)
    {
      return m_pPointer == pObject;
    }
    
    /*------------------------------------------------------------------------*/
    /* != operator                                                            */
    /*------------------------------------------------------------------------*/
    bool operator != (OBJECT* pObject)
    {
      return m_pPointer != pObject;
    }
  
  
    /*------------------------------------------------------------------------*/
    /* test and set                                                           */
    /*------------------------------------------------------------------------*/
    bool bTestAndSet(OBJECT* pIfObject, OBJECT* pSetObject)
    {
      if (pIfObject == m_pPointer)
        m_pPointer = pSetObject;
    }
  };
}

