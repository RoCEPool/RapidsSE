#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snVCH::snVCH(void)
: Scan(CN_SNVCH)
{
  _precondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
    
  _checkInitialised_(CN_SNVCH);
  
  _postcondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snVCH::~snVCH(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNVCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
Stz* snVCH::sz(char** aacCrs, Column* pCol, Formatters* pScnFmt,
               bool bSawLeadingEnclosed,
               i8& nChars_)
{
  _precondition_(_MAGIC_,CN_SNVCH);
  
  if ( ! StrLib::bExtractVarchar(aacCrs,
                                 m_caVch,
                                 pCol->iColumnLength(),
                                 bSawLeadingEnclosed,
                                 pScnFmt->m_cEnclosedBy_Leading,
                                 pScnFmt->m_cEnclosedBy_Trailing,
                                 pScnFmt->m_cEscapeChar,
                                 pScnFmt->m_cFieldDelimiter,
                                 pScnFmt->m_cRecordTerminator,
                                 pScnFmt->m_bAllowNonPrintable,
                                 nChars_) )
    throw C_UNKNOWN;

  return (Stz*) &m_caVch[0];
}



/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snVCH::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNVCH);
  
  return &m_xFooter;
}

