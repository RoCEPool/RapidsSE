/*============================================================================*/
/* EntryVec.cpp -- index entry vector                                         */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryVec::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: EntryVec class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntryVec::EntryVec(void)
: Object(CN_ENTRYVEC)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTRYVEC);
  
  _setFooter_();
  
  for (u8 u=0; u < C_FLAT_LEVELS; u++)
    m_pEntry[u] = nullptr;
  
  _checkInitialised_(CN_ENTRY);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ENTRYVEC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntryVec::~EntryVec(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTRYVEC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* [] operator                                                                */
/*----------------------------------------------------------------------------*/
Entry* EntryVec::operator [](u8 uLevel)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTRYVEC,_FOOTER_);
  
  return m_pEntry[uLevel];
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* EntryVec::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTRY);
  
  return &m_xFooter;
}

