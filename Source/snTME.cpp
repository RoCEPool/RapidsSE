#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snTME::snTME(void)
: Scan(CN_SNTME)
{
  _precondition_(_MAGIC_,CN_SNTME,_FOOTER_);
  
  _checkInitialised_(CN_SNTME);
  
  _postcondition_(_MAGIC_,CN_SNTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snTME::~snTME(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNTME,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 snTME::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNTME);
  
  i8 iHour, iMinute, iSecond, iMicro;
  
  if ( ! StrLib::bExtractTime(aacCrs, iHour, iMinute, iSecond, iMicro) )
    throw C_UNKNOWN;
  
  m_xTme.xTme.m_uHour   = iHour;
  m_xTme.xTme.m_uMinute = iMinute;
  m_xTme.xTme.m_uSecond = iSecond;
  m_xTme.xTme.m_uMicro  = iMicro;
  m_xTme.xTme.m_uSpare  = 0;
  
  return m_xTme.m_iI8;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snTME::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNTME);
  
  return &m_xFooter;
}

