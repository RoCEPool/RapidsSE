#include "Values.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PtrVal* Values::_aPtrVal(void* aAddr)
{
  PtrVal* aPtrVal = reinterpret_cast<PtrVal*>(aAddr);
  
  RASSERT_TYPE(aPtrVal,CN_PTRVAL);
  
  return aPtrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* PtrVal::operator new(size_t)
{
  vFatal("fatal: PtrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PtrVal::PtrVal(void)
: Value(CN_PTRVAL)
{
  m_pObj = nullptr;
  
  _checkInitialised_(CN_PTRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Object* pObject)
{
  m_pObj = pObject;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Value* aValue)
{
  m_aValue = aValue;
}

/*----------------------------------------------------------------------------*/
/* as integer                                                                 */
/*----------------------------------------------------------------------------*/
i8 PtrVal::iAsInt(void)
{
  return (i8)m_pObj;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 PtrVal::nSize(void) const
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* get pointer to proper object                                               */
/*----------------------------------------------------------------------------*/
Object* PtrVal::pObj(void) const
{
  return pPoolCheck<Object*>(m_pObj);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void PtrVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = reinterpret_cast<void*>(m_pObj);
}

