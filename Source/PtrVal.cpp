#include "Values.h"
#include "Dictionaries.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PtrVal* Values::_pPtrVal(void* aAddr)
{
  PtrVal* pPtrVal = reinterpret_cast<PtrVal*>(aAddr);
  
  RASSERT( !pPtrVal || CN_PTRVAL == pPtrVal->eClass() );
  
  return pPtrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* PtrVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: PtrVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PtrVal::PtrVal(void)
: Value(CN_PTRVAL)
{
  m_pPtr = nullptr;
  
  _checkInitialised_(CN_PTRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Object* pObject)
{
  m_pPtr = pObject;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 PtrVal::nSize(void) const
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* as pointer to in memory pool object                                        */
/*----------------------------------------------------------------------------*/
Object* PtrVal::pPtr(void) const
{
  return pPoolCheck<Object*>(m_pPtr);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void PtrVal::vToString(Str* aWorkspace)
{
  StrLib::wToPointer(m_pPtr,aWorkspace->a());
}

