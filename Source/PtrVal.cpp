#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PtrVal* SenVM::_aPtrVal(void* aAddr)
{
  PtrVal* aPtrVal = reinterpret_cast<PtrVal*>(aAddr);
  
  RASSERT_TYPE(aPtrVal,CN_PTRVAL);
  
  return aPtrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* PtrVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: PtrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PtrVal::PtrVal(void)
: StkVal(CN_PTRVAL)
{
  _Header::vClass(CN_PTRVAL);
  
  m_pObj = nullptr;

  _checkInitialised_(CN_PTRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Object* pObject)
{
  m_pObj = pObject;
}

/*----------------------------------------------------------------------------*/
/* get pointer to proper object                                               */
/*----------------------------------------------------------------------------*/
Object* PtrVal::pObj(void)
{
  return pPoolCheck<Object*>(m_pObj);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
 
/*----------------------------------------------------------------------------*/
/* as integer                                                                 */
/*----------------------------------------------------------------------------*/
i8 PtrVal::iAsInt(void)
{
  return (i8)m_pObj;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 PtrVal::nStackBytes(void)
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void PtrVal::vToString(Stz* szStz)
{
  * szStz = reinterpret_cast<void*>(m_pObj);
}

