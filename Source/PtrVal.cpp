#include "Values.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PtrVal* Values::_pPtrVal(void* aAddr)
{
  PtrVal* pPtrVal = reinterpret_cast<PtrVal*>(aAddr);
  
  RASSERT_TYPE(pPtrVal,CN_PTRVAL);
  
  return pPtrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* PtrVal::operator new(size_t)
{
  vFatal("fatal: PtrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PtrVal::PtrVal(void)
: Value(CN_PTRVAL)
{
  m_pPtr = nullptr;
  
  _checkInitialised_(CN_PTRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Object* pObject)
{
  m_pPtr = pObject;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::operator =(Value* aValue)
{
  m_aValue = aValue;
}

/*----------------------------------------------------------------------------*/
/* as integer                                                                 */
/*----------------------------------------------------------------------------*/
i8 PtrVal::iAsInt(void)
{
  return (i8)m_pPtr;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 PtrVal::nSize(void) const
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* as pointer to in memory pool object                                        */
/*----------------------------------------------------------------------------*/
Object* PtrVal::pPtr(void) const
{
  return pPoolCheck<Object*>(m_pPtr);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void PtrVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = reinterpret_cast<void*>(m_pPtr);
}

