/*============================================================================*/
/* PtrVal.cpp -- Layout of a Pointer to a Proper Object when on Stack         */
/*============================================================================*/

#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* PtrVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: PtrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}


/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
 

/*----------------------------------------------------------------------------*/
/* return a value                                                             */
/*----------------------------------------------------------------------------*/
Object* PtrVal::pObj(void)
{
  vClass(CN_PTRVAL);
  
  return m_pObj;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void PtrVal::vObj(Object* pObject)
{
  vClass(CN_PTRVAL);
  m_pObj = pObject;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a PtrVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 PtrVal::nStackUsage(void)
{
  return sizeof(PtrVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void PtrVal::vToStz(Stz* szDst)
{
  * szDst = reinterpret_cast<void*>(m_pObj);
}

