/*============================================================================*/
/* RightVec.hpp -- array of level pointers/references/offsets                 */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

extern i8 gnIndexOffsets;

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
RightVec* DBobjects::_aRightVec(void* aAddr)
{
  RightVec* aRightVec = reinterpret_cast<RightVec*>(aAddr);
  
  return aRightVec;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RightVec::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: RightVec class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RightVec::operator new(size_t iSize, RightVec* pRightVec)
{
  RASSERT(iSize);
  return pRightVec;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RightVec::RightVec(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RightVec::~RightVec(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get the offset for a given offset (offset is 0 or 1)                       */
/*----------------------------------------------------------------------------*/
i8 RightVec::iOffset(on nOffsetNo)
{
  ASSERT(nOffsetNo >= 0_on && nOffsetNo < gnIndexOffsets);
  
  u8 uOffset = m_nOffset[*nOffsetNo];
  
  return uOffset;
}

/*----------------------------------------------------------------------------*/
/* set the offset for a given offset (offset is 0 or 1)                       */
/*----------------------------------------------------------------------------*/
void RightVec::vOffset(on nOffsetNo, i8 iOffset)
{
  ASSERT(nOffsetNo >= 0_on && nOffsetNo < gnIndexOffsets);
  
  m_nOffset[*nOffsetNo] = iOffset;
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calculate number of bytes required to hold n offsets                       */
/*----------------------------------------------------------------------------*/
i8 RightVec::nBytesRequired(i8 nOffsets)
{
  ASSERT(nOffsets >= 0 && nOffsets <= gnIndexOffsets);
  
  i8 nBytes = nOffsets * sizeof(u8);
  
  return nBytes;
}

