void Step::vAddSteps_Table2(void)
{
  vAddStep("table[].set"_Stz,                &Step::vTableSet);
}

/*----------------------------------------------------------------------------*/
/* table[].set -- set table                                                   */
/*----------------------------------------------------------------------------*/
void Step::vTableSet(void)
{
  ENTRY("vTableSet"_Stz);
  
  Object* pPtrObject;
  if ( ! m_pDataStack->bPopObject(pPtrObject) )
    THROW_DSTACK();
  
  m_pRegSet->m_xpTable = _pTable(pPtrObject);
  
  EXIT();
}


