#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BcdVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: BcdVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BcdVal::vBcd(i8 iInt)
{
  vClass(CN_INTVAL);
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a BcdVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 BcdVal::nStackUsage(void)
{
  return sizeof(BcdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BcdVal::vToStz(Stz* szDst)
{
  if (C_DATUM_NULL == m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = m_iInt;
}

