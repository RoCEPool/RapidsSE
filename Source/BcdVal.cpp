#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
BcdVal* Values::_pBcdVal(void* aAddr)
{
  BcdVal* pBcdVal = reinterpret_cast<BcdVal*>(aAddr);
  
  RASSERT( !pBcdVal || CN_BCDVAL == pBcdVal->eClass() );
  
  return pBcdVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* BcdVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: BcdVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
BcdVal::BcdVal(void)
: Value(CN_BCDVAL)
{
  m_iBcd = 0;
  
  _checkInitialised_(CN_BOLVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BcdVal::operator =(Bcd xBcd)
{
  //vTrace("BcdVal: diff %lld\n"_Str,nSub(&m_iBcd,this));
  
  m_iBcd = xBcd.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void BcdVal::operator =(i8 iBcd)
{
  //vTrace("BcdVal: diff %lld\n"_Str,nSub(&m_iBcd,this));
  
  m_iBcd = iBcd;
}

/*----------------------------------------------------------------------------*/
/* get iBcd                                                                   */
/*----------------------------------------------------------------------------*/
i8 BcdVal::iBcd(void) const
{
  return m_iBcd;
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* BcdVal::aInt(void)
{
  return &m_iBcd;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 BcdVal::nSize(void) const
{
  return sizeof(BcdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void BcdVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_iBcd;
}

