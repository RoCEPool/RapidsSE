#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Scratch* System::_pScratch(void* aAddress)
{
  Scratch* pScratch = reinterpret_cast<Scratch*>(aAddress);
  
  RASSERT( !pScratch || CN_SCRATCH == pScratch->eClass() );
  
  return pScratch;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Scratch::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  void* pObject = HeapMem::pAllocate(CN_SCRATCH);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Scratch::operator new(size_t iSize, Scratch* pScratch)
{
  RASSERT(iSize);
  return pScratch;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Scratch::operator delete(void* aAddress)
{
  ASSERT(aAddress);
  
  Object* pObject = reinterpret_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Scratch::Scratch(void)
: Object(CN_SCRATCH)
{
  _precondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);

  m_xWsp.vFill(0x00,CN_SCRATCH);
  
  _checkInitialised_(CN_SCRATCH);

  _postcondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Scratch::~Scratch(void)
{
  _precondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* get work area                                                              */
/*----------------------------------------------------------------------------*/
char* Scratch::aWspArea(void)
{
  _precondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);
  
  return m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/* get work area                                                              */
/*----------------------------------------------------------------------------*/
Stz* Scratch::aWspStr(void)
{
  _precondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);
  
  return m_xWsp.aStr();
}

/*----------------------------------------------------------------------------*/
/* get wsp bytes used                                                         */
/*----------------------------------------------------------------------------*/
i8 Scratch::nWspLength(void)
{
  _precondition_(_MAGIC_,CN_SCRATCH,_FOOTER_);

  return m_xWsp.nLength();
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Scratch::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SCRATCH);
  
  return &m_xFooter;
}

