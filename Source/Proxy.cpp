/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Proxy::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PROXY);
  
  return &m_xFooter;
}

