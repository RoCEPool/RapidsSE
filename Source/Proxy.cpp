/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Proxy::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Dictionary class cannot be new'd"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Proxy::operator delete(void* pBufferAddress)
{
  RASSERT(pBufferAddress);
  vFatal("fatal: Dictionary class cannot be deleted"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Proxy::Proxy(void)
: Object(CN_PROXY)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PROXY,_FOOTER_);
  
  _checkInitialised_(CN_PROXY);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_PROXY,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Proxy::~Proxy(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PROXY,_FOOTER_);
}

