#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Row::operator new(size_t)
{
  vFatal("fatal: Row class cannot be new'd\n");
  
  //vExitFatal();
  
  exit(EXIT_FAILURE);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Row::operator new(size_t, Row* pRow)
{
  return pRow;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Row::Row(void)
: cn(CN_ROW)
{
  _poolAddress_(this);
  _magic_();
  
  m_iTxId      = -1;
  m_iDataBytes = 0;
  
  _class_(CN_ROW);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Row::~Row(void)
{
  _poolAddress_(this);
}

/*----------------------------------------------------------------------------*/
/* get data                                                                   */
/*----------------------------------------------------------------------------*/
char* Row::pData(void)
{
  _poolAddress_(this);
  
  char* pDataAddr = pcAdd(this,sizeof(Row));
  
  return pPoolCheck<char*>(pDataAddr);
}

/*----------------------------------------------------------------------------*/
/* get data bytes                                                             */
/*----------------------------------------------------------------------------*/
i8 Row::iDataBytes(void)
{
  _poolAddress_(this);
  
  return m_iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* set data bytes                                                             */
/*----------------------------------------------------------------------------*/
void Row::vDataBytes(i8 iDataBytes)
{
  _poolAddress_(this);
  
  m_iDataBytes = iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Row::vDump(void) 
{
  _poolAddress_(this);
  
  vTrace("Row %p: TxId %lld DataBytes %lld %s (%lld bytes)\n",
         this,
         m_iTxId,
         m_iDataBytes,
         pData(),
         String::iSize(pData())
         );
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this row                                              */
/*----------------------------------------------------------------------------*/
i8 Row::iSize(void)
{
  i8 iBytes = sizeof(Row) + m_iDataBytes;
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/* get tx id                                                                  */
/*----------------------------------------------------------------------------*/
i8 Row::iTxId(void)
{
  return m_iTxId;
}

/*----------------------------------------------------------------------------*/
/* set tx id                                                                  */
/*----------------------------------------------------------------------------*/
void Row::vTxId(i8 iTxId)
{
  m_iTxId = iTxId;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get bytes required for row                                                               */
/*----------------------------------------------------------------------------*/
i8 Row::iBytesRequired(const char* w)
{
  i8 iBytes = sizeof(Row) + String::iSize(w);
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/* get bytes required for row                                                               */
/*----------------------------------------------------------------------------*/
i8 Row::iBytesRequired(i8 iDataBytes)
{
  i8 iBytes = sizeof(Row) + iDataBytes;
  
  return iBytes;
}

