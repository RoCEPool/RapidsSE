/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Row::Row(void)
: Object(CN_ROW)
{
  _poolAddress_(this);
  _magic_();
  
  m_iDataBytes = 0;
  
  _class_(CN_ROW);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Row::~Row(void)
{
  _poolAddress_(this);
}

/*----------------------------------------------------------------------------*/
/* get data                                                                   */
/*----------------------------------------------------------------------------*/
char* Row::pData(void)
{
  _poolAddress_(this);
  
  char* pAddress = reinterpret_cast<char*>(this) + sizeof(Row);
  
  return pPoolCheck<char*>((void*)pAddress);
}

/*----------------------------------------------------------------------------*/
/* get data bytes                                                             */
/*----------------------------------------------------------------------------*/
i8 Row::iDataBytes(void) const
{
  _poolAddress_(this);
  
  return m_iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Row::vDump(void) 
{
  _poolAddress_(this);
  
  vTrace("Row %p: PrevRow %p DataBytes %lld %s\n",
         this,
         pPrevRow(),
         m_iDataBytes,
         pData()
         );
}

/*----------------------------------------------------------------------------*/
/* get previous row                                                           */
/*----------------------------------------------------------------------------*/
Row* Row::pPrevRow(void) const
{
  _poolAddress_(this);
  
  return nullptr; //pPoolCheck<Row*>(pPrevSlab());
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this row                                              */
/*----------------------------------------------------------------------------*/
i8 Row::iSize(void) const
{
  return sizeof(Row) - 1 + m_iDataBytes;
}

