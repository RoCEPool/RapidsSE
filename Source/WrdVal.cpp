#include "Dictionaries.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* WrdVal::operator new(size_t iSize)
{
  vFatal("fatal: WrdVal class cannot be new'd\n");
  
  //vExitFatal();
  
  exit(EXIT_FAILURE);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
WrdVal::WrdVal(void)
: Value(CN_WRDVAL)
{
  m_pWord = nullptr;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void WrdVal::operator =(Word* pValue)
{
  m_pWord = pValue;
}

/*----------------------------------------------------------------------------*/
/* get pWord                                                                  */
/*----------------------------------------------------------------------------*/
Word* WrdVal::pWord(void) const
{
  return m_pWord;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 WrdVal::iSize(void) const
{
  return sizeof(WrdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void WrdVal::vToCommand(char* aWorkspace)
{
  String::vCopy(aWorkspace,m_pWord->aName());
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void WrdVal::vToString(char* aWorkspace)
{
  String::wToPointer(m_pWord,aWorkspace);
}

