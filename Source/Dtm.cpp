/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Dtm::operator new(size_t)
{
  vFatal("fatal: Dtm class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Dtm::Dtm(void)
{
  m_iValue = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Dtm::~Dtm(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
i8 Dtm::nCopy(byte* ayDst, byte* aySrc)
{
  * (i8*)ayDst = * (i8*)aySrc;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
i8 Dtm::nCopy(byte* ayDst, i8 iValue)
{
  * (i8*)ayDst = iValue;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
void Dtm::vCopy(byte* ayDst, byte* aySrc)
{
  * (i8*)ayDst = * (i8*)aySrc;
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
void Dtm::vCopy(byte* ayDst, i8 iValue)
{
  * (i8*)ayDst = iValue;
}

/*----------------------------------------------------------------------------*/
/* compute date as i8                                                         */
/*----------------------------------------------------------------------------*/
i8 Dtm::iDte(i8 iYear, i8 iMonth, i8 iDay)
{
  Dtm xDtm;
  
  xDtm.xDte.m_uYearDelta = iYear - C_YEAR_BASE;
  xDtm.xDte.m_uMonth     = iMonth;
  xDtm.xDte.m_uDay       = iDay;
  
  xDtm.xDte.m_uSpare     = 0;

  return xDtm.m_iValue;
}

/*----------------------------------------------------------------------------*/
/* compute interval as i8                                                     */
/*----------------------------------------------------------------------------*/
i8 Dtm::iIvl(i8 iSecond, i8 iMilli)
{
  Dtm xDtm;
  
  xDtm.xIvl.m_uSecond = iSecond;
  xDtm.xIvl.m_uMilli  = iMilli;
  
  return xDtm.m_iValue;
}

/*----------------------------------------------------------------------------*/
/* compute time as i8                                                         */
/*----------------------------------------------------------------------------*/
i8 Dtm::iTme(i8 iHour, i8 iSecond, i8 iMinute, i8 iMicro)
{
  Dtm xDtm;
  
  xDtm.xTme.m_uHour   = iHour;
  xDtm.xTme.m_uSecond = iSecond;
  xDtm.xTme.m_uMinute = iMinute;
  xDtm.xTme.m_uMicro  = iMicro;
  
  xDtm.xTme.m_uSpare  = 0;
  
  return xDtm.m_iValue;
}

/*----------------------------------------------------------------------------*/
/* compute timestamp as i8                                                    */
/*----------------------------------------------------------------------------*/
i8 Dtm::iTsp(i8 iYear, i8 iMonth,  i8 iDay,
             i8 iHour, i8 iSecond, i8 iMinute, i8 iMicro)
{
  Dtm xDtm;
  
  xDtm.xTsp.m_uYearDelta = iYear - C_YEAR_BASE;
  xDtm.xTsp.m_uMonth     = iMonth;
  xDtm.xTsp.m_uDay       = iDay;
  
  xDtm.xTsp.m_uHour      = iHour;
  xDtm.xTsp.m_uSecond    = iSecond;
  xDtm.xTsp.m_uMinute    = iMinute;
  xDtm.xTsp.m_uMicro     = iMicro;
  
  xDtm.xTsp.m_uSpare     = 0;
  
  return xDtm.m_iValue;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get as i8                                                                  */
/*----------------------------------------------------------------------------*/
i8 Dtm::iAsI8(void)
{
  return m_iValue;
}

/*----------------------------------------------------------------------------*/
/* set as i8                                                                  */
/*----------------------------------------------------------------------------*/
void Dtm::vAsI8(i8 iAsI8)
{
  m_iValue = iAsI8;
}

/*----------------------------------------------------------------------------*/
/* test if null                                                               */
/*----------------------------------------------------------------------------*/
bool Dtm::bIsNull(void)
{
  if (C_DATUM_NULL == m_iValue)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set to null                                                                */
/*----------------------------------------------------------------------------*/
void Dtm::vSetNull(void)
{
  m_iValue = C_DATUM_NULL;
}

