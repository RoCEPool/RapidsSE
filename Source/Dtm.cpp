#include "Library.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Dtm::Dtm(void)
{
  m_iWrd = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Dtm::~Dtm(void) noexcept(false)
{
}


/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
i8 Dtm::nCopy(byte* ayDst, byte* aySrc)
{
  * (i8*)ayDst = * (i8*)aySrc;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
i8 Dtm::nCopy(byte* ayDst, i8 iValue)
{
  * (i8*)ayDst = iValue;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
void Dtm::vCopy(byte* ayDst, byte* aySrc)
{
  * (i8*)ayDst = * (i8*)aySrc;
}

/*----------------------------------------------------------------------------*/
/* copy datum (return the number of bytes copied)                             */
/*----------------------------------------------------------------------------*/
void Dtm::vCopy(byte* ayDst, i8 iValue)
{
  * (i8*)ayDst = iValue;
}

/*----------------------------------------------------------------------------*/
/* compute date as i8                                                         */
/*----------------------------------------------------------------------------*/
i8 Dtm::iDte(i8 iYear, i8 iMonth, i8 iDay)
{
  Dtm xDtm;
  
  xDtm.m_wDte.m_uYearDelta = iYear - C_YEAR_BASE;
  xDtm.m_wDte.m_uMonth     = iMonth;
  xDtm.m_wDte.m_uDay       = iDay;
  
  xDtm.m_wDte.m_uSpare     = 0;

  return xDtm;
}

/*----------------------------------------------------------------------------*/
/* compute interval as i8                                                     */
/*----------------------------------------------------------------------------*/
i8 Dtm::iIvl(i8 iSecond, i8 iMilli)
{
  Dtm xDtm;
  
  xDtm.m_wIvl.m_uSecond = iSecond;
  xDtm.m_wIvl.m_uMicro  = iMilli * C_1K;
  
  return xDtm;
}

/*----------------------------------------------------------------------------*/
/* compute time as i8                                                         */
/*----------------------------------------------------------------------------*/
i8 Dtm::iTme(i8 iHour, i8 iSecond, i8 iMinute, i8 iMicro)
{
  Dtm xDtm;
  
  xDtm.m_wTme.m_uHour   = iHour;
  xDtm.m_wTme.m_uSecond = iSecond;
  xDtm.m_wTme.m_uMinute = iMinute;
  xDtm.m_wTme.m_uMicro  = iMicro;
  
  xDtm.m_wTme.m_uSpare  = 0;
  
  return xDtm;
}

/*----------------------------------------------------------------------------*/
/* compute timestamp as i8                                                    */
/*----------------------------------------------------------------------------*/
i8 Dtm::iTsp(i8 iYear, i8 iMonth,  i8 iDay,
             i8 iHour, i8 iSecond, i8 iMinute, i8 iMicro)
{
  Dtm xDtm;
  
  xDtm.m_wTsp.m_uYearDelta = iYear - C_YEAR_BASE;
  xDtm.m_wTsp.m_uMonth     = iMonth;
  xDtm.m_wTsp.m_uDay       = iDay;
  
  xDtm.m_wTsp.m_uHour      = iHour;
  xDtm.m_wTsp.m_uSecond    = iSecond;
  xDtm.m_wTsp.m_uMinute    = iMinute;
  xDtm.m_wTsp.m_uMicro     = iMicro;
  xDtm.m_wTsp.m_uLocal     = C_TSP_LOCAL;
  xDtm.m_wTsp.m_uSpare     = 0;
  
  return xDtm;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get as i8                                                                  */
/*----------------------------------------------------------------------------*/
i8 Dtm::iAsI8(void)
{
  return m_iWrd;
}

/*----------------------------------------------------------------------------*/
/* set as i8                                                                  */
/*----------------------------------------------------------------------------*/
void Dtm::vAsI8(i8 iAsI8)
{
  m_iWrd = iAsI8;
}

/*----------------------------------------------------------------------------*/
/* calc byte magnitude                                                        */
/*----------------------------------------------------------------------------*/
i8 Dtm::iByteMagn(void)
{
  i8 iMagn = IntLib::iByteMagnitude(m_iWrd);
  
  return iMagn;
}

/*----------------------------------------------------------------------------*/
/* set to unknown                                                             */
/*----------------------------------------------------------------------------*/
void Dtm::vSetUnknown(void)
{
  m_iWrd = C_UNKNOWN;
}

/*----------------------------------------------------------------------------*/
/* set to null                                                                */
/*----------------------------------------------------------------------------*/
void Dtm::vSetNull(void)
{
  m_iWrd = C_DATUM_NULL;
}

