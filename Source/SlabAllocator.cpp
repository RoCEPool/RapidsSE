#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SlabAllocator::SlabAllocator(void)
: Object(CN_SLABALLOCATOR)
{
  _magic_();
  
  _checkInitialised_(CN_SLABALLOCATOR);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SlabAllocator::~SlabAllocator(void)
{
  _magic_();
  
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SlabAllocator::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SLABALLOCATOR);
  return &m_xFooter;
}

