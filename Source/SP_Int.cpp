/*============================================================================*/
/* SP_Int.cpp - Int sprint helper                                             */
/*============================================================================*/

#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Int::SP_Int(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
  
  // set default Int format
  vFormat(F_INT);
  
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Int::~SP_Int(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint SP_Int and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* SP_Int::sz(i8 iInt)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  iInt);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Int::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(C_I8_MAX);
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Int::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(73);
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Int::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(C_I8_MIN);
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SP_Int::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL);
  
  return &m_xFooter;
}

