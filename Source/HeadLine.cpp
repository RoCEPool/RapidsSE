#include "Data.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
HeadLine::HeadLine(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
HeadLine::~HeadLine(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return meta code                                                           */
/*----------------------------------------------------------------------------*/
i8 HeadLine::iMetaCode(i8 i_Meta)
{
  //w8 iCode = w8_1N(C_HEAD_PRE_BYTES * C_NIBBLES_PER_BYTE + i_Meta);
  w8 iCode = w8_1B(C_HEAD_PRE_BYTES + i_Meta);

  return iCode;
}

/*----------------------------------------------------------------------------*/
/* store meta code                                                            */
/*----------------------------------------------------------------------------*/
void HeadLine::vMetaCode(i8 i_Meta, w8 wArg)
{
  //v1N(C_HEAD_PRE_BYTES * C_NIBBLES_PER_BYTE + i_Meta,wArg);
  v1B(C_HEAD_PRE_BYTES + i_Meta,wArg);
}

/*----------------------------------------------------------------------------*/
/* return size of head in bytes                                               */
/*----------------------------------------------------------------------------*/
i8 HeadLine::nBytes(void)
{
  i8 nSizeBytes = nWords() * C_BYTES_PER_WORD;
  
  return nSizeBytes;
}

/*----------------------------------------------------------------------------*/
/* return size of head in words                                               */
/*----------------------------------------------------------------------------*/
i8 HeadLine::nWords(void)
{
  i8 nSizeWords = w8_1B(0);
  
  return nSizeWords;
}

