#include "Magic.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
cn::cn(void)
{
  // do nothing here
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
cn::cn(eCN eClassNo)
{
  m_eClassNo = eClassNo;
  pDF[eClassNo] = nullptr;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
cn::cn(eCN eClassNo, pDUMPFUN* pDumpFun)
{
  m_eClassNo = eClassNo;
  pDF[eClassNo] = pDumpFun;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
cn::~cn(void)
{
  
}

/*----------------------------------------------------------------------------*/
/* assign a magic number                                                      */
/*----------------------------------------------------------------------------*/
void cn::operator =(eCN eClassNo)
{
  m_eClassNo = eClassNo;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool cn::operator ==(eCN eClassNo) const
{
  return m_eClassNo == eClassNo;
}

