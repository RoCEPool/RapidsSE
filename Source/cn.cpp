/*----------------------------------------------------------------------------*/
eCN cn::eClass(void) const
{
  return m_eClassNo;
}

/*----------------------------------------------------------------------------*/
/* set class                                                                  */
/*----------------------------------------------------------------------------*/
void cn::vClass(eCN eClassNo)
{
  m_eClassNo = eClassNo;
}

/*----------------------------------------------------------------------------*/
/* get dump function                                                          */
/*----------------------------------------------------------------------------*/
pDUMPFUN* cn::pGetDump()
{
  return pDF[m_eClassNo];
}

/*----------------------------------------------------------------------------*/
/* set dump function                                                          */
/*----------------------------------------------------------------------------*/
void cn::vSetDump(eCN eClass, pDUMPFUN* pDumpFunc)
{
  pDF[eClass] = pDumpFunc;
}

