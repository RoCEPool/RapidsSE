#include "Operators.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
StopMarker* ControlData::_pStopMarker(void* aAddr)
{
  StopMarker* pOp = reinterpret_cast<StopMarker*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* StopMarker::operator new(size_t)
{
  StopMarker* pStopMarker =
    static_cast<StopMarker*>(HeapMem::pAllocate(CN_STOPMARKER));
  
  return pStopMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void StopMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StopMarker::StopMarker(void)
: Operand(CN_STARTMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STOPMARKER,_FOOTER_);

  _checkInitialised_(CN_STOPMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_STOPMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
StopMarker::~StopMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STOPMARKER,_FOOTER_);
}


