#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set transaction entry                                                      */
/*----------------------------------------------------------------------------*/
void _LogEntryTxn::vSet(LogEntry* pLogEntry, Tx* pTxn, eXA eTxnAct)
{
  pLogEntry->m_eKind = EK_TXN;
  
  m_iTxnId  = pTxn->m_iUniqueId;
  m_eTxnAct = eTxnAct;
}

/*----------------------------------------------------------------------------*/
/* cat sprint to given string                                                 */
/*----------------------------------------------------------------------------*/
void _LogEntryTxn::vSprint(s4K& sString)
{
  SP_Id spId;
  
  sString.vCatSprint("{,%s,%s}"_Stz,
                
                spId.sz("X"_Stz,m_iTxnId),
                aXA[m_eTxnAct]);
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryTxn::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("X"_Stz,m_iTxnId),
                aXA[m_eTxnAct]);
}

