#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set transaction entry                                                      */
/*----------------------------------------------------------------------------*/
void _LogEntryTxn::vSet(LogEntry* pLogEntry, i8 iTxnId, eXA eTxnAct)
{
  pLogEntry->m_eKind = EK_TXN;
  
  m_iTxnId  = iTxnId;
  m_eTxnAct = eTxnAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryTxn::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz(m_iTxnId),
                aXA[m_eTxnAct]);
}

