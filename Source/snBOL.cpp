#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snBOL::snBOL(void)
: Sprint(CN_SNBOL)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
  
  _checkInitialised_(CN_SNBOL);
  
  _postcondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snBOL::~snBOL(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint snBOL and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* snBOL::sz(i8 iBol)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  if (iBol)
    StrLib::vCopy(m_caResult,(char*)"true"_Stz);
  else
    StrLib::vCopy(m_caResult,(char*)"false"_Stz);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snBOL::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNBOL);
  
  return &m_xFooter;
}

