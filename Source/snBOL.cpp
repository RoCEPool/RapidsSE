#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snBOL::snBOL(void)
: Scan(CN_SNBOL)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
  
  _checkInitialised_(CN_SNBOL);
  
  _postcondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snBOL::~snBOL(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 snBOL::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNBOL);
  
  if ( ! StrLib::bExtractBoolean(aacCrs,m_xBol.m_iBol) )
    throw C_UNKNOWN;
  
  return m_xBol.m_iBol;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snBOL::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNBOL);
  
  return &m_xFooter;
}

