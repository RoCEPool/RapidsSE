#include "Tasking.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TaskVal::operator new(size_t iSize)
{
  vFatal("fatal: TaskVal class cannot be new'd\n");
  
  //vExitFatal();
  
  exit(EXIT_FAILURE);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TaskVal::TaskVal(void)
: OnStack(CN_TASKVAL)
{
  m_pTask = nullptr;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TaskVal::operator =(Task* pTask)
{
  m_pTask = pTask;
}

/*----------------------------------------------------------------------------*/
/* get pTask                                                                  */
/*----------------------------------------------------------------------------*/
Task* TaskVal::pTask(void) const
{
  return m_pTask;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TaskVal::iSize(void) const
{
  return sizeof(WrdVal);
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void TaskVal::vToCommand(char* aWorkspace)
{
  char* pz;
  
  String::vCopy(aWorkspace,"0x");
  pz = String::zTerminator(aWorkspace);
  String::vAppendHex(&pz,(i8)m_pTask);
  //String::vCopy(sBuffer,pStr);
  String::vAppendString(&pz," >tx");
  String::vAppendNull(&pz);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TaskVal::vToString(char* aWorkspace)
{
  String::wToPointer(m_pTask,aWorkspace);
}

