/*============================================================================*/
/* Scan.cpp - Scan Utility                                                */
/*============================================================================*/

#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Scan::Scan(eCN eClass)
: Object(eClass)
{
#ifdef WITH_CHECK_INITIALISED
  MemLib::vZero(m_caFormat,sizeof(m_caFormat),CN_SPDTE);
  MemLib::vZero(m_caResult,sizeof(m_caResult),CN_SPDTE);
#else
  m_caFormat[0] = '\0';
  m_caResult[0] = '\0';
#endif

 }

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Scan::~Scan(void) noexcept(false)
{
  _precondition_(_MAGIC_,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get result as Stz*                                                         */
/*----------------------------------------------------------------------------*/
Stz* Scan::sz(void)
{
  _precondition_(_MAGIC_,_FOOTER_);

  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* get format as Stz*                                                         */
/*----------------------------------------------------------------------------*/
Stz* Scan::szFormat(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return (Stz*) &m_caFormat[0];
}

/*----------------------------------------------------------------------------*/
/* set format                                                                 */
/*----------------------------------------------------------------------------*/
void Scan::vFormat(const Stz* szFormat)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vCopy(m_caFormat,(char*)szFormat);
}

/*----------------------------------------------------------------------------*/
/* get result as Stz*                                                         */
/*----------------------------------------------------------------------------*/
Stz* Scan::szResult(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* set result                                                                 */
/*----------------------------------------------------------------------------*/
void Scan::vResult(const Stz* szResult)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vCopy(m_caFormat,(char*)szResult);
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Scan::aFooter(void)
{
  _precondition_(_MAGIC_);
  
  return &m_xFooter;
}

