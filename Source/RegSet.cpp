RegSet* Registers::_pRegSet(void* aAddr)
{
  RegSet* pRegSet = reinterpret_cast<RegSet*>(aAddr);
  
  RASSERT_TYPE(pRegSet,CN_REGSET);
  
  return pRegSet;
}

