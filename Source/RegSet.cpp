#include "Tasks.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
RegSet* Tasks::_pRegSet(void* aAddr)
{
  RegSet* pRegSet = reinterpret_cast<RegSet*>(aAddr);
  
  RASSERT_TYPE(pRegSet,CN_REGSET);
  
  return pRegSet;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RegSet::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_REGSET);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void RegSet::operator delete(void* aAddr)
{
  RegSet* pRegSet = reinterpret_cast<RegSet*>(aAddr);
  
  HeapMem::vFree(pRegSet);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RegSet::RegSet(void)
: Object(CN_REGSET)
{
  _precondition_(_MAGIC_,CN_REGSET,_FOOTER_);
    
  _checkInitialised_(CN_REGSET);
  
  _postcondition_(_MAGIC_,CN_REGSET,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RegSet::~RegSet(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_REGSET,_FOOTER_);
}

