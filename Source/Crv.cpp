Crv::~Crv(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calc the bytes need for a crv row given size of crw buffer                 */
/*----------------------------------------------------------------------------*/
i8 Crv::nCrvBytesNeed(i8 nCrwBytes)
{
  i8 nBytesNeeded = sizeof(Crv) - sizeof(Crw) + nCrwBytes;
  
  ASSERT(nBytesNeeded == nCrwBytes + 16); // cross-check
  
  return nBytesNeeded;
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* take a consistent copy of the given compact row                            */
/*----------------------------------------------------------------------------*/
void Crv::vTakeVersion(Ref xwRef, Crw* aCrw, i8 nCrwBytes)
{
  m_nCrvSize = nCrvBytesNeed(nCrwBytes);
  
  m_xwRef = xwRef;
  
  MemLib::vCopy(&m_xCrw_RC,aCrw,nCrwBytes,CN_CRVBUFFER);
}


