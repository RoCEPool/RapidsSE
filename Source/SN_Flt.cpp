#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Flt::SN_Flt(void)
: Scan(CN_SNFLT)
{
  _precondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
    
  _checkInitialised_(CN_SNFLT);
  
  _postcondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Flt::~SN_Flt(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
d8 SN_Flt::d(char** aacCrs, Column* pCol, Format* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNFLT);
  
  if ( ! StrLib::bExtractFloat(aacCrs,m_wDtm.m_dFlt) )
    THROW("StrLib::bExtractFloat"_Stz);

  return m_wDtm.m_dFlt;
}



/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Flt::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNFLT);
  
  return &m_xFooter;
}

