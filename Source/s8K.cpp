/*============================================================================*/
/* s8K.cpp -- a 8KB-byte s-string                                             */
/*============================================================================*/

#include "Magic.h"
#include "Memory.hpp"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(void)
: s(CN_S8K,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  Memory::vCheckInitialised(this,sizeof(s8K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(s8K& rArg)
: s(CN_S8K,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(rArg.a());
  
  Memory::vCheckInitialised(this,sizeof(s8K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(const char* aArg)
: s(CN_S8K,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg);
  
  Memory::vCheckInitialised(this,sizeof(s8K));
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(const char* aArg, i8 nChars)
: s(CN_S8K,C_S_SIZE)
{
  Memory::vZero(m_mWorkspace, C_S_SIZE);
  
  s::vCopy(aArg,nChars);
  
  Memory::vCheckInitialised(this,sizeof(s8K));
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s8K::~s8K(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (s& rArg)
{
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s8K::pFooter(void)
{
  return &m_xFooter;
}

