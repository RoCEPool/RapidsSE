/*============================================================================*/
/* s8K.cpp -- a 8KB-byte s-string                                             */
/*============================================================================*/

#include "Magic.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(void)
: s(C_S_SIZE)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(s8K& rArg)
: s(C_S_SIZE)
{
  s::vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(const char* aArg)
: s(C_S_SIZE)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s8K::s8K(const char* aArg, i8 nChars)
: s(C_S_SIZE)
{
  s::vCopy(aArg,nChars);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s8K::~s8K(void)
{
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (const char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (char* aArg)
{
  s::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s8K::operator = (s& rArg)
{
  vCopy(rArg.a());
}

