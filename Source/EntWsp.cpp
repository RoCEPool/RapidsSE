#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: RowWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize, EntWsp* pEntWsp)
{
  RASSERT(iSize);
  return pEntWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWsp::EntWsp(void)
: Header(CN_ENTWSP)
{
  _precondition_(_MAGIC_,CN_ENTWSP);

  //m_xRowNo
  m_iDataBytes = 0;

  _setFooter_();
  
  _checkInitialisedSize_(sizeof(EntWsp));
  
  _postcondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWsp::~EntWsp(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void EntWsp::vShow(void)
{
  vTrace("EntWsp %p: rowNo %llu.%llu\n",
         this,
         m_xRowNo.uBuffer(),
         m_xRowNo.uRow()
         );
}

/*----------------------------------------------------------------------------*/
/* get row no                                                                 */
/*----------------------------------------------------------------------------*/
RowNo& EntWsp::xRowNo(void)
{
  return m_xRowNo;
}

/*----------------------------------------------------------------------------*/
/* set row no                                                                 */
/*----------------------------------------------------------------------------*/
void EntWsp::vRowNo(RowNo& xRowNo)
{
  m_xRowNo = xRowNo;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* EntWsp::pFooter(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP);
  
  Footer* pFooter = static_cast<Footer*>(
                      pvAdd(this,sizeof(EntWsp) + m_iDataBytes));
  
  return pFooter;
}

