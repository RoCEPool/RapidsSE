#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: RowWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize, EntWsp* pEntWsp)
{
  RASSERT(iSize);
  return pEntWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWsp::EntWsp(i8 iDataBytes)
: Header(CN_ENTWSP)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTWSP);

  //m_xRowNo
  m_iDataBytes = iDataBytes;

  _setFooter_();
  
  _checkInitialisedSize_(sizeof(EntWsp));
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWsp::~EntWsp(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* EntWsp::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ENTWSP);
  
  Footer* pFooter = static_cast<Footer*>(
                      pvAdd(this,sizeof(EntWsp) + m_iDataBytes));
  
  return pFooter;
}

