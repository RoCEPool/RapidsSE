#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: EntWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntWsp::operator new(size_t iSize, EntWsp* pEntWsp)
{
  RASSERT(iSize);
  return pEntWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWsp::EntWsp(void)
: Header(CN_ENTWSP)
{
  _precondition_(_MAGIC_,CN_ENTWSP);

  //m_xRowId
  m_nDataBytes = 0;

  _setFooter_();
  
  _checkInitialisedSize_(sizeof(EntWsp));
  
  _postcondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWsp::~EntWsp(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void EntWsp::vShow(void)
{
  i8* pKeyData = reinterpret_cast<i8*>(m_mDataArea);
  i8 iKey;
  memcpy(&iKey,m_mDataArea,8);
  vTrace("EntWsp %p: rowId %llu.%llu key (size:%lld value:%lld)\n",
         this,
         m_xRowId.uBuffer(),
         m_xRowId.uRow(),
         m_nDataBytes,
         iKey
         );
}

/*----------------------------------------------------------------------------*/
/* get row id                                                                 */
/*----------------------------------------------------------------------------*/
RowId& EntWsp::xRowId(void)
{
  return m_xRowId;
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void EntWsp::vRowId(RowId& xRowId)
{
  m_xRowId = xRowId;
}

/*----------------------------------------------------------------------------*/
/* add a key                                                                  */
/*----------------------------------------------------------------------------*/
void EntWsp::vAddKey(KeyWsp& xKeyWsp)
{
  char* pDst = pDataNext();
  char* pSrc = xKeyWsp.pDataArea();
  i8 nBytes  = xKeyWsp.nDataBytes();
  
  Memory::vCopy(pDst,pSrc,nBytes);
  
  m_nDataBytes += nBytes;
}

/*----------------------------------------------------------------------------*/
/* get data area                                                              */
/*----------------------------------------------------------------------------*/
char* EntWsp::pDataArea(void)
{
  return m_mDataArea;
}

/*----------------------------------------------------------------------------*/
/* get number of data bytes in the key                                        */
/*----------------------------------------------------------------------------*/
i8 EntWsp::nDataBytes(void)
{
  return m_nDataBytes;
}

/*----------------------------------------------------------------------------*/
/* get next avaliable point in data area                                      */
/*----------------------------------------------------------------------------*/
char* EntWsp::pDataNext(void)
{
  return &m_mDataArea[m_nDataBytes];
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* EntWsp::pFooter(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP);
  
  return &m_xFooter;
}

