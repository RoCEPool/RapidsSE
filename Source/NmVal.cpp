/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmVal::NmVal(void)
: Object(CN_NMVAL)
{
  _precondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
  
  m_sName  = "<none>"_Stz;
  m_iValue = C_UNKNOWN;
  
  _checkInitialised_(CN_NMVAL);
  
  _postcondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmVal::NmVal(Stz* szName)
: Object(CN_NMVAL)
{
  _precondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
  
  m_sName  = szName;
  m_iValue = C_UNKNOWN;
  
  _checkInitialised_(CN_NMVAL);
  
  _postcondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmVal::NmVal(Stz* szName, i8 iValue)
: Object(CN_NMVAL)
{
  _precondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
  
  m_sName  = szName;
  m_iValue = iValue;
  
  _checkInitialised_(CN_NMVAL);
  
  _postcondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
NmVal::~NmVal(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_NMVAL,_FOOTER_);
}

