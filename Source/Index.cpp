/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Index::operator new(size_t iSize)
{
  Index* pIndex = nullptr;
  
  return pIndex;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Index::operator delete(void* pTableAddress)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Index::Index(i8 iTxId, const char* pIndexName)
: Object(CN_INDEX)
{
  _poolAddress_(this);
  _magic_();
  
  m_iTxId = iTxId;
  m_sIndexName = pIndexName;
  
  _class_(CN_INDEX);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Index::~Index(void)
{
  _poolAddress_(this);
}

/*----------------------------------------------------------------------------*/
/* get the index name                                                         */
/*----------------------------------------------------------------------------*/
char* Index::pIndexName(void)
{
  _poolAddress_(this);
  
  return m_sIndexName.a();
}

/*----------------------------------------------------------------------------*/
/* get the txid                                                               */
/*----------------------------------------------------------------------------*/
i8 Index::iTxId(void) const
{
  _poolAddress_(this);
  
  return m_iTxId;
}

/*----------------------------------------------------------------------------*/
/* vDump                                                                      */
/*----------------------------------------------------------------------------*/
void Index::vDump(void)
{
  _poolAddress_(this);
  
  vTrace("Index %p: TxId %lld IndexName %s\n",
         this,
         m_iTxId,
         m_sIndexName.a()
         );
}

