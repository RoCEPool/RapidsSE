/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Index::operator new(size_t iSize)
{
  Index* pIndex = nullptr;
  
  return pIndex;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Index::operator delete(void* pTableAddress)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Index::Index(const char* pIndexName)
: Object(CN_INDEX)
{
  _poolAddress_(this);
  _magic_();
  
  m_sIndexName = pIndexName;
  
  _class_(CN_INDEX);
  
  Memory::vCheckInitialised(this,sizeof(Index));
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Index::~Index(void)
{
  _poolAddress_(this);
}

/*----------------------------------------------------------------------------*/
/* get the index name                                                         */
/*----------------------------------------------------------------------------*/
char* Index::pIndexName(void)
{
  _poolAddress_(this);
  
  return m_sIndexName.a();
}

/*----------------------------------------------------------------------------*/
/* vDump                                                                      */
/*----------------------------------------------------------------------------*/
void Index::vDump(void)
{
  _poolAddress_(this);
  
  vTrace("Index %p: %s\n",
         this,
         m_sIndexName.a()
         );
}

