/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint bits and return Stz* to result                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_Bits::sz(u8 iWord)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
    
  #define BYTE_TO_BINARY(byte)  \
    (byte & 0x80 ? '1' : '0'), \
    (byte & 0x40 ? '1' : '0'), \
    (byte & 0x20 ? '1' : '0'), \
    (byte & 0x10 ? '1' : '0'), \
    (byte & 0x08 ? '1' : '0'), \
    (byte & 0x04 ? '1' : '0'), \
    (byte & 0x02 ? '1' : '0'), \
    (byte & 0x01 ? '1' : '0')
  
  m_caResult[0] = '\0';
  Stz* szDst = (Stz*)m_caResult;
  
  for (i8 i_Byte = C_BYTES_PER_WORD - 1; i_Byte >= 0; i_Byte--) {
    u8 uByte = IntLib::uByte(iWord,i_Byte);
    StrLib::vSprintCat(szDst,"%c%c%c%c%c%c%c%c"_Stz,BYTE_TO_BINARY(uByte));
  }
  
  return (Stz*) &m_caResult[0];
}


