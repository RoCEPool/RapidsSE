/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void EntWrk_v2::vShow(ColumnVec* pColVec)
{
  i8 iKey;
  
  Int::vCopy(&iKey,aKey());
  
  vTrace("EntWrk %p: Id %lli.%lli Offsets: %llu "_Stz,
         this,
         m_xId.iBuffer(),
         m_xId.iRow(),
         m_nOffsets
  );

  vTrace("key (size:%lld value:%lld) "_Stz,
         nKeySize(),
         iKey
         );
  
  if (m_bHasData) {
    Row* aThisRow = aRow();
    aThisRow->vShow(pColVec);
  }
  
  vTrace("\n"_Stz);
}

