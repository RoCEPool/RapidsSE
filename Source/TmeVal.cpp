/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void TmeVal::vMaxValue(void)
{
  xTme.m_uSpare = 0;
  
  xTme.m_uMicro  = 999999;
  xTme.m_uSecond = 59;
  xTme.m_uMinute = 59;
  xTme.m_uHour   = 23;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void TmeVal::vMidValue(void)
{
  xTme.m_uSpare = 0;
  
  xTme.m_uMicro  = 1;
  xTme.m_uSecond = 2;
  xTme.m_uMinute = 3;
  xTme.m_uHour   = 4;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void TmeVal::vMinValue(void)
{
  xTme.m_uSpare = 0;
  
  xTme.m_uMicro  = 0;
  xTme.m_uSecond = 0;
  xTme.m_uMinute = 0;
  xTme.m_uHour   = 0;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void TmeVal::vNullValue(void)
{
  vSetNull();
}

