#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TmeVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: TmeVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Tme TmeVal::wTme(void)
{
  ASSERT(bIsClass(CN_TMEVAL));
  
  return m_wTme;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void TmeVal::vTme(Tme wTme)
{
  vClass(CN_TMEVAL);
  m_wTme = wTme;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a TmeVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 TmeVal::nStackUsage(void)
{
  return sizeof(TmeVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TmeVal::vToStz(Stz* szDst)
{
  if (m_wTme.bIsNull()) {
    szDst->vConcat(C_NULL);
    return;
  }
  
  * szDst = m_wTme;
}

