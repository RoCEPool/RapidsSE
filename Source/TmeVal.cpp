#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TmeVal* Values::_aTmeVal(void* aAddr)
{
  TmeVal* aTmeVal = reinterpret_cast<TmeVal*>(aAddr);
  
  RASSERT_TYPE(aTmeVal,CN_TMEVAL);
  
  return aTmeVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TmeVal::operator new(size_t)
{
  vFatal("fatal: TmeVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TmeVal::TmeVal(void)
: Value(CN_TMEVAL)
{
  
  _checkInitialised_(CN_TMEVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TmeVal::operator =(i8 iTme)
{
  //vTrace("TmeVal: diff %lld\n"_Stz,nSub(&m_iTme,this));
  
  *aInt() = iTme;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TmeVal::operator =(Tme xTme)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = xTme.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iTme                                                                   */
/*----------------------------------------------------------------------------*/
i8 TmeVal::iTme(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TmeVal::nSize(void)
{
  return sizeof(TmeVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* TmeVal::aInt(void)
{
  return (i8*)&xTme;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TmeVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  StrLib::vSprint(aWorkspace,
                  "%ll02d:%ll02d:%ll02d.%lld"_Stz,
                  (i8)xTme.m_uHour,
                  (i8)xTme.m_uMinute,
                  (i8)xTme.m_uSecond,
                  (i8)xTme.m_uMicro
                  );
}

/*----------------------------------------------------------------------------*/
