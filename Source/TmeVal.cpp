#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
TmeVal* Values::_pTmeVal(void* aAddr)
{
  TmeVal* pTmeVal = reinterpret_cast<TmeVal*>(aAddr);
  
  RASSERT( !pTmeVal || CN_TMEVAL == pTmeVal->eClass() );
  
  return pTmeVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TmeVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: TmeVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TmeVal::TmeVal(void)
: Value(CN_INTVAL)
{
  
  _checkInitialised_(CN_TMEVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TmeVal::operator =(i8 iTme)
{
  //vTrace("TmeVal: diff %lld\n"_Str,nSub(&m_iTme,this));
  
  *aInt() = iTme;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void TmeVal::operator =(Tme xTme)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  *aInt() = xTme.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iTme                                                                   */
/*----------------------------------------------------------------------------*/
i8 TmeVal::iTme(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 TmeVal::nSize(void)
{
  return sizeof(TmeVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* TmeVal::aInt(void)
{
  return (i8*)&x;
}

