/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Predicate* Plans::_pPredicate(void* aAddr)
{
  Predicate* pPredicate = reinterpret_cast<Predicate*>(aAddr);
  
  RASSERT_TYPE(pPredicate,CN_PREDICATE);
 
  return pPredicate;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Predicate::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_PREDICATE);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Predicate::operator delete(void* pDataAddress)
{
  AccessPath* pAccessPath = reinterpret_cast<AccessPath*>(pDataAddress);
  
  HeapMem::vFree(pAccessPath);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Predicate::Predicate(void)
: Object(CN_PREDICATE)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PREDICATE,_FOOTER_);
  
  m_ePredicate = PK_NONE;
  m_pArg1  = nullptr;
  m_pArg2  = nullptr;
  m_pRelOp = nullptr;
  
  _checkInitialised_(CN_PREDICATE);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_PREDICATE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Predicate::~Predicate(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PREDICATE,_FOOTER_);
  
  if (m_pRelOp)
    delete m_pRelOp;

  if (m_pArg1)
    delete m_pArg1;
  
  if (m_pArg2)
    delete m_pArg2;
}

