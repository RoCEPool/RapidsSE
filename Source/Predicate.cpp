/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Predicte::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PREDICATE);
  
  return &m_xFooter;
}

