/*----------------------------------------------------------------------------*/
/* show predicate                                                             */
/*----------------------------------------------------------------------------*/
void Predicate::vShow(void)
{
  vTrace("  Predicate: %s : %s %s %s\n"_Stz,
         aPK[m_ePredicate],
         m_pArg1  ? m_pArg1->sArgVal().szStz() : C_NO_ARG,
         m_pArg2  ? m_pArg2->sArgVal().szStz() : C_NO_ARG,
         m_pRelOp ? aRO[m_pRelOp->eRelOp()]    : C_NO_ARG
         );
}

/*----------------------------------------------------------------------------*/
/* get column name                                                            */
/*----------------------------------------------------------------------------*/
s256& Predicate::sColumnNm(void)
{
  //ASSERT(PK_COLUMN_LITERAL_OP == m_ePredicate);

  return m_pArg1->sArgVal();
}

/*----------------------------------------------------------------------------*/
/* get literal datum                                                          */
/*----------------------------------------------------------------------------*/
s256& Predicate::sDatumStr(void)
{
  ASSERT(PK_COLUMN_LITERAL_OP == m_ePredicate);
  
  return m_pArg2->sArgVal();
}

/*----------------------------------------------------------------------------*/
/* show predicate                                                             */
/*----------------------------------------------------------------------------*/
void Predicate::vNewLitArg(s256& sDatumArg)
{
  Arg* pDtmValArg = new Arg;
  pDtmValArg->vArgVal(sDatumArg);
  vArg2(pDtmValArg);
}

/*----------------------------------------------------------------------------*/
/* show predicate                                                             */
/*----------------------------------------------------------------------------*/
void Predicate::vNewRelOp(eRO eRelOp)
{
  RelOp* pRelOp = new RelOp;
  pRelOp->vRelOp(eRelOp);
  vRelOp(pRelOp);
}

