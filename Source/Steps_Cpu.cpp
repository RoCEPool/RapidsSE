#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Cpu(void)
{
  vAddStep("cpu.rdtscp"_Stz,      &Step::vCpuRdtscp);
}

/*----------------------------------------------------------------------------*/
/* cpu.rdtscp -- read cpu time stamp counter                                  */
/*----------------------------------------------------------------------------*/
void Step::vCpuRdtscp(void)
{
  ENTRY();
  
  i8 iTscp = TickingDevice::iGetTick();
  
  m_pDataStack->vPushInt(iTscp);
  
  EXIT();
}

