#include "Rows.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Ref::SP_Ref(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
  
  // set default enclosing char
  vFormat(F_VCH_enclose);
  
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Ref::~SP_Ref(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return Stz* of result                                                      */
/*----------------------------------------------------------------------------*/
void SP_Ref::vRef(Rrf wRef)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);

  StrLib::vSprint(m_caResult,
                  "%lld.%04lld+%lld"_Stz,
                  
                  wRef.iBuffer(),
                  wRef.iItem(),
                  wRef.nSkipLevels());
}

/*----------------------------------------------------------------------------*/
/* return Stz* of result                                                      */
/*----------------------------------------------------------------------------*/
Stz* SP_Ref::sz(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);

  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/* sprint Vch and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* SP_Ref::sz(Rrf wRef)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);

  vRef(wRef);
  
  return (Stz*) &m_caResult[0];
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
__aFooterFunction(SP_Ref);

