/*============================================================================*/
/* Footer.cpp -- Footer for Concrete Classes                                  */
/*============================================================================*/

#include "CorrectnessAlgebra.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer::Footer(void)
{
  m_uFooter = C_FOOTER;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer::~Footer(void) noexcept(false)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* ASSERT footer                                                              */
/*----------------------------------------------------------------------------*/
void Footer::vAssertFooter(void) const
{
  ASSERT(m_uFooter == C_FOOTER);
}

/*----------------------------------------------------------------------------*/
/* test for valid footer                                                      */
/*----------------------------------------------------------------------------*/
bool Footer::bValidFooter(void)
{
  if (m_uFooter == C_FOOTER)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set footer                                                                 */
/*----------------------------------------------------------------------------*/
void Footer::vSetFooter(void)
{
  m_uFooter = C_FOOTER;
}

