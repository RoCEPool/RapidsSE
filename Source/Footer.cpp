#include "Magic.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer::Footer(void)
{
  m_uFooter = FOOTER;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer::~Footer(void)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/* ASSERT footer                                                              */
/*----------------------------------------------------------------------------*/
void Footer::vAssertFooter(void) const
{
  ASSERT(m_uFooter == FOOTER);
}

/*----------------------------------------------------------------------------*/
/* set footer                                                                 */
/*----------------------------------------------------------------------------*/
void Footer::vSetFooter(void)
{
  m_uFooter = FOOTER;
}

