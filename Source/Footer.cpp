#include "Common.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Footer::Footer(void)
{
  m_uFooter = FOOTER;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Footer::~Footer(void)
{
  vAssertFooter();
}

/*----------------------------------------------------------------------------*/
/* ASSERT footer                                                              */
/*----------------------------------------------------------------------------*/
void Footer::vAssertFooter(void) const
{
  ASSERT(m_uFooter == FOOTER);
}

/*----------------------------------------------------------------------------*/
/* get footer                                                                 */
/*----------------------------------------------------------------------------*/
u8 Footer::uFooter(void)
{
  return m_uFooter;
}

/*----------------------------------------------------------------------------*/
/* set footer                                                                 */
/*----------------------------------------------------------------------------*/
void Footer::vSetFooter(void)
{
  m_uFooter = FOOTER;
}

