/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Clause* CompilerStream::_pClause(void* aAddr)
{
  Clause* pClause = reinterpret_cast<Clause*>(aAddr);
  
  return pClause;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void Clause::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Clause::Clause(eCN eClassNo, TokenVec* pTknVec, i8& i_Tkn_)
: Operand(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
  
  m_pTokenVec = new TokenVec(false);
  
  // -- -- -- -- -- -- -- -- -- --
  
  i8 nTkn = pTknVec->nTokens();
  
  while (i_Tkn_ < nTkn) {
    Token* pTkn = pTknVec->pGet(i_Tkn_);
    
    if (StrLib::bOneOf((char**)szaClauseWords,pTkn->szText()->aChar()))
      break;
    
    m_pTokenVec->vAdd(new Token(pTkn));
    i_Tkn_++;
  }
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Clause::~Clause(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  delete m_pTokenVec;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TokenVec* Clause::pTokenVec(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_pTokenVec;
}

