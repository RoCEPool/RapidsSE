#include "Measurement.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Numbat::Numbat(Stz* szName)
: Object(CN_NUMBAT)
{
  _precondition_(_MAGIC_,CN_NUMBAT,_FOOTER_);
  
  m_sName  = szName;
  
  _checkInitialised_(CN_NUMBAT);
  
  _postcondition_(_MAGIC_,CN_NUMBAT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Numbat::~Numbat(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_NUMBAT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* add value                                                                  */
/*----------------------------------------------------------------------------*/
void Numbat::vAdd(i8 iArg)
{
  _precondition_(_MAGIC_,CN_NUMBAT,_FOOTER_);
  
  i8 i_Mag = IntLib::iByteMagnitude(iArg) - 1;
  
  
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Numbat::aFooter(void)
{
  _precondition_(_MAGIC_,CN_NUMBAT);
  
  return &m_xFooter;
}


