#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snFLT::snFLT(void)
: Sprint(CN_SNFLT)
{
  _precondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
  
  // set default Flt format
  vFormat(F_FLT);
  
  _checkInitialised_(CN_SNFLT);
  
  _postcondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snFLT::~snFLT(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNFLT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint snFLT and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* snFLT::sz(d8 dFlt)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  dFlt);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snFLT::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNFLT);
  
  return &m_xFooter;
}

