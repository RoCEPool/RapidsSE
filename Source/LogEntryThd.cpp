#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set thread entry                                                           */
/*----------------------------------------------------------------------------*/
void _LogEntryThd::vSet(LogEntry* pLogEntry, i8 iThdId, eHA eThdAct)
{
  pLogEntry->m_eKind = EK_THD;
  
  m_iThdId  = iThdId;
  m_eThdAct = eThdAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryThd::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("H"_Stz,m_iThdId),
                aHA[m_eThdAct]);
}

