void* JobDicPath::operator new(size_t)
{
  vFatal("fatal: JobDicPath class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
JobDicPath::JobDicPath(void)
{
  m_pSession = nullptr;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
JobDicPath::JobDicPath(Interface::Session* pSession)
{
  m_pSession = pSession;
  
  s32 sDicName;
  
  if (pSession) {
    i8 nDicNames = pSession->m_oDicStack.iCount();
    for (i8 i_Name = 0; i_Name < nDicNames; i_Name++) {
      sDicName = pSession->m_oDicStack.pPick(i_Name)->sName();
      m_xDicPath.vDicName(i_Name,sDicName);
    }
  }

}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
JobDicPath::~JobDicPath(void) noexcept(false)
{
  
}

