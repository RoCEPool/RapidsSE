#include "Common.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SysCall::SysCall(void)
: Header(CN_SYSCALL)
{
  m_eStatus  = eSysCall_NOTSET;
  m_iErrNo   = 0;
  
  _checkInitialised_(CN_SYSCALL);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SysCall::~SysCall(void)
{
  _magic_();

}

/*----------------------------------------------------------------------------*/
/* clear previous state                                                       */
/*----------------------------------------------------------------------------*/
void SysCall::vClear(void)
{
  _magic_();
  
  m_eStatus = eSysCall_NOTSET;
  m_iErrNo = 0;
}

/*----------------------------------------------------------------------------*/
/* set error number                                                           */
/*----------------------------------------------------------------------------*/
void SysCall::vError(i8 iErrNo)
{
  _magic_();
  
  m_eStatus = eSysCall_ERROR;
  m_iErrNo = iErrNo;
}

/*----------------------------------------------------------------------------*/
/* get error number                                                           */
/*----------------------------------------------------------------------------*/
i8 SysCall::iError(void)
{
  _magic_();
  
  return m_iErrNo;
}

/*----------------------------------------------------------------------------*/
/* set failure result                                                         */
/*----------------------------------------------------------------------------*/
void SysCall::vFailure(i8 iErrNo)
{
  _magic_();
  
  m_eStatus = eSysCall_SUCCESS;
  m_iErrNo  = iErrNo;
}

/*----------------------------------------------------------------------------*/
/* set successful result                                                      */
/*----------------------------------------------------------------------------*/
void SysCall::vSuccess(void)
{
  _magic_();
  
  m_eStatus = eSysCall_SUCCESS;
  m_iErrNo  = 0;
}

/*----------------------------------------------------------------------------*/
/* had an error                                                               */
/*----------------------------------------------------------------------------*/
bool SysCall::bHadError(void)
{
  _magic_();

  if (eSysCall_ERROR == m_eStatus)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SysCall::pFooter(void)
{
  return &m_xFooter;
}

