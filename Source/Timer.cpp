#include "Timer.hpp"

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* Timer::operator new(size_t, Timer* pTimer)
{
  return pTimer;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void Timer::operator delete(void* pTimerAddress)
{
  // do nothing
  // must be explicitly free'd by caller
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Timer::Timer(void)
: Header(CN_TIMER)
{
  vInit();
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Timer::~Timer(void)
{
}

/*----------------------------------------------------------------------------*/
/* init                                                                       */
/*----------------------------------------------------------------------------*/
void Timer::vInit(void)
{
  m_iStart  = 0;
  m_iUpdate = 0;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Timer::vReset(void)
{
  m_iStart  = 0;
  m_iUpdate = 0;
}

/*----------------------------------------------------------------------------*/
/* start                                                                      */
/*----------------------------------------------------------------------------*/
void Timer::vStart(void)
{
  m_iStart  = iRdtscp();
  m_iUpdate = 0;
}

/*----------------------------------------------------------------------------*/
/* update                                                                     */
/*----------------------------------------------------------------------------*/
void Timer::vUpdate(void)
{
  ASSERT(m_iStart);
  m_iUpdate = iRdtscp();
}

/*----------------------------------------------------------------------------*/
/* nanoseconds                                                                */
/*----------------------------------------------------------------------------*/
i8 Timer::iNanoseconds(void)
{
  ASSERT(m_iStart);
  ASSERT(m_iUpdate);
  
  i8 iTicks = (m_iUpdate - m_iStart);
  i8 iTicksPerSecond = System::iClockFrequency();
  
  i8 iNano = iTicks * C_1Bn / iTicksPerSecond;
  
  return iNano;
}

/*----------------------------------------------------------------------------*/
/* microseconds                                                               */
/*----------------------------------------------------------------------------*/
i8 Timer::iMicroseconds(void)
{
  ASSERT(m_iStart);
  ASSERT(m_iUpdate);
  
  i8 iTicks = (m_iUpdate - m_iStart);
  i8 iTicksPerSecond = System::iClockFrequency();
  
  i8 iMicro = iTicks * C_1M / iTicksPerSecond;
  
  return iMicro;
}

/*----------------------------------------------------------------------------*/
/* milliseconds                                                               */
/*----------------------------------------------------------------------------*/
i8 Timer::iMilliseconds(void)
{
  ASSERT(m_iStart);
  ASSERT(m_iUpdate);
  
  i8 iTicks = (m_iUpdate - m_iStart);
  i8 iTicksPerSecond = System::iClockFrequency();
  
  i8 iMilli = iTicks * C_1K / iTicksPerSecond;
  
  return iMilli;
}

/*----------------------------------------------------------------------------*/
/* seconds                                                                    */
/*----------------------------------------------------------------------------*/
i8 Timer::iSeconds(void)
{
  ASSERT(m_iStart);
  ASSERT(m_iUpdate);
  
  i8 iTicks = (m_iUpdate - m_iStart);
  i8 iTicksPerSecond = System::iClockFrequency();
  
  i8 iSeconds = iTicks / iTicksPerSecond;
  
  return iSeconds;
}

/*----------------------------------------------------------------------------*/
/* number of ticks                                                            */
/*----------------------------------------------------------------------------*/
i8 Timer::iTicks(void)
{
  ASSERT(m_iStart);
  ASSERT(m_iUpdate);

  i8 iTicks = (m_iUpdate - m_iStart);
  
  return iTicks;
}

