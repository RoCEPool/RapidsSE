#include "Datums.h"

#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Edt::operator new(size_t)
{
  vFatal("fatal: Edt class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Edt::Edt(void)
{
  m_iValue = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Edt::~Edt(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get as i8                                                                  */
/*----------------------------------------------------------------------------*/
i8 Edt::iAsI8(void)
{
  return m_iValue;
}

/*----------------------------------------------------------------------------*/
/* set as i8                                                                  */
/*----------------------------------------------------------------------------*/
void Edt::vAsI8(i8 iAsI8)
{
  m_iValue = iAsI8;
}

/*----------------------------------------------------------------------------*/
/* get year                                                                   */
/*----------------------------------------------------------------------------*/
i8 Edt::iYear(void)
{
  return x.m_uYearInEra + C_BASE_YEAR;
}

/*----------------------------------------------------------------------------*/
/* get month                                                                  */
/*----------------------------------------------------------------------------*/
i8 Edt::iMonth(void)
{
  return x.m_uMonth;
}

/*----------------------------------------------------------------------------*/
/* get day                                                                    */
/*----------------------------------------------------------------------------*/
i8 Edt::iDay(void)
{
  return x.m_uDay;
}

/*----------------------------------------------------------------------------*/
/*-- Null --------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* test if null                                                               */
/*----------------------------------------------------------------------------*/
bool Edt::bIsNull(void)
{
  if (C_DATUM_NULL == m_iValue)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* set to null                                                                */
/*----------------------------------------------------------------------------*/
void Edt::vSetNull(void)
{
  m_iValue = C_DATUM_NULL;
}

/*----------------------------------------------------------------------------*/
/* sprint Edt datum                                                           */
/*----------------------------------------------------------------------------*/
void Edt::vSprint(Stz* aDst)
{
  if (bIsNull()) {
    StrLib::vSprint(aDst,"null%c"_Stz,'\0');
    return;
  }
  
  StrLib::vSprint(aDst,"%02lld-%02lld-%02lld%c"_Stz,
                  (i8)x.m_uYearInEra + C_BASE_YEAR,
                  (i8)x.m_uMonth,
                  (i8)x.m_uDay,
                  '\0');
}

/*----------------------------------------------------------------------------*/
/*-- Extract and Sprint ------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* copy Edt datum                                                             */
/*----------------------------------------------------------------------------*/
i8 Edt::nCopy(void* aDst, void* aSrc)
{
  *(i8*)aDst = *(i8*)aSrc;
  
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* copy Edt datum                                                             */
/*----------------------------------------------------------------------------*/
void Edt::vCopy(void* aDst, void* aSrc)
{
  *(i8*)aDst = *(i8*)aSrc;
}

/*----------------------------------------------------------------------------*/
/* sprint Edt datum                                                           */
/*----------------------------------------------------------------------------*/
void Edt::vSprint(Stz* aDst, Stz* aSrc)
{
  Edt* aEdt = (Edt*)aSrc;
  
  if (aEdt->bIsNull())
    StrLib::vSprint(aDst,"null%c"_Stz,
                    '\0');
  else
    StrLib::vSprint(aDst,"%02lld-%02lld-%02lld%c"_Stz,
                    aEdt->x.m_uYearInEra + C_BASE_YEAR,
                    aEdt->x.m_uMonth,
                    aEdt->x.m_uDay,
                    '\0');
}

/*----------------------------------------------------------------------------*/
/* sprint Edt datum                                                           */
/*----------------------------------------------------------------------------*/
void Edt::vSprintEscaped(Stz* aDst, Stz* aSrc)
{
  Edt* aEdt = (Edt*)aSrc;
  
  if (aEdt->bIsNull())
    StrLib::vSprint(aDst,"null%c"_Stz,
                    '\0');
  else
    StrLib::vSprint(aDst,"%02lld-%02lld-%02lld%c"_Stz,
                    aEdt->x.m_uYearInEra + C_BASE_YEAR,
                    aEdt->x.m_uMonth,
                    aEdt->x.m_uDay,
                    '\0');
}

