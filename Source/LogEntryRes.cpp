#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryRes::vSet(LogEntry* pLogEntry, i8 iResId, eRK eResKnd, eRA eResAct)
{
  pLogEntry->m_eKind = EK_RES;
  
  m_iResId  = iResId;
  m_eResKnd = eResKnd;
  m_eResAct = eResAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryRes::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s,%s"_Stz,
              
                aRK_Short[m_eResKnd],
                spId.sz(m_iResId),
                aRA[m_eResAct]);
}

