#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntryRes::vSet(LogEntry* pLogEntry, i8 iResId, eRK eResKnd, eRA eResAct)
{
  pLogEntry->m_eKind = EK_RES;
  
  m_iResId  = iResId;
  m_eResKnd = eResKnd;
  m_eResAct = eResAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryRes::vWriteCsv(File* pFile)
{
  pFile->vPrint("%lld,%s,%s"_Stz,
              
                m_iResId,
                aRK_Short[m_eResKnd],
                aRA[m_eResAct]);
}

