#include "Threads.h"

pthread_key_t giTLS_ThreadKey = -1;
pthread_key_t giTLS_TaskKey   = -1;

/*----------------------------------------------------------------------------*/
/* initialise tls                                                             */
/*----------------------------------------------------------------------------*/
void TlsKeys::vInit(void)
{
  bool b = Pthread::bTlsCreate(&giTLS_ThreadKey);
  ASSERT(b);
  
  //ASSERT(!b);
  b = Pthread::bTlsCreate(&giTLS_TaskKey);
  ASSERT(b);
}


