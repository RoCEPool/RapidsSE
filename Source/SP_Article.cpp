/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Article::SP_Article(void)
: SP(CN_SPELAPSED)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
  
  _checkInitialised_(CN_SPELAPSED);
  
  _postcondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Article::~SP_Article(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Article and return that Stz*                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Article::sz(Article* pArticle)
{
  _precondition_(_MAGIC_,CN_SPELAPSED,_FOOTER_);
  
  Object* pObject = pArticle->pObject();
  
  StrLib::vSprint(m_caResult,
                  "%p %s : %p %s"_Stz,
                  
                  pArticle,
                  pArticle->szName(),
                  
                  pObject,
                  aCN[pObject->eClass()],
                  
                  C_ENDARGS);
  
  return (Stz*) &m_caResult[0];
}


