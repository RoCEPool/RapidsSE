#include "Values.h"
#include "Memory.hpp"
#include "StorageEngine.h"

extern BufferPool*  gpBufferPool;

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s48K::s48K(void)
: StrVal(CN_S48K,C_S48K_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S48K_DATAAREA);
  
  _checkInitialised_(CN_S48K);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s48K::s48K(s48K& rArg)
: StrVal(CN_S48K,C_S48K_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);

  Memory::vZero(m_mDataArea, C_S48K_DATAAREA);
  
  StrVal::vCopy(rArg.a());
  
  _checkInitialised_(CN_S48K);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
s48K::s48K(const char* aArg)
: StrVal(CN_S48K,C_S48K_DATAAREA)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
  Memory::vZero(m_mDataArea, C_S48K_DATAAREA);
  
  StrVal::vCopy(aArg);
  
  _checkInitialised_(CN_S48K);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
s48K::~s48K(void)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s48K::operator = (const char* aArg)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
  StrVal::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s48K::operator = (char* aArg)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
  StrVal::vCopy(aArg);
}

/*----------------------------------------------------------------------------*/
/* assignment operator                                                        */
/*----------------------------------------------------------------------------*/
void s48K::operator = (StrVal& rArg)
{
  _precondition_(_MAGIC_,CN_S48K,_FOOTER_);
  
  vCopy(rArg.a());
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* s48K::pFooter(void)
{
  _precondition_(_MAGIC_,CN_S48K);
  
  return &m_xFooter;
}

