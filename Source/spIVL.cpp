#include "Transform.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
spIVL::spIVL(void)
: Sprint(CN_SPIVL)
{
  _precondition_(_MAGIC_,CN_SPIVL,_FOOTER_);
  
  // set default Ivl format
  vFormat(F_IVL);
  
  _checkInitialised_(CN_SPIVL);
  
  _postcondition_(_MAGIC_,CN_SPIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
spIVL::~spIVL(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Ivl and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* spIVL::sz(i8 iIvl)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(iIvl,0);
}

/*----------------------------------------------------------------------------*/
/* sprint Ivl and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* spIVL::sz(i8 iIvl, i8 iScale)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  iIvl);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spIVL::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(0x1UL << 53,1023);
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spIVL::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(73,73);
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* spIVL::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(0,0);
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* spIVL::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPIVL);
  
  return &m_xFooter;
}

