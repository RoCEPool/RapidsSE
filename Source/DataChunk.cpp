#include "Structures.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
DataChunk* Structures::_pDataChunk(void* aAddr)
{
  DataChunk* pDataChunk = reinterpret_cast<DataChunk*>(aAddr);
    
  return pDataChunk;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DataChunk::operator new(size_t)
{
  vFatal("fatal: JobObjectName class cannot be new'd\n"_Stz);

  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DataChunk::DataChunk(eCN eClass)
: Object(eClass)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  m_nDataBytes = 0;
  m_aLastDataByte = nullptr;
  
  m_xWsp.vFill(0xEF,eClass);
 
  _postcondition_(_ADDRESS_,_MAGIC_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
DataChunk::~DataChunk(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get wsp as string pointer                                                  */
/*----------------------------------------------------------------------------*/
Stz* DataChunk::aStr(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  return m_xWsp.aStr();
}

