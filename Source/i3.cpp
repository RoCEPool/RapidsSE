/*============================================================================*/
/* i3.cpp -- a 3-byte integer                                                 */
/*============================================================================*/

#include "Base.h"
  
/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
i3::i3(void)
{
  m_iValue = 0;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
i3::i3(i8 iArg)
{
  m_iValue = iArg;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
i3::~i3(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Reference ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get value                                                                  */
/*----------------------------------------------------------------------------*/
i8 i3::operator *(void)
{
  return m_iValue;
}

/*----------------------------------------------------------------------------*/
/* set value                                                                  */
/*----------------------------------------------------------------------------*/
void i3::operator =(i8 iArg)
{
  m_iValue = iArg;
}

/*----------------------------------------------------------------------------*/
/*-- Comparison --------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* > operator                                                                 */
/*----------------------------------------------------------------------------*/
bool i3::operator >(i8 iArg)
{
  return iArg > m_iValue;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool i3::operator >=(i8 iArg)
{
  return iArg >= m_iValue;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool i3::operator ==(i8 iArg)
{
  return iArg == m_iValue;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool i3::operator !=(i8 iArg)
{
  return iArg != m_iValue;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool i3::operator <=(i8 iArg)
{
  return iArg <= m_iValue;
}

/*----------------------------------------------------------------------------*/
/* < operator                                                                 */
/*----------------------------------------------------------------------------*/
bool i3::operator <(i8 iArg)
{
  return iArg < m_iValue;
}

/*----------------------------------------------------------------------------*/
/*-- Numeric -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
i8 i3::operator +(i8 iArg)
{
  return m_iValue + iArg;
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
i8 i3::operator -(i8 iArg)
{
  return m_iValue - iArg;
}

/*----------------------------------------------------------------------------*/
/* prefix increment                                                           */
/*----------------------------------------------------------------------------*/
i8 i3::operator ++(void)
{
  return ++m_iValue;
}

/*----------------------------------------------------------------------------*/
/* postfix increment                                                          */
/*----------------------------------------------------------------------------*/
i8 i3::operator ++(int)
{
  return ++m_iValue;
}

/*----------------------------------------------------------------------------*/
/* prefix decrement                                                           */
/*----------------------------------------------------------------------------*/
i8 i3::operator --(void)
{
  return --m_iValue;
}

/*----------------------------------------------------------------------------*/
/* postfix decrement                                                          */
/*----------------------------------------------------------------------------*/
i8 i3::operator --(int)
{
  return --m_iValue;
}

/*----------------------------------------------------------------------------*/
/* _i3 3-byte literal suffix                                                  */
/*----------------------------------------------------------------------------*/
i3 Base::operator "" _i3(u8 uArg)
{
  return (i3)uArg;
}

