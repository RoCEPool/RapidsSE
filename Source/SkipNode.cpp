void* SkipNode::operator new(size_t iSize, i4 iLevel)
{
  int nBytes = sizeof(SkipNode) + ((int)iLevel * sizeof(SkipNode*));
  
  void* pNode = static_cast<void*>(malloc(nBytes));
  
  ((SkipNode*)pNode)->m_iForward = iLevel;
  
  return pNode;
}

