void Prefetch::Test(void)
{
  vTrace("Prefetch Utility\n"_Stz);
  
  Timer xTimer;
  
  vTrace("Allocating 1GB chunk\n"_Stz);
  char* aChunk = (char*)malloc(C_1GB);
  
  xTimer.vStart();
  xTimer.vUpdate();
  vTrace("Time %lldns\n"_Stz,xTimer.iNanoseconds());
  
  vTrace("Freeing 1GB chunk\n"_Stz);
  free(aChunk);
}

