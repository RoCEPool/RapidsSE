/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Schema* MetaData::_pSchema(void* aAddr)
{
  Schema* pSchema = reinterpret_cast<Schema*>(aAddr);
  
  if (pSchema && CN_SCHEMA != pSchema->eClass())
    vTrace("_pSchema got class %s\n"_Stz,aCN[pSchema->eClass()]);
  
  RASSERT_TYPE(pSchema,CN_SCHEMA);
  
  return pSchema;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Schema::operator new(size_t)
{
  Schema* pSchema = nullptr;
  
  return pSchema;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Schema::operator delete(void*)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Schema::Schema(void)
: Object(CN_SCHEMA)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SCHEMA,_FOOTER_);
  
  
  _checkInitialised_(CN_SCHEMA);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_SCHEMA,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Schema::~Schema(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SCHEMA,_FOOTER_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Schema::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SCHEMA);
  
  return &m_xFooter;
}


