#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Int::SN_Int(void)
: Scan(CN_SNINT)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
  
  _checkInitialised_(CN_SNINT);
  
  _postcondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Int::~SN_Int(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNINT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Int::i(char** aacCrs, Column* pCol, Formatters* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNINT);
  
  if ( ! StrLib::bExtractInteger(aacCrs,&m_wDtm.m_iInt,
                                 true/*bWithSign*/) )
    throw C_UNKNOWN;

  return m_wDtm.m_iInt;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Int::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNINT);
  
  return &m_xFooter;
}

