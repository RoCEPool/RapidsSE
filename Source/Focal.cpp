#include "Correctness.h"

#include "AM.hpp"

/*----------------------------------------------------------------------------*/
/* constructor (for non-tracked focal objects -- mainly locks in HeapBuffer)  */
/*----------------------------------------------------------------------------*/
Focal::Focal(eCN eClassNo)
: Object(eClassNo)
{
  m_i_Focal   = C_UNKNOWN;
  m_iUniqueId = C_UNKNOWN;
  m_i_Log     = C_UNKNOWN;
  m_iTick_    = AM::iRdTimePoint();
  
  m_iActNo    = C_UNKNOWN;
  m_iForId    = C_UNKNOWN;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Focal::Focal(eCN eClassNo, i8 iUniqueId)
: Object(eClassNo)
{
  m_i_Focal   = C_UNKNOWN;
  m_iUniqueId = iUniqueId;
  m_i_Log     = C_UNKNOWN;
  m_iTick_    = AM::iRdTimePoint();
  
  m_iActNo    = C_UNKNOWN;
  m_iForId    = C_UNKNOWN;

  AM::vFocalAdd(this);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Focal::~Focal(void) noexcept(false)
{
  if (C_UNKNOWN != m_i_Focal)
    AM::vFocalRemove(this);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* inc action sequence number                                                 */
/*----------------------------------------------------------------------------*/
i8 Focal::iActNo(void)
{
  return m_iActNo;
}

/*----------------------------------------------------------------------------*/
/* inc action sequence number                                                 */
/*----------------------------------------------------------------------------*/
void Focal::vIncActNo(void)
{
  m_iActNo++;
}


