#include "Structures.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
GraphCursor* Structures::_pGraphCursor(void* pAddr)
{
  GraphCursor* pGraphCursor = reinterpret_cast<GraphCursor*>(pAddr);
  
  return pGraphCursor;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* GraphCursor::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  void* pObject = Heap::pAllocate(CN_GRAPHCURSOR);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* GraphCursor::operator new(size_t iSize, GraphCursor* pGraphCursor)
{
  RASSERT(iSize);
  
  return pGraphCursor;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void GraphCursor::operator delete(void* pGraphAddress)
{
  Graph* pGraph = reinterpret_cast<Graph*>(pGraphAddress);
  
  Heap::vFree(pGraph);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
GraphCursor::GraphCursor(void)
: Object(CN_GRAPHCURSOR)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
  
  _checkInitialised_(CN_GRAPHCURSOR);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
GraphCursor::~GraphCursor(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* dump the graph                                                             */
/*----------------------------------------------------------------------------*/
void GraphCursor::vDump(eCN eClass, Object* pObject, const char* pTab)
{
  vTrace("%sGraphCursor: %p\n", pTab, pObject);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* GraphCursor::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR);
  
  return &m_xFooter;
}

