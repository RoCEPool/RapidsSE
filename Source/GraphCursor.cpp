#include "Structures.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
GraphCursor* Structures::_pGraphCursor(void* aAddr)
{
  GraphCursor* pGraphCursor = reinterpret_cast<GraphCursor*>(aAddr);
  
  RASSERT_TYPE(pGraphCursor,CN_GRAPHCURSOR);
  
  return pGraphCursor;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* GraphCursor::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_GRAPHCURSOR);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* GraphCursor::operator new(size_t, GraphCursor* pGraphCursor)
{
  return pGraphCursor;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void GraphCursor::operator delete(void* pGraphAddress)
{
  Graph* pGraph = reinterpret_cast<Graph*>(pGraphAddress);
  
  HeapMem::vFree(pGraph);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
GraphCursor::GraphCursor(void)
: Object(CN_GRAPHCURSOR)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
  
  _checkInitialised_(CN_GRAPHCURSOR);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
GraphCursor::~GraphCursor(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* dump the graph                                                             */
/*----------------------------------------------------------------------------*/
void GraphCursor::vDump(eCN eClass, Object* pObject, Stz* aTab)
{
  vTrace("\n"_Stz);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* GraphCursor::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_GRAPHCURSOR);
  
  return &m_xFooter;
}

