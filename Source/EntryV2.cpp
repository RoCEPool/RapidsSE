/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryV2::operator new(size_t)
{
  vFatal("fatal: EntryV2 class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EntryV2::operator new(size_t, EntryV2* aEntry)
{
  return aEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntryV2::EntryV2(eCN eClassNo, i8 nThisBytes, i8 nOffsets)
: Header(eClassNo)
{
  m_xId.vOffsets(nOffsets);
  m_nBytes = 0;
  m_aBytes[0] = 0;
  
  _checkInitialised_(eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntryV2::~EntryV2(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get bytes array                                                             */
/*----------------------------------------------------------------------------*/
byte* EntryV2::aBytes(void)
{
  return m_aBytes;
}

/*----------------------------------------------------------------------------*/
/* get number of bytes in the entry                                           */
/*----------------------------------------------------------------------------*/
i8 EntryV2::nBytes(void)
{
  return m_nBytes;
}

/*----------------------------------------------------------------------------*/
/* get entry size                                                             */
/*----------------------------------------------------------------------------*/
i8 EntryV2::iSize(void)
{
  i8 nOffsets = m_xId.nOffsets();
  i8 nOffsetBytes = sizeof(i4) * nOffsets;

  i8 nBytes = sizeof(EntryV2) - sizeof(byte) + m_nBytes + nOffsetBytes;
  
  return nBytes;
}

