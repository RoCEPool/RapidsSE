#include "ScanSprint.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Dte::SN_Dte(void)
: Scan(CN_SNDTE)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
  
  _checkInitialised_(CN_SNDTE);
  
  _postcondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Dte::~SN_Dte(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNDTE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Dte::i(char** aacCrs, Column* pCol, Format* pScnFmt)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  i8 iYear, iMonth, iDay;
  
  if ( ! StrLib::bExtractDate2(aacCrs,
                               iYear, iMonth, iDay,
                               pScnFmt->m_eDateComponent,
                               pScnFmt->m_cDateSeparator) )
    THROW("StrLib::bExtractDate2"_Stz);

  m_wDtm.xDte.m_uYearDelta  = iYear - C_YEAR_BASE;
  m_wDtm.xDte.m_uMonth = iMonth;
  m_wDtm.xDte.m_uDay   = iDay;
  m_wDtm.xDte.m_uSpare = 0;
  
  return m_wDtm.m_iI8;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Dte::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNDTE);
  
  return &m_xFooter;
}

