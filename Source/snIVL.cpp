#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
snIVL::snIVL(void)
: Sprint(CN_SNIVL)
{
  _precondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
  
  // set default Ivl format
  vFormat(F_IVL);
  
  _checkInitialised_(CN_SNIVL);
  
  _postcondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
snIVL::~snIVL(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint Ivl and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* snIVL::sz(i8 iIvl)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(iIvl,0);
}

/*----------------------------------------------------------------------------*/
/* sprint Ivl and return Stz* to result                                       */
/*----------------------------------------------------------------------------*/
Stz* snIVL::sz(i8 iIvl, i8 iScale)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  StrLib::vSprint(m_caResult,
                  (Stz*)m_caFormat,
                  iIvl);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* snIVL::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNIVL);
  
  return &m_xFooter;
}

