#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryLog::vSet(LogEntry* pLogEntry, i8 iLogId, eGA eLogAct)
{
  pLogEntry->m_eKind = EK_LOG;
  
  m_iLogId  = iLogId;
  m_eLogAct = eLogAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryLog::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("G"_Stz,m_iLogId),
                aLA[m_eLogAct]);
}

