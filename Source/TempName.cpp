/*============================================================================*/
/* TempName.cpp - temporary name generator                                    */
/*============================================================================*/

#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TempName::TempName(void)
: Object(CN_SINCE)
{
  _precondition_(_MAGIC_,CN_SINCE,_FOOTER_);
  
  m_oSince.vNow();
  
  m_sClicker = "aaaaaaaa"_Stz;
  
  _checkInitialised_(CN_SINCE);
  
  _postcondition_(_MAGIC_,CN_SINCE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TempName::~TempName(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SINCE,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* generate next name                                                         */
/*----------------------------------------------------------------------------*/
void TempName::vNextName(s32& sName)
{
  _precondition_(_MAGIC_,CN_SINCE,_FOOTER_);
  
  sName.vSprint("%x_%s"_Stz,
                m_oSince.iSeconds(),
                m_sClicker.aStz());
  
  StrLib::vClick(m_sClicker.aChar());
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* TempName::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SINCE);
  
  return &m_xFooter;
}

