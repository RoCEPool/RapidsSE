/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
LogicalOp* LogicalPlans::_pFilter(void* aAddr)
{
  LogicalOp* pFilter = reinterpret_cast<LogicalOp*>(aAddr);
  
  return pFilter;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void LogicalOp::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
LogicalOp::LogicalOp(eCN eClassNo, TokenVec* pTokenVec)
: Operand(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
  
  m_sName = C_NO_NAME;
  m_pTokenVec = new TokenVec(false);
  
  // -- -- -- -- -- -- -- -- -- --
  
  if (pTokenVec)
    m_pTokenVec->vCopyVector(pTokenVec);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
LogicalOp::~LogicalOp(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  delete m_pTokenVec;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*                                                                            */
/*----------------------------------------------------------------------------*/
void LogicalOp::vAsString(s4K& sFilterStr)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  sFilterStr = m_sName;
  
  for (i8 i_Tkn = 0; i_Tkn < m_pTokenVec->nTokens(); i_Tkn++) {
    sFilterStr.vConcat(" "_Stz);
    sFilterStr.vConcat(m_pTokenVec->pGet(i_Tkn)->szChars());
  }
}

