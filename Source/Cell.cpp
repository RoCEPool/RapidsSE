/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Cell* Forth::_pCell(void* aAddr)
{
  Cell* pCell = reinterpret_cast<Cell*>(aAddr);
  
  return pCell;
}

