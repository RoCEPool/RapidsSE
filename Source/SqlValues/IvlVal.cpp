#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IvlVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: IvlVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Ivl IvlVal::wIvl(void)
{
  ASSERT(bIsClass(CN_IVLVAL));
  
  return m_wIvl;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void IvlVal::vIvl(Ivl wIvl)
{
  vClass(CN_IVLVAL);
  m_wIvl = wIvl;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a IvlVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 IvlVal::nStackUsage(void)
{
  return sizeof(IvlVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IvlVal::vToStz(Stz* szDst)
{
  if (m_wIvl.bIsNull()) {
    szDst->vConcat(C_NULL);
    return;
  }
  
  * szDst = m_wIvl;
}

