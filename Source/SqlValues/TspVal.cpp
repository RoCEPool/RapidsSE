#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* TspVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: TspVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return sql value                                                           */
/*----------------------------------------------------------------------------*/
Tsp TspVal::wTsp(void)
{
  ASSERT(bIsClass(CN_TSPVAL));
  
  return m_wTsp;
}

/*----------------------------------------------------------------------------*/
/* assign sql value                                                           */
/*----------------------------------------------------------------------------*/
void TspVal::vTsp(Tsp wTsp)
{
  vClass(CN_TSPVAL);
  m_wTsp = wTsp;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a TspVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 TspVal::nStackUsage(void)
{
  return sizeof(TspVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void TspVal::vToStz(Stz* szDst)
{
  if (m_wTsp.bIsNull()) {
    szDst->vConcat(C_NULL);
    return;
  }
  
  * szDst = m_wTsp;
}

