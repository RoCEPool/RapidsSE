#include "Values.h"
#include "StorageEngine.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
FipVal* Values::_aFipVal(void* aAddr)
{
  FipVal* aFipVal = reinterpret_cast<FipVal*>(aAddr);
  
  RASSERT_TYPE(aFipVal,CN_FIPVAL);
  
  return aFipVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FipVal::operator new(size_t)
{
  vFatal("fatal: FipVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FipVal::FipVal(void)
: Value(CN_FIPVAL)
{
  m_aCell = nullptr;
  
  _checkInitialised_(CN_FIPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void FipVal::operator =(Cell* aCell)
{
  m_aCell = aCell;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 FipVal::nSize(void) const
{
  return sizeof(FipVal);
}

/*----------------------------------------------------------------------------*/
/* get pVal                                                                   */
/*----------------------------------------------------------------------------*/
Cell* FipVal::aIpPtr(void) const
{
  return pPoolCheck<Cell*>(m_aCell);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FipVal::vToString(Stz* aWorkspace)
{
  *aWorkspace = reinterpret_cast<void*>(m_aCell);
}

