/*============================================================================*/
/* FipVal.cpp -- Layout of a Forth Instruction Pointer when on Stack          */
/*============================================================================*/

#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
FipVal* SenVM::_aFipVal(void* aAddr)
{
  FipVal* aFipVal = reinterpret_cast<FipVal*>(aAddr);
  
  RASSERT_TYPE(aFipVal,CN_FIPVAL);
  
  return aFipVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FipVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: FipVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FipVal::FipVal(void)
: StkVal(CN_FIPVAL)
{
  _Header::vClass(CN_FIPVAL);
  
  m_aFip = nullptr;
  
  _checkInitialised_(CN_FIPVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void FipVal::operator =(Cell* aFip)
{
  m_aFip = aFip;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get instruction pointer                                                    */
/*----------------------------------------------------------------------------*/
Cell* FipVal::aFip(void)
{
  return pPoolCheck<Cell*>(m_aFip);
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a FipVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 FipVal::nStackBytes(void)
{
  return sizeof(FipVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FipVal::vToString(Stz* szDst)
{
  * szDst = reinterpret_cast<void*>(m_aFip);
}

