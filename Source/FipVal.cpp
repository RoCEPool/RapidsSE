/*============================================================================*/
/* FipVal.cpp -- Layout of a Forth Instruction Pointer when on Stack          */
/*============================================================================*/

#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* FipVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: FipVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return value                                                               */
/*----------------------------------------------------------------------------*/
Cell* FipVal::aFip(void)
{
  vClass(CN_FIPVAL);
  
  return m_aFip;
}

/*----------------------------------------------------------------------------*/
/* assign value                                                               */
/*----------------------------------------------------------------------------*/
void FipVal::vFip(Cell* aFip)
{
  vClass(CN_FIPVAL);
  m_aFip = aFip;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a FipVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 FipVal::nStackUsage(void)
{
  return sizeof(FipVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void FipVal::vToStz(Stz* szDst)
{
  * szDst = reinterpret_cast<void*>(m_aFip);
}

