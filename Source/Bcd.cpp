/*----------------------------------------------------------------------------*/
/* sprint bcd datum                                                           */
/*----------------------------------------------------------------------------*/
void Bcd::vSprint(Stz* aDst, MetaData::Column* pColumn)
{
  bool bNegative = false;
  
  if (bIsNull()) {
    StrLib::vSprint(aDst,"null%c"_Stz, '\0');
  return;
 }
  
  i8 iDigits = 1;
  for (i8 i_Digit = 0; i_Digit < pColumn->iColumnScale(); i_Digit++)
    iDigits *= 10;
  
  i8 iBcd_Whole = m_iBcd / iDigits;
  i8 iBcd_Fraction = m_iBcd % iDigits;
  
  if (iBcd_Fraction < 0 || iBcd_Whole < 0) {
    bNegative = true;
    iBcd_Fraction = iBcd_Fraction * -1;
    iBcd_Whole = iBcd_Whole * -1;
  }
  
  if (pColumn->iColumnScale())
    StrLib::vSprint(aDst,"%s%lld.%.*lld%c"_Stz,
                    bNegative ? "-" : "",
                    iBcd_Whole,
                    pColumn->iColumnScale(),
                    iBcd_Fraction,'\0');
  else
    StrLib::vSprint(aDst,"%s%lld%c"_Stz, bNegative ? "-" : "",iBcd_Whole, '\0');

}

/*----------------------------------------------------------------------------*/
/* sprint bcd datum                                                           */
/*----------------------------------------------------------------------------*/
void Bcd::vSprint(Stz* aDst, Stz* aSrc, MetaData::Column* pColumn)
{
  bool bNegative = false;
  Bcd* aBcd = (Bcd*)aSrc;
  
  if (aBcd->bIsNull())
    StrLib::vSprint(aDst,"null%c"_Stz,
                    '\0');
  else {
    i8 iBcd = *(i8*)aSrc;
    i8 iDigits = 1;
    for (i8 i_Digit = 0; i_Digit < pColumn->iColumnScale(); i_Digit++)
      iDigits *= 10;
    
    i8 iBcd_Whole = iBcd / iDigits;
    i8 iBcd_Fraction = iBcd % iDigits;
    
    if (iBcd_Fraction < 0 || iBcd_Whole < 0) {
      bNegative = true;
      iBcd_Fraction = iBcd_Fraction * -1;
      iBcd_Whole = iBcd_Whole * -1;
    }
    
    if (pColumn->iColumnScale())
      StrLib::vSprint(aDst,"%s%lld.%.*lld%c"_Stz,
                      bNegative ? "-" : "",
                      iBcd_Whole,
                      pColumn->iColumnScale(),
                      iBcd_Fraction,'\0');
    else
      StrLib::vSprint(aDst,"%s%lld%c"_Stz, bNegative ? "-" : "",iBcd_Whole, '\0');
  }
}

/*----------------------------------------------------------------------------*/
/* is the size valid ?                                                        */
/*----------------------------------------------------------------------------*/
bool Bcd::bIsValidSize(i8 iPrecision, i8 iScale)
{
  if (iPrecision > C_MAX_PRECISION_BCD)
    return false;
  
  if (iScale > iPrecision)
    return false;
  
  if (iScale > C_MAX_PRECISION_BCD)
    return false;
  
  return true;
}

