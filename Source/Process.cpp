#include "System.h"

/*----------------------------------------------------------------------------*/
/* get process id                                                             */
/*----------------------------------------------------------------------------*/
i8 Process::iGetPid(void)
{
  i8 iPid = getpid();
  
  return iPid;
}

/*----------------------------------------------------------------------------*/
/* kill process                                                               */
/*----------------------------------------------------------------------------*/
bool Process::bKillPid(i8 iPid)
{
  i8 iResult = kill((pid_t)iPid,SIGKILL);
  
  if (! iResult)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* test process id exists                                                     */
/*----------------------------------------------------------------------------*/
bool Process::bTestPid(i8 iPid)
{
  i8 iResult = kill((pid_t)iPid,0);
  
  if (! iResult)
    return true;
  else
    return false;
}

