/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
XmitOp* PushDown::_pXmitOp(void* aAddr)
{
  XmitOp* pXmitOp = reinterpret_cast<XmitOp*>(aAddr);
  
  return pXmitOp;
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
XmitOp::XmitOp(void)
: Op(CN_XMITOP)
{
  _precondition_(_MAGIC_,CN_XMITOP);
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
XmitOp::~XmitOp(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_XMITOP);
}

