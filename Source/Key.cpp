/*============================================================================*/
/* Key.cpp -- key part of an index entry                                      */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get bytes required for row                                                 */
/*----------------------------------------------------------------------------*/
i8 Key::iBytesRequired(const char* w)
{
  i8 iBytes = sizeof(Key) + String::iSize(w);
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/* get bytes required for row                                                 */
/*----------------------------------------------------------------------------*/
i8 Key::iBytesRequired(i8 iDataBytes)
{
  i8 iBytes = sizeof(Entry) + iDataBytes;
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Key class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize, Key* pKey)
{
  RASSERT(iSize);
  return pKey;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Key::Key(i8 iDataBytes)
{
  m_iDataBytes = iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Key::~Key(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get data                                                                   */
/*----------------------------------------------------------------------------*/
char* Key::pData(void)
{
  char* pDataAddr = pcAdd(this,sizeof(Row));
  
  return pPoolCheck<char*>(pDataAddr);
}

/*----------------------------------------------------------------------------*/
/* get data bytes                                                             */
/*----------------------------------------------------------------------------*/
i8 Key::iDataBytes(void)
{
  return m_iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* set data bytes                                                             */
/*----------------------------------------------------------------------------*/
void Key::vDataBytes(i8 iDataBytes)
{
  m_iDataBytes = iDataBytes;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Key::vContentDump(void)
{
  vTrace("Key %p: (%lld bytes)\n",
         this,
         m_iDataBytes
         );
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this key                                              */
/*----------------------------------------------------------------------------*/
i8 Key::iSize(void)
{
  i8 iBytes = sizeof(Key) + m_iDataBytes;
  
  return iBytes;
}

