#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Key* DBobjects::_aKey(void* aAddr)
{
  Key* aKey = reinterpret_cast<Key*>(aAddr);
  
  return aKey;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Key class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize, Key* pKey)
{
  RASSERT(iSize);
  return pKey;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Key::Key(KeyWsp& xKeyWsp)
{
  vKey(xKeyWsp);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Key::~Key(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator <                                                                 */
/*----------------------------------------------------------------------------*/
bool Key::operator <(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)aWspStr();
  i8 iDatumB = *(i8*)pKeyArg->aWspStr();
  
  bool b = iDatumA < iDatumB;
  
  return b;
}

/*----------------------------------------------------------------------------*/
/* operator <=                                                                */
/*----------------------------------------------------------------------------*/
bool Key::operator <=(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)aWspStr();
  i8 iDatumB = *(i8*)pKeyArg->aWspStr();
  
  bool b = iDatumA <= iDatumB;
  
  return b;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void Key::vKey(Key& xKey)
{
  Str* aSrc = reinterpret_cast<Str*>(&xKey);
  Str* aDst = aWspStr();
  i8 nBytes  = xKey.nSize();
  
  MemLib::vCopy(aDst,&xKey,nBytes);
}

/*----------------------------------------------------------------------------*/
/* set key from given key workspace                                           */
/*----------------------------------------------------------------------------*/
void Key::vKey(KeyWsp& xKeyWsp)
{
  Str* aDst = aWspStr();
  Str* aSrc = xKeyWsp.aWspStr();
  i8 nBytes  = xKeyWsp.nWspUsed();
  
  i8 iVal = *(i8*)aSrc;
  
  MemLib::vCopy(aDst,aSrc,nBytes);
}

/*----------------------------------------------------------------------------*/
/* get next element from key                                                  */
/*----------------------------------------------------------------------------*/
char* Key::aElement(Column* pColumn, i8& nBytes, char** aaCursor)
{
  char* aElement = pColumn->aValue(nBytes,aaCursor);
  
  return aElement;
}

/*----------------------------------------------------------------------------*/
/* show the contents of this key                                              */
/*----------------------------------------------------------------------------*/
void Key::vShow(eCT eColumnType)
{
  i8 iKey;
  Str* pKey;
  
  switch (eColumnType) {
    case CT_INTEGER:
      iKey = *(i8*)aWspStr();
      vTrace("Key %p: (size %lld value:%lld)\n"_Str,
             this,
             nSize(),
             iKey
             );
      break;
      
    case CT_VARCHAR:
      pKey = aWspStr();
      vTrace("Key %p: (size %lld value:%s)\n"_Str,
             this,
             nSize(),
             pKey
             );
      break;
      
    default:
      ASSERT(0);
  }
  
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
char* Key::aWspArea(void)
{
  return m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
Str* Key::aWspStr(void)
{
  return m_xWsp.aStr();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this key                                              */
/*----------------------------------------------------------------------------*/
i8 Key::nSize(void)
{
  i8 nBytes = sizeof(i8);
  
  return nBytes;
}

