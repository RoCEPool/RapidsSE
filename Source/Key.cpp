/*============================================================================*/
/* Key.cpp -- key part of an index entry                                      */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Key class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize, Key* pKey)
{
  RASSERT(iSize);
  return pKey;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Key::Key(KeyWsp& xKeyWsp)
{
  vKey(xKeyWsp);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Key::~Key(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator <                                                                 */
/*----------------------------------------------------------------------------*/
bool Key::operator <(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)aWspArea();
  i8 iDatumB = *(i8*)pKeyArg->aWspArea();
  
  bool b = iDatumA < iDatumB;
  
  return b;
}

/*----------------------------------------------------------------------------*/
/* operator <=                                                                */
/*----------------------------------------------------------------------------*/
bool Key::operator <=(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)aWspArea();
  i8 iDatumB = *(i8*)pKeyArg->aWspArea();
  
  bool b = iDatumA <= iDatumB;
  
  return b;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void Key::vKey(Key& xKey)
{
  Str* aSrc = reinterpret_cast<Str*>(&xKey);
  Str* aDst = aWspArea();
  i8 nBytes  = xKey.nSize();
  
  MemLib::vCopy(aDst,&xKey,nBytes);
}

/*----------------------------------------------------------------------------*/
/* set key from given key workspace                                           */
/*----------------------------------------------------------------------------*/
void Key::vKey(KeyWsp& xKeyWsp)
{
  Str* aDst = aWspArea();
  Str* aSrc = xKeyWsp.aWspArea();
  i8 nBytes  = xKeyWsp.nWspUsed();
  
  MemLib::vCopy(aDst,aSrc,nBytes);
}

/*----------------------------------------------------------------------------*/
/* show the contents of this key                                              */
/*----------------------------------------------------------------------------*/
void Key::vShow(void)
{
  i8 iKey = *(i8*)aWspArea();
  
  vTrace("Key %p: (size %lld value:%lld)\n"_Str,
         this,
         nSize(),
         iKey
         );
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
char* Key::sWspArea(void)
{
  return m_xWsp.sArea();
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
Str* Key::aWspArea(void)
{
  return m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this key                                              */
/*----------------------------------------------------------------------------*/
i8 Key::nSize(void)
{
  i8 nBytes = sizeof(i8);
  
  return nBytes;
}

