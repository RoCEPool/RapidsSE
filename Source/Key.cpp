/*----------------------------------------------------------------------------*/
/* operator <                                                                 */
/*----------------------------------------------------------------------------*/
bool Key::operator <(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)pDataArea();
  i8 iDatumB = *(i8*)pKeyArg->pDataArea();
  
  bool b = iDatumA < iDatumB;
  
  return b;
}

