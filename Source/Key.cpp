/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Key class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Key::operator new(size_t iSize, Key* pKey)
{
  RASSERT(iSize);
  return pKey;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Key::Key(KeyWsp& xKeyWsp)
{
  vKey(xKeyWsp);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Key::~Key(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator <                                                                 */
/*----------------------------------------------------------------------------*/
bool Key::operator <(Key* pKeyArg)
{
  i8 iDatumA = *(i8*)pDataArea();
  i8 iDatumB = *(i8*)pKeyArg->pDataArea();
  
  bool b = iDatumA < iDatumB;
  
  return b;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void Key::vKey(Key& xKey)
{
  // more ???
  char* pDst = pDataArea();
  i8 nBytes  = xKey.nDataBytes();
  Memory::vCopy(pDst,&xKey,nBytes);
}

/*----------------------------------------------------------------------------*/
/* set key from key wsp                                                       */
/*----------------------------------------------------------------------------*/
void Key::vKey(KeyWsp& xKeyWsp)
{
  char* pDst = pDataArea();
  char* pSrc = xKeyWsp.pWspArea();
  i8 nBytes  = xKeyWsp.nWspUsed();
  
  Memory::vCopy(pDst,pSrc,nBytes);
}

/*----------------------------------------------------------------------------*/
/* show the contents of this key                                              */
/*----------------------------------------------------------------------------*/
void Key::vShow(void)
{
  i8 iKey;
  V::vCopyIntDatum(&iKey,pDataArea());
  
  vTrace("Key %p: (size %lld value:%lld)\n",
         this,
         iSize(),
         iKey
         );
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get pointer to data area                                                   */
/*----------------------------------------------------------------------------*/
char* Key::pDataArea(void)
{
  //i8 iKeySize = sizeof(Key);
  //char* pDataArea = reinterpret_cast<char*>(this); //pAdd<char*>(this,sizeof(Key));
  //return pPoolCheck<char*>(pDataArea);
  
  char* pDataArea = reinterpret_cast<char*>(this);
  
  return pDataArea;
}

/*----------------------------------------------------------------------------*/
/* get number of data bytes in the key                                        */
/*----------------------------------------------------------------------------*/
i8 Key::nDataBytes(void)
{
  return sizeof(i8);
}

/*----------------------------------------------------------------------------*/
/* get size in bytes of this key                                              */
/*----------------------------------------------------------------------------*/
i8 Key::iSize(void)
{
  //i8 nBytes = sizeof(Key) + sizeof(i8);
  i8 nBytes = sizeof(i8);
  return nBytes;
}

