/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ZedOp* PushDown::_pZedOp(void* aAddr)
{
  ZedOp* pZedOp = reinterpret_cast<ZedOp*>(aAddr);
  
  return pZedOp;
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
ZedOp::ZedOp(void)
: Op(CN_ZEDOP)
{
  _precondition_(_MAGIC_,CN_ZEDOP);
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
ZedOp::~ZedOp(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_ZEDOP);
}

