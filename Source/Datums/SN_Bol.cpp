#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Bol::SN_Bol(void)
: Scan(CN_SNBOL)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
  
  _checkInitialised_(CN_SNBOL);
  
  _postcondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Bol::~SN_Bol(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Bol::i(char** aacCrs, Format* pFmt)
{
  _precondition_(_MAGIC_,CN_SNBOL);
  
  if ( ! StrLib::bExtractBoolean(aacCrs,m_wDtm.m_wBol.m_iAsI8) ) {
    THROW_USER("StrLib::bExtractBoolean"_Stz);
  }
  return m_wDtm;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Bol::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNBOL);
  
  return &m_xFooter;
}

