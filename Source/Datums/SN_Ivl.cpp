#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SN_Ivl::SN_Ivl(void)
: Scan(CN_SNIVL)
{
  _precondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
  
  _checkInitialised_(CN_SNIVL);
  
  _postcondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SN_Ivl::~SN_Ivl(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SNIVL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* scan                                                                       */
/*----------------------------------------------------------------------------*/
i8 SN_Ivl::i(char** aacCrs, Format* pFmt)
{
  _precondition_(_MAGIC_,CN_SNIVL);
  
  i8 iSecond, iMilli;
  
  if ( ! StrLib::bExtractInterval(aacCrs, iSecond, iMilli) )
    THROW_USER("StrLib::bExtractInterval"_Stz);

  m_wDtm.m_wIvl.m_uSecond = iSecond;
  m_wDtm.m_wIvl.m_uMicro  = iMilli * C_1K;
  
  return m_wDtm;
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SN_Ivl::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SNIVL);
  
  return &m_xFooter;
}

