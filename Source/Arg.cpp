/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Arg* Plans::_pArg(void* aAddr)
{
  Arg* pArg = reinterpret_cast<Arg*>(aAddr);
  
  RASSERT_TYPE(pArg,CN_ARG);
 
  return pArg;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Arg::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_ARG);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Arg::operator delete(void* pDataAddress)
{
  AccessPath* pAccessPath = reinterpret_cast<AccessPath*>(pDataAddress);
  
  HeapMem::vFree(pAccessPath);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Arg::Arg(void)
: Object(CN_ARG)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
  
  m_eArgKind = AK_NONE;
  m_sArgVal  = "<not set>"_Stz;
  
  _checkInitialised_(CN_ARG);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Arg::Arg(eAK eArgKind, Stz* aArgVal)
: Object(CN_ARG)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
  
  m_eArgKind = eArgKind;
  m_sArgVal  = aArgVal;
  
  _checkInitialised_(CN_ARG);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Arg::~Arg(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
}

