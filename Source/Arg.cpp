{
  m_sArgVal = sArgVal;
}

/*----------------------------------------------------------------------------*/
/* set arg value                                                              */
/*----------------------------------------------------------------------------*/
bool Arg::bIsColumnNm(s256& sColNm)
{
  if (m_sArgVal.bSame(sColNm))
    return true;
  else
      return false;
}

