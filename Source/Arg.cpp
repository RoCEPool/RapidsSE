#include "Plans.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Arg* Plans::_pArg(void* aAddr)
{
  Arg* pArg = reinterpret_cast<Arg*>(aAddr);
  
  RASSERT( ! pArg || CN_ARG == pArg->eClass() );
 
  return pArg;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Arg::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  void* pObject = Heap::pAllocate(CN_ARG);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Arg::operator delete(void* pDataAddress)
{
  AccessPath* pAccessPath = reinterpret_cast<AccessPath*>(pDataAddress);
  
  Heap::vFree(pAccessPath);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Arg::Arg(void)
: Object(CN_ARG)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
  
  m_eArg = AK_NONE;
  
  _checkInitialised_(CN_ARG);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Arg::~Arg(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Arg::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ARG);
  
  return &m_xFooter;
}

