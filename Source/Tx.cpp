#include "Transactions.h"

extern TxCollection*  gpTxCollection;

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Tx::operator new(size_t iSize)
{
  ASSERT(gpTxCollection);
  
  Tx* pTx = gpTxCollection->pAllocTx();
  
  return pTx;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Tx::operator new(size_t iSize, Tx* pTx)
{
  return pTx;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Tx::operator delete(void* pTxAddress)
{
  Tx* pTx = reinterpret_cast<Tx*>(pTxAddress);
  
  gpTxCollection->vFreeTx(pTx);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Tx::Tx(void)
: Object(CN_TX)
{
  m_iTxSlot = -1;
  m_iTxId   = -1;
  m_ePhase  = TP_NONE;
  
  Memory::vCheckInitialised(this,sizeof(Tx));
}

/*----------------------------------------------------------------------------*/
/* get tx array slot                                                          */
/*----------------------------------------------------------------------------*/
i8 Tx::iTxSlot(void)
{
  return m_iTxSlot;
}

/*----------------------------------------------------------------------------*/
/* set tx array slot                                                          */
/*----------------------------------------------------------------------------*/
void Tx::vTxSlot(i8 iTxSlot)
{
  m_iTxSlot = iTxSlot;
}

/*----------------------------------------------------------------------------*/
/* get tx id                                                                  */
/*----------------------------------------------------------------------------*/
i8 Tx::iTxId(void)
{
  return m_iTxId;
}

/*----------------------------------------------------------------------------*/
/* set tx id                                                                  */
/*----------------------------------------------------------------------------*/
void Tx::vTxId(i8 iTxId)
{
  m_iTxId = iTxId;
}

/*----------------------------------------------------------------------------*/
/* get phase                                                                  */
/*----------------------------------------------------------------------------*/
eTP Tx::ePhase(void)
{
  return m_ePhase;
}

/*----------------------------------------------------------------------------*/
/* set phase                                                                  */
/*----------------------------------------------------------------------------*/
void Tx::vPhase(eTP ePhase)
{
  m_ePhase = ePhase;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Tx::vDump(void)
{
  vTrace("Tx: %p %lld %s\n",
         this,
         m_ePhase,
         pTP[m_ePhase]);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Tx::pFooter(void)
{
  return &m_xFooter;
}

