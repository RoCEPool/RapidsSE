#include "Transactions.h"

extern TxList*  gpTxList;

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Tx::operator new(size_t iSize)
{
  ASSERT(gpTxList);
  
  Tx* pTx = gpTxList->pAllocTx();
  
  return pTx;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Tx::operator delete(void* pTxAddress)
{
  Tx* pTx = reinterpret_cast<Tx*>(pTxAddress);
  
  gpTxList->vFreeTx(pTx);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Tx::Tx(void)
: Object(CN_TX)
{
  m_ePhase = TP_ALLOCATED;
}

/*----------------------------------------------------------------------------*/
/* dump                                                                       */
/*----------------------------------------------------------------------------*/
void Tx::vDump(void)
{
  vTrace("Tx: %p %lld %s\n",
         this,
         m_ePhase,
         pTP[m_ePhase]);
}

