/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
HashOp* PushDown::_pHashOp(void* aAddr)
{
  HashOp* pHashOp = reinterpret_cast<HashOp*>(aAddr);
  
  return pHashOp;
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
HashOp::HashOp(void)
: Op(CN_HASHOP)
{
  _precondition_(_MAGIC_,CN_HASHOP);
}

/*----------------------------------------------------------------------------*/
/* initialize object                                                          */
/*----------------------------------------------------------------------------*/
HashOp::~HashOp(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_HASHOP);
}

