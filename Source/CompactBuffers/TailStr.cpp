/*============================================================================*/
/* TailStr.hpp -- a string tail line                                          */
/*============================================================================*/

#include "CompactBuffers.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TailStr::TailStr(void)
{
  MemLib::vZero(m_yaByte, sizeof(m_yaByte), CN_ROWCOMPACTOR);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TailStr::TailStr(Stz* szStz)
{
  vSet(szStz);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TailStr::~TailStr(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return size of tail in bytes                                               */
/*----------------------------------------------------------------------------*/
i8 TailStr::nBytes(void)
{
  i8 nSizeBytes = nUnits() * sizeof(SpaceUnit);
  
  return nSizeBytes;
}

/*----------------------------------------------------------------------------*/
/* return size of tail in units                                               */
/*----------------------------------------------------------------------------*/
i8 TailStr::nUnits(void)
{
  i8 nSizeUnits = w8_1B(0);
  
  return nSizeUnits;
}

/*----------------------------------------------------------------------------*/
/* return size of tail in words                                               */
/*----------------------------------------------------------------------------*/
i8 TailStr::nWords(void)
{
  i8 nSizeWords = nBytes() / C_BYTES_PER_WORD;

  return nSizeWords;
}

/*----------------------------------------------------------------------------*/
/* get the size <L> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
i8 TailStr::iL(void)
{
  i8 nUnits = w8_1B(+ C_U_1B);
  
  return nUnits;
}

/*----------------------------------------------------------------------------*/
/* set the size <L> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
void TailStr::vL(i8 nL)
{
  v1B(+ C_U_1B,nL);
}

/*----------------------------------------------------------------------------*/
/* get the size <U> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
i8 TailStr::iU(void)
{
  i8 nUnits = w8_1B(0);
  
  return nUnits;
}

/*----------------------------------------------------------------------------*/
/* set the size <U> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
void TailStr::vU(i8 nUnits)
{
  v1B(0,nUnits);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign string a                                                            */
/*----------------------------------------------------------------------------*/
void TailStr::vAssign(Stz* szStz)
{
  i8 nL = StrLib::nCopy((char*)sz(),(char*)szStz);
  
  vL(nL);
}

/*----------------------------------------------------------------------------*/
/* assign string and set tail line details                                    */
/*----------------------------------------------------------------------------*/
void TailStr::vSet(Stz* szStz)
{
//  vReset();
  MemLib::vZero(m_yaByte, sizeof(m_yaByte), CN_ROWCOMPACTOR);

  i8 nL = StrLib::nCopy((char*)sz(),(char*)szStz) + C_1B;
  
  vL(nL);
  
  i8 nSizeBytes = C_U_1B + C_L_1B + nL;
  i8 nU = MemLib::nQuantaRequired(nSizeBytes,sizeof(SpaceUnit));
  vU(nU);
}

/*----------------------------------------------------------------------------*/
/* get the string from this tail line                                         */
/*----------------------------------------------------------------------------*/
Stz* TailStr::sz(void)
{
  Stz* szStz = (Stz*) &m_yaByte[C_U_1B + C_L_1B];
  
  return szStz;
}

/*----------------------------------------------------------------------------*/
/* dump string tail line                                                      */
/*----------------------------------------------------------------------------*/
void TailStr::vDump(void)
{
  i8 nSizeBytes = nBytes();
  MemLib::vWordDump(this,nSizeBytes);
}

/*----------------------------------------------------------------------------*/
/* reset string tail line                                                     */
/*----------------------------------------------------------------------------*/
void TailStr::vReset(void)
{
  MemLib::vZero(m_yaByte, sizeof(m_yaByte), CN_ROWCOMPACTOR);
}

