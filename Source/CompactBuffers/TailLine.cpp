#include "CompactBuffers.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
TailLine::TailLine(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
TailLine::~TailLine(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return size of tail in bytes                                               */
/*----------------------------------------------------------------------------*/
i8 TailLine::nBytes(void)
{
  i8 nSizeBytes = nUnits() * sizeof(SpaceUnit);
  
  return nSizeBytes;
}

/*----------------------------------------------------------------------------*/
/* return size of tail in units                                               */
/*----------------------------------------------------------------------------*/
i8 TailLine::nUnits(void)
{
  i8 nSizeUnits = w8_1B(0);
  
  return nSizeUnits;
}

/*----------------------------------------------------------------------------*/
/* return size of tail in words                                               */
/*----------------------------------------------------------------------------*/
i8 TailLine::nWords(void)
{
  i8 nSizeWords = nBytes() / C_BYTES_PER_WORD;

  return nSizeWords;
}

/*----------------------------------------------------------------------------*/
/* get the size <L> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
i8 TailLine::iL(void)
{
  i8 nUnits = w8_1B(+ C_U_1B);
  
  return nUnits;
}

/*----------------------------------------------------------------------------*/
/* set the size <L> of this TailStr in units                                  */
/*----------------------------------------------------------------------------*/
void TailLine::vL(i8 nL)
{
  v1B(+ C_U_1B,nL);
}

/*----------------------------------------------------------------------------*/
/* get the size <U> of this tailline in units                                 */
/*----------------------------------------------------------------------------*/
i8 TailLine::iU(void)
{
  i8 nUnits = w8_1B(0);
  
  return nUnits;
}

/*----------------------------------------------------------------------------*/
/* set the size <U> of this tailline in units                                 */
/*----------------------------------------------------------------------------*/
void TailLine::vU(i8 nUnits)
{
  v1B(0,nUnits);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign string                                                              */
/*----------------------------------------------------------------------------*/
void TailLine::vAssign(Stz* szStz)               //! still need to do long tails
{
  //           -- TailLine --
  // **********************************
  // * <U><L><StringN> ////////////// *
  // **********************************
  //
  
  char* azStr = (char*)szStz;
  i8 nL = StrLib::nCopy((char*)sz(),azStr) + C_NULL_1B;
  
  vL(nL);
}

/*----------------------------------------------------------------------------*/
/* dump tail line                                                             */
/*----------------------------------------------------------------------------*/
void TailLine::vDump(void)
{
  i8 nSizeBytes = nBytes();
  MemLib::vWordDump(this,nSizeBytes);
}

/*----------------------------------------------------------------------------*/
/* get the string from this tail line                                         */
/*----------------------------------------------------------------------------*/
Stz* TailLine::sz(void)
{
  //           -- TailLine --
  // **********************************
  // * <U><L><StringN> ////////////// *
  // **********************************
  //
  
  Stz* szStz = (Stz*) &m_yaByte[C_U_1B + C_L_1B];
  
  return szStz;
}

