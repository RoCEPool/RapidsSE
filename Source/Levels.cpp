/*============================================================================*/
/* Levels.hpp -- array of level pointers/references/offsets                   */
/*============================================================================*/

#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Levels* DBobjects::_aLevels(void* aAddr)
{
  Levels* aLevels = reinterpret_cast<Levels*>(aAddr);
  
  return aLevels;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Levels::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Levels class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Levels::operator new(size_t iSize, Levels* pLevels)
{
  RASSERT(iSize);
  return pLevels;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Levels::Levels(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Levels::~Levels(void)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calculate number of bytes required to hold n levels                        */
/*----------------------------------------------------------------------------*/
i8 Levels::nBytesRequired(i8 nLevels)
{
  i8 nBytes = nLevels * sizeof(i8);
  
  return nBytes;
}

