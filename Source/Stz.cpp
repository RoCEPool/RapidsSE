/*----------------------------------------------------------------------------*/
/* iToI8: convert arg to i8                                                   */
/*----------------------------------------------------------------------------*/
i8 Stz::iToI8(void)
{
  //i8 i = atoll(s);
  
  //return i;
  
  const char* ps = aChar();
  
  i8 i = 0;
  
  // skip leading 0's
  while (*ps && '0' == *ps)
    ps++;
  
  if (*ps && ('x' == *ps || 'X' == *ps)) {
    ps++;
    while (*ps && StrLib::bIsHex(*ps)) {
      i8 j = StrLib::iHexToInw(*ps++);
      i = i * 16 + j;
    }
  }
  else {
    while (*ps && StrLib::bIsDigit(*ps)) {
      i8 j = (*ps++ - '0');
      i = i * 10 + j;
    }
  }
  
  return i;
}

