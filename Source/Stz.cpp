/*----------------------------------------------------------------------------*/
/* bEqual: test if this Stz is equal to arg (same case)                       */
/*----------------------------------------------------------------------------*/
bool Stz::bEqual(Stz* aArg)
{
  i8 iDiff = strcmp(s(),aArg->s());
  
  if (0 == iDiff)
    return true;
  else
    return false;
}

