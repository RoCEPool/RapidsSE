/*----------------------------------------------------------------------------*/
/* get tab                                                                    */
/*----------------------------------------------------------------------------*/
Stz* Stz::aTab(i8 iDepth)
{
  switch(iDepth) {
    case  0:  return ""_Stz;
    case  1:  return "  "_Stz;
    case  2:  return "    "_Stz;
    case  3:  return "      "_Stz;
    case  4:  return "        "_Stz;
    case  5:  return "          "_Stz;
    case  6:  return "            "_Stz;
    case  7:  return "              "_Stz;
    case  8:  return "                "_Stz;
    case  9:  return "                  "_Stz;
    case 10:  return "                    "_Stz;
    case 11:  return "                      "_Stz;
    case 12:  return "                        "_Stz;
    case 13:  return "                          "_Stz;
    case 14:  return "                            "_Stz;
    case 15:  return "                              "_Stz;
    case 16:  return "                                "_Stz;
    default:  return "  (tabbed-out)                    "_Stz;
  }
}


