/*----------------------------------------------------------------------------*/
/* add a new member set with given name                                       */
/*----------------------------------------------------------------------------*/
MemberVar* MemberSet::pAddMemberVar(Stz* szVarNm)
{
  _precondition_(_MAGIC_,CN_METACLASS,_FOOTER_);
  
  MemberVar* pMemberVar = new MemberVar;
  
  pMemberVar->vVarNm(szVarNm);
  
  vAppend(pMemberVar);
  
  return pMemberVar;
}


