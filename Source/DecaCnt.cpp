#include "System.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DecaCnt::DecaCnt(Stz* szName)
: Object(CN_DECACNT)
{
  _precondition_(_MAGIC_,CN_DECACNT,_FOOTER_);
  
  m_sName  = szName;
  m_iCount = 0;
  
  _checkInitialised_(CN_DECACNT);
  
  _postcondition_(_MAGIC_,CN_DECACNT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
DecaCnt::~DecaCnt(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_DECACNT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* generate next name                                                         */
/*----------------------------------------------------------------------------*/
void DecaCnt::vInc(Stz* szFormat,...)
{
  _precondition_(_MAGIC_,CN_DECACNT,_FOOTER_);

  m_iCount++;
  
  if (IntLib::bIsDecaCycle(m_iCount)) {
    vTrace("%s %lld:"_Stz,m_sName.aStz(),m_iCount);
    va_list xArgs;
    va_start(xArgs,szFormat);
    vPrint(szFormat,xArgs);
    va_end(xArgs);
  }
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* DecaCnt::aFooter(void)
{
  _precondition_(_MAGIC_,CN_DECACNT);
  
  return &m_xFooter;
}

