#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntrySsn::vSet(LogEntry* pLogEntry, Session* pSession, i8 iSsnId, eAA eSsnAct)
{
  pLogEntry->m_eKind = EK_SSN;
  
  m_iSsnId  = iSsnId;
  m_eSsnAct = eSsnAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntrySsn::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("A"_Stz,m_iSsnId),
                aAA[m_eSsnAct]);
}

