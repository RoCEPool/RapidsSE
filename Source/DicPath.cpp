/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* DicPath::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  vFatal("fatal: DicPath class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
DicPath::DicPath(void)
: Object(CN_DICPATH)
{
  m_iDicDepth = -1;
  for (i8 i_Depth = 0; i_Depth < C_DIC_STACK; i_Depth++)
    m_sDicPath[i_Depth] = ""_Stz;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
DicPath::~DicPath(void)
{
}

