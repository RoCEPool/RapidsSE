#include "Rows.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Rsb* Rows::_aRsb(void* aAddr)
{
  return (Rsb*) aAddr;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Rsb::Rsb(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Rsb::~Rsb(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* convert logical cell to cell subscript                                     */
/*----------------------------------------------------------------------------*/
i8 Rsb::i_Cell_lglToNtv(i8 iLogicalCell)
{
  ASSERT(iLogicalCell >= 0);
  
  return -1 * iLogicalCell;
}

/*----------------------------------------------------------------------------*/
/* get i8 integer                                                             */
/*----------------------------------------------------------------------------*/
bool Rsb::bIsNull_ntv(i8 i_Cell)
{
  ASSERT(i_Cell <= 0);
  
  i8* aI8 = (i8*) & m_maCells[i_Cell];
  
  i8 iVal = * aI8;

  if (C_DATUM_NULL == iVal)
    return true;
  else
    return false;
}


/*----------------------------------------------------------------------------*/
/* get d8 float                                                               */
/*----------------------------------------------------------------------------*/
d8 Rsb::dVal_ntv(i8 i_Cell)
{
  ASSERT(i_Cell <= 0);
  
  d8* aD8 = (d8*) & m_maCells[i_Cell];
  
  d8 dVal = * aD8;
  
  return dVal;
}

/*----------------------------------------------------------------------------*/
/* get i8 integer                                                             */
/*----------------------------------------------------------------------------*/
i8 Rsb::iVal_ntv(i8 i_Cell)
{
  ASSERT(i_Cell <= 0);
  
  i8* aI8 = (i8*) & m_maCells[i_Cell];
  
  i8 iVal = * aI8;

  return iVal;
}

/*----------------------------------------------------------------------------*/
/* get Stz* string                                                            */
/*----------------------------------------------------------------------------*/
Stz* Rsb::szVal_ntv(i8 i_Cell)
{
  ASSERT(i_Cell <= 0);
  
#ifdef WITH_RSB_STROFS
  
  Stz* szStz = (Stz*) m_maCells[i_Cell];

#else
  
  Stz* szStz = (Stz*) m_maCells[i_Cell];

#endif
  
  return szStz;
}

