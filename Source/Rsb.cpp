#include "Rows.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Rsb* Rows::_aRsb(void* aAddr)
{
  return (Rsb*) aAddr;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Rsb::Rsb(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Rsb::~Rsb(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* convert logical cell to cell subscript                                     */
/*----------------------------------------------------------------------------*/
i8 Rsb::i_Cell(i8 iLogicalCell)
{
  return -1 * iLogicalCell;
}

/*----------------------------------------------------------------------------*/
/* get i8 integer                                                             */
/*----------------------------------------------------------------------------*/
bool Rsb::bIsNull(i8 i_Cell)
{
  i8* aI8 = (i8*) & m_maCells[i_Cell];
  
  i8 iVal = * aI8;

  if (C_DATUM_NULL == iVal)
    return true;
  else
    return false;
}


/*----------------------------------------------------------------------------*/
/* get d8 float                                                               */
/*----------------------------------------------------------------------------*/
d8 Rsb::dVal(i8 i_Cell)
{
  d8* aD8 = (d8*) & m_maCells[i_Cell];
  
  d8 dVal = * aD8;
  
  return dVal;
}

/*----------------------------------------------------------------------------*/
/* get i8 integer                                                             */
/*----------------------------------------------------------------------------*/
i8 Rsb::iVal(i8 i_Cell)
{
  i8* aI8 = (i8*) & m_maCells[i_Cell];
  
  i8 iVal = * aI8;

  return iVal;
}

/*----------------------------------------------------------------------------*/
/* get Stz* string                                                            */
/*----------------------------------------------------------------------------*/
Stz* Rsb::szVal(i8 i_Cell)
{
  Stz* szStz = (Stz*) m_maCells[i_Cell];

  return szStz;
}

