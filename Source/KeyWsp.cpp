/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: KeyWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize, KeyWsp* pKeyWsp)
{
  RASSERT(iSize);
  return pKeyWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
KeyWsp::KeyWsp(void)
: Object(CN_KEYWSP)
{
  _precondition_(_MAGIC_,CN_KEYWSP);

  //m_xRowId
  m_nDataBytes = 0;

  //_setFooter_();
  
  _checkInitialisedSize_(sizeof(KeyWsp));
  
  _postcondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
KeyWsp::~KeyWsp(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void KeyWsp::vShow(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
  
  vTrace("KeyWsp %p: databytes %lld\n",
         this,
         m_nDataBytes
         );
}

/*----------------------------------------------------------------------------*/
/* add element to key                                                         */
/*----------------------------------------------------------------------------*/
void KeyWsp::vAddElement(Values::ValWsp &xValWsp)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
  
  // for the moment we only allow one element per key
  ASSERT( ! m_nDataBytes );
  
  eCN eClass = xValWsp.eClass();
  char* pDst = pDataNext();
  char* pSrc = xValWsp.pDataArea();

  //m_nDataBytes += V::nCopyDatum(eClass,pDst,pSrc);
  
  i8 iKey = xValWsp.iAsInt();
  m_nDataBytes += V::nCopyDatum(eClass,pDst,&iKey);
}

/*----------------------------------------------------------------------------*/
/* get data area                                                              */
/*----------------------------------------------------------------------------*/
char* KeyWsp::pDataArea(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);

  return m_mDataArea;
}

/*----------------------------------------------------------------------------*/
/* get number of data bytes in the key                                        */
/*----------------------------------------------------------------------------*/
i8 KeyWsp::nDataBytes(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);

  return m_nDataBytes;
}

/*----------------------------------------------------------------------------*/
/* get next avaliable point in data area                                      */
/*----------------------------------------------------------------------------*/
char* KeyWsp::pDataNext(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
  
  return &m_mDataArea[m_nDataBytes];
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* KeyWsp::pFooter(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP);
  
  return &m_xFooter;
}

