#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: KeyWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize, KeyWsp* pKeyWsp)
{
  RASSERT(iSize);
  return pKeyWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
KeyWsp::KeyWsp(void)
: Header(CN_ENTWSP)
{
  _precondition_(_MAGIC_,CN_ENTWSP);

  //m_xRowId
  m_iDataBytes = 0;

  _setFooter_();
  
  _checkInitialisedSize_(sizeof(KeyWsp));
  
  _postcondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
KeyWsp::~KeyWsp(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void KeyWsp::vShow(void)
{
  vTrace("KeyWsp %p: \n",
         this
         );
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* KeyWsp::pFooter(void)
{
  _precondition_(_MAGIC_,CN_ENTWSP);
  
  Footer* pFooter = static_cast<Footer*>(
                      pvAdd(this,sizeof(KeyWsp) + m_iDataBytes));
  
  return pFooter;
}

