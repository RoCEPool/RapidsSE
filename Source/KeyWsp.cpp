#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: KeyWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* KeyWsp::operator new(size_t iSize, KeyWsp* pKeyWsp)
{
  RASSERT(iSize);
  return pKeyWsp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
KeyWsp::KeyWsp(void)
: Object(CN_KEYWSP)
{
  _precondition_(_MAGIC_,CN_KEYWSP);
  
  _checkInitialisedSize_(sizeof(KeyWsp));
  
  _postcondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
KeyWsp::~KeyWsp(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show                                                                       */
/*----------------------------------------------------------------------------*/
void KeyWsp::vShow(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
  
  vTrace("KeyWsp %p: bytesUsed %lld\n",
         this,
         nBytesUsed()
         );
}

/*----------------------------------------------------------------------------*/
/* add element to key                                                         */
/*----------------------------------------------------------------------------*/
void KeyWsp::vAddElement(Values::ValWsp &xValWsp)
{
  _precondition_(_MAGIC_,CN_KEYWSP,_FOOTER_);
  
  // for the moment we only allow one element per key
  ASSERT( ! nBytesUsed() );
  
  eCN eClass = xValWsp.eClass();
  char* pDst = pNextChunk();
  char* pSrc = xValWsp.pDataArea();
  
  i8 iSrc = *(i8*)pSrc;

  i8 nBytesTaken = V::nCopyDatum(eClass,pDst,pSrc);
  
  vTakeBytes(nBytesTaken);
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* KeyWsp::pFooter(void)
{
  _precondition_(_MAGIC_,CN_KEYWSP);
  
  return &m_xFooter;
}

