#include "Operators.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PulseMarker* ControlData::_pPulseMarker(void* aAddr)
{
  PulseMarker* pPulseMarker = reinterpret_cast<PulseMarker*>(aAddr);
  
  return pPulseMarker;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* PulseMarker::operator new(size_t)
{
  PulseMarker* pPulseMarker =
    static_cast<PulseMarker*>(HeapMem::pAllocate(CN_PULSEMARKER));
  
  return pPulseMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void PulseMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PulseMarker::PulseMarker(void)
: Operand(CN_PULSEMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PULSEMARKER,_FOOTER_);

  _checkInitialised_(CN_PULSEMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_PULSEMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
PulseMarker::~PulseMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PULSEMARKER,_FOOTER_);
}


