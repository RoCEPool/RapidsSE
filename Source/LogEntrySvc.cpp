#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntrySvc::vSet(LogEntry* pLogEntry, i8 iSvcId, eVA eSvcAct)
{
  pLogEntry->m_eKind = EK_SVC;
  
  m_iSvcId  = iSvcId;
  m_eSvcAct = eSvcAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntrySvc::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("S"_Stz,m_iSvcId),
                aVA[m_eSvcAct]);
}

