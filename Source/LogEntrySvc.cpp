#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set resource entry                                                         */
/*----------------------------------------------------------------------------*/
void _LogEntrySvc::vSet(LogEntry* pLogEntry, Job* pJob, eVA eSvcAct)
{
  pLogEntry->m_eKind = EK_SVC;
  
  m_iSvcId  = pJob->m_iUniqueId;
  m_eSvcAct = eSvcAct;
}

/*----------------------------------------------------------------------------*/
/* cat sprint to given string                                                 */
/*----------------------------------------------------------------------------*/
void _LogEntrySvc::vSprint(s4K& sString)
{
  SP_Id spId;
  
  sString.vCatSprint("{%s,%s}"_Stz,
                
                spId.sz("S"_Stz,m_iSvcId),
                aVA[m_eSvcAct]);
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntrySvc::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz("S"_Stz,m_iSvcId),
                aVA[m_eSvcAct]);
}

