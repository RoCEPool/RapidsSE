#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get total bytes required for entry                                         */
/*----------------------------------------------------------------------------*/
i8 Entry::iBytesRequired(i8 iDataBytes)
{
  i8 iBytes = sizeof(Entry) + sizeof(Footer) + iDataBytes;
  
  return iBytes;
}

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Entry::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Entry class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Entry::operator new(size_t iSize, Entry* pEntry)
{
  RASSERT(iSize);
  
  return pEntry;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Entry::Entry(i8 iDataBytes)
{
  //_precondition_(_MAGIC_,CN_ENTRY);

  vWspUsed(iDataBytes);

  //_setFooter_();
  
  _checkInitialised_(CN_ENTRY);
  
  //_postcondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Entry::Entry(EntWsp& xEntWsp)
{
  //_precondition_(_MAGIC_,CN_ENTRY);
  
  vEntry(xEntWsp);
  
  //_setFooter_();
  
  //_checkInitialised_(CN_ENTRY);
  
  //_postcondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Entry::~Entry(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* show content                                                               */
/*----------------------------------------------------------------------------*/
void Entry::vContentDump(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY);
  
  i8 iKeyData;
  V::nCopyDatum(CN_INTVAL, &iKeyData,aWspArea());
  
  vTrace("Entry %p: Row %llu.%llu Key (size:%lld value:%lld)\n",
         this,
         uBuffer(),
         uRow(),
         nWspUsed(),
         iKeyData
         );
}

/*----------------------------------------------------------------------------*/
/* get row id                                                                 */
/*----------------------------------------------------------------------------*/
RowId& Entry::xRowId(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  // return reference to the RowId inherited class
  return dynamic_cast<RowId&>(*this);
}

/*----------------------------------------------------------------------------*/
/* set row id                                                                 */
/*----------------------------------------------------------------------------*/
void Entry::vRowId(RowId& xRowId)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Entry::xRowId() = xRowId;
}

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void Entry::vEntry(EntWsp& xEntWsp)
{
  //_precondition_(_MAGIC_,CN_ENTRY);

  vRowId(xEntWsp.xRowId());

  char* pDst = aWspArea();
  char* pSrc = xEntWsp.aWspArea();
  i8 nBytes  = xEntWsp.nWspUsed();

  Memory::vCopy(pDst,pSrc,nBytes);
  
  vWspUsed(nBytes);
}

/*----------------------------------------------------------------------------*/
/* get key                                                                    */
/*----------------------------------------------------------------------------*/
Key& Entry::xKey(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Key* pKey = reinterpret_cast<Key*>(aWspArea());

  return reinterpret_cast<Key&>(pKey);
}

/*----------------------------------------------------------------------------*/
/* get key                                                                    */
/*----------------------------------------------------------------------------*/
Key* Entry::pKey(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Key* pKey = reinterpret_cast<Key*>(aWspArea());
  
  return pKey;
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void Entry::vKey(Key& xKey)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Key* pKey = reinterpret_cast<Key*>(aWspArea());

  pKey->vKey(xKey);
  
  vWspTake(pKey->nSize());
}

/*----------------------------------------------------------------------------*/
/* set key                                                                    */
/*----------------------------------------------------------------------------*/
void Entry::vKey(KeyWsp& xKeyWsp)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);
  
  Key* pKey = reinterpret_cast<Key*>(aWspArea());
  
  pKey->vKey(xKeyWsp);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get size in bytes of this entry                                            */
/*----------------------------------------------------------------------------*/
i8 Entry::nSize(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY,_FOOTER_);

  i8 nBytes = sizeof(Entry) + nWspUsed();
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Entry::pFooter(void)
{
  //_precondition_(_MAGIC_,CN_ENTRY);
  
  Footer* pFooter = pAdd<Footer*>(this,sizeof(Entry) + nWspUsed());
  
  return pFooter;
}

