#include "Operators.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ErrorMarker* ControlData::_pErrorMarker(void* aAddr)
{
  ErrorMarker* pErrorMarker = reinterpret_cast<ErrorMarker*>(aAddr);
  
  return pErrorMarker;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* ErrorMarker::operator new(size_t)
{
  ErrorMarker* pErrorMarker =
    static_cast<ErrorMarker*>(HeapMem::pAllocate(CN_ERRORMARKER));
  
  return pErrorMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void ErrorMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ErrorMarker::ErrorMarker(void)
: Operand(CN_ENDMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ERRORMARKER,_FOOTER_);

  _checkInitialised_(CN_ENDMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_ERRORMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
ErrorMarker::~ErrorMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_ERRORMARKER,_FOOTER_);
}


