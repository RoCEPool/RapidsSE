/*----------------------------------------------------------------------------*/
/* get size of row (needed for MiniHeap_t<ITEM>::aAdjacentItem(ITEM* aItem))  */
/*----------------------------------------------------------------------------*/
i8 Row2::nSizeBytes(StreamDef* pStreamDef)
{
  i8 nSize = sizeof(Row2) + (pStreamDef->nColumns(0) - 1) * sizeof(Dtm);
  return nSize;
}

/*----------------------------------------------------------------------------*/
/* dump the row                                                               */
/*----------------------------------------------------------------------------*/
void Row2::vDump(StreamDef* pStreamDef)
{
  
  vTrace("ROW: %p"_Stz, this);
  
  for (i8 i_Col = 0; i_Col < pStreamDef->nColumns(C_ALL); i_Col++) {
    
    Column* pCol = pStreamDef->pGetColumn(i_Col);
    // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    // vch
    
    if (DM_VCH == pCol->eDatum()) {
      
      if (m_waColVal[i_Col].bIsNull()) {
        vTrace(" NULL "_Stz);
        continue;
      }
      
      char* acSrcString = (char*)m_waColVal[i_Col].m_szVch;
      
      vTrace(" %s "_Stz, acSrcString);
      
      continue;
    }
    
    // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    // all others
    
    vTrace(" %d "_Stz, m_waColVal[i_Col].m_iWrd);
  }

  vTrace("\n"_Stz);
}

