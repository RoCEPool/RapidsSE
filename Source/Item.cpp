extern AttachMap* gpAttachMap;

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Item* DBobjects::_pItem(void* aAddr)
{
  Item* pItem = reinterpret_cast<Item*>(aAddr);
  
  return pItem;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Item::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: Item class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Item::operator new(size_t iSize, Item* pItem)
{
  RASSERT(iSize);
  return pItem;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Item::Item(eCN eClassNo, i8 nThisBytes)
: Object(eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  m_nThisBytes = nThisBytes;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Item::~Item(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


/*----------------------------------------------------------------------------*/
/* get size in bytes of this item                                             */
/*----------------------------------------------------------------------------*/
i8 Item::nSizeItem(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,_FOOTER_); 
  
  return m_nThisBytes;
}

