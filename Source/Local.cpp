#include "Forth.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Local* Forth::_pLocal(void* aAddr)
{
  Local* pLocal = reinterpret_cast<Local*>(aAddr);
  
  RASSERT_TYPE(pLocal,CN_LOCAL);
  
  return pLocal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Local::operator new(size_t)
{
  vFatal("fatal: Local class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Local::Local(void)
: Object(CN_LOCAL)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
  
  MemLib::vZero(m_xWsp.ayArea(),C_WSP_LOCAL,CN_LOCAL);
  
 _checkInitialised_(CN_LOCAL);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of value nested in the wsp                                     */
/*----------------------------------------------------------------------------*/
Value* Local::aNestedValue(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
  
  Value* aValue = reinterpret_cast<Value*>(m_xWsp.ayArea());
  
  return aValue;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Local::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_LOCAL);
  
  return &m_xFooter;
}

