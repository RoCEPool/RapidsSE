#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Local* SenVM::_pLocal(void* aAddr)
{
  Local* pLocal = reinterpret_cast<Local*>(aAddr);
  
  RASSERT_TYPE(pLocal,CN_LOCAL);
  
  return pLocal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Local::operator new(size_t)
{
  THROW_FATAL("fatal: Local class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Local::Local(void)
: Object(CN_LOCAL)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
  
  MemLib::vZero(m_xWsp.ayArea(),C_WSP_LOCAL,CN_LOCAL);
  
 _checkInitialised_(CN_LOCAL);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get address of value nested in the wsp                                     */
/*----------------------------------------------------------------------------*/
ForthValue* Local::aLocalValue(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_LOCAL,_FOOTER_);
  
  ForthValue* aValue = reinterpret_cast<ForthValue*>(m_xWsp.ayArea());
  
  return aValue;
}

