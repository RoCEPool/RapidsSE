#include "Resources.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Resource* Resources::_pResource(void* aAddress)
{
  Resource* pResource = reinterpret_cast<Resource*>(aAddress);
  
  return pResource;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo, ReqTuple* aReqTuple)
: Focal(eClassNo,AM::iNextResourceId(),nullptr)
, m_xReqTuple(aReqTuple)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
    
  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);  
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo, ReqTuple* aReqTuple, Focal* pFor)
: Focal(eClassNo,AM::iNextResourceId(),pFor)
, m_xReqTuple(aReqTuple)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Resource::~Resource(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get resource id                                                            */
/*----------------------------------------------------------------------------*/
i8 Resource::iResId(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iUniqueId;
}

/*----------------------------------------------------------------------------*/
/* get request tuple                                                          */
/*----------------------------------------------------------------------------*/
ReqTuple* Resource::aReqTuple(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  return & m_xReqTuple;
}


