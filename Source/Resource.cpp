#include "Resources.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Resource* Resources::_pResource(void* aAddress)
{
  Resource* pResource = reinterpret_cast<Resource*>(aAddress);
  
  return pResource;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo)
: Focal(eClassNo,AM::iNextResourceId(),C_UNKNOWN)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
    
  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);  
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Resource::Resource(eCN eClassNo, Focal* pFor)
: Focal(eClassNo,AM::iNextResourceId(),pFor->m_iUniqueId)
{
  _precondition_(_ADDRESS_,_MAGIC_,eClassNo);
  
  _postcondition_(_ADDRESS_,_MAGIC_,eClassNo);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Resource::~Resource(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get resource id                                                            */
/*----------------------------------------------------------------------------*/
i8 Resource::iResId(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_iUniqueId;
}

