#include "Measurement.h"

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ClassFlags* Measurement::_pClassFlags(void* aAddr)
{
  ClassFlags* pClassFlags = reinterpret_cast<ClassFlags*>(aAddr);
  
  RASSERT_TYPE(pClassFlags,CN_CLASSFLAGS);
  
  return pClassFlags;
}

/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* ClassFlags::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_CLASSFLAGS);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void ClassFlags::operator delete(void*)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ClassFlags::ClassFlags(void)
: Object(CN_CLASSFLAGS)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
    
  _checkInitialised_(CN_CLASSFLAGS);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
ClassFlags::~ClassFlags(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* are all set?                                                               */
/*----------------------------------------------------------------------------*/
bool ClassFlags::bAll(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
  
  return m_bAll;
}

/*----------------------------------------------------------------------------*/
/* set all                                                                    */
/*----------------------------------------------------------------------------*/
void ClassFlags::vAll(bool bAll)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
  
  m_bAll = bAll;
}

/*----------------------------------------------------------------------------*/
/* is a particular class set?                                                 */
/*----------------------------------------------------------------------------*/
bool ClassFlags::bClass(eCN eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
  
  return m_bClass[eClassNo];
}

/*----------------------------------------------------------------------------*/
/* set a particular class                                                     */
/*----------------------------------------------------------------------------*/
void ClassFlags::vClass(eCN eClassNo, bool bFlag)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
  
  m_bClass[eClassNo] = bFlag;
}

/*----------------------------------------------------------------------------*/
/* is bAll or a particular class set?                                         */
/*----------------------------------------------------------------------------*/
bool ClassFlags::bFlagged(eCN eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS,_FOOTER_);
  
  if (m_bAll || m_bClass[eClassNo])
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* ClassFlags::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_CLASSFLAGS);
  
  return &m_xFooter;
}

