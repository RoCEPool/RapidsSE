void* Values::_pStrFxd(void* pAddr)
{
  Object* pStrFxd = reinterpret_cast<Object*>(pAddr);
  
  RASSERT( !pStrFxd || CN_STRFXD == pStrFxd->eClass() );
  
  return pStrFxd;
}

