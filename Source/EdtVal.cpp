#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* EdtVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: EdtVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void EdtVal::vEdt(Edt wEdt)
{
  vClass(CN_INTVAL);
  m_wEdt = wEdt;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a EdtVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 EdtVal::nStackUsage(void)
{
  return sizeof(EdtVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void EdtVal::vToStz(Stz* szDst)
{
  if (C_DATUM_NULL == m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = m_iInt;
}

