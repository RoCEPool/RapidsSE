#include "Sprinting.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
spBOL::spBOL(void)
: Sprint(CN_SPBOL)
{
  _precondition_(_MAGIC_,CN_SPBOL,_FOOTER_);
  
  _checkInitialised_(CN_SPBOL);
  
  _postcondition_(_MAGIC_,CN_SPBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
spBOL::~spBOL(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPBOL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint spBOL and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* spBOL::sz(i8 iBol)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  if (iBol)
    StrLib::vCopy(m_caResult,(char*)"true"_Stz);
  else
    StrLib::vCopy(m_caResult,(char*)"false"_Stz);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* spBOL::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPBOL);
  
  return &m_xFooter;
}

