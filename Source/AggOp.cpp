/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
AggOp* DataOperators::_pAggOp(void* aAddr)
{
  AggOp* pAggOp = reinterpret_cast<AggOp*>(aAddr);
  
  return pAggOp;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
AggOp::AggOp(Stz* szOpLabel, Digest* pDigest)
: Op(CN_AGGOP,szOpLabel,pDigest,nullptr,false)
{
  _precondition_(_MAGIC_,CN_AGGOP);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
AggOp::~AggOp(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_AGGOP);
}

