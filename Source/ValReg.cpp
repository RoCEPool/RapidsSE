#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ValReg* Values::_pValReg(void* pAddr)
{
  ValReg* pValReg = reinterpret_cast<ValReg*>(pAddr);
  
  RASSERT( !pValReg || CN_VALREG == pValReg->eClass() );
  
  return pValReg;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ValReg::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: ValReg class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ValReg::ValReg(void)
: Value(CN_VALREG)
{
  Memory::vZero(m_wWorkspace,C_VALREG_WORKSPACE);
  
  *(this) = (i8)0;
  
 _checkInitialised_(CN_VALREG);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValReg::operator =(i8 iInt)
{
  vClass(CN_INTVAL);
  
  *_pIntVal(this) = iInt;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValReg::operator =(Object* pPtr)
{
  vClass(CN_PTRVAL);
  
  *_pPtrVal(this) = pPtr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValReg::operator =(char* pStr)
{
  vClass(CN_STRVAL);

  *_pStrVal(this) = pStr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValReg::operator =(const char* pStr)
{
  vClass(CN_STRVAL);

  *_pStrVal(this) = pStr;
}

