/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
EntWrkV2::EntWrkV2(eCN eClassNo)
: Object(eClassNo)
{
  _precondition_(_MAGIC_);

  // check initialisation of rowid
  ASSERT(0 == m_xId.iBuffer() && 0 == m_xId.iItem());
  
  m_nOffsets = -1;
  
  m_xWsp.vInit();
  
  m_aEmbedded = m_xWsp.aArea();
  
  _checkInitialisedSize_(sizeof(EntWrkV2));
  
  _postcondition_(_MAGIC_,eClassNo,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
EntWrkV2::~EntWrkV2(void) noexcept(false)
{
  _precondition_(_MAGIC_,_FOOTER_);
}

