/*----------------------------------------------------------------------------*/
/* new operator                                                               */
/*----------------------------------------------------------------------------*/
void* NmStr::operator new(size_t)
{
  void* pObject = HeapMem::pAllocate(CN_NMSTR);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* delete operator                                                            */
/*----------------------------------------------------------------------------*/
void NmStr::operator delete(void* aAddr)
{
  Object* pObject = reinterpret_cast<Object*>(aAddr);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmStr::NmStr(void)
: Object(CN_NMSTR)
{
  _precondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
  
  m_sName  = "<none>"_Stz;
  m_sValue = ""_Stz;
  
  _checkInitialised_(CN_NMSTR);
  
  _postcondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmStr::NmStr(Stz* szName)
: Object(CN_NMSTR)
{
  _precondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
  
  m_sName  = szName;
  m_sValue = ""_Stz;

  _checkInitialised_(CN_NMSTR);
  
  _postcondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
NmStr::NmStr(Stz* szName, Stz* szValue)
: Object(CN_NMSTR)
{
  _precondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
  
  m_sName  = szName;
  m_sValue = szValue;
  
  _checkInitialised_(CN_NMSTR);
  
  _postcondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
NmStr::~NmStr(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_NMSTR,_FOOTER_);
}

