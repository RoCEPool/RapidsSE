/*----------------------------------------------------------------------------*/
/* things to check at boot time                                               */
/*----------------------------------------------------------------------------*/
void Data::vCheckAssumptions(void)
{
  RASSERT(sizeof(HeadLine) == sizeof(Word));
  RASSERT(sizeof(TailLine) == sizeof(SpaceUnit));
  RASSERT(sizeof(FreeItem) <= sizeof(Ent));
  RASSERT(sizeof(NEO)      == C_NEO_SIZE);
}

