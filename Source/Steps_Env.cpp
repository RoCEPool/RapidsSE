#include "Steps.h"

/*----------------------------------------------------------------------------*/
/* add primitives                                                             */
/*----------------------------------------------------------------------------*/
void Step::vAddSteps_Env(void)
{
  vAddStep("env@"_Stz,            &Step::vEnvGet);
}

/*----------------------------------------------------------------------------*/
/* env@ -- get environment variable                                           */
/*----------------------------------------------------------------------------*/
void Step::vEnvGet(void)
{
  ENTRY(); // ENTRY("vEnvGet"_Stz);
  
  s32 sEnvName;
  
  if ( ! m_pDataStack->bPopStr(sEnvName) )
    THROW_DSTACK();
  
  s256 sEnvVal;
  
  if (! Env::bGet(sEnvName,sEnvVal))
    sEnvVal = ""_Stz;
  
  m_pDataStack->vPushStr(sEnvVal);
  
  EXIT();
}

