/*----------------------------------------------------------------------------*/
/* get next offset number                                                     */
/*----------------------------------------------------------------------------*/
u8 ln::operator *(void)
{
  return m_uLevelNo;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator ==(ln n)
{
  return m_uLevelNo == *n;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator !=(ln n)
{
  return m_uLevelNo != *n;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator <=(ln n)
{
  return m_uLevelNo <= *n;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator >=(ln n)
{
  return m_uLevelNo >= *n;
}

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
ln ln::operator +(u8 u)
{
  return m_uLevelNo + u;
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
ln ln::operator -(u8 u)
{
  return m_uLevelNo - u;
}

/*----------------------------------------------------------------------------*/
/* postfix increment                                                          */
/*----------------------------------------------------------------------------*/
ln ln::operator ++(int)
{
  return ++m_uLevelNo;
}

/*----------------------------------------------------------------------------*/
/* _ln level number literal suffix                                            */
/*----------------------------------------------------------------------------*/
ln DBobjects::operator "" _ln(unsigned long long u)
{
  return (ln)u;
}

