#include "DBobjects.h"
  
/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ln::ln(void)
{
  // DO NOT INITIALISE -- ray
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
ln::~ln(void)
{
}

/*----------------------------------------------------------------------------*/
/* zero level                                                                 */
/*----------------------------------------------------------------------------*/
ln ln::nZeroLevel(void)
{
  ln nZeroLevel;
  nZeroLevel = 0;
  
  return nZeroLevel;
}

/*----------------------------------------------------------------------------*/
/* convert level no to offset no                                              */
/*----------------------------------------------------------------------------*/
on ln::nToOffsetNo(void)
{
  on nOffsetNo;
  u8 uOffsetNo = m_uLevelNo - 1;
  
  nOffsetNo = uOffsetNo;
  return nOffsetNo;
}

/*----------------------------------------------------------------------------*/
/* assign                                                                     */
/*----------------------------------------------------------------------------*/
void ln::operator =(i8 i)
{
  m_uLevelNo = i;
}

/*----------------------------------------------------------------------------*/
/* get next offset number                                                     */
/*----------------------------------------------------------------------------*/
i8 ln::operator *(void)
{
  return m_uLevelNo;
}

/*----------------------------------------------------------------------------*/
/* == operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator ==(i8 i)
{
  return m_uLevelNo == i;
}

/*----------------------------------------------------------------------------*/
/* != operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator !=(i8 i)
{
  return m_uLevelNo != i;
}

/*----------------------------------------------------------------------------*/
/* <= operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator <=(i8 i)
{
  return m_uLevelNo <= i;
}

/*----------------------------------------------------------------------------*/
/* < operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator <(i8 i)
{
  return m_uLevelNo < i;
}

/*----------------------------------------------------------------------------*/
/* >= operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator >=(i8 i)
{
  return m_uLevelNo >= i;
}

/*----------------------------------------------------------------------------*/
/* > operator                                                                */
/*----------------------------------------------------------------------------*/
bool ln::operator >(i8 i)
{
  return m_uLevelNo > i;
}

/*----------------------------------------------------------------------------*/
/* add operator                                                               */
/*----------------------------------------------------------------------------*/
ln ln::operator +(i8 i)
{
  u8 uValue = m_uLevelNo + i;
  
  ln nValue;
  nValue = uValue;
  
  return nValue;
}

/*----------------------------------------------------------------------------*/
/* subtract operator                                                          */
/*----------------------------------------------------------------------------*/
ln ln::operator -(i8 i)
{
  u8 uValue = m_uLevelNo - i;
  
  ln nValue;
  nValue = uValue;
  
  return nValue;
}

/*----------------------------------------------------------------------------*/
/* postfix increment                                                          */
/*----------------------------------------------------------------------------*/
ln ln::operator ++(int)
{
  ++m_uLevelNo;
  return *this;
}

/*----------------------------------------------------------------------------*/
/* postfix decrement                                                          */
/*----------------------------------------------------------------------------*/
ln ln::operator --(int)
{
  --m_uLevelNo;
  return *this;
}

/*----------------------------------------------------------------------------*/
/* _ln level number literal suffix                                            */
/*----------------------------------------------------------------------------*/
ln DBobjects::operator "" _ln(unsigned long long u)
{
  ln nValue;
  nValue = u;
  
  return nValue;
}

