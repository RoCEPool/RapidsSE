/*----------------------------------------------------------------------------*/
/* get address after this freeEntry                                           */
/*----------------------------------------------------------------------------*/
char* FreeItem::aAddressAfter(void)
{
  i8 nFreeEntryBytes = nSizeItem_WithoutOffsets();
  
  char* aAfter = aAdd<char*>(this,nFreeEntryBytes);
  
  return aAfter;
}

