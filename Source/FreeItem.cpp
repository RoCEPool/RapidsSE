/*----------------------------------------------------------------------------*/
/* test for valid free entry                                                  */
/*----------------------------------------------------------------------------*/
bool FreeItem::bValidFreeEntry(void)
{
  
  if (! bValidMagic())
    return false;
  
  if (CN_FREEENTRY != eClass())
    return false;

  return true;
}

