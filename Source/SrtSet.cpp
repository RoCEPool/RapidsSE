/*============================================================================*/
/* SrtSet.cpp -- Row Ref Set                                                  */
/*============================================================================*/

#include "Rows.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
SrtSet* Rows::_pSrtSet(void* aAddr)
{
  SrtSet* pSrtSet = reinterpret_cast<SrtSet*>(aAddr);
  
  return pSrtSet;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* SrtSet::operator new(size_t, void* aAddr)
{
  return aAddr;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void SrtSet::operator delete(void* aAddr)
{
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SrtSet::SrtSet(i8 nRowRefs)
: Header(CN_SRTSET)
{
  m_xKey     = C_UNKNOWN;
  m_nRowRefs = nRowRefs;
  
  for (i8 i_RowRef = 0; i_RowRef < nRowRefs; i_RowRef++)
    m_iaRowRef[i_RowRef] = C_DATUM_NULL;
  
  _checkInitialised_(CN_SRTSET);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SrtSet::~SrtSet(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* how many bytes required for a SrtSet with given number of row ref's        */
/*----------------------------------------------------------------------------*/
i8 SrtSet::nBytesReq(i8 nRowRefs)
{
  i8 nBytes = sizeof(SrtSet) - sizeof(i8) + (nRowRefs * sizeof(i8));
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get key from this srt set                                                  */
/*----------------------------------------------------------------------------*/
i8 SrtSet::iKey(void)
{
  return m_xKey;
}

/*----------------------------------------------------------------------------*/
/* set key in this srt set                                                    */
/*----------------------------------------------------------------------------*/
void SrtSet::vKey(i8 xKey)
{
  m_xKey = xKey;
}

/*----------------------------------------------------------------------------*/
/* get the number of row refs in this srt set                                 */
/*----------------------------------------------------------------------------*/
i8 SrtSet::nRowRefs(void)
{
  return m_nRowRefs;
}

/*----------------------------------------------------------------------------*/
/* get a row ref from this srt set                                            */
/*----------------------------------------------------------------------------*/
i8 SrtSet::iRowRef(i8 i_RowRef)
{
  ASSERT(i_RowRef < m_nRowRefs);
  
  return m_iaRowRef[i_RowRef];
}

/*----------------------------------------------------------------------------*/
/* set a row ref in this srt set                                              */
/*----------------------------------------------------------------------------*/
void SrtSet::vRowRef(i8 i_RowRef, i8 iRowRef)
{
  ASSERT(i_RowRef < m_nRowRefs);
  
  m_iaRowRef[i_RowRef] = iRowRef;
}

/*----------------------------------------------------------------------------*/
/* get size of this SrtSet                                                    */
/*----------------------------------------------------------------------------*/
i8 SrtSet::nSizeBytes(void)
{
  i8 nBytes = sizeof(SrtSet) - sizeof(i8) + (m_nRowRefs * sizeof(i8));

  return nBytes;
}

