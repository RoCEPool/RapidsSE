/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(i8 iInt)
{
  vClass(CN_INTVAL);
  
  *pAsIntVal() = iInt;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(Object* pPtr)
{
  vClass(CN_PTRVAL);
  
  *pAsPtrVal() = pPtr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(char* pStr)
{
  vClass(CN_STRVAL);

  *pAsStrVal() = pStr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(const char* pStr)
{
  vClass(CN_STRVAL);

  *pAsStrVal() = pStr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::vAssignBinary(Object* pObject)
{
  vClass(CN_BINVAL);
  
  *pAsBinVal() = pObject;
}

