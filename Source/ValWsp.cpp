/*============================================================================*/
/* ValWsp.cpp - workspace for moving values to/from thread and task stacks    */
/*============================================================================*/

#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
ValWsp* Values::_pValWsp(void* aAddr)
{
  ValWsp* pValWsp = reinterpret_cast<ValWsp*>(aAddr);
  
  RASSERT( !pValWsp || CN_VALWSP == pValWsp->eClass() );
  
  return pValWsp;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ValWsp::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: ValWsp class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ValWsp::ValWsp(void)
: Value(CN_VALWSP)
{
  _precondition_(_MAGIC_,CN_VALWSP);                    //! need to add _FOOTER_
  
  _postcondition_(_MAGIC_,CN_VALWSP);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(i8 iInt)
{
  vClass(CN_INTVAL);
  _precondition_(_MAGIC_,CN_INTVAL);
  
  *_pIntVal(this) = iInt;  
}

/*----------------------------------------------------------------------------*/
/* assign/copy a pointer into workspace                                       */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(Object* pPtr)
{
  vClass(CN_PTRVAL);
  _precondition_(_MAGIC_,CN_PTRVAL);
  
  *_pPtrVal(this) = pPtr;
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(char* pStr)
{
  vClass(CN_STRVAL);
  _precondition_(_MAGIC_,CN_STRVAL);

  _pStrVbl(this)->vAssign(pStr);
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::operator =(const char* pStr)
{
  vClass(CN_STRVAL);
  _precondition_(_MAGIC_,CN_STRVAL);

  _pStrVbl(this)->vAssign(pStr);
}

/*----------------------------------------------------------------------------*/
/* assign/copy a string into workspace                                        */
/*----------------------------------------------------------------------------*/
void ValWsp::vAssignBinary(Object* pObject)
{
  vClass(CN_BINVAL);
  _precondition_(_MAGIC_,CN_BINVAL);
  
  *_pBinVal(this) = pObject;
}

/*----------------------------------------------------------------------------*/
/* get integer (ignoring type)                                                */
/*----------------------------------------------------------------------------*/
i8 ValWsp::iAsInt(void)
{
  _precondition_(_MAGIC_);
  
  IntVal* pIntVal = reinterpret_cast<IntVal*>(this);
  
  i8 i = pIntVal->iInt();
  
  return i;
}

/*----------------------------------------------------------------------------*/
/* get wsp area                                                               */
/*----------------------------------------------------------------------------*/
char* ValWsp::aWspArea(void)
{
  return m_xWsp.aArea();
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* ValWsp::pFooter(void)
{
  _precondition_(_MAGIC_);
  
  return &m_xFooter;
}

