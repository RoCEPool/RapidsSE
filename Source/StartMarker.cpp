/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
StartMarker* ControlData::_pStartMarker(void* aAddr)
{
  StartMarker* pOp = reinterpret_cast<StartMarker*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* StartMarker::operator new(size_t)
{
  StartMarker* pStartMarker =
    static_cast<StartMarker*>(HeapMem::pAllocate(CN_STARTMARKER));
  
  return pStartMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void StartMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StartMarker::StartMarker(void)
: Operand(CN_STARTMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STARTMARKER,_FOOTER_);

  _checkInitialised_(CN_STARTMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_STARTMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
StartMarker::~StartMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STARTMARKER,_FOOTER_);
}


