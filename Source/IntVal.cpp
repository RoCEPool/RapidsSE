#include "SqlValues.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: IntVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* return a value                                                             */
/*----------------------------------------------------------------------------*/
i8 IntVal::iInt(void)
{
  vClass(CN_INTVAL);
  
  return u.m_iInt;
}

/*----------------------------------------------------------------------------*/
/* return a value                                                             */
/*----------------------------------------------------------------------------*/
Int IntVal::wInt(void)
{
  vClass(CN_INTVAL);
  
  Int wI;
  
  wI.m_iInt = u.m_iInt;
  
  return wI;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::vInt(i8 iInt)
{
  vClass(CN_INTVAL);
  u.m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::vInt(Int wInt)
{
  vClass(CN_INTVAL);
  u.m_iInt = wInt.m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a IntVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 IntVal::nStackUsage(void)
{
  return sizeof(IntVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVal::vToStz(Stz* szDst)
{
  if (C_DATUM_NULL == u.m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = u.m_iInt;
}

