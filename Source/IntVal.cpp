#include "Values.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVal::operator new(size_t)
{
  vFatal("fatal: IntVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IntVal::IntVal(void)
: ForthValue(CN_INTVAL)
{
  m_xHeader.vSetClass(CN_INTVAL);
  
  m_iInt = 0;
  
  _checkInitialised_(CN_INTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::operator =(i8 iInt)
{
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get iInt                                                                   */
/*----------------------------------------------------------------------------*/
i8 IntVal::iInt(void) const
{
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IntVal::nSize(void) const
{
  return sizeof(IntVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVal::vToString(Stz* aWorkspace)
{
  if (C_DATUM_NULL == m_iInt) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  * aWorkspace = m_iInt;
}


