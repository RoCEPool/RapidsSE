/*============================================================================*/
/* IntVal.cpp -- Layout of an i8 Integer when on Stack                        */
/*============================================================================*/

#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: IntVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IntVal::IntVal(void)
: StkVal(CN_INTVAL)
{
  _Header::vClass(CN_INTVAL);
  
  m_iInt = 0;
  
  _checkInitialised_(CN_INTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::operator =(i8 iInt)
{
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get iInt                                                                   */
/*----------------------------------------------------------------------------*/
i8 IntVal::iInt(void)
{
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get how many bytes are needed to push a IntVal on stack                    */
/*----------------------------------------------------------------------------*/
i8 IntVal::nStackBytes(void)
{
  return sizeof(IntVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVal::vToString(Stz* szDst)
{
  if (C_DATUM_NULL == m_iInt) {
    szDst->vConcat("null"_Stz);
    return;
  }
  
  * szDst = m_iInt;
}

