/*============================================================================*/
/* IntVal.cpp - integer value                                                 */
/*============================================================================*/

#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IntVal* Values::_pIntVal(void* pAddr)
{
  IntVal* pIntVal = reinterpret_cast<IntVal*>(pAddr);
  
  RASSERT( !pIntVal || CN_INTVAL == pIntVal->eClass() );
  
  return pIntVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: IntVal class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IntVal::IntVal(void)
: Value(CN_INTVAL)
{
  m_iInt = 0;
  
  _checkInitialised_(CN_INTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::operator =(i8 iInt)
{
  //vTrace("IntVal: diff %lld\n",nSub(&m_iInt,this));
  
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get iInt                                                                   */
/*----------------------------------------------------------------------------*/
i8 IntVal::iInt(void) const
{
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IntVal::iSize(void) const
{
  return sizeof(IntVal);
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void IntVal::vToCommand(char* aWorkspace)
{
  String::wToString(m_iInt,aWorkspace);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVal::vToString(char* aWorkspace)
{
  String::wToString(m_iInt,aWorkspace);
}

