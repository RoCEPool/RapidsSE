/*============================================================================*/
/* IntVal.cpp - integer value                                                 */
/*============================================================================*/

#include "Values.h"

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IntVal::operator new(size_t)
{
  vFatal("fatal: IntVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IntVal::IntVal(void)
: Value(CN_INTVAL)
{
  m_iInt = 0;
  
  _checkInitialised_(CN_INTVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IntVal::operator =(i8 iInt)
{
  //vTrace("IntVal: diff %lld\n"_Stz,nSub(&m_iInt,this));
  
  m_iInt = iInt;
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* IntVal::aInt(void)
{
  return &m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get iInt                                                                   */
/*----------------------------------------------------------------------------*/
i8 IntVal::iInt(void) const
{
  return m_iInt;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IntVal::nSize(void) const
{
  return sizeof(IntVal);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IntVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }
  
  *aWorkspace = m_iInt;
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void IntVal::vMaxValue(void)
{
  m_iInt = C_I8_MAX;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void IntVal::vMidValue(void)
{
  m_iInt = 73;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void IntVal::vMinValue(void)
{
  m_iInt = C_I8_MIN;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void IntVal::vNullValue(void)
{
  //vSetNull();
  
  m_iInt = C_DATUM_NULL;
}

