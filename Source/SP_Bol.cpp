#include "Datums.h"

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
SP_Bol::SP_Bol(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
  
  _checkInitialised_(CN_SPSMALL);
  
  _postcondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
SP_Bol::~SP_Bol(void) noexcept(false)
{
  _precondition_(_MAGIC_,CN_SPSMALL,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* sprint SP_Bol and return Stz* to result                                     */
/*----------------------------------------------------------------------------*/
Stz* SP_Bol::sz(i8 iBol)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  if (iBol)
    StrLib::vCopy(m_caResult,(char*)"true"_Stz);
  else
    StrLib::vCopy(m_caResult,(char*)"false"_Stz);

  return (Stz*) &m_caResult[0];
}


/*----------------------------------------------------------------------------*/
/*-- Samples -----------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Bol::szMax(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(true);
}

/*----------------------------------------------------------------------------*/
/* mid                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Bol::szMid(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(true);
}

/*----------------------------------------------------------------------------*/
/* min                                                                        */
/*----------------------------------------------------------------------------*/
Stz* SP_Bol::szMin(void)
{
  _precondition_(_MAGIC_,_FOOTER_);
  
  return sz(false);
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SP_Bol::aFooter(void)
{
  _precondition_(_MAGIC_,CN_SPSMALL);
  
  return &m_xFooter;
}

