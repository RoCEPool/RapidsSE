#include "CompilerStream.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Stmt_Select* CompilerStream::_pStmt_Select(void* aAddr)
{
  Stmt_Select* pOp = reinterpret_cast<Stmt_Select*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* Stmt_Select::operator new(size_t)
{
  Stmt_Select* pStmt_Select =
    static_cast<Stmt_Select*>(HeapMem::pAllocate(CN_STMT_SELECT));
  
  return pStmt_Select;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void Stmt_Select::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Stmt_Select::Stmt_Select(void)
: Operand(CN_STMT_SELECT)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STMT_SELECT,_FOOTER_);
  
  m_pTokenVec = new TokenVec(false);

  _checkInitialised_(CN_STMT_SELECT);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_STMT_SELECT,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Stmt_Select::~Stmt_Select(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STMT_SELECT,_FOOTER_);
  
  delete m_pTokenVec;
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* parse statement                                                            */
/*----------------------------------------------------------------------------*/
bool Stmt_Select::bParse(TokenVec* pTokenVec)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STMT_SELECT,_FOOTER_);
  
  return true;
}

/*----------------------------------------------------------------------------*/
/* get token vector                                                           */
/*----------------------------------------------------------------------------*/
TokenVec* Stmt_Select::pTokenVec(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_STMT_SELECT,_FOOTER_);
  
  return m_pTokenVec;
}


