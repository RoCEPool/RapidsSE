#include "CompilerStream.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Filter* CompilerStream::_pFilter(void* aAddr)
{
  Filter* pFilter = reinterpret_cast<Filter*>(aAddr);
  
  return pFilter;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void Filter::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Filter::Filter(eCN eClassNo, TokenVec* pTokenVec)
: Operand(eClassNo)
{
  _precondition_(_MAGIC_,eClassNo);
  
  m_pTokenVec = new TokenVec(false);
  
  // -- -- -- -- -- -- -- -- -- --
  
  if (pTokenVec)
    m_pTokenVec->vCopyVector(pTokenVec);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Filter::~Filter(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  delete m_pTokenVec;
}

