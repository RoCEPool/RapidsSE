/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* generate                                                                   */
/*----------------------------------------------------------------------------*/
void SchemaTest::vGenerate(void)
{
}


/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* SchemaTest::aFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_SCHEMATEST);
  
  return &m_xFooter;
}

