/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* ReqTuple::operator new(size_t)
{
  vFatal("fatal: ReqTuple class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ReqTuple::ReqTuple(ReqTuple* aReqTuple)
{
  vSet(aReqTuple);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
ReqTuple::ReqTuple(Stz* szService, bool bFlag)
{
  vSet(nullptr);
  
  m_sPurpose = szService;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
ReqTuple::~ReqTuple(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/* set                                                                        */
/*----------------------------------------------------------------------------*/
void ReqTuple::vSet(ReqTuple* aReqTuple)
{
  if (aReqTuple) {
    m_iReqId     = aReqTuple->m_iReqId;
    m_iForId     = aReqTuple->m_iForId;
    m_i_State    = aReqTuple->m_i_State;

    m_iLogLevel  = aReqTuple->m_iLogLevel;
    m_sPurpose   = aReqTuple->m_sPurpose;
    
    return;
  }
  
  m_iReqId     = C_UNKNOWN;
  m_iForId     = C_UNKNOWN;
  m_i_State    = C_UNKNOWN;

  m_iLogLevel  = 0;
  
  //m_sPurpose   = "?"_Stz;
}


