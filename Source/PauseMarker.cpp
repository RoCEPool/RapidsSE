#include "PushDown.h"


/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
PauseMarker* PushDown::_pPauseMarker(void* aAddr)
{
  PauseMarker* pOp = reinterpret_cast<PauseMarker*>(aAddr);
  
  return pOp;
}

/*----------------------------------------------------------------------------*/
/* allocate from heap                                                         */
/*----------------------------------------------------------------------------*/
void* PauseMarker::operator new(size_t)
{
  PauseMarker* pEndMarker =
    static_cast<PauseMarker*>(HeapMem::pAllocate(CN_PAUSEMARKER));
  
  return pEndMarker;
}

/*----------------------------------------------------------------------------*/
/* free back to the heap                                                      */
/*----------------------------------------------------------------------------*/
void PauseMarker::operator delete(void* aAddress)
{
  Object* pObject = static_cast<Object*>(aAddress);
  
  HeapMem::vFree(pObject);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
PauseMarker::PauseMarker(void)
: Operand(CN_PAUSEMARKER)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);

  _checkInitialised_(CN_PAUSEMARKER);

  _postcondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
PauseMarker::~PauseMarker(void) noexcept(false)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_PAUSEMARKER,_FOOTER_);
}


