/*============================================================================*/
/* IvlVal.cpp - integer value                                                 */
/*============================================================================*/

#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IvlVal* Values::_aIvlVal(void* aAddr)
{
  IvlVal* aIvlVal = reinterpret_cast<IvlVal*>(aAddr);
  
  RASSERT_TYPE(aIvlVal,CN_IVLVAL);
  
  return aIvlVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IvlVal::operator new(size_t)
{
  vFatal("fatal: IvlVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IvlVal::IvlVal(void)
: Value(CN_IVLVAL)
{
  
  _checkInitialised_(CN_IVLVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(i8 iIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = iIvl;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(Dtm xIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = xIvl.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iIvl                                                                   */
/*----------------------------------------------------------------------------*/
i8 IvlVal::iIvl(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IvlVal::nSize(void)
{
  return sizeof(IvlVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* IvlVal::aInt(void)
{
  return (i8*)&xIvl;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IvlVal::vToString(Stz* aWorkspace)
{
  if (bIsNull()) {
    aWorkspace->vConcat("null"_Stz);
    return;
  }

  StrLib::vSprint(aWorkspace,
                  "%lld.%lld"_Stz,
                  (i8)xIvl.m_uSecond,
                  (i8)xIvl.m_uMilli
                  );
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* max value                                                                  */
/*----------------------------------------------------------------------------*/
void IvlVal::vMaxValue(void)
{
  xIvl.m_uMilli  = 1023;
  xIvl.m_uSecond = 0x1UL << 53;
}

/*----------------------------------------------------------------------------*/
/* mid value                                                                  */
/*----------------------------------------------------------------------------*/
void IvlVal::vMidValue(void)
{
  xIvl.m_uMilli  = 73;
  xIvl.m_uSecond = 73;
}

/*----------------------------------------------------------------------------*/
/* min value                                                                  */
/*----------------------------------------------------------------------------*/
void IvlVal::vMinValue(void)
{
  xIvl.m_uMilli  = 0;
  xIvl.m_uSecond = 0;
}

/*----------------------------------------------------------------------------*/
/* null value                                                                 */
/*----------------------------------------------------------------------------*/
void IvlVal::vNullValue(void)
{
  vSetNull();
}

