#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IvlVal* Values::_pIvlVal(void* aAddr)
{
  IvlVal* pIvlVal = reinterpret_cast<IvlVal*>(aAddr);
  
  RASSERT( !pIvlVal || CN_IVLVAL == pIvlVal->eClass() );
  
  return pIvlVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IvlVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: IvlVal class cannot be new'd\n"_Str);
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IvlVal::IvlVal(void)
: Value(CN_INTVAL)
{
  m_iIvl = 0;
  
  _checkInitialised_(CN_IVLVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(i8 iIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  m_iIvl = iIvl;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(Ivl xIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Str,nSub(&m_iIvl,this));
  
  m_iIvl = xIvl.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iIvl                                                                   */
/*----------------------------------------------------------------------------*/
i8 IvlVal::iIvl(void) const
{
  return m_iIvl;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IvlVal::nSize(void) const
{
  return sizeof(IvlVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* IvlVal::aInt(void)
{
  return &m_iIvl;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void IvlVal::vToString(Str* aWorkspace)
{
  *aWorkspace = m_iIvl;
}

