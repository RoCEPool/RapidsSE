#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
IvlVal* Values::_pIvlVal(void* aAddr)
{
  IvlVal* pIvlVal = reinterpret_cast<IvlVal*>(aAddr);
  
  RASSERT_CAST( !pIvlVal || CN_IVLVAL == pIvlVal->eClass() );
  
  return pIvlVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* IvlVal::operator new(size_t)
{
  //UNUSED(iSize)
  vFatal("fatal: IvlVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
IvlVal::IvlVal(void)
: Value(CN_INTVAL)
{
  
  _checkInitialised_(CN_IVLVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(i8 iIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = iIvl;
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void IvlVal::operator =(Ivl xIvl)
{
  //vTrace("IvlVal: diff %lld\n"_Stz,nSub(&m_iIvl,this));
  
  *aInt() = xIvl.iAsI8();
}

/*----------------------------------------------------------------------------*/
/* get iIvl                                                                   */
/*----------------------------------------------------------------------------*/
i8 IvlVal::iIvl(void)
{
  return *aInt();
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 IvlVal::nSize(void)
{
  return sizeof(IvlVal);
}

/*----------------------------------------------------------------------------*/
/* get aInt                                                                   */
/*----------------------------------------------------------------------------*/
i8* IvlVal::aInt(void)
{
  return (i8*)&x;
}

