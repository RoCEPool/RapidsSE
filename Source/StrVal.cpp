/*============================================================================*/
/* StrVal.cpp - string value                                                  */
/*============================================================================*/

#include "Values.h"

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
StrVal* Values::_pStrVal(void* pAddr)
{
  StrVal* pStrVal = reinterpret_cast<StrVal*>(pAddr);
  
  RASSERT( !pStrVal || CN_STRVAL == pStrVal->eClass() );
  
  return pStrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: StrVal class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t iSize, StrVal* pStrVal)
{
  RASSERT(iSize);

  return pStrVal;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(void)
: Value(CN_STRVAL)
{
  m_iChars = 0;
  
  _checkInitialised_(CN_STRVAL);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(i8 iChars)
: Value(CN_STRVAL)
{
  m_iChars = iChars;
  
  Memory::vZero(pData(),m_iChars);
  
  _checkInitialised_(CN_STRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void StrVal::operator =(const char* sStr)
{
  //ASSERT(m_iChars);
  
  String::vCopy(m_sStr,sStr);
  m_iChars = String::iSize(m_sStr);
}

/*----------------------------------------------------------------------------*/
/* get iChars                                                                 */
/*----------------------------------------------------------------------------*/
i8 StrVal::iChars(void) const
{
  return m_iChars;
}

/*----------------------------------------------------------------------------*/
/* reset string value                                                         */
/*----------------------------------------------------------------------------*/
void StrVal::vReset(void)
{
  m_iChars = 0;
}

/*----------------------------------------------------------------------------*/
/* get size in bytes                                                          */
/*----------------------------------------------------------------------------*/
i8 StrVal::iSize(void) const
{
  i8 iOverrun = m_iChars > 8 ? m_iChars - 8 : 0;
  
  i8 iSize = sizeof(StrVal) + iOverrun;
  
  return iSize;
}

/*----------------------------------------------------------------------------*/
/* set size in bytes                                                          */
/*----------------------------------------------------------------------------*/
void StrVal::vSize(void)
{
  m_iChars = String::iSize(m_sStr);
}

/*----------------------------------------------------------------------------*/
/* set size in bytes                                                          */
/*----------------------------------------------------------------------------*/
void StrVal::vSize(i8 iSize)
{
  m_iChars = iSize;
}

/*----------------------------------------------------------------------------*/
/* get sStr                                                                   */
/*----------------------------------------------------------------------------*/
char* StrVal::sStr(void)
{
  return &m_sStr[0];
}

/*----------------------------------------------------------------------------*/
/* get data area                                                              */
/*----------------------------------------------------------------------------*/
char* StrVal::pData(void)
{
  return &m_sStr[0];
}

/*----------------------------------------------------------------------------*/
/* convert to command                                                         */
/*----------------------------------------------------------------------------*/
void StrVal::vToCommand(char* aWorkspace)
{
  String::vCopy(aWorkspace,"\"");
  String::vCopy(aWorkspace,m_sStr);
  String::vCopy(aWorkspace,"\"");
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void StrVal::vToString(char* aWorkspace)
{
  String::vCopy(aWorkspace,m_sStr);
}

/*----------------------------------------------------------------------------*/
/* copy a string into workspace                                               */
/*----------------------------------------------------------------------------*/
void StrVal::vCopyString(char* aStr, i8 iLength)
{
  vClass(CN_STRVAL);
  
  String::vCopyLen(m_sStr,aStr,iLength);
  
  m_iChars = String::iSize(m_sStr);
}

/*----------------------------------------------------------------------------*/
/*-- Static ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* calculate number of bytes reqired to hold string of given length           */
/*----------------------------------------------------------------------------*/
i8 StrVal::nBytesRequired(i8 iLength)
{
  i8 nBytes = sizeof(StrVal) + iLength + 1 - 8;
  
  return nBytes;
}

