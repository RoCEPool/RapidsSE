/*============================================================================*/
/* StrVal.cpp -- Layout of a String when on Stack                             */
/*============================================================================*/

#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
StrVal* SenVM::_aStrVal(void* aAddr)
{
  StrVal* aStrVal = reinterpret_cast<StrVal*>(aAddr);
  
  RASSERT( ! aStrVal || CN_STRVAL == aStrVal->eClass() );
  
  return aStrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t)
{
  vThrow(FK_FATAL,VL_FATAL,__func__,__FILE__,__LINE__,
         "fatal: StrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(void)
: StkVal(CN_STRVAL)
{
  _Header::vClass(CN_STRVAL);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign given str                                                           */
/*----------------------------------------------------------------------------*/
void StrVal::vAssign(Stz* szStz)
{
  m_nBytesFollowing = StrLib::nCopy(m_caStr,szStz->azChar()) + 1;
}

/*----------------------------------------------------------------------------*/
/* get char*                                                                  */
/*----------------------------------------------------------------------------*/
char* StrVal::azChar(void)
{
  return m_caStr;
}

/*----------------------------------------------------------------------------*/
/* get adddress of Stz area                                                   */
/*----------------------------------------------------------------------------*/
Stz* StrVal::szStz(void)
{
  return reinterpret_cast<Stz*>(m_caStr);
}

/*----------------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get size of this StrVal in bytes                                           */
/*----------------------------------------------------------------------------*/
i8 StrVal::nStackBytes(void)
{
  i8 nBytes = sizeof(StrVal)
                - sizeof(m_caStr)
                + m_nBytesFollowing;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void StrVal::vToString(Stz* szStz)
{
  StrLib::vCopy(szStz->azChar(),m_caStr);
}

