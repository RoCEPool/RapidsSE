/*============================================================================*/
/* StrVal.cpp -- null-terminated string value                                 */
/*============================================================================*/

#include "SenVM.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
StrVal* SenVM::_aStrVal(void* aAddr)
{
  StrVal* aStrVal = reinterpret_cast<StrVal*>(aAddr);
  
  RASSERT( ! aStrVal || CN_STRVAL == aStrVal->eClass() );
  
  return aStrVal;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t)
{
  vFatal("fatal: StrVal class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(void)
: ForthValue(CN_STRVAL)
{
  m_xHeader.vSetClass(CN_STRVAL);
}


/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assign given str                                                           */
/*----------------------------------------------------------------------------*/
void StrVal::vAssign(Stz* aStz)
{
  m_nBytesFollowing = StrLib::nCopy(m_caStr,aStz->azChar()) + 1;
}

/*----------------------------------------------------------------------------*/
/* get char*                                                                  */
/*----------------------------------------------------------------------------*/
char* StrVal::azChar(void)
{
  return m_caStr;
}

/*----------------------------------------------------------------------------*/
/* get size of this StrVal in bytes                                           */
/*----------------------------------------------------------------------------*/
i8 StrVal::nSize(void)
{
  i8 nBytes = sizeof(StrVal)
                - sizeof(m_caStr)
                + m_nBytesFollowing;
  
  return nBytes;
}

/*----------------------------------------------------------------------------*/
/* get adddress of Stz area                                                   */
/*----------------------------------------------------------------------------*/
Stz* StrVal::aStz(void)
{
  return reinterpret_cast<Stz*>(m_caStr);
}

/*----------------------------------------------------------------------------*/
/* convert to string                                                          */
/*----------------------------------------------------------------------------*/
void StrVal::vToString(Stz* aStz)
{
  StrLib::vCopy(aStz->azChar(),m_caStr);
}

