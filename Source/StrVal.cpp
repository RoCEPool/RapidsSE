#include "Values.h"


/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t iSize)
{
  RASSERT(iSize);
  vFatal("fatal: StrVal class cannot be new'd\n");
  
  RASSERT(0);
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* StrVal::operator new(size_t iSize, StrVal* pStrVal)
{
  RASSERT(iSize);

  return pStrVal;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(void)
: sRefactor(CN_STRVAL)
{
  m_nDataBytes = 0;
  
  _checkInitialised_(CN_STRVAL);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
StrVal::StrVal(i8 iChars)
: sRefactor(CN_STRVAL)
{
  m_nDataBytes = iChars;
  
  Memory::vZero(pDataArea(),m_nDataBytes);
  
  _checkInitialised_(CN_STRVAL);
}

/*----------------------------------------------------------------------------*/
/* assign a value                                                             */
/*----------------------------------------------------------------------------*/
void StrVal::operator =(const char* sStr)
{
  //ASSERT(m_nDataBytes);
  
  String::vCopy(pDataArea(),sStr);
  m_nDataBytes = String::iSize(pDataArea());
}

