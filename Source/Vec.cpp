#include "DBobjects.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
Vec* DBobjects::_pVec(void* aAddr)
{
  Vec* pVec = reinterpret_cast<Vec*>(aAddr);
  
  RASSERT( !pVec || CN_COLUMNVEC == pVec->eClass() );
  
  return pVec;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* Vec::operator new(size_t iSize)
{
  RASSERT(iSize);
  
  void* pObject = Heap::pAllocate(CN_COLUMNVEC);
  
  return pObject;
}

/*----------------------------------------------------------------------------*/
/* operator delete                                                            */
/*----------------------------------------------------------------------------*/
void Vec::operator delete(void* pDataAddress)
{
  Data* pData = reinterpret_cast<Data*>(pDataAddress);
  
  Heap::vFree(pData);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Vec::Vec(void)
: Object(CN_COLUMNVEC)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);
  
  m_nItems = 0;
  
  for (i8 iItem = 0; iItem < C_VEC; iItem++)
    m_pItem[iItem] = nullptr;
  
  _setFooter_();
  
  _checkInitialised_(CN_COLUMNVEC);
  
  _postcondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Vec::~Vec(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* add an iterm                                                               */
/*----------------------------------------------------------------------------*/
void Vec::vAdd(Object* pItem)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);
  
  // check we have a free slot
  ASSERT(m_nItems >= 0 && m_nItems < C_VEC - 1);
  
  // get column number
  i8 iItem = m_nItems++;
  ASSERT(m_nItems > 0 && m_nItems < C_VEC);
  
  // there shouldnt already be a column
  ASSERT( ! m_pItem[iItem] );
  
  // set column
  m_pItem[iItem] = pItem;
}

/*----------------------------------------------------------------------------*/
/* get number of actual items                                                 */
/*----------------------------------------------------------------------------*/
i8 Vec::nItems(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);

  ASSERT(m_nItems >= 0 && m_nItems < C_VEC);
  
  return m_nItems;
}

/*----------------------------------------------------------------------------*/
/* get a specific item                                                        */
/*----------------------------------------------------------------------------*/
Object* Vec::pGet(i8 iItem)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC,_FOOTER_);
 
  ASSERT(iItem >= 0 && iItem < m_nItems);
  
  Object* pItem = m_pItem[iItem];
  
  return pItem;
}

/*----------------------------------------------------------------------------*/
/*-- Footer ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get location of footer                                                     */
/*----------------------------------------------------------------------------*/
Footer* Vec::pFooter(void)
{
  _precondition_(_ADDRESS_,_MAGIC_,CN_COLUMNVEC);
  
  return &m_xFooter;
}

