/*============================================================================*/
/* FreeChunk.cpp - free chunk in heap                                         */
/*============================================================================*/

#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* FreeChunk::operator new(size_t, FreeChunk* aFreeChunk)
{
  return aFreeChunk;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void FreeChunk::operator delete(void*)
{
  vFatal("fatal: FreeChunk class cannot be deleted"_Stz);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FreeChunk::FreeChunk(void)
: Header(CN_NONE)
{
  m_pNextFree = nullptr;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
FreeChunk::~FreeChunk(void) noexcept(false)
{
  vFatal("fatal: FreeChunk class cannot be deleted"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* initialize a free chunk                                                    */
/*----------------------------------------------------------------------------*/
void FreeChunk::vInit(eCN eWasClass)
{
  vSetMagic();
  vSetClass(CN_FREECHUNK);
  m_eWasClass = eWasClass;
}

/*----------------------------------------------------------------------------*/
/* get the was-class of the free chunk                                        */
/*----------------------------------------------------------------------------*/
eCN FreeChunk::eWasClass(void)
{
  return m_eWasClass;
}

/*----------------------------------------------------------------------------*/
/* set the was-class of the free chunk                                        */
/*----------------------------------------------------------------------------*/
void FreeChunk::vWasClass(eCN eWasClass)
{
  m_eWasClass = eWasClass;
}

/*----------------------------------------------------------------------------*/
/* get next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
FreeChunk* FreeChunk::pNextFree(void)
{
  return m_pNextFree;
}

/*----------------------------------------------------------------------------*/
/* set next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
void FreeChunk::vNextFree(FreeChunk* pNextFree)
{
  m_pNextFree = pNextFree;
}

