#include "Pool.h"

/*----------------------------------------------------------------------------*/
/* new                                                                        */
/*----------------------------------------------------------------------------*/
void* FreeChunk::operator new(size_t, FreeChunk* pFreeChunk)
{
  //UNUSED(iSize)
  return pFreeChunk;
}

/*----------------------------------------------------------------------------*/
/* delete                                                                     */
/*----------------------------------------------------------------------------*/
void FreeChunk::operator delete(void*)
{
  vFatal("fatal: FreeChunk class cannot be deleted"_Stz);
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
FreeChunk::FreeChunk(void)
: Object(CN_NONE)
{
  m_pNextFree = nullptr;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
FreeChunk::~FreeChunk(void) noexcept(false)
{
  vFatal("fatal: FreeChunk class cannot be deleted"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* initialize a free chunk                                                    */
/*----------------------------------------------------------------------------*/
void FreeChunk::vInit(eCN eClassNo)
{
  _precondition_(_ADDRESS_,_MAGIC_);

  vSetMagic();
  vSetClass(eClassNo);
}

/*----------------------------------------------------------------------------*/
/* get next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
FreeChunk* FreeChunk::pNextFree(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_pNextFree;
}

/*----------------------------------------------------------------------------*/
/* set next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
void FreeChunk::vNextFree(FreeChunk* pNextFree)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_pNextFree = pNextFree;
}

