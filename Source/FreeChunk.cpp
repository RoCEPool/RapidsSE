/*----------------------------------------------------------------------------*/
/* get next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
FreeChunk* FreeChunk::pNextFree(void)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  return m_pNextFree;
}

/*----------------------------------------------------------------------------*/
/* set next free chunk in chain                                               */
/*----------------------------------------------------------------------------*/
void FreeChunk::vNextFree(FreeChunk* pNextFree)
{
  _precondition_(_ADDRESS_,_MAGIC_);
  
  m_pNextFree = pNextFree;
}

