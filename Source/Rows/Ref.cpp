/*============================================================================*/
/* Rrf.cpp -- Reference to another buffer item                                */
/*============================================================================*/

#include "Rows.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Rrf::Rrf(void)
{
  vSetNil();
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
Rrf::Rrf(u8 uBuffer, u8 uItem, u8 uLevels)
{
  m_uBuffer  = uBuffer;
  m_uItem    = uItem;
  m_uLevels  = uLevels;
  
  m_uKind    = KE_GENERAL;
  m_uPayload = 0;
  m_uFree    = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
Rrf::~Rrf(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* assignment                                                                 */
/*----------------------------------------------------------------------------*/
void Rrf::operator =(Rrf xwRef)
{
  vSet(xwRef);
}

/*----------------------------------------------------------------------------*/
/* get contents as an i8 integer                                              */
/*----------------------------------------------------------------------------*/
i8 Rrf::iAsI8(void)
{
  return m_iAsI8;
}

/*----------------------------------------------------------------------------*/
/* get buffer                                                                 */
/*----------------------------------------------------------------------------*/
i8 Rrf::iBuffer(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Rrf::vBuffer(i8 iBuffer)
{
  m_uBuffer = iBuffer;
}

/*----------------------------------------------------------------------------*/
/* get free                                                                   */
/*----------------------------------------------------------------------------*/
bool Rrf::bFree(void)
{
  return (bool)m_uFree;
}

/*----------------------------------------------------------------------------*/
/* set buffer                                                                 */
/*----------------------------------------------------------------------------*/
void Rrf::vFree(bool bFree)
{
  m_uFree = bFree;
}

/*----------------------------------------------------------------------------*/
/* get size of free entry                                                     */
/*----------------------------------------------------------------------------*/
i8 Rrf::nFreeSize(void)
{
  return (i8)m_uBuffer;
}

/*----------------------------------------------------------------------------*/
/* set size of free entry                                                     */
/*----------------------------------------------------------------------------*/
void Rrf::vFreeSize(i8 nFreeSize)
{
  m_uBuffer = nFreeSize;
}

/*----------------------------------------------------------------------------*/
/* is nil reference?                                                          */
/*----------------------------------------------------------------------------*/
bool Rrf::bIsNil(void)
{
  if (0 == m_uBuffer)
    return true;
  else
    return false;
}

/*----------------------------------------------------------------------------*/
/* get item                                                                   */
/*----------------------------------------------------------------------------*/
i8 Rrf::iItem(void)
{
  return (i8)m_uItem;
}

/*----------------------------------------------------------------------------*/
/* set item                                                                   */
/*----------------------------------------------------------------------------*/
void Rrf::vItem(i8 iItem)
{
  m_uItem = iItem;
}

/*----------------------------------------------------------------------------*/
/* get entry key kind                                                        */
/*----------------------------------------------------------------------------*/
eKE Rrf::eKind(void)
{
  return (eKE)m_uKind;
}

/*----------------------------------------------------------------------------*/
/* set entry key kind                                                        */
/*----------------------------------------------------------------------------*/
void Rrf::vKind(eKE eKind)
{
  m_uKind = eKind;
}

/*----------------------------------------------------------------------------*/
/* is there a payload after ent?                                              */
/*----------------------------------------------------------------------------*/
bool Rrf::bPayload(void)
{
  return (bool)m_uPayload;
}

/*----------------------------------------------------------------------------*/
/* set is there a payload                                                     */
/*----------------------------------------------------------------------------*/
void Rrf::vPayload(bool bPayLoad)
{
  m_uPayload = bPayLoad;
}

/*----------------------------------------------------------------------------*/
/* reset                                                                      */
/*----------------------------------------------------------------------------*/
void Rrf::vReset(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uLevels  = 0;
  
  m_uKind    = 0;
  m_uPayload = 0;
  m_uFree    = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* set ref                                                                    */
/*----------------------------------------------------------------------------*/
void Rrf::vSet(Rrf xwRef)
{
  m_uBuffer  = xwRef.m_uBuffer;
  m_uItem    = xwRef.m_uItem;
  m_uLevels  = xwRef.m_uLevels;
  
  m_uKind    = xwRef.m_uKind;
  m_uPayload = xwRef.m_uPayload;
  m_uFree    = xwRef.m_uFree;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* set nil ref                                                                */
/*----------------------------------------------------------------------------*/
void Rrf::vSetNil(void)
{
  m_uBuffer  = 0;
  m_uItem    = 0;
  m_uLevels  = 0;
  
  m_uKind    = 0;
  m_uPayload = 0;
  m_uFree    = 0;
  m_uSpare   = 0;
}

/*----------------------------------------------------------------------------*/
/* get number of skip levels                                                  */
/*----------------------------------------------------------------------------*/
i8 Rrf::nSkipLevels(void)
{
  return (i8)m_uLevels;
}

/*----------------------------------------------------------------------------*/
/* set number of offsets that follow                                          */
/*----------------------------------------------------------------------------*/
void Rrf::vSkipLevels(i8 nSkipLevels)
{
  m_uLevels = nSkipLevels;
}

