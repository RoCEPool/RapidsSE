/*----------------------------------------------------------------------------*/
/* get input                                                                  */
/*----------------------------------------------------------------------------*/
bool Prompt::bGetInput(s& sPrompt, s& sInput)
{
  printf("%s",sPrompt.a());
  
  char* y = sInput.a();
  
  char c;
  
  while ('\n' != (c = getc(stdin))) {
    *y++ = c;
  }
  *y = '\0';
  
  return true;
}

