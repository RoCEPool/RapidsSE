#include "Logging.h"

/*----------------------------------------------------------------------------*/
/* set entry                                                                  */
/*----------------------------------------------------------------------------*/
void _LogEntryLck::vSet(LogEntry* pLogEntry, i8 iLckId, eLA eLckAct)
{
  pLogEntry->m_eKind = EK_LCK;
  
  m_iLckId  = iLckId;
  m_eLckAct = eLckAct;
}

/*----------------------------------------------------------------------------*/
/* write to csv file                                                          */
/*----------------------------------------------------------------------------*/
void _LogEntryLck::vWriteCsv(File* pFile)
{
  SP_Id spId;
  
  pFile->vPrint(",%s,%s"_Stz,
                
                spId.sz(m_iLckId),
                aIA[m_eLckAct]);
}

