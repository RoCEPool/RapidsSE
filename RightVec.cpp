/*============================================================================*/
/* RightVec.cpp -- Right vector (array of offsets)                            */
/*============================================================================*/

#include "Structures.h"

/*----------------------------------------------------------------------------*/
/*-- LifeCycle ---------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* safe cast                                                                  */
/*----------------------------------------------------------------------------*/
RightVec* Structures::_aRightVec(void* aAddr)
{
  RightVec* aRightVec = reinterpret_cast<RightVec*>(aAddr);
  
  return aRightVec;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RightVec::operator new(size_t)
{
  vFatal("fatal: RightVec class cannot be new'd\n"_Stz);
  
  NEVER_REACH;
}

/*----------------------------------------------------------------------------*/
/* operator new                                                               */
/*----------------------------------------------------------------------------*/
void* RightVec::operator new(size_t, RightVec* pRightVec)
{
  return pRightVec;
}

/*----------------------------------------------------------------------------*/
/* constructor                                                                */
/*----------------------------------------------------------------------------*/
RightVec::RightVec(void)
{
}

/*----------------------------------------------------------------------------*/
/* destructor                                                                 */
/*----------------------------------------------------------------------------*/
RightVec::~RightVec(void) noexcept(false)
{
}

/*----------------------------------------------------------------------------*/
/*-- Public ------------------------------------------------------------------*/
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
/* get the offset for a given offset (offset is 0 or 1)                       */
/*----------------------------------------------------------------------------*/
i8 RightVec::iOffset(i8 i_OffsetNo)
{
  u8 uOffset = m_nOffset[i_OffsetNo];
  
  return uOffset;
}

/*----------------------------------------------------------------------------*/
/* set the offset for a given offset (offset is 0 or 1)                       */
/*----------------------------------------------------------------------------*/
void RightVec::vOffset(i8 i_OffsetNo, i8 iOffset)
{
  m_nOffset[i_OffsetNo] = iOffset;
}

